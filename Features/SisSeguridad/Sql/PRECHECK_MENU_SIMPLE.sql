-- R50 preflight: selecting SIS does not change the authenticated database user.
SELECT USER USUARIO_CONEXION, SYS_CONTEXT('USERENV','CURRENT_SCHEMA') ESQUEMA_ACTIVO FROM DUAL;
SELECT OWNER, OBJECT_NAME, OBJECT_TYPE FROM ALL_OBJECTS
 WHERE OWNER='SIS' AND OBJECT_NAME='OSS_MOD';
DECLARE
  v_owner VARCHAR2(30);
  v_count NUMBER;
BEGIN
  v_owner:=SYS_CONTEXT('USERENV','CURRENT_SCHEMA');
  IF v_owner<>'SIS' THEN
    RAISE_APPLICATION_ERROR(-20010,'Seleccione SIS como esquema activo. La instalacion no se inicio.');
  END IF;
  FOR obj IN (
    SELECT OBJECT_NAME,OBJECT_TYPE FROM ALL_OBJECTS
     WHERE OWNER='SIS' AND OBJECT_NAME IN (
       'OSS_MOD','OSS_MENU','OSS_PERM','OSS_MENU_PERM','OSS_ROL','OSS_ROL_MENU',
       'OSS_ROL_PERM','OSS_USR_ROL','OSS_USR_PERM','OSS_SEG_AUD','OSS_USUARIO_ROL',
       'OSS_SEG_MENU_REV','OSS_SEG_MENU_CTL','OSS_SEG_MENU_MAP','OSS_SEG_MENU_MIG','OSS_SEG_MENU_AUD')
       AND OBJECT_TYPE IN ('VIEW','SYNONYM','SEQUENCE','PACKAGE','PROCEDURE','FUNCTION','TYPE','MATERIALIZED VIEW')
  ) LOOP
    SELECT COUNT(*) INTO v_count FROM ALL_TABLES WHERE OWNER='SIS' AND TABLE_NAME=obj.OBJECT_NAME;
    IF v_count=0 THEN
      RAISE_APPLICATION_ERROR(-20011,'Conflicto: SIS.'||obj.OBJECT_NAME||' existe como '||obj.OBJECT_TYPE||'. No se elimina ni sustituye.');
    END IF;
  END LOOP;
END;
/
