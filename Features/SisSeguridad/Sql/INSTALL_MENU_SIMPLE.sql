  END;
  PROCEDURE SAVE_ROLE(p_ID IN OUT NUMBER,p_MOD NUMBER,p_KEY VARCHAR2,p_NAME VARCHAR2,p_DESC VARCHAR2,
    p_ACTIVE NUMBER,p_MENUS CLOB,p_PERMS CLOB,p_SET_PERMS NUMBER,p_ACTOR NUMBER) IS
    list ids; n NUMBER;
  BEGIN
    SELECT COUNT(*) INTO n FROM OSS_MOD WHERE CODIGO_MOD=p_MOD AND ACTIVO=1;
    IF n<>1 OR p_KEY IS NULL OR p_NAME IS NULL OR p_ACTIVE NOT IN(0,1) THEN RAISE_APPLICATION_ERROR(-20001,'Rol o modulo invalido.'); END IF;
    IF NVL(p_ID,0)=0 THEN
      SELECT SEQ_OSS_SM_ROL.NEXTVAL INTO p_ID FROM DUAL;
      INSERT INTO OSS_ROL(CODIGO_ROL,CODIGO_MOD,CLAVE,NOMBRE,DESCRIPCION,ACTIVO,USUARIO_INS,FECHA_INS)
        VALUES(p_ID,p_MOD,p_KEY,p_NAME,p_DESC,p_ACTIVE,p_ACTOR,SYSDATE);
    ELSE
      UPDATE OSS_ROL SET NOMBRE=p_NAME,DESCRIPCION=p_DESC,ACTIVO=p_ACTIVE,USUARIO_UPD=p_ACTOR,FECHA_UPD=SYSDATE
        WHERE CODIGO_ROL=p_ID AND CODIGO_MOD=p_MOD AND CLAVE=p_KEY;
      IF SQL%ROWCOUNT<>1 THEN RAISE_APPLICATION_ERROR(-20001,'Rol inexistente o identidad modificada.'); END IF;
    END IF;
    list:=split(p_MENUS);
    DELETE FROM OSS_ROL_MENU WHERE CODIGO_ROL=p_ID;
    FOR i IN 1..list.COUNT LOOP
      SELECT COUNT(*) INTO n FROM OSS_MENU m JOIN OSS_MOD mo ON mo.CODIGO_MOD=m.CODIGO_MOD
        WHERE m.CODIGO_MENU=list(i) AND m.ACTIVO=1 AND mo.ACTIVO=1;
      IF n<>1 THEN RAISE_APPLICATION_ERROR(-20001,'Opcion inexistente o inactiva.'); END IF;
      INSERT INTO OSS_ROL_MENU(CODIGO_ROL,CODIGO_MENU,USUARIO_INS,FECHA_INS) VALUES(p_ID,list(i),p_ACTOR,SYSDATE);
    END LOOP;
    IF p_SET_PERMS=1 THEN
      list:=split(p_PERMS); DELETE FROM OSS_ROL_PERM WHERE CODIGO_ROL=p_ID;
      FOR i IN 1..list.COUNT LOOP INSERT INTO OSS_ROL_PERM(CODIGO_ROL,CODIGO_PERM,USUARIO_INS,FECHA_INS) VALUES(p_ID,list(i),p_ACTOR,SYSDATE); END LOOP;
    END IF;
  END;
  PROCEDURE SAVE_NODE(p_ID IN OUT NUMBER,p_MOD NUMBER,p_PARENT NUMBER,p_TITLE VARCHAR2,p_PATH VARCHAR2,p_ICON VARCHAR2,p_ORDER NUMBER,p_ACTIVE NUMBER,p_ACTOR NUMBER) IS
  BEGIN
    IF NVL(p_ID,0)=0 THEN
      SELECT SEQ_OSS_SM_MENU.NEXTVAL INTO p_ID FROM DUAL;
      INSERT INTO OSS_MENU(CODIGO_MENU,CODIGO_MOD,CODIGO_PADRE,TITULO,PATH,ICONO,ORDEN,ACTIVO,USUARIO_INS,FECHA_INS)
        VALUES(p_ID,p_MOD,p_PARENT,p_TITLE,p_PATH,p_ICON,p_ORDER,p_ACTIVE,p_ACTOR,SYSDATE);
    ELSE
      UPDATE OSS_MENU SET CODIGO_MOD=p_MOD,CODIGO_PADRE=p_PARENT,TITULO=p_TITLE,PATH=p_PATH,ICONO=p_ICON,ORDEN=p_ORDER,ACTIVO=p_ACTIVE,USUARIO_UPD=p_ACTOR,FECHA_UPD=SYSDATE WHERE CODIGO_MENU=p_ID;
      IF SQL%ROWCOUNT<>1 THEN RAISE_APPLICATION_ERROR(-20001,'Opcion inexistente.'); END IF;
    END IF;
  END;
  PROCEDURE SAVE_USER(p_USER NUMBER,p_EMPRESA NUMBER,p_ROLES CLOB,p_ACTOR NUMBER) IS list ids; n NUMBER;
  BEGIN
    SELECT COUNT(*) INTO n FROM SIS_USUARIOS WHERE CODIGO_USUARIO=p_USER AND CODIGO_EMPRESA=p_EMPRESA;
    IF n<>1 THEN RAISE_APPLICATION_ERROR(-20001,'Usuario inexistente en la empresa.'); END IF;
    list:=split(p_ROLES);
    UPDATE OSS_USR_ROL SET ACTIVO=0,USUARIO_UPD=p_ACTOR,FECHA_UPD=SYSDATE WHERE CODIGO_USUARIO=p_USER AND CODIGO_EMPRESA=p_EMPRESA;
    FOR i IN 1..list.COUNT LOOP
      SELECT COUNT(*) INTO n FROM OSS_ROL r JOIN OSS_MOD m ON m.CODIGO_MOD=r.CODIGO_MOD
        WHERE r.CODIGO_ROL=list(i) AND r.ACTIVO=1 AND m.ACTIVO=1;
      IF n<>1 THEN RAISE_APPLICATION_ERROR(-20001,'Rol inexistente o inactivo.'); END IF;
      UPDATE OSS_USR_ROL SET ACTIVO=1,USUARIO_UPD=p_ACTOR,FECHA_UPD=SYSDATE
        WHERE CODIGO_USUARIO=p_USER AND CODIGO_EMPRESA=p_EMPRESA AND CODIGO_ROL=list(i);
      IF SQL%ROWCOUNT=0 THEN INSERT INTO OSS_USR_ROL(CODIGO_USR_ROL,CODIGO_USUARIO,CODIGO_EMPRESA,CODIGO_ROL,ACTIVO,USUARIO_INS,FECHA_INS)
        VALUES(SEQ_OSS_SM_UR.NEXTVAL,p_USER,p_EMPRESA,list(i),1,p_ACTOR,SYSDATE); END IF;
    END LOOP;
  END;
  PROCEDURE MAP_NODE(p_HASH VARCHAR2,p_MOD VARCHAR2,p_PARENT NUMBER,p_TITLE VARCHAR2,p_PATH VARCHAR2,
    p_ICON VARCHAR2,p_ORDER NUMBER,p_ID OUT NUMBER) IS m NUMBER;
  BEGIN
    BEGIN SELECT CODIGO_MENU INTO p_ID FROM OSS_SEG_MENU_MAP WHERE HUELLA=p_HASH; RETURN; EXCEPTION WHEN NO_DATA_FOUND THEN NULL; END;
    BEGIN SELECT CODIGO_MOD INTO m FROM OSS_MOD WHERE CODIGO=p_MOD AND ACTIVO=1;
    EXCEPTION WHEN NO_DATA_FOUND THEN
      SELECT COUNT(*) INTO m FROM OSS_MOD WHERE CODIGO=p_MOD;
      IF m>0 THEN RAISE_APPLICATION_ERROR(-20001,'Modulo inactivo.'); END IF;
      SELECT SEQ_OSS_SM_MOD.NEXTVAL INTO m FROM DUAL;
      INSERT INTO OSS_MOD(CODIGO_MOD,CODIGO,NOMBRE,ORDEN,ACTIVO,FECHA_INS) VALUES(m,p_MOD,p_MOD,0,1,SYSDATE);
    END;
    SELECT SEQ_OSS_SM_MENU.NEXTVAL INTO p_ID FROM DUAL;
    INSERT INTO OSS_MENU(CODIGO_MENU,CODIGO_MOD,CODIGO_PADRE,TITULO,PATH,ICONO,ORDEN,ACTIVO,FECHA_INS)
      VALUES(p_ID,m,p_PARENT,p_TITLE,p_PATH,p_ICON,p_ORDER,1,SYSDATE);
    INSERT INTO OSS_SEG_MENU_MAP VALUES(p_HASH,p_ID);
  END;
  PROCEDURE MAP_PERM(p_KEY VARCHAR2,p_MOD NUMBER,p_ID OUT NUMBER) IS n NUMBER;
  BEGIN
    BEGIN SELECT CODIGO_PERM INTO p_ID FROM OSS_PERM WHERE CLAVE=p_KEY AND ACTIVO=1;
    EXCEPTION WHEN NO_DATA_FOUND THEN
      SELECT COUNT(*) INTO n FROM OSS_PERM WHERE CLAVE=p_KEY;
      IF n>0 THEN RAISE_APPLICATION_ERROR(-20001,'Permiso inactivo.'); END IF;
      SELECT SEQ_OSS_SM_PERM.NEXTVAL INTO p_ID FROM DUAL;
      INSERT INTO OSS_PERM(CODIGO_PERM,CODIGO_MOD,CLAVE,NOMBRE,ACTIVO,FECHA_INS) VALUES(p_ID,p_MOD,p_KEY,p_KEY,1,SYSDATE);
    END;
  END;
  PROCEDURE LINK_PERM(p_MENU NUMBER,p_PERM NUMBER) IS n NUMBER;
  BEGIN
    SELECT COUNT(*) INTO n FROM OSS_MENU_PERM WHERE CODIGO_MENU=p_MENU AND CODIGO_PERM=p_PERM;
    IF n=0 THEN INSERT INTO OSS_MENU_PERM(CODIGO_MENU,CODIGO_PERM,USUARIO_INS,FECHA_INS) VALUES(p_MENU,p_PERM,NULL,SYSDATE); END IF;
  END;
  PROCEDURE BACKUP_USER(p_USER NUMBER,p_EMPRESA NUMBER,p_HASH VARCHAR2,p_SOURCE CLOB,p_ACTOR NUMBER) IS v NUMBER;
  BEGIN
    SELECT VERSION INTO v FROM OSS_SEG_MENU_REV WHERE ID=1;
    INSERT INTO OSS_SEG_MENU_MIG VALUES(SEQ_OSS_SM_MIG.NEXTVAL,p_USER,p_EMPRESA,p_HASH,p_SOURCE,p_ACTOR,SYSDATE,v);
  END;
  PROCEDURE CLEAR_PERMS(p_USER NUMBER,p_EMPRESA NUMBER,p_ACTOR NUMBER) IS
  BEGIN
    UPDATE OSS_USR_PERM SET ACTIVO=0,USUARIO_UPD=p_ACTOR,FECHA_UPD=SYSDATE WHERE CODIGO_USUARIO=p_USER AND CODIGO_EMPRESA=p_EMPRESA;
  END;
  PROCEDURE CLEAR_CACHE(p_USER NUMBER,p_EMPRESA NUMBER) IS n NUMBER;
  BEGIN
    SELECT COUNT(*) INTO n FROM SIS_USUARIOS WHERE CODIGO_USUARIO=p_USER AND CODIGO_EMPRESA=p_EMPRESA;
    IF n<>1 THEN RAISE_APPLICATION_ERROR(-20001,'Usuario fuera de empresa.'); END IF;
    DELETE FROM OSS_USUARIO_ROL WHERE CODIGO_USUARIO=p_USER;
  END;
  PROCEDURE WRITE_CACHE(p_USER NUMBER,p_EMPRESA NUMBER,p_MOD VARCHAR2,p_JSON CLOB) IS login VARCHAR2(50);
  BEGIN
    SELECT LOGIN INTO login FROM SIS_USUARIOS WHERE CODIGO_USUARIO=p_USER AND CODIGO_EMPRESA=p_EMPRESA;
    INSERT INTO OSS_USUARIO_ROL(CODIGO_USUARIO_ROL,USUARIO,CODIGO_USUARIO,DESCRIPCION,JSON_MENU)
      VALUES(SEQ_OSS_SM_CACHE.NEXTVAL,login,p_USER,p_MOD,p_JSON);
  END;
  PROCEDURE SET_MODE(p_USER NUMBER,p_EMPRESA NUMBER,p_ACTIVE NUMBER) IS n NUMBER;
  BEGIN
    SELECT COUNT(*) INTO n FROM SIS_USUARIOS WHERE CODIGO_USUARIO=p_USER AND CODIGO_EMPRESA=p_EMPRESA;
    IF n<>1 OR p_ACTIVE NOT IN(0,1) THEN RAISE_APPLICATION_ERROR(-20001,'Modo invalido.'); END IF;
    MERGE INTO OSS_SEG_MENU_CTL t USING(SELECT p_USER u,p_EMPRESA e FROM DUAL) s
      ON(t.CODIGO_USUARIO=s.u AND t.CODIGO_EMPRESA=s.e)
      WHEN MATCHED THEN UPDATE SET ACTIVO=p_ACTIVE
      WHEN NOT MATCHED THEN INSERT(CODIGO_USUARIO,CODIGO_EMPRESA,ACTIVO) VALUES(s.u,s.e,p_ACTIVE);
  END;
  PROCEDURE FINISH(p_EMPRESA NUMBER,p_USER NUMBER,p_ACTOR NUMBER,p_ACTION VARCHAR2,p_DETAIL CLOB) IS
  BEGIN
    UPDATE OSS_SEG_MENU_REV SET VERSION=VERSION+1 WHERE ID=1;
    INSERT INTO OSS_SEG_AUD(CODIGO_AUD,CODIGO_USUARIO,CODIGO_EMPRESA,ACCION,DETALLE,USUARIO_ACCION,FECHA_ACCION)
      VALUES(SEQ_OSS_SM_AUD.NEXTVAL,p_USER,p_EMPRESA,p_ACTION,DBMS_LOB.SUBSTR(p_DETAIL,1000,1),p_ACTOR,SYSDATE);
    INSERT INTO OSS_SEG_MENU_AUD VALUES(SEQ_OSS_SM_DET.NEXTVAL,p_EMPRESA,p_USER,p_ACTOR,p_ACTION,p_DETAIL,SYSDATE);
  END;
END;
