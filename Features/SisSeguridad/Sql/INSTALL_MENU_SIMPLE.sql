CREATE OR REPLACE PACKAGE BODY SIS.PKG_OSS_MENU_SIMPLE AS
  TYPE ids IS TABLE OF NUMBER INDEX BY BINARY_INTEGER;
  PROCEDURE RESET_WRITE IS BEGIN g_WRITING:=FALSE; END;
  -- Read CLOB as bounded text output, avoiding LOB locators in legacy ref cursors.
  PROCEDURE READ_JSON(p_ID NUMBER,p_OFFSET NUMBER,p_TEXT OUT VARCHAR2,p_TOTAL OUT NUMBER,p_NEXT OUT NUMBER) IS
    v_json CLOB;
  BEGIN
    IF p_OFFSET<1 OR p_OFFSET<>TRUNC(p_OFFSET) OR p_OFFSET IS NULL THEN
      RAISE_APPLICATION_ERROR(-20004,'Posicion JSON invalida.');
    END IF;
    SELECT JSON_MENU INTO v_json FROM OSS_USUARIO_ROL WHERE CODIGO_USUARIO_ROL=p_ID;
    p_TOTAL:=NVL(DBMS_LOB.GETLENGTH(v_json),0);
    p_TEXT:=DBMS_LOB.SUBSTR(v_json,500,p_OFFSET);
    p_NEXT:=p_OFFSET+NVL(LENGTH(p_TEXT),0);
  END;

  FUNCTION split(p_text CLOB) RETURN ids IS
    r ids; posi PLS_INTEGER:=1; stopi PLS_INTEGER; s VARCHAR2(30);
  BEGIN
    IF p_text IS NULL THEN RETURN r; END IF;
    WHILE posi<=DBMS_LOB.GETLENGTH(p_text) LOOP
      stopi:=DBMS_LOB.INSTR(p_text,',',posi); IF stopi=0 THEN stopi:=DBMS_LOB.GETLENGTH(p_text)+1; END IF;
      IF stopi-posi>10 OR r.COUNT>=10000 THEN RAISE_APPLICATION_ERROR(-20001,'Seleccion demasiado grande.'); END IF;
      s:=DBMS_LOB.SUBSTR(p_text,stopi-posi,posi);
      IF NOT REGEXP_LIKE(s,'^[0-9]+$') OR TO_NUMBER(s)<=0 THEN RAISE_APPLICATION_ERROR(-20001,'Identificador invalido.'); END IF;
      r(r.COUNT+1):=TO_NUMBER(s); posi:=stopi+1;
    END LOOP;
    RETURN r;
  END;
  PROCEDURE READ_DATA(p_KIND VARCHAR2,p_EMPRESA NUMBER,p_USER NUMBER,p_RESULT OUT SYS_REFCURSOR) IS
  BEGIN
    CASE p_KIND
    WHEN 'REV' THEN OPEN p_RESULT FOR SELECT VERSION FROM OSS_SEG_MENU_REV WHERE ID=1;
    WHEN 'MODS' THEN OPEN p_RESULT FOR SELECT * FROM OSS_MOD ORDER BY ORDEN,CODIGO_MOD;
    WHEN 'MENUS' THEN OPEN p_RESULT FOR SELECT * FROM OSS_MENU ORDER BY ORDEN,CODIGO_MENU;
    WHEN 'ROLES' THEN OPEN p_RESULT FOR SELECT * FROM OSS_ROL ORDER BY NOMBRE,CODIGO_ROL;
    WHEN 'GRANTS' THEN OPEN p_RESULT FOR SELECT * FROM OSS_ROL_MENU;
    WHEN 'PERMS' THEN OPEN p_RESULT FOR SELECT * FROM OSS_PERM WHERE ACTIVO=1;
    WHEN 'RPERMS' THEN OPEN p_RESULT FOR SELECT * FROM OSS_ROL_PERM;
    WHEN 'MPERMS' THEN OPEN p_RESULT FOR SELECT * FROM OSS_MENU_PERM;
    WHEN 'USER' THEN OPEN p_RESULT FOR SELECT CODIGO_USUARIO,USUARIO,LOGIN,STATUS,IS_SUPERUSER FROM SIS_USUARIOS
      WHERE CODIGO_USUARIO=p_USER AND CODIGO_EMPRESA=p_EMPRESA;
    WHEN 'UR' THEN OPEN p_RESULT FOR SELECT CODIGO_ROL FROM OSS_USR_ROL
      WHERE CODIGO_USUARIO=p_USER AND CODIGO_EMPRESA=p_EMPRESA AND ACTIVO=1;
    WHEN 'UP' THEN OPEN p_RESULT FOR SELECT CODIGO_PERM,TIPO FROM OSS_USR_PERM
      WHERE CODIGO_USUARIO=p_USER AND CODIGO_EMPRESA=p_EMPRESA AND ACTIVO=1;
    WHEN 'LEGACY' THEN OPEN p_RESULT FOR SELECT r.CODIGO_USUARIO_ROL,r.CODIGO_USUARIO,r.USUARIO,r.DESCRIPCION,r.JSON_MENU
      FROM OSS_USUARIO_ROL r JOIN SIS_USUARIOS u ON r.USUARIO IN(u.LOGIN,UPPER(u.LOGIN),LOWER(u.LOGIN))
      WHERE u.CODIGO_USUARIO=p_USER AND u.CODIGO_EMPRESA=p_EMPRESA ORDER BY r.CODIGO_USUARIO_ROL;
    WHEN 'SOURCE' THEN OPEN p_RESULT FOR SELECT r.CODIGO_USUARIO_ROL,r.CODIGO_USUARIO,r.USUARIO,r.DESCRIPCION,r.JSON_MENU
      FROM OSS_USUARIO_ROL r WHERE r.CODIGO_USUARIO=p_USER OR EXISTS(
        SELECT 1 FROM SIS_USUARIOS u WHERE u.CODIGO_USUARIO=p_USER AND u.CODIGO_EMPRESA=p_EMPRESA
          AND UPPER(TRIM(r.USUARIO))=UPPER(TRIM(u.LOGIN))) ORDER BY r.CODIGO_USUARIO_ROL;
    WHEN 'LEGACY_META' THEN OPEN p_RESULT FOR SELECT r.CODIGO_USUARIO_ROL,r.CODIGO_USUARIO,r.USUARIO,r.DESCRIPCION,CAST(NULL AS VARCHAR2(1)) JSON_MENU
      FROM OSS_USUARIO_ROL r JOIN SIS_USUARIOS u ON r.USUARIO IN(u.LOGIN,UPPER(u.LOGIN),LOWER(u.LOGIN))
      WHERE u.CODIGO_USUARIO=p_USER AND u.CODIGO_EMPRESA=p_EMPRESA ORDER BY r.CODIGO_USUARIO_ROL;
    WHEN 'SOURCE_META' THEN OPEN p_RESULT FOR SELECT r.CODIGO_USUARIO_ROL,r.CODIGO_USUARIO,r.USUARIO,r.DESCRIPCION,CAST(NULL AS VARCHAR2(1)) JSON_MENU
      FROM OSS_USUARIO_ROL r WHERE r.CODIGO_USUARIO=p_USER OR EXISTS(
        SELECT 1 FROM SIS_USUARIOS u WHERE u.CODIGO_USUARIO=p_USER AND u.CODIGO_EMPRESA=p_EMPRESA
          AND UPPER(TRIM(r.USUARIO))=UPPER(TRIM(u.LOGIN))) ORDER BY r.CODIGO_USUARIO_ROL;
    WHEN 'CTL' THEN OPEN p_RESULT FOR SELECT ACTIVO FROM OSS_SEG_MENU_CTL
      WHERE CODIGO_USUARIO=p_USER AND CODIGO_EMPRESA=p_EMPRESA;
    WHEN 'COUNTS' THEN OPEN p_RESULT FOR SELECT CODIGO_ROL,COUNT(*) TOTAL FROM OSS_USR_ROL WHERE ACTIVO=1 GROUP BY CODIGO_ROL;
    WHEN 'AFFECTED' THEN OPEN p_RESULT FOR SELECT DISTINCT CODIGO_USUARIO,CODIGO_EMPRESA FROM OSS_USR_ROL WHERE ACTIVO=1;
    WHEN 'MIG' THEN OPEN p_RESULT FOR SELECT CODIGO_MIG,HUELLA,FECHA_INS,USUARIO_INS,VERSION FROM OSS_SEG_MENU_MIG
      WHERE CODIGO_USUARIO=p_USER AND CODIGO_EMPRESA=p_EMPRESA ORDER BY CODIGO_MIG DESC;
    ELSE RAISE_APPLICATION_ERROR(-20001,'Lectura no admitida.'); END CASE;
  END;
  PROCEDURE LOCK_REV(p_EXPECTED NUMBER,p_REV OUT NUMBER) IS
  BEGIN
    g_WRITING:=FALSE;
    SELECT VERSION INTO p_REV FROM OSS_SEG_MENU_REV WHERE ID=1 FOR UPDATE WAIT 10;
    IF p_EXPECTED IS NOT NULL AND p_EXPECTED<>p_REV THEN RAISE_APPLICATION_ERROR(-20002,'Los datos cambiaron. Recargue antes de guardar.'); END IF;
