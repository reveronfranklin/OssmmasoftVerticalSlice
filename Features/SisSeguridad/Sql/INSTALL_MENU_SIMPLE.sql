DECLARE
  v_count NUMBER;
  v_dups NUMBER;
BEGIN
  IF SYS_CONTEXT('USERENV','CURRENT_SCHEMA') <> 'SIS' THEN
    RAISE_APPLICATION_ERROR(-20010,'Seleccione SIS como esquema activo antes de ejecutar este bloque.');
  END IF;
  SELECT COUNT(1) INTO v_count FROM all_indexes WHERE owner='SIS' AND index_name = 'IDX_OSS_USR_ROL_U01';
  IF v_count = 0 THEN
    SELECT COUNT(1)
      INTO v_dups
      FROM (
        SELECT CODIGO_USUARIO, UPPER(TRIM(DESCRIPCION)) DESCRIPCION
          FROM OSS_USUARIO_ROL
         GROUP BY CODIGO_USUARIO, UPPER(TRIM(DESCRIPCION))
        HAVING COUNT(1) > 1
      );

    IF v_dups = 0 THEN
      EXECUTE IMMEDIATE 'CREATE UNIQUE INDEX IDX_OSS_USR_ROL_U01 ON OSS_USUARIO_ROL (CODIGO_USUARIO, UPPER(TRIM(DESCRIPCION)))';
    END IF;
  END IF;
END;
