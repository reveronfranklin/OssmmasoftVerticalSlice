DECLARE
  n NUMBER;
  PROCEDURE seq(p_name VARCHAR2, p_table VARCHAR2, p_col VARCHAR2) IS v NUMBER;
  BEGIN
    SELECT COUNT(*) INTO n FROM all_sequences WHERE sequence_owner='SIS' AND sequence_name=p_name;
    IF n=0 THEN
      EXECUTE IMMEDIATE 'SELECT NVL(MAX('||p_col||'),0)+1 FROM '||p_table INTO v;
      EXECUTE IMMEDIATE 'CREATE SEQUENCE '||p_name||' START WITH '||v||' NOCACHE';
    END IF;
  END;
BEGIN
  IF SYS_CONTEXT('USERENV','CURRENT_SCHEMA') <> 'SIS' THEN
    RAISE_APPLICATION_ERROR(-20010,'Seleccione SIS como esquema activo antes de ejecutar este bloque.');
  END IF;
  SELECT COUNT(*) INTO n FROM all_tables WHERE owner='SIS' AND table_name='OSS_SEG_MENU_REV';
  IF n=0 THEN EXECUTE IMMEDIATE 'CREATE TABLE OSS_SEG_MENU_REV (ID NUMBER PRIMARY KEY, VERSION NUMBER NOT NULL)';
    EXECUTE IMMEDIATE 'INSERT INTO OSS_SEG_MENU_REV VALUES (1,1)'; END IF;
  SELECT COUNT(*) INTO n FROM all_tables WHERE owner='SIS' AND table_name='OSS_SEG_MENU_CTL';
  IF n=0 THEN EXECUTE IMMEDIATE 'CREATE TABLE OSS_SEG_MENU_CTL (
    CODIGO_USUARIO NUMBER NOT NULL, CODIGO_EMPRESA NUMBER NOT NULL, ACTIVO NUMBER(1) DEFAULT 1 NOT NULL,
    CONSTRAINT PK_OSS_SEG_MENU_CTL PRIMARY KEY(CODIGO_USUARIO,CODIGO_EMPRESA),
    CONSTRAINT CK_OSS_SEG_MENU_CTL CHECK(ACTIVO IN (0,1)))'; END IF;
  SELECT COUNT(*) INTO n FROM all_tables WHERE owner='SIS' AND table_name='OSS_SEG_MENU_MAP';
  IF n=0 THEN EXECUTE IMMEDIATE 'CREATE TABLE OSS_SEG_MENU_MAP (
    HUELLA VARCHAR2(64) PRIMARY KEY, CODIGO_MENU NUMBER NOT NULL,
    CONSTRAINT FK_OSS_SEG_MENU_MAP FOREIGN KEY(CODIGO_MENU) REFERENCES OSS_MENU(CODIGO_MENU))'; END IF;
  SELECT COUNT(*) INTO n FROM all_tables WHERE owner='SIS' AND table_name='OSS_SEG_MENU_MIG';
  IF n=0 THEN EXECUTE IMMEDIATE 'CREATE TABLE OSS_SEG_MENU_MIG (
    CODIGO_MIG NUMBER PRIMARY KEY, CODIGO_USUARIO NUMBER NOT NULL, CODIGO_EMPRESA NUMBER NOT NULL,
    HUELLA VARCHAR2(64) NOT NULL, ORIGEN CLOB NOT NULL, USUARIO_INS NUMBER NOT NULL,
    FECHA_INS DATE DEFAULT SYSDATE NOT NULL, VERSION NUMBER NOT NULL)'; END IF;
  SELECT COUNT(*) INTO n FROM all_tables WHERE owner='SIS' AND table_name='OSS_SEG_MENU_AUD';
  IF n=0 THEN EXECUTE IMMEDIATE 'CREATE TABLE OSS_SEG_MENU_AUD (
    CODIGO_AUD NUMBER PRIMARY KEY, CODIGO_EMPRESA NUMBER NOT NULL, CODIGO_USUARIO NUMBER,
    USUARIO_ACCION NUMBER NOT NULL, ACCION VARCHAR2(50) NOT NULL, DETALLE CLOB NOT NULL,
    FECHA_ACCION DATE DEFAULT SYSDATE NOT NULL)'; END IF;
  seq('SEQ_OSS_SM_DET','OSS_SEG_MENU_AUD','CODIGO_AUD');
  seq('SEQ_OSS_SM_MENU','OSS_MENU','CODIGO_MENU');
  seq('SEQ_OSS_SM_MOD','OSS_MOD','CODIGO_MOD');
  seq('SEQ_OSS_SM_ROL','OSS_ROL','CODIGO_ROL');
  seq('SEQ_OSS_SM_PERM','OSS_PERM','CODIGO_PERM');
  seq('SEQ_OSS_SM_UR','OSS_USR_ROL','CODIGO_USR_ROL');
  seq('SEQ_OSS_SM_AUD','OSS_SEG_AUD','CODIGO_AUD');
  seq('SEQ_OSS_SM_CACHE','OSS_USUARIO_ROL','CODIGO_USUARIO_ROL');
  seq('SEQ_OSS_SM_MIG','OSS_SEG_MENU_MIG','CODIGO_MIG');
