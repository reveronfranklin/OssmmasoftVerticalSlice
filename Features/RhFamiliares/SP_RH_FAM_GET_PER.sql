CREATE OR REPLACE PROCEDURE RH.SP_RH_FAM_GET_PER (
    p_EMPRESA IN NUMBER, p_PERSONA IN NUMBER,
    p_RESULT OUT SYS_REFCURSOR, p_MESSAGE OUT VARCHAR2
) AS
BEGIN
    OPEN p_RESULT FOR
        SELECT f.*, p.DESCRIPCION PARIENTE_DESCRIPCION,
               s.DESCRIPCION ESTADO_SALUD_DESCRIPCION
          FROM RH.RH_FAMILIARES f
          LEFT JOIN RH.RH_DESCRIPTIVAS p ON p.DESCRIPCION_ID = f.PARIENTE_ID
          LEFT JOIN RH.RH_DESCRIPTIVAS s ON s.DESCRIPCION_ID = f.ESTADO_SALUD_ID
                                      AND s.TITULO_ID = 72
         WHERE f.CODIGO_EMPRESA = p_EMPRESA
           AND f.CODIGO_PERSONA = p_PERSONA
         ORDER BY f.CODIGO_FAMILIAR;
    p_MESSAGE := 'success';
END SP_RH_FAM_GET_PER;
/
