CREATE OR REPLACE PROCEDURE RH.SP_RH_FAM_SAVE (
    p_EMPRESA IN NUMBER, p_CREAR IN NUMBER, p_PERSONA IN NUMBER,
    p_FAMILIAR IN NUMBER, p_CEDULA IN NUMBER, p_NACIONALIDAD IN VARCHAR2,
    p_NOMBRE IN VARCHAR2, p_APELLIDO IN VARCHAR2, p_FECHA IN DATE,
    p_PARIENTE IN NUMBER, p_SEXO IN VARCHAR2, p_NIVEL IN NUMBER,
    p_GRADO IN NUMBER, p_ESTADO IN NUMBER, p_ESTADO_PRESENTE IN NUMBER,
    p_LOGIN IN VARCHAR2, p_RESULT OUT SYS_REFCURSOR, p_MESSAGE OUT VARCHAR2
) AS
    v_count NUMBER;
    v_id NUMBER;
    v_usuario NUMBER;
    v_estado NUMBER;
BEGIN
    -- Empty cursor also covers all expected validation failures.
    OPEN p_RESULT FOR SELECT * FROM RH.RH_FAMILIARES WHERE 1 = 0;
    SELECT COUNT(*) INTO v_count FROM RH.RH_PERSONAS
     WHERE CODIGO_PERSONA = p_PERSONA AND CODIGO_EMPRESA = p_EMPRESA;
    IF v_count = 0 THEN
        p_MESSAGE := 'Persona no existe para la empresa configurada'; RETURN;
    END IF;
    SELECT MAX(CODIGO_USUARIO) INTO v_usuario FROM SIS.SIS_USUARIOS
     WHERE UPPER(LOGIN) = UPPER(p_LOGIN) AND CODIGO_EMPRESA = p_EMPRESA
       AND NVL(STATUS, '1') IN ('1', 'A');
    IF v_usuario IS NULL THEN
        p_MESSAGE := 'Usuario autenticado no valido'; RETURN;
    END IF;
    IF p_CEDULA <= 0 OR p_CEDULA IS NULL OR TRIM(p_NOMBRE) IS NULL
       OR TRIM(p_APELLIDO) IS NULL OR p_FECHA IS NULL
       OR NVL(p_NACIONALIDAD, '?') NOT IN ('V', 'E')
       OR NVL(p_SEXO, '?') NOT IN ('M', 'F') THEN
        p_MESSAGE := 'Datos del familiar invalidos'; RETURN;
    END IF;
    SELECT COUNT(*) INTO v_count FROM RH.RH_DESCRIPTIVAS
     WHERE DESCRIPCION_ID = p_PARIENTE;
    IF v_count = 0 THEN
        p_MESSAGE := 'Tipo pariente invalido'; RETURN;
    END IF;
    IF p_CREAR = 0 THEN
        BEGIN
            SELECT ESTADO_SALUD_ID INTO v_estado FROM RH.RH_FAMILIARES
             WHERE CODIGO_FAMILIAR = p_FAMILIAR AND CODIGO_PERSONA = p_PERSONA
               AND CODIGO_EMPRESA = p_EMPRESA FOR UPDATE;
        EXCEPTION WHEN NO_DATA_FOUND THEN
            p_MESSAGE := 'Familiar no existe para la persona y empresa'; RETURN;
        END;
    END IF;
    -- Preserve an unresolvable historical value when it has not changed.
    IF p_ESTADO_PRESENTE = 1 AND p_ESTADO IS NOT NULL
       AND (v_estado IS NULL OR v_estado <> p_ESTADO OR p_CREAR = 1) THEN
        SELECT COUNT(*) INTO v_count FROM RH.RH_DESCRIPTIVAS
         WHERE DESCRIPCION_ID = p_ESTADO AND TITULO_ID = 72;
        IF v_count = 0 THEN
            p_MESSAGE := 'Estado de salud no pertenece al titulo 72'; RETURN;
        END IF;
    END IF;
    IF p_ESTADO_PRESENTE = 1 THEN v_estado := p_ESTADO; END IF;
    IF p_CREAR = 1 THEN
        LOCK TABLE RH.RH_FAMILIARES IN EXCLUSIVE MODE;
        SELECT NVL(MAX(CODIGO_FAMILIAR), 0) + 1 INTO v_id FROM RH.RH_FAMILIARES;
        INSERT INTO RH.RH_FAMILIARES (CODIGO_FAMILIAR, CODIGO_PERSONA,
            CEDULA_FAMILIAR, NACIONALIDAD, NOMBRE, APELLIDO, FECHA_NACIMIENTO,
            PARIENTE_ID, SEXO, NIVEL_EDUCATIVO_ID, GRADO, ESTADO_SALUD_ID,
            USUARIO_INS, FECHA_INS, CODIGO_EMPRESA)
        VALUES (v_id, p_PERSONA, p_CEDULA, p_NACIONALIDAD, TRIM(p_NOMBRE),
            TRIM(p_APELLIDO), p_FECHA, p_PARIENTE, p_SEXO, p_NIVEL, p_GRADO,
            v_estado, v_usuario, SYSDATE, p_EMPRESA);
    ELSE
        v_id := p_FAMILIAR;
        UPDATE RH.RH_FAMILIARES SET CEDULA_FAMILIAR = p_CEDULA,
            NACIONALIDAD = p_NACIONALIDAD, NOMBRE = TRIM(p_NOMBRE),
            APELLIDO = TRIM(p_APELLIDO), FECHA_NACIMIENTO = p_FECHA,
            PARIENTE_ID = p_PARIENTE, SEXO = p_SEXO, NIVEL_EDUCATIVO_ID = p_NIVEL,
            GRADO = p_GRADO, ESTADO_SALUD_ID = v_estado,
            USUARIO_UPD = v_usuario, FECHA_UPD = SYSDATE
         WHERE CODIGO_FAMILIAR = v_id AND CODIGO_PERSONA = p_PERSONA
           AND CODIGO_EMPRESA = p_EMPRESA;
    END IF;
    CLOSE p_RESULT;
    OPEN p_RESULT FOR
        SELECT f.*, p.DESCRIPCION PARIENTE_DESCRIPCION,
               s.DESCRIPCION ESTADO_SALUD_DESCRIPCION
          FROM RH.RH_FAMILIARES f
          LEFT JOIN RH.RH_DESCRIPTIVAS p ON p.DESCRIPCION_ID = f.PARIENTE_ID
          LEFT JOIN RH.RH_DESCRIPTIVAS s ON s.DESCRIPCION_ID = f.ESTADO_SALUD_ID
                                      AND s.TITULO_ID = 72
         WHERE f.CODIGO_EMPRESA = p_EMPRESA
           AND f.CODIGO_FAMILIAR = v_id;
    p_MESSAGE := 'success';
END SP_RH_FAM_SAVE;
