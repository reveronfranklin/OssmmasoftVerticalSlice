CREATE OR REPLACE PROCEDURE RH.SP_RH_FAM_DEL (
    p_EMPRESA IN NUMBER, p_FAMILIAR IN NUMBER, p_MESSAGE OUT VARCHAR2
) AS
BEGIN
    DELETE FROM RH.RH_FAMILIARES
     WHERE CODIGO_FAMILIAR = p_FAMILIAR AND CODIGO_EMPRESA = p_EMPRESA;
    IF SQL%ROWCOUNT = 0 THEN
        p_MESSAGE := 'Familiar no existe para la empresa configurada';
    ELSE
        p_MESSAGE := 'success';
    END IF;
END SP_RH_FAM_DEL;
/
