-- SP_SOP_EMAIL_GET: 16 caracteres (Oracle 10g).
CREATE OR REPLACE PROCEDURE SIS.SP_SOP_EMAIL_GET(
 p_TICKET_ID NUMBER,
 p_CODIGO_EMPRESA NUMBER,
 p_ResultSet OUT SYS_REFCURSOR,
 p_Message OUT VARCHAR2) AS
BEGIN
 OPEN p_ResultSet FOR
 SELECT EMAIL_ID, PARA_LIST, CC_LIST, SUBJECT, ESTADO, INTENTOS,
        CREATED_AT, FECHA_ENVIO, ERROR_ENVIO
 FROM SIS.SIS_EMAIL_QUEUE
 WHERE CODIGO_EMPRESA = p_CODIGO_EMPRESA
   AND REFERENCIA_ID = p_TICKET_ID
   AND MODULO_ORIGEN = 'SOPORTE_AUTO'
   AND SUBJECT = 'Ticket SOP-' || TO_CHAR(p_TICKET_ID) || ' asignado'
 ORDER BY EMAIL_ID DESC;
 p_Message := 'success';
END;
/
