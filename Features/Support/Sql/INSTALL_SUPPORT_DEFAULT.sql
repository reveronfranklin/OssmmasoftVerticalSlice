EXCEPTION WHEN NO_DATA_FOUND THEN p_EMAIL:=NULL;
END;';
 EXECUTE IMMEDIATE 'CREATE OR REPLACE PROCEDURE SIS.SP_SOP_TKT_AUTO(
 p_EMPRESA NUMBER,p_SOLICITANTE NUMBER,p_TIPO NUMBER,p_MODULO NUMBER,
 p_PRIORIDAD NUMBER,p_RESPONSABLE NUMBER,p_ASUNTO VARCHAR2,p_DESCRIPCION VARCHAR2,
 p_PARA VARCHAR2,p_CC VARCHAR2,p_FROM VARCHAR2,p_NOMBRE VARCHAR2,p_ID OUT NUMBER) AS
 v_responsable NUMBER; v_count NUMBER; v_message VARCHAR2(4000);
 v_to VARCHAR2(150); v_cc VARCHAR2(150); v_subject VARCHAR2(250); v_body CLOB;
BEGIN
 SAVEPOINT SOP_AUTO_START;
 -- Serializa con cambios de configuracion; no se acepta un responsable del cliente.
 SELECT RESPONSABLE_ID INTO v_responsable FROM SIS.SOP_CONFIG
 WHERE CODIGO_EMPRESA=p_EMPRESA FOR UPDATE;
 IF v_responsable<>p_RESPONSABLE THEN RAISE_APPLICATION_ERROR(-20060,''Configuracion modificada.''); END IF;
 SELECT TRIM(EMAIL) INTO v_to FROM SIS.SIS_USUARIOS WHERE CODIGO_EMPRESA=p_EMPRESA
 AND CODIGO_USUARIO=v_responsable AND NVL(STATUS,''1'') IN (''1'',''A'') AND ES_ANALISTA_SOPORTE=1;
 SELECT TRIM(EMAIL) INTO v_cc FROM SIS.SIS_USUARIOS WHERE CODIGO_EMPRESA=p_EMPRESA
 AND CODIGO_USUARIO=p_SOLICITANTE AND NVL(STATUS,''1'') IN (''1'',''A'') AND NVL(IS_SUPERUSER,0)<>1;
 IF v_to IS NULL OR v_cc IS NULL OR LOWER(v_to)<>LOWER(p_PARA) OR LOWER(v_cc)<>LOWER(p_CC)
 THEN RAISE_APPLICATION_ERROR(-20060,''Contactos modificados o incompletos.''); END IF;
 IF p_ASUNTO IS NULL OR LENGTH(p_ASUNTO)>200 OR p_DESCRIPCION IS NULL
 THEN RAISE_APPLICATION_ERROR(-20060,''Asunto y descripcion requeridos.''); END IF;
 SELECT COUNT(*) INTO v_count FROM SIS.SOP_TIPO_SOLICITUD
 WHERE CODIGO_EMPRESA=p_EMPRESA AND TIPO_SOLICITUD_ID=p_TIPO AND ACTIVO=1;
 IF v_count<>1 THEN RAISE_APPLICATION_ERROR(-20060,''Tipo de solicitud no valido.''); END IF;
 SELECT COUNT(*) INTO v_count FROM SIS.SOP_MODULO
 WHERE CODIGO_EMPRESA=p_EMPRESA AND MODULO_ID=p_MODULO AND ACTIVO=1;
 IF v_count<>1 THEN RAISE_APPLICATION_ERROR(-20060,''Modulo no valido.''); END IF;
 SIS.SP_SOP_TKT_INS(p_SOLICITANTE,p_TIPO,p_MODULO,p_ASUNTO,p_DESCRIPCION,p_PRIORIDAD,
 p_SOLICITANTE,p_EMPRESA,p_ID,v_message);
 IF LOWER(v_message) NOT IN (''success'',''suscces'') OR p_ID IS NULL OR p_ID<=0
 THEN RAISE_APPLICATION_ERROR(-20060,''No se pudo crear el ticket.''); END IF;
 SIS.SP_SOP_TKT_ASSIGN(p_ID,v_responsable,p_SOLICITANTE,''Responsable predeterminado de Soporte'',p_EMPRESA,v_message);
 IF LOWER(v_message) NOT IN (''success'',''suscces'') THEN RAISE_APPLICATION_ERROR(-20060,''No se pudo asignar el ticket.''); END IF;
 -- Sustituye exclusivamente los correos legacy de ESTE ticket nuevo. No reactiva la cola antigua.
 DELETE FROM SIS.SIS_EMAIL_QUEUE WHERE CODIGO_EMPRESA=p_EMPRESA AND REFERENCIA_ID=p_ID AND MODULO_ORIGEN=''SOPORTE'';
 v_subject:=''Ticket SOP-''||TO_CHAR(p_ID)||'' asignado'';
 v_body:=TO_CLOB(''Se ha creado y asignado el ticket SOP-''||TO_CHAR(p_ID)||''.''||CHR(10)||
 ''Asunto: ''||p_ASUNTO||CHR(10)||''Descripcion: ''||p_DESCRIPCION||CHR(10)||
 ''Consulte el detalle en Soporte > Tickets.'');
 INSERT INTO SIS.SIS_EMAIL_QUEUE(EMAIL_ID,CODIGO_EMPRESA,MODULO_ORIGEN,REFERENCIA_ID,
 TO_EMAIL,SUBJECT,BODY_TEXT,ESTADO,INTENTOS,MAX_INTENTOS,CREATED_AT,FECHA_PROGRAMADA,
 ACTOR_ID,PARA_LIST,CC_LIST,REMITENTE,REMITENTE_NOMBRE)
 VALUES(SIS.SEQ_EMAIL_Q.NEXTVAL,p_EMPRESA,''SOPORTE_AUTO'',p_ID,v_to,v_subject,v_body,
 ''PENDIENTE'',0,1,SYSDATE,SYSDATE,p_SOLICITANTE,v_to,
 CASE WHEN LOWER(v_to)=LOWER(v_cc) THEN NULL ELSE v_cc END,p_FROM,p_NOMBRE);
EXCEPTION WHEN OTHERS THEN
 ROLLBACK TO SOP_AUTO_START;
 p_ID:=NULL;
 RAISE;
END;';
 EXECUTE IMMEDIATE 'CREATE OR REPLACE PROCEDURE SIS.SP_SOP_EVT_GET(
 p_EMPRESA NUMBER,p_TICKET NUMBER,p_ROWS OUT SYS_REFCURSOR) AS
BEGIN
 OPEN p_ROWS FOR SELECT t.USUARIO_SOLICITANTE_ID SOLICITANTE,
 t.USUARIO_RESPONSABLE_ID RESPONSABLE,TRIM(s.EMAIL) MAIL_SOL,TRIM(r.EMAIL) MAIL_RESP
 FROM SIS.SOP_TICKET t
 LEFT JOIN SIS.SIS_USUARIOS s ON s.CODIGO_USUARIO=t.USUARIO_SOLICITANTE_ID
 AND s.CODIGO_EMPRESA=t.CODIGO_EMPRESA AND NVL(s.STATUS,''1'') IN (''1'',''A'')
 LEFT JOIN SIS.SIS_USUARIOS r ON r.CODIGO_USUARIO=t.USUARIO_RESPONSABLE_ID
 AND r.CODIGO_EMPRESA=t.CODIGO_EMPRESA AND NVL(r.STATUS,''1'') IN (''1'',''A'')
 WHERE t.CODIGO_EMPRESA=p_EMPRESA AND t.TICKET_ID=p_TICKET;
END;';
 EXECUTE IMMEDIATE 'CREATE OR REPLACE PROCEDURE SIS.SP_SOP_EVT_EXEC(
 p_EMPRESA NUMBER,p_TICKET NUMBER,p_ACTOR NUMBER,p_EVENTO VARCHAR2,
 p_TEXTO VARCHAR2,p_INTERNO NUMBER,p_ESTADO NUMBER,
 p_SOLICITANTE NUMBER,p_RESPONSABLE NUMBER,p_MAIL_SOL VARCHAR2,p_MAIL_RESP VARCHAR2,
 p_PRIV_RESP NUMBER,p_FROM VARCHAR2,p_NOMBRE VARCHAR2,p_ID OUT NUMBER,p_ENCOLADOS OUT NUMBER) AS
 v_sol NUMBER; v_resp NUMBER; v_old NUMBER; v_prev NUMBER; v_message VARCHAR2(4000);
 v_to VARCHAR2(150); v_cc VARCHAR2(150); v_mail_sol VARCHAR2(150); v_mail_resp VARCHAR2(150);
 v_subject VARCHAR2(250); v_body CLOB; v_estado VARCHAR2(80); v_numero VARCHAR2(50);
 PROCEDURE add_recipient(mail VARCHAR2) IS
 BEGIN
  IF mail IS NULL THEN RAISE_APPLICATION_ERROR(-20061,''Destinatario sin correo.''); END IF;
  IF v_to IS NULL THEN v_to:=mail;
  ELSIF LOWER(v_to)<>LOWER(mail) THEN v_cc:=mail; END IF;
 END;
BEGIN
 SAVEPOINT SOP_EVT_START;
 p_ID:=0;p_ENCOLADOS:=0;
 SELECT USUARIO_SOLICITANTE_ID,USUARIO_RESPONSABLE_ID,ESTADO_ID,TICKET_NUMERO
 INTO v_sol,v_resp,v_old,v_numero FROM SIS.SOP_TICKET
 WHERE CODIGO_EMPRESA=p_EMPRESA AND TICKET_ID=p_TICKET FOR UPDATE;
 IF v_sol<>p_SOLICITANTE OR NVL(v_resp,-1)<>NVL(p_RESPONSABLE,-1)
 THEN RAISE_APPLICATION_ERROR(-20061,''Participantes modificados.''); END IF;
 IF p_EVENTO NOT IN (''COMENTARIO'',''ESTADO'',''CIERRE'') OR p_EVENTO IS NULL
 OR NVL(p_INTERNO,0) NOT IN (0,1) THEN RAISE_APPLICATION_ERROR(-20061,''Evento invalido.''); END IF;
 IF p_EVENTO=''COMENTARIO'' AND (p_TEXTO IS NULL OR LENGTHB(p_TEXTO)>4000)
 THEN RAISE_APPLICATION_ERROR(-20061,''Comentario requerido, maximo 4000 bytes.''); END IF;
 IF p_EVENTO=''CIERRE'' AND p_TEXTO IS NULL THEN RAISE_APPLICATION_ERROR(-20061,''Resolucion requerida.''); END IF;
 IF p_EVENTO=''ESTADO'' AND p_ESTADO=v_old THEN RETURN; END IF;
 SELECT MAX(TRIM(EMAIL)) INTO v_mail_sol FROM SIS.SIS_USUARIOS
 WHERE CODIGO_EMPRESA=p_EMPRESA AND CODIGO_USUARIO=v_sol AND NVL(STATUS,''1'') IN (''1'',''A'');
 SELECT MAX(TRIM(EMAIL)) INTO v_mail_resp FROM SIS.SIS_USUARIOS
 WHERE CODIGO_EMPRESA=p_EMPRESA AND CODIGO_USUARIO=v_resp AND NVL(STATUS,''1'') IN (''1'',''A'');
 -- No se usan direcciones suministradas por el navegador. Se valida la instantanea del servidor.
 IF NVL(v_mail_sol,''-'')<>NVL(p_MAIL_SOL,''-'') OR NVL(v_mail_resp,''-'')<>NVL(p_MAIL_RESP,''-'')
 THEN RAISE_APPLICATION_ERROR(-20061,''Contactos modificados.''); END IF;
 IF p_EVENTO=''COMENTARIO'' AND p_INTERNO=1 THEN
  -- Nunca se envia al solicitante, aunque tambien figure como responsable.
  IF v_resp IS NOT NULL AND v_resp<>p_ACTOR AND v_resp<>v_sol AND p_PRIV_RESP=1 THEN add_recipient(v_mail_resp); END IF;
 ELSE
  IF v_sol<>p_ACTOR THEN add_recipient(v_mail_sol); END IF;
  IF v_resp IS NOT NULL AND v_resp<>p_ACTOR THEN add_recipient(v_mail_resp); END IF;
 END IF;
 SELECT NVL(MAX(EMAIL_ID),0) INTO v_prev FROM SIS.SIS_EMAIL_QUEUE
 WHERE CODIGO_EMPRESA=p_EMPRESA AND REFERENCIA_ID=p_TICKET AND MODULO_ORIGEN=''SOPORTE'';
 IF p_EVENTO=''COMENTARIO'' THEN
  SIS.SP_SOP_COMM_INS(p_TICKET,p_ACTOR,p_TEXTO,p_INTERNO,p_EMPRESA,p_ID,v_message);
  IF p_INTERNO=1 THEN
   UPDATE SIS.SOP_TICKET_HISTORIAL SET COMENTARIO=''Comentario interno''
   WHERE CODIGO_EMPRESA=p_EMPRESA AND TICKET_ID=p_TICKET AND TIPO_CAMBIO=''COMENTARIO''
   AND VALOR_NUEVO=TO_CHAR(p_ID);
   IF v_resp IS NOT NULL AND v_resp<>p_ACTOR AND v_resp<>v_sol AND p_PRIV_RESP=1 THEN
    INSERT INTO SIS.SOP_TICKET_NOTIF(NOTIF_ID,CODIGO_EMPRESA,TICKET_ID,USUARIO_DESTINO_ID,TIPO_DESTINO,EVENTO,TITULO,MENSAJE,CANAL)
    VALUES(SIS.SEQ_SOP_NOTIF.NEXTVAL,p_EMPRESA,p_TICKET,v_resp,''RESPONSABLE'',''COMENTADO'',''Comentario interno'',''Nuevo comentario interno en su ticket.'',''INTERNA'');
   END IF;
  END IF;
  v_subject:=CASE WHEN p_INTERNO=1 THEN ''Comentario interno'' ELSE ''Nuevo comentario'' END;
  v_body:=TO_CLOB(v_subject||'' en ticket ''||v_numero||''.''||CHR(10)||p_TEXTO);
 ELSIF p_EVENTO=''ESTADO'' THEN
  SELECT NOMBRE INTO v_estado FROM SIS.SOP_ESTADO
  WHERE CODIGO_EMPRESA=p_EMPRESA AND ESTADO_ID=p_ESTADO AND ACTIVO=1;
  SIS.SP_SOP_TKT_STATUS_UPD(p_TICKET,p_ESTADO,p_ACTOR,p_TEXTO,p_EMPRESA,v_message);
  v_subject:=''Cambio de estatus'';
  v_body:=TO_CLOB(''El ticket ''||v_numero||'' cambio a: ''||v_estado||''.'');
 ELSE
  SIS.SP_SOP_TKT_CLOSE(p_TICKET,p_ACTOR,p_TEXTO,p_EMPRESA,v_message);
  v_subject:=''Ticket cerrado'';
  v_body:=TO_CLOB(''El ticket ''||v_numero||'' fue cerrado.''||CHR(10)||''Resolucion: ''||p_TEXTO);
 END IF;
 IF v_message IS NULL OR LOWER(v_message) NOT IN (''success'',''suscces'')
 THEN RAISE_APPLICATION_ERROR(-20061,''No se pudo registrar el evento.''); END IF;
 DELETE FROM SIS.SIS_EMAIL_QUEUE WHERE CODIGO_EMPRESA=p_EMPRESA AND REFERENCIA_ID=p_TICKET
 AND MODULO_ORIGEN=''SOPORTE'' AND EMAIL_ID>v_prev;
 IF v_to IS NOT NULL THEN
  IF p_FROM IS NULL THEN RAISE_APPLICATION_ERROR(-20061,''Remitente no configurado.''); END IF;
  INSERT INTO SIS.SIS_EMAIL_QUEUE(EMAIL_ID,CODIGO_EMPRESA,MODULO_ORIGEN,REFERENCIA_ID,
  TO_EMAIL,SUBJECT,BODY_TEXT,ESTADO,INTENTOS,MAX_INTENTOS,CREATED_AT,FECHA_PROGRAMADA,
  ACTOR_ID,PARA_LIST,CC_LIST,REMITENTE,REMITENTE_NOMBRE)
  VALUES(SIS.SEQ_EMAIL_Q.NEXTVAL,p_EMPRESA,''SOPORTE_AUTO'',p_TICKET,v_to,
  v_subject||'' - ''||v_numero,v_body,''PENDIENTE'',0,1,SYSDATE,SYSDATE,p_ACTOR,
  v_to,v_cc,p_FROM,p_NOMBRE);
  p_ENCOLADOS:=1;
 END IF;
EXCEPTION WHEN OTHERS THEN
 ROLLBACK TO SOP_EVT_START;p_ID:=0;p_ENCOLADOS:=0;RAISE;
END;';
 EXECUTE IMMEDIATE 'CREATE OR REPLACE PROCEDURE SIS.SP_SOP_COMM_VISIBLE(
 p_TICKET_ID NUMBER,p_CODIGO_EMPRESA NUMBER,p_VER_INTERNO NUMBER,
 p_ResultSet OUT SYS_REFCURSOR,p_Message OUT VARCHAR2) AS
BEGIN
 OPEN p_ResultSet FOR SELECT c.COMENTARIO_ID,c.TICKET_ID,c.USUARIO_ID,NVL(u.USUARIO,'''') USUARIO,
 c.COMENTARIO,c.ES_INTERNO,c.FECHA_COMENTARIO FROM SIS.SOP_TICKET_COMENTARIO c
 LEFT JOIN SIS.SIS_USUARIOS u ON u.CODIGO_USUARIO=c.USUARIO_ID AND u.CODIGO_EMPRESA=c.CODIGO_EMPRESA
 WHERE c.CODIGO_EMPRESA=p_CODIGO_EMPRESA AND c.TICKET_ID=p_TICKET_ID
 AND (NVL(c.ES_INTERNO,0)=0 OR p_VER_INTERNO=1)
 ORDER BY c.FECHA_COMENTARIO,c.COMENTARIO_ID;
 p_Message:=''Success'';
END;';
 EXECUTE IMMEDIATE 'CREATE OR REPLACE PROCEDURE SIS.SP_SOP_HIST_VISIBLE(
 p_TICKET_ID NUMBER,p_CODIGO_EMPRESA NUMBER,p_VER_INTERNO NUMBER,
 p_ResultSet OUT SYS_REFCURSOR,p_Message OUT VARCHAR2) AS
BEGIN
 OPEN p_ResultSet FOR SELECT h.HISTORIAL_ID,h.TICKET_ID,h.TIPO_CAMBIO,NVL(h.CAMPO,'''') CAMPO,
 NVL(h.VALOR_ANTERIOR,'''') VALOR_ANTERIOR,NVL(h.VALOR_NUEVO,'''') VALOR_NUEVO,
 NVL(h.COMENTARIO,'''') COMENTARIO,h.USUARIO_ID,h.FECHA_CAMBIO
 FROM SIS.SOP_TICKET_HISTORIAL h WHERE h.CODIGO_EMPRESA=p_CODIGO_EMPRESA AND h.TICKET_ID=p_TICKET_ID
 AND (p_VER_INTERNO=1 OR NOT EXISTS(SELECT 1 FROM SIS.SOP_TICKET_COMENTARIO c
 WHERE c.CODIGO_EMPRESA=h.CODIGO_EMPRESA AND c.TICKET_ID=h.TICKET_ID
 AND h.TIPO_CAMBIO=''COMENTARIO'' AND h.VALOR_NUEVO=TO_CHAR(c.COMENTARIO_ID) AND c.ES_INTERNO=1))
 ORDER BY h.FECHA_CAMBIO,h.HISTORIAL_ID;
 p_Message:=''Success'';
END;';
 EXECUTE IMMEDIATE 'CREATE OR REPLACE PACKAGE SIS.PKG_EMAIL_MANUAL AS
 PROCEDURE CREAR(p_EMPRESA NUMBER,p_ACTOR NUMBER,p_SOL VARCHAR2,p_HASH VARCHAR2,p_PARA VARCHAR2,p_CC VARCHAR2,p_CCO VARCHAR2,p_ASUNTO VARCHAR2,p_TEXTO CLOB,p_FROM VARCHAR2,p_NOMBRE VARCHAR2,p_ID OUT NUMBER);
 PROCEDURE LISTAR(p_EMPRESA NUMBER,p_ACTOR NUMBER,p_SOL VARCHAR2,p_PAGE NUMBER,p_SIZE NUMBER,p_ROWS OUT SYS_REFCURSOR,p_TOTAL OUT NUMBER);
 PROCEDURE TOMAR(p_EMPRESA NUMBER,p_TOKEN VARCHAR2,p_ROWS OUT SYS_REFCURSOR);
 PROCEDURE FINALIZAR(p_EMPRESA NUMBER,p_ID NUMBER,p_TOKEN VARCHAR2,p_ESTADO VARCHAR2,p_ERROR VARCHAR2);
END PKG_EMAIL_MANUAL;';
 EXECUTE IMMEDIATE 'CREATE OR REPLACE PACKAGE BODY SIS.PKG_EMAIL_MANUAL AS
 PROCEDURE CREAR(p_EMPRESA NUMBER,p_ACTOR NUMBER,p_SOL VARCHAR2,p_HASH VARCHAR2,p_PARA VARCHAR2,p_CC VARCHAR2,p_CCO VARCHAR2,p_ASUNTO VARCHAR2,p_TEXTO CLOB,p_FROM VARCHAR2,p_NOMBRE VARCHAR2,p_ID OUT NUMBER) IS
 n NUMBER; h VARCHAR2(64);
 BEGIN
 -- Lock the authenticated user to serialize idempotency and hourly quota checks.
 SELECT CODIGO_USUARIO INTO n FROM SIS.SIS_USUARIOS WHERE CODIGO_EMPRESA=p_EMPRESA AND CODIGO_USUARIO=p_ACTOR FOR UPDATE;
 BEGIN
 SELECT EMAIL_ID,HUELLA INTO p_ID,h FROM SIS.SIS_EMAIL_QUEUE WHERE CODIGO_EMPRESA=p_EMPRESA AND ACTOR_ID=p_ACTOR AND SOLICITUD=p_SOL;
 IF h<>p_HASH THEN RAISE_APPLICATION_ERROR(-20002,''La solicitud ya existe con otro contenido.''); END IF;
 RETURN;
 EXCEPTION WHEN NO_DATA_FOUND THEN NULL; END;
 SELECT COUNT(*) INTO n FROM SIS.SIS_EMAIL_QUEUE WHERE CODIGO_EMPRESA=p_EMPRESA AND ACTOR_ID=p_ACTOR AND MODULO_ORIGEN=''MANUAL_R52'' AND CREATED_AT>SYSDATE-1/24;
 IF n>=20 THEN RAISE_APPLICATION_ERROR(-20003,''Limite de 20 solicitudes por hora alcanzado.''); END IF;
 SELECT SIS.SEQ_EMAIL_Q.NEXTVAL INTO p_ID FROM DUAL;
 INSERT INTO SIS.SIS_EMAIL_QUEUE(EMAIL_ID,CODIGO_EMPRESA,MODULO_ORIGEN,TO_EMAIL,SUBJECT,BODY_TEXT,ESTADO,INTENTOS,MAX_INTENTOS,CREATED_AT,FECHA_PROGRAMADA,ACTOR_ID,SOLICITUD,HUELLA,PARA_LIST,CC_LIST,CCO_LIST,REMITENTE,REMITENTE_NOMBRE)
 VALUES(p_ID,p_EMPRESA,''MANUAL_R52'',SUBSTR(p_PARA,1,INSTR(p_PARA||'';'','';'')-1),p_ASUNTO,p_TEXTO,''PENDIENTE'',0,1,SYSDATE,SYSDATE,p_ACTOR,p_SOL,p_HASH,p_PARA,p_CC,p_CCO,p_FROM,p_NOMBRE);
 END;
 PROCEDURE LISTAR(p_EMPRESA NUMBER,p_ACTOR NUMBER,p_SOL VARCHAR2,p_PAGE NUMBER,p_SIZE NUMBER,p_ROWS OUT SYS_REFCURSOR,p_TOTAL OUT NUMBER) IS BEGIN
 SELECT COUNT(*) INTO p_TOTAL FROM SIS.SIS_EMAIL_QUEUE WHERE CODIGO_EMPRESA=p_EMPRESA AND ACTOR_ID=p_ACTOR AND MODULO_ORIGEN=''MANUAL_R52'' AND (p_SOL IS NULL OR SOLICITUD=p_SOL);
 OPEN p_ROWS FOR SELECT * FROM (SELECT q.EMAIL_ID,q.SOLICITUD,q.SUBJECT,q.ESTADO,q.INTENTOS,q.CREATED_AT,q.FECHA_ENVIO,q.ERROR_ENVIO,q.PARA_LIST,q.CC_LIST,q.CCO_LIST,ROW_NUMBER() OVER(ORDER BY q.CREATED_AT DESC,q.EMAIL_ID DESC) RN FROM SIS.SIS_EMAIL_QUEUE q WHERE q.CODIGO_EMPRESA=p_EMPRESA AND q.ACTOR_ID=p_ACTOR AND q.MODULO_ORIGEN=''MANUAL_R52'' AND (p_SOL IS NULL OR q.SOLICITUD=p_SOL)) WHERE RN>(p_PAGE-1)*p_SIZE AND RN<=p_PAGE*p_SIZE;
 END;
 PROCEDURE TOMAR(p_EMPRESA NUMBER,p_TOKEN VARCHAR2,p_ROWS OUT SYS_REFCURSOR) IS
 id NUMBER; busy EXCEPTION; PRAGMA EXCEPTION_INIT(busy,-54);
 BEGIN
 UPDATE SIS.SIS_EMAIL_QUEUE SET ESTADO=''INCIERTO'',ERROR_ENVIO=''Proceso interrumpido. Revisar antes de reenviar.'',UPDATED_AT=SYSDATE WHERE CODIGO_EMPRESA=p_EMPRESA AND MODULO_ORIGEN IN (''MANUAL_R52'',''SOPORTE_AUTO'') AND ESTADO=''ENVIANDO'' AND UPDATED_AT<SYSDATE-30/1440;
 FOR r IN (SELECT EMAIL_ID FROM SIS.SIS_EMAIL_QUEUE WHERE CODIGO_EMPRESA=p_EMPRESA AND MODULO_ORIGEN IN (''MANUAL_R52'',''SOPORTE_AUTO'') AND ESTADO=''PENDIENTE'' ORDER BY EMAIL_ID) LOOP
 BEGIN
 SELECT EMAIL_ID INTO id FROM SIS.SIS_EMAIL_QUEUE WHERE EMAIL_ID=r.EMAIL_ID AND CODIGO_EMPRESA=p_EMPRESA AND ESTADO=''PENDIENTE'' FOR UPDATE NOWAIT;
 UPDATE SIS.SIS_EMAIL_QUEUE SET ESTADO=''ENVIANDO'',CLAIM_TOKEN=p_TOKEN,INTENTOS=INTENTOS+1,UPDATED_AT=SYSDATE,MESSAGE_ID=p_TOKEN||SUBSTR(REMITENTE,INSTR(REMITENTE,''@'')) WHERE EMAIL_ID=id;
 EXIT;
 EXCEPTION WHEN busy THEN NULL; WHEN NO_DATA_FOUND THEN NULL; END;
 END LOOP;
