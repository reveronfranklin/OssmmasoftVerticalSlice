SELECT OBJECT_NAME, OBJECT_TYPE, STATUS
FROM ALL_OBJECTS WHERE OWNER='SIS'
AND OBJECT_NAME IN ('PKG_EMAIL_MANUAL','SIS_EMAIL_QUEUE','SEQ_EMAIL_Q',
                   'UX_EMAIL_SOL','IX_EMAIL_MANUAL')
ORDER BY OBJECT_NAME, OBJECT_TYPE;
SELECT NAME, TYPE, LINE, POSITION, TEXT
FROM ALL_ERRORS WHERE OWNER='SIS' AND NAME='PKG_EMAIL_MANUAL'
ORDER BY TYPE, SEQUENCE;
SELECT COLUMN_NAME, DATA_TYPE, DATA_LENGTH
FROM ALL_TAB_COLUMNS WHERE OWNER='SIS' AND TABLE_NAME='SIS_EMAIL_QUEUE'
AND COLUMN_NAME IN ('ACTOR_ID','SOLICITUD','HUELLA','PARA_LIST','CC_LIST',
 'CCO_LIST','REMITENTE','REMITENTE_NOMBRE','CLAIM_TOKEN')
ORDER BY COLUMN_NAME;
SELECT CODIGO_MENU, CODIGO_PADRE, TITULO, PATH, ACTIVO
FROM SIS.OSS_MENU WHERE RTRIM(PATH,'/')='/apps/sis/correos';
SELECT CODIGO_PERM, CLAVE, ACTIVO
FROM SIS.OSS_PERM WHERE CLAVE='sistema.correos.enviar';
-- Solo cantidades: no expone destinatarios ni cuerpos de mensajes.
SELECT ESTADO, COUNT(*) CANTIDAD
FROM SIS.SIS_EMAIL_QUEUE
WHERE CODIGO_EMPRESA=13 AND MODULO_ORIGEN='MANUAL_R52'
GROUP BY ESTADO ORDER BY ESTADO;
