DECLARE n NUMBER; BEGIN
 IF SYS_CONTEXT('USERENV','CURRENT_SCHEMA') <> 'SIS' THEN RAISE_APPLICATION_ERROR(-20001,'Seleccione SIS como esquema activo.'); END IF;
 SELECT COUNT(*) INTO n FROM ALL_TABLES WHERE OWNER='SIS' AND TABLE_NAME='SIS_EMAIL_QUEUE';
 IF n=0 THEN EXECUTE IMMEDIATE 'CREATE TABLE SIS.SIS_EMAIL_QUEUE (
  EMAIL_ID NUMBER(10) NOT NULL,
  CODIGO_EMPRESA NUMBER(10) NOT NULL,
  MODULO_ORIGEN VARCHAR2(40) NOT NULL,
  REFERENCIA_ID NUMBER(10),
  TO_EMAIL VARCHAR2(150) NOT NULL,
  TO_NAME VARCHAR2(150),
  SUBJECT VARCHAR2(250) NOT NULL,
  BODY_HTML CLOB,
  BODY_TEXT CLOB,
  ESTADO VARCHAR2(20) DEFAULT ''PENDIENTE'' NOT NULL,
  INTENTOS NUMBER(5) DEFAULT 0 NOT NULL,
  MAX_INTENTOS NUMBER(5) DEFAULT 3 NOT NULL,
  FECHA_PROGRAMADA DATE DEFAULT SYSDATE,
  FECHA_ENVIO DATE,
  MESSAGE_ID VARCHAR2(200),
  ERROR_ENVIO VARCHAR2(1000),
  CREATED_AT DATE DEFAULT SYSDATE NOT NULL,
  UPDATED_AT DATE
, CONSTRAINT PK_EMAIL_Q PRIMARY KEY (EMAIL_ID))'; END IF;
END;
