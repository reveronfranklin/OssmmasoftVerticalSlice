DECLARE
 n NUMBER;
 PROCEDURE add_col(nm VARCHAR2, typ VARCHAR2) IS c NUMBER; BEGIN
 SELECT COUNT(*) INTO c FROM ALL_TAB_COLUMNS WHERE OWNER='SIS' AND TABLE_NAME='SIS_EMAIL_QUEUE' AND COLUMN_NAME=nm;
 IF c=0 THEN EXECUTE IMMEDIATE 'ALTER TABLE SIS.SIS_EMAIL_QUEUE ADD ('||nm||' '||typ||')'; END IF;
 END;
BEGIN
 IF SYS_CONTEXT('USERENV','CURRENT_SCHEMA') <> 'SIS' THEN RAISE_APPLICATION_ERROR(-20001,'Seleccione SIS como esquema activo.'); END IF;
 SELECT COUNT(*) INTO n FROM ALL_SEQUENCES WHERE SEQUENCE_OWNER='SIS' AND SEQUENCE_NAME='SEQ_EMAIL_Q';
 IF n=0 THEN
 SELECT NVL(MAX(EMAIL_ID),0)+1 INTO n FROM SIS.SIS_EMAIL_QUEUE;
 EXECUTE IMMEDIATE 'CREATE SEQUENCE SIS.SEQ_EMAIL_Q START WITH '||TO_CHAR(n,'FM99999999999999999990');
 END IF;
 add_col('ACTOR_ID','NUMBER(10)'); add_col('SOLICITUD','VARCHAR2(36)'); add_col('HUELLA','VARCHAR2(64)');
 add_col('PARA_LIST','VARCHAR2(3000)'); add_col('CC_LIST','VARCHAR2(3000)'); add_col('CCO_LIST','VARCHAR2(3000)');
 add_col('REMITENTE','VARCHAR2(150)'); add_col('REMITENTE_NOMBRE','VARCHAR2(150)'); add_col('CLAIM_TOKEN','VARCHAR2(36)');
 SELECT COUNT(*) INTO n FROM ALL_INDEXES WHERE OWNER='SIS' AND INDEX_NAME='UX_EMAIL_SOL';
 IF n=0 THEN EXECUTE IMMEDIATE 'CREATE UNIQUE INDEX SIS.UX_EMAIL_SOL ON SIS.SIS_EMAIL_QUEUE(CASE WHEN MODULO_ORIGEN=''MANUAL_R52'' THEN CODIGO_EMPRESA END, CASE WHEN MODULO_ORIGEN=''MANUAL_R52'' THEN ACTOR_ID END, CASE WHEN MODULO_ORIGEN=''MANUAL_R52'' THEN SOLICITUD END)'; END IF;
 SELECT COUNT(*) INTO n FROM ALL_INDEXES WHERE OWNER='SIS' AND INDEX_NAME='IX_EMAIL_MANUAL';
 IF n=0 THEN EXECUTE IMMEDIATE 'CREATE INDEX SIS.IX_EMAIL_MANUAL ON SIS.SIS_EMAIL_QUEUE(CODIGO_EMPRESA,ACTOR_ID,CREATED_AT)'; END IF;
END;
