 EXECUTE IMMEDIATE 'DECLARE n NUMBER; BEGIN
 IF SYS_CONTEXT(''USERENV'',''CURRENT_SCHEMA'') <> ''SIS'' THEN RAISE_APPLICATION_ERROR(-20001,''Seleccione SIS como esquema activo.''); END IF;
 SELECT COUNT(*) INTO n FROM ALL_TABLES WHERE OWNER=''SIS'' AND TABLE_NAME=''SIS_EMAIL_QUEUE'';
 IF n=0 THEN EXECUTE IMMEDIATE ''CREATE TABLE SIS.SIS_EMAIL_QUEUE (
  EMAIL_ID NUMBER(10) NOT NULL,
  CODIGO_EMPRESA NUMBER(10) NOT NULL,
  MODULO_ORIGEN VARCHAR2(40) NOT NULL,
  REFERENCIA_ID NUMBER(10),
  TO_EMAIL VARCHAR2(150) NOT NULL,
  TO_NAME VARCHAR2(150),
  SUBJECT VARCHAR2(250) NOT NULL,
  BODY_HTML CLOB,
  BODY_TEXT CLOB,
  ESTADO VARCHAR2(20) DEFAULT ''''PENDIENTE'''' NOT NULL,
  INTENTOS NUMBER(5) DEFAULT 0 NOT NULL,
  MAX_INTENTOS NUMBER(5) DEFAULT 3 NOT NULL,
  FECHA_PROGRAMADA DATE DEFAULT SYSDATE,
  FECHA_ENVIO DATE,
  MESSAGE_ID VARCHAR2(200),
  ERROR_ENVIO VARCHAR2(1000),
  CREATED_AT DATE DEFAULT SYSDATE NOT NULL,
  UPDATED_AT DATE
, CONSTRAINT PK_EMAIL_Q PRIMARY KEY (EMAIL_ID))''; END IF;
END;';
 EXECUTE IMMEDIATE 'DECLARE
 n NUMBER;
 PROCEDURE add_col(nm VARCHAR2, typ VARCHAR2) IS c NUMBER; BEGIN
 SELECT COUNT(*) INTO c FROM ALL_TAB_COLUMNS WHERE OWNER=''SIS'' AND TABLE_NAME=''SIS_EMAIL_QUEUE'' AND COLUMN_NAME=nm;
 IF c=0 THEN EXECUTE IMMEDIATE ''ALTER TABLE SIS.SIS_EMAIL_QUEUE ADD (''||nm||'' ''||typ||'')''; END IF;
 END;
BEGIN
 IF SYS_CONTEXT(''USERENV'',''CURRENT_SCHEMA'') <> ''SIS'' THEN RAISE_APPLICATION_ERROR(-20001,''Seleccione SIS como esquema activo.''); END IF;
 SELECT COUNT(*) INTO n FROM ALL_SEQUENCES WHERE SEQUENCE_OWNER=''SIS'' AND SEQUENCE_NAME=''SEQ_EMAIL_Q'';
 IF n=0 THEN
 SELECT NVL(MAX(EMAIL_ID),0)+1 INTO n FROM SIS.SIS_EMAIL_QUEUE;
 EXECUTE IMMEDIATE ''CREATE SEQUENCE SIS.SEQ_EMAIL_Q START WITH ''||TO_CHAR(n,''FM99999999999999999990'');
 END IF;
 add_col(''ACTOR_ID'',''NUMBER(10)''); add_col(''SOLICITUD'',''VARCHAR2(36)''); add_col(''HUELLA'',''VARCHAR2(64)'');
 add_col(''PARA_LIST'',''VARCHAR2(3000)''); add_col(''CC_LIST'',''VARCHAR2(3000)''); add_col(''CCO_LIST'',''VARCHAR2(3000)'');
 add_col(''REMITENTE'',''VARCHAR2(150)''); add_col(''REMITENTE_NOMBRE'',''VARCHAR2(150)''); add_col(''CLAIM_TOKEN'',''VARCHAR2(36)'');
 SELECT COUNT(*) INTO n FROM ALL_INDEXES WHERE OWNER=''SIS'' AND INDEX_NAME=''UX_EMAIL_SOL'';
 IF n=0 THEN EXECUTE IMMEDIATE ''CREATE UNIQUE INDEX SIS.UX_EMAIL_SOL ON SIS.SIS_EMAIL_QUEUE(CASE WHEN MODULO_ORIGEN=''''MANUAL_R52'''' THEN CODIGO_EMPRESA END, CASE WHEN MODULO_ORIGEN=''''MANUAL_R52'''' THEN ACTOR_ID END, CASE WHEN MODULO_ORIGEN=''''MANUAL_R52'''' THEN SOLICITUD END)''; END IF;
 SELECT COUNT(*) INTO n FROM ALL_INDEXES WHERE OWNER=''SIS'' AND INDEX_NAME=''IX_EMAIL_MANUAL'';
 IF n=0 THEN EXECUTE IMMEDIATE ''CREATE INDEX SIS.IX_EMAIL_MANUAL ON SIS.SIS_EMAIL_QUEUE(CODIGO_EMPRESA,ACTOR_ID,CREATED_AT)''; END IF;
END;';
 EXECUTE IMMEDIATE 'CREATE OR REPLACE PACKAGE SIS.PKG_EMAIL_MANUAL AS
 PROCEDURE CREAR(p_EMPRESA NUMBER,p_ACTOR NUMBER,p_SOL VARCHAR2,p_HASH VARCHAR2,p_PARA VARCHAR2,p_CC VARCHAR2,p_CCO VARCHAR2,p_ASUNTO VARCHAR2,p_TEXTO CLOB,p_FROM VARCHAR2,p_NOMBRE VARCHAR2,p_ID OUT NUMBER);
 PROCEDURE LISTAR(p_EMPRESA NUMBER,p_ACTOR NUMBER,p_SOL VARCHAR2,p_PAGE NUMBER,p_SIZE NUMBER,p_ROWS OUT SYS_REFCURSOR,p_TOTAL OUT NUMBER);
 PROCEDURE TOMAR(p_EMPRESA NUMBER,p_TOKEN VARCHAR2,p_ROWS OUT SYS_REFCURSOR);
 PROCEDURE FINALIZAR(p_EMPRESA NUMBER,p_ID NUMBER,p_TOKEN VARCHAR2,p_ESTADO VARCHAR2,p_ERROR VARCHAR2);
END PKG_EMAIL_MANUAL;';
 EXECUTE IMMEDIATE 'CREATE OR REPLACE PACKAGE BODY SIS.PKG_EMAIL_MANUAL AS
 PROCEDURE CREAR(p_EMPRESA NUMBER,p_ACTOR NUMBER,p_SOL VARCHAR2,p_HASH VARCHAR2,p_PARA VARCHAR2,p_CC VARCHAR2,p_CCO VARCHAR2,p_ASUNTO VARCHAR2,p_TEXTO CLOB,p_FROM VARCHAR2,p_NOMBRE VARCHAR2,p_ID OUT NUMBER) IS
 n NUMBER; h VARCHAR2(64);
 BEGIN
 -- Lock the authenticated user to serialize idempotency and hourly quota checks.
 SELECT CODIGO_USUARIO INTO n FROM SIS.SIS_USUARIOS WHERE CODIGO_EMPRESA=p_EMPRESA AND CODIGO_USUARIO=p_ACTOR FOR UPDATE;
 BEGIN
 SELECT EMAIL_ID,HUELLA INTO p_ID,h FROM SIS.SIS_EMAIL_QUEUE WHERE CODIGO_EMPRESA=p_EMPRESA AND ACTOR_ID=p_ACTOR AND SOLICITUD=p_SOL;
 IF h<>p_HASH THEN RAISE_APPLICATION_ERROR(-20002,''La solicitud ya existe con otro contenido.''); END IF;
 RETURN;
 EXCEPTION WHEN NO_DATA_FOUND THEN NULL; END;
 SELECT COUNT(*) INTO n FROM SIS.SIS_EMAIL_QUEUE WHERE CODIGO_EMPRESA=p_EMPRESA AND ACTOR_ID=p_ACTOR AND MODULO_ORIGEN=''MANUAL_R52'' AND CREATED_AT>SYSDATE-1/24;
 IF n>=20 THEN RAISE_APPLICATION_ERROR(-20003,''Limite de 20 solicitudes por hora alcanzado.''); END IF;
 SELECT SIS.SEQ_EMAIL_Q.NEXTVAL INTO p_ID FROM DUAL;
 INSERT INTO SIS.SIS_EMAIL_QUEUE(EMAIL_ID,CODIGO_EMPRESA,MODULO_ORIGEN,TO_EMAIL,SUBJECT,BODY_TEXT,ESTADO,INTENTOS,MAX_INTENTOS,CREATED_AT,FECHA_PROGRAMADA,ACTOR_ID,SOLICITUD,HUELLA,PARA_LIST,CC_LIST,CCO_LIST,REMITENTE,REMITENTE_NOMBRE)
 VALUES(p_ID,p_EMPRESA,''MANUAL_R52'',SUBSTR(p_PARA,1,INSTR(p_PARA||'';'','';'')-1),p_ASUNTO,p_TEXTO,''PENDIENTE'',0,1,SYSDATE,SYSDATE,p_ACTOR,p_SOL,p_HASH,p_PARA,p_CC,p_CCO,p_FROM,p_NOMBRE);
 END;
 PROCEDURE LISTAR(p_EMPRESA NUMBER,p_ACTOR NUMBER,p_SOL VARCHAR2,p_PAGE NUMBER,p_SIZE NUMBER,p_ROWS OUT SYS_REFCURSOR,p_TOTAL OUT NUMBER) IS BEGIN
 SELECT COUNT(*) INTO p_TOTAL FROM SIS.SIS_EMAIL_QUEUE WHERE CODIGO_EMPRESA=p_EMPRESA AND ACTOR_ID=p_ACTOR AND MODULO_ORIGEN=''MANUAL_R52'' AND (p_SOL IS NULL OR SOLICITUD=p_SOL);
 OPEN p_ROWS FOR SELECT * FROM (SELECT q.EMAIL_ID,q.SOLICITUD,q.SUBJECT,q.ESTADO,q.INTENTOS,q.CREATED_AT,q.FECHA_ENVIO,q.ERROR_ENVIO,q.PARA_LIST,q.CC_LIST,q.CCO_LIST,ROW_NUMBER() OVER(ORDER BY q.CREATED_AT DESC,q.EMAIL_ID DESC) RN FROM SIS.SIS_EMAIL_QUEUE q WHERE q.CODIGO_EMPRESA=p_EMPRESA AND q.ACTOR_ID=p_ACTOR AND q.MODULO_ORIGEN=''MANUAL_R52'' AND (p_SOL IS NULL OR q.SOLICITUD=p_SOL)) WHERE RN>(p_PAGE-1)*p_SIZE AND RN<=p_PAGE*p_SIZE;
 END;
 PROCEDURE TOMAR(p_EMPRESA NUMBER,p_TOKEN VARCHAR2,p_ROWS OUT SYS_REFCURSOR) IS
 id NUMBER; busy EXCEPTION; PRAGMA EXCEPTION_INIT(busy,-54);
 BEGIN
 UPDATE SIS.SIS_EMAIL_QUEUE SET ESTADO=''INCIERTO'',ERROR_ENVIO=''Proceso interrumpido. Revisar antes de reenviar.'',UPDATED_AT=SYSDATE WHERE CODIGO_EMPRESA=p_EMPRESA AND MODULO_ORIGEN=''MANUAL_R52'' AND ESTADO=''ENVIANDO'' AND UPDATED_AT<SYSDATE-30/1440;
 FOR r IN (SELECT EMAIL_ID FROM SIS.SIS_EMAIL_QUEUE WHERE CODIGO_EMPRESA=p_EMPRESA AND MODULO_ORIGEN=''MANUAL_R52'' AND ESTADO=''PENDIENTE'' ORDER BY EMAIL_ID) LOOP
 BEGIN
 SELECT EMAIL_ID INTO id FROM SIS.SIS_EMAIL_QUEUE WHERE EMAIL_ID=r.EMAIL_ID AND CODIGO_EMPRESA=p_EMPRESA AND ESTADO=''PENDIENTE'' FOR UPDATE NOWAIT;
 UPDATE SIS.SIS_EMAIL_QUEUE SET ESTADO=''ENVIANDO'',CLAIM_TOKEN=p_TOKEN,INTENTOS=INTENTOS+1,UPDATED_AT=SYSDATE,MESSAGE_ID=p_TOKEN||SUBSTR(REMITENTE,INSTR(REMITENTE,''@'')) WHERE EMAIL_ID=id;
 EXIT;
 EXCEPTION WHEN busy THEN NULL; WHEN NO_DATA_FOUND THEN NULL; END;
 END LOOP;
 OPEN p_ROWS FOR SELECT EMAIL_ID,PARA_LIST,CC_LIST,CCO_LIST,SUBJECT,BODY_TEXT,REMITENTE,REMITENTE_NOMBRE,MESSAGE_ID FROM SIS.SIS_EMAIL_QUEUE WHERE CODIGO_EMPRESA=p_EMPRESA AND EMAIL_ID=id AND CLAIM_TOKEN=p_TOKEN;
 END;
 PROCEDURE FINALIZAR(p_EMPRESA NUMBER,p_ID NUMBER,p_TOKEN VARCHAR2,p_ESTADO VARCHAR2,p_ERROR VARCHAR2) IS BEGIN
 IF p_ESTADO NOT IN (''ACEPTADO_SMTP'',''ERROR'',''INCIERTO'') THEN RAISE_APPLICATION_ERROR(-20004,''Estado invalido.''); END IF;
 UPDATE SIS.SIS_EMAIL_QUEUE SET ESTADO=p_ESTADO,ERROR_ENVIO=p_ERROR,UPDATED_AT=SYSDATE,FECHA_ENVIO=CASE WHEN p_ESTADO=''ACEPTADO_SMTP'' THEN SYSDATE ELSE NULL END WHERE EMAIL_ID=p_ID AND CODIGO_EMPRESA=p_EMPRESA AND MODULO_ORIGEN=''MANUAL_R52'' AND CLAIM_TOKEN=p_TOKEN AND ESTADO=''ENVIANDO'';
 IF SQL%ROWCOUNT<>1 THEN RAISE_APPLICATION_ERROR(-20005,''No se pudo registrar el resultado. Revisar la solicitud.''); END IF;
 END;
END PKG_EMAIL_MANUAL;';
