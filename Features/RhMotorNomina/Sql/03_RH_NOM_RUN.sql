CREATE OR REPLACE PACKAGE RH_PKG_NOM_RUN AS
  PROCEDURE CREAR(p_EMPRESA NUMBER,p_ACTOR NUMBER,p_MODELO NUMBER,p_VERSION NUMBER,p_MODO VARCHAR2,
    p_CLAVE VARCHAR2,p_HASH VARCHAR2,p_DATOS CLOB,p_HASH_DATOS VARCHAR2,p_ID OUT NUMBER);
  PROCEDURE POR_CLAVE(p_EMPRESA NUMBER,p_ACTOR NUMBER,p_CLAVE VARCHAR2,p_RESULT OUT SYS_REFCURSOR);
  PROCEDURE LISTAR(p_EMPRESA NUMBER,p_ACTOR NUMBER,p_PAGE NUMBER,p_SIZE NUMBER,p_RESULT OUT SYS_REFCURSOR,p_TOTAL OUT NUMBER);
  PROCEDURE LEER(p_EMPRESA NUMBER,p_ACTOR NUMBER,p_ID NUMBER,p_RESULT OUT SYS_REFCURSOR);
  PROCEDURE DOCUMENTO(p_EMPRESA NUMBER,p_ACTOR NUMBER,p_ID NUMBER,p_TIPO VARCHAR2,p_RESULT OUT SYS_REFCURSOR);
  PROCEDURE TOMAR(p_EMPRESA NUMBER,p_TOKEN VARCHAR2,p_ID OUT NUMBER,p_ACTOR OUT NUMBER);
  PROCEDURE TERMINAR(p_EMPRESA NUMBER,p_ID NUMBER,p_TOKEN VARCHAR2,p_ESTADO VARCHAR2,p_RESULT CLOB,p_HASH VARCHAR2,p_MENSAJE VARCHAR2);
  PROCEDURE CANCELAR(p_EMPRESA NUMBER,p_ACTOR NUMBER,p_ID NUMBER,p_VERSION NUMBER);
END;
/
CREATE OR REPLACE PACKAGE BODY RH_PKG_NOM_RUN AS
  PROCEDURE CREAR(p_EMPRESA NUMBER,p_ACTOR NUMBER,p_MODELO NUMBER,p_VERSION NUMBER,p_MODO VARCHAR2,
    p_CLAVE VARCHAR2,p_HASH VARCHAR2,p_DATOS CLOB,p_HASH_DATOS VARCHAR2,p_ID OUT NUMBER) IS
    v_hash VARCHAR2(64);v_count NUMBER;v_actor NUMBER;
  BEGIN
    IF p_EMPRESA IS NULL OR p_EMPRESA<=0 OR p_ACTOR IS NULL OR p_ACTOR<=0
       OR p_MODELO IS NULL OR p_MODELO<=0 OR p_VERSION IS NULL OR p_VERSION<=0
       OR p_MODO IS NULL OR p_MODO NOT IN ('LOTE_MANUAL','ACTUAL','COMPARACION_PRUEBA','CAPTURA_PRENOMINA')
       OR p_CLAVE IS NULL OR LENGTH(p_CLAVE)>80 OR NOT REGEXP_LIKE(p_CLAVE,'^[A-Za-z0-9:_-]+$')
       OR LENGTH(p_HASH)<>64 OR LENGTH(p_HASH_DATOS)<>64 OR p_HASH IS NULL OR p_HASH_DATOS IS NULL
       OR p_DATOS IS NULL OR DBMS_LOB.GETLENGTH(p_DATOS)>4194304 THEN
      RAISE_APPLICATION_ERROR(-20001,'Solicitud de corrida invalida.');
    END IF;
    BEGIN
      INSERT INTO RH_NOM_RUN_ACT(CODIGO_EMPRESA,ACTOR) VALUES(p_EMPRESA,p_ACTOR);
    EXCEPTION WHEN DUP_VAL_ON_INDEX THEN NULL; END;
    SELECT ACTOR INTO v_actor FROM RH_NOM_RUN_ACT
      WHERE CODIGO_EMPRESA=p_EMPRESA AND ACTOR=p_ACTOR FOR UPDATE;
    -- El mutex dura hasta commit/rollback del caller y serializa el COUNT+INSERT.
    BEGIN
      SELECT ID_RUN,HASH_SOL INTO p_ID,v_hash FROM RH_NOM_RUN WHERE CODIGO_EMPRESA=p_EMPRESA AND ACTOR=p_ACTOR AND CLAVE_SOL=p_CLAVE;
      IF v_hash<>p_HASH THEN RAISE_APPLICATION_ERROR(-20002,'La clave ya identifica otra solicitud.'); END IF;
      RETURN;
    EXCEPTION WHEN NO_DATA_FOUND THEN NULL; END;
    SELECT COUNT(*) INTO v_count FROM RH_NOM_RUN WHERE CODIGO_EMPRESA=p_EMPRESA AND ACTOR=p_ACTOR AND ESTADO IN ('PENDIENTE','EN_CURSO');
    IF v_count>=5 THEN RAISE_APPLICATION_ERROR(-20001,'Demasiadas corridas pendientes del usuario.'); END IF;
    p_ID:=RH_NOM_RUN_SEQ.NEXTVAL;
    BEGIN
      INSERT INTO RH_NOM_RUN(ID_RUN,CODIGO_EMPRESA,ACTOR,ID_MODELO,VER_MODELO,MODO,ESTADO,CLAVE_SOL,HASH_SOL,DATOS_JSON,HASH_DATOS)
      VALUES(p_ID,p_EMPRESA,p_ACTOR,p_MODELO,p_VERSION,p_MODO,'PENDIENTE',p_CLAVE,p_HASH,p_DATOS,p_HASH_DATOS);
    EXCEPTION WHEN DUP_VAL_ON_INDEX THEN
      SELECT ID_RUN,HASH_SOL INTO p_ID,v_hash FROM RH_NOM_RUN WHERE CODIGO_EMPRESA=p_EMPRESA AND ACTOR=p_ACTOR AND CLAVE_SOL=p_CLAVE;
      IF v_hash<>p_HASH THEN RAISE_APPLICATION_ERROR(-20002,'La clave ya identifica otra solicitud.'); END IF;
    END;
  END;
  PROCEDURE POR_CLAVE(p_EMPRESA NUMBER,p_ACTOR NUMBER,p_CLAVE VARCHAR2,p_RESULT OUT SYS_REFCURSOR) IS
  BEGIN OPEN p_RESULT FOR SELECT ID_RUN,CODIGO_EMPRESA,ACTOR,ID_MODELO,VER_MODELO,MODO,ESTADO,CLAVE_SOL,HASH_SOL,HASH_DATOS,HASH_RESULT,MENSAJE,VERSION,CANCELAR,INTENTOS,FECHA_INS,FECHA_INICIO,FECHA_FIN
    FROM RH_NOM_RUN WHERE CODIGO_EMPRESA=p_EMPRESA AND ACTOR=p_ACTOR AND CLAVE_SOL=p_CLAVE; END;
  PROCEDURE LISTAR(p_EMPRESA NUMBER,p_ACTOR NUMBER,p_PAGE NUMBER,p_SIZE NUMBER,p_RESULT OUT SYS_REFCURSOR,p_TOTAL OUT NUMBER) IS
  BEGIN
    IF p_PAGE IS NULL OR p_PAGE<1 OR p_PAGE>100000 OR p_SIZE IS NULL OR p_SIZE<1 OR p_SIZE>100 THEN RAISE_APPLICATION_ERROR(-20001,'Pagina invalida.'); END IF;
    SELECT COUNT(*) INTO p_TOTAL FROM RH_NOM_RUN WHERE CODIGO_EMPRESA=p_EMPRESA AND ACTOR=p_ACTOR;
    OPEN p_RESULT FOR SELECT * FROM (SELECT ID_RUN,CODIGO_EMPRESA,ACTOR,ID_MODELO,VER_MODELO,MODO,ESTADO,CLAVE_SOL,HASH_SOL,HASH_DATOS,HASH_RESULT,MENSAJE,VERSION,CANCELAR,INTENTOS,FECHA_INS,FECHA_INICIO,FECHA_FIN,
      ROW_NUMBER() OVER(ORDER BY ID_RUN DESC) RN FROM RH_NOM_RUN WHERE CODIGO_EMPRESA=p_EMPRESA AND ACTOR=p_ACTOR)
      WHERE RN>(p_PAGE-1)*p_SIZE AND RN<=p_PAGE*p_SIZE;
  END;
  PROCEDURE LEER(p_EMPRESA NUMBER,p_ACTOR NUMBER,p_ID NUMBER,p_RESULT OUT SYS_REFCURSOR) IS
  BEGIN OPEN p_RESULT FOR SELECT ID_RUN,CODIGO_EMPRESA,ACTOR,ID_MODELO,VER_MODELO,MODO,ESTADO,CLAVE_SOL,HASH_SOL,HASH_DATOS,HASH_RESULT,MENSAJE,VERSION,CANCELAR,INTENTOS,FECHA_INS,FECHA_INICIO,FECHA_FIN
    FROM RH_NOM_RUN WHERE CODIGO_EMPRESA=p_EMPRESA AND ACTOR=p_ACTOR AND ID_RUN=p_ID; END;
  PROCEDURE DOCUMENTO(p_EMPRESA NUMBER,p_ACTOR NUMBER,p_ID NUMBER,p_TIPO VARCHAR2,p_RESULT OUT SYS_REFCURSOR) IS
  BEGIN
    IF p_TIPO NOT IN ('ENTRADA','RESULTADO') OR p_TIPO IS NULL THEN RAISE_APPLICATION_ERROR(-20001,'Documento invalido.'); END IF;
    IF p_TIPO='ENTRADA' THEN
    OPEN p_RESULT FOR SELECT X.HUELLA,X.LARGO,N.PARTE,
      DBMS_LOB.SUBSTR(X.DOCUMENTO,1000,(N.PARTE-1)*1000+1) FRAGMENTO
      FROM (SELECT DATOS_JSON DOCUMENTO,HASH_DATOS HUELLA,DBMS_LOB.GETLENGTH(DATOS_JSON) LARGO
              FROM RH_NOM_RUN WHERE CODIGO_EMPRESA=p_EMPRESA AND ACTOR=p_ACTOR AND ID_RUN=p_ID) X,
           (SELECT LEVEL PARTE FROM DUAL CONNECT BY LEVEL<=4195) N
      WHERE N.PARTE<=CEIL(X.LARGO/1000) ORDER BY N.PARTE;
    ELSE
    OPEN p_RESULT FOR SELECT X.HUELLA,X.LARGO,N.PARTE,
      DBMS_LOB.SUBSTR(X.DOCUMENTO,1000,(N.PARTE-1)*1000+1) FRAGMENTO
      FROM (SELECT RESULT_JSON DOCUMENTO,HASH_RESULT HUELLA,DBMS_LOB.GETLENGTH(RESULT_JSON) LARGO
              FROM RH_NOM_RUN WHERE CODIGO_EMPRESA=p_EMPRESA AND ACTOR=p_ACTOR AND ID_RUN=p_ID) X,
           (SELECT LEVEL PARTE FROM DUAL CONNECT BY LEVEL<=4195) N
      WHERE N.PARTE<=CEIL(X.LARGO/1000) ORDER BY N.PARTE;
    END IF;
  END;
  PROCEDURE TOMAR(p_EMPRESA NUMBER,p_TOKEN VARCHAR2,p_ID OUT NUMBER,p_ACTOR OUT NUMBER) IS
    v_id NUMBER;
  BEGIN
    p_ID:=0;p_ACTOR:=0;
    IF LENGTH(p_TOKEN)<>32 OR p_TOKEN IS NULL THEN RAISE_APPLICATION_ERROR(-20001,'Token interno invalido.'); END IF;
    UPDATE RH_NOM_RUN SET ESTADO=CASE WHEN CANCELAR=1 THEN 'CANCELADO' ELSE 'ERROR' END,
      MENSAJE=CASE WHEN CANCELAR=1 THEN 'Cancelada sin movimientos.' ELSE 'Limite de recuperaciones agotado.' END,
      VERSION=VERSION+1,FECHA_FIN=SYSDATE,TOKEN_RUN=NULL,VENCE_RUN=NULL
      WHERE CODIGO_EMPRESA=p_EMPRESA AND ESTADO='EN_CURSO' AND VENCE_RUN<SYSDATE
        AND (CANCELAR=1 OR INTENTOS>=3);
    SELECT MIN(ID_RUN) INTO v_id FROM RH_NOM_RUN WHERE CODIGO_EMPRESA=p_EMPRESA AND CANCELAR=0 AND INTENTOS<3
      AND (ESTADO='PENDIENTE' OR (ESTADO='EN_CURSO' AND VENCE_RUN<SYSDATE));
    IF v_id IS NULL THEN RETURN; END IF;
    UPDATE RH_NOM_RUN SET ESTADO='EN_CURSO',TOKEN_RUN=p_TOKEN,VENCE_RUN=SYSDATE+5/1440,INTENTOS=INTENTOS+1,VERSION=VERSION+1,FECHA_INICIO=NVL(FECHA_INICIO,SYSDATE)
     WHERE ID_RUN=v_id AND CODIGO_EMPRESA=p_EMPRESA AND CANCELAR=0 AND INTENTOS<3
       AND (ESTADO='PENDIENTE' OR (ESTADO='EN_CURSO' AND VENCE_RUN<SYSDATE));
    IF SQL%ROWCOUNT=1 THEN SELECT ID_RUN,ACTOR INTO p_ID,p_ACTOR FROM RH_NOM_RUN WHERE ID_RUN=v_id AND CODIGO_EMPRESA=p_EMPRESA; END IF;
  END;
  PROCEDURE TERMINAR(p_EMPRESA NUMBER,p_ID NUMBER,p_TOKEN VARCHAR2,p_ESTADO VARCHAR2,p_RESULT CLOB,p_HASH VARCHAR2,p_MENSAJE VARCHAR2) IS
    v_cancel NUMBER;
  BEGIN
    IF p_ESTADO IS NULL OR p_ESTADO NOT IN ('COMPLETADO','ERROR') OR LENGTH(p_MENSAJE)>500
       OR (p_ESTADO='COMPLETADO' AND (p_RESULT IS NULL OR p_HASH IS NULL))
       OR (p_RESULT IS NOT NULL AND (p_HASH IS NULL OR LENGTH(p_HASH)<>64 OR DBMS_LOB.GETLENGTH(p_RESULT)>2097152))
       OR (p_RESULT IS NULL AND p_HASH IS NOT NULL) THEN RAISE_APPLICATION_ERROR(-20001,'Resultado invalido.'); END IF;
    BEGIN SELECT CANCELAR INTO v_cancel FROM RH_NOM_RUN WHERE CODIGO_EMPRESA=p_EMPRESA AND ID_RUN=p_ID AND ESTADO='EN_CURSO' AND TOKEN_RUN=p_TOKEN FOR UPDATE NOWAIT;
    EXCEPTION WHEN NO_DATA_FOUND THEN RAISE_APPLICATION_ERROR(-20002,'La corrida fue tomada por otro proceso.'); END;
    IF v_cancel=1 THEN
      UPDATE RH_NOM_RUN SET ESTADO='CANCELADO',RESULT_JSON=NULL,HASH_RESULT=NULL,MENSAJE='Cancelada sin movimientos.',VERSION=VERSION+1,FECHA_FIN=SYSDATE,TOKEN_RUN=NULL,VENCE_RUN=NULL WHERE ID_RUN=p_ID;
    ELSE
      UPDATE RH_NOM_RUN SET ESTADO=p_ESTADO,RESULT_JSON=p_RESULT,HASH_RESULT=p_HASH,MENSAJE=p_MENSAJE,VERSION=VERSION+1,FECHA_FIN=SYSDATE,TOKEN_RUN=NULL,VENCE_RUN=NULL WHERE ID_RUN=p_ID;
    END IF;
  END;
  PROCEDURE CANCELAR(p_EMPRESA NUMBER,p_ACTOR NUMBER,p_ID NUMBER,p_VERSION NUMBER) IS
  BEGIN
    UPDATE RH_NOM_RUN SET CANCELAR=1,VERSION=VERSION+1,
      ESTADO=CASE WHEN ESTADO='PENDIENTE' THEN 'CANCELADO' ELSE ESTADO END,
      FECHA_FIN=CASE WHEN ESTADO='PENDIENTE' THEN SYSDATE ELSE FECHA_FIN END
     WHERE CODIGO_EMPRESA=p_EMPRESA AND ACTOR=p_ACTOR AND ID_RUN=p_ID AND VERSION=p_VERSION AND ESTADO IN ('PENDIENTE','EN_CURSO');
    IF SQL%ROWCOUNT<>1 THEN RAISE_APPLICATION_ERROR(-20002,'La corrida cambio o ya termino.'); END IF;
  END;
END;
