-- Oracle 10g. RH_NOM_RUN=10, RH_NOM_RUN_SEQ=14, RH_PKG_NOM_RUN=14.
-- Corridas de SIMULACION/DIAGNOSTICO, sin DML en movimientos o historicos de nomina.
DECLARE
  n NUMBER;
BEGIN
  IF SYS_CONTEXT('USERENV','SESSION_USER')<>'RH' OR SYS_CONTEXT('USERENV','CURRENT_SCHEMA')<>'RH' THEN
    RAISE_APPLICATION_ERROR(-20001,'Instalar como RH.');
  END IF;
  SELECT COUNT(*) INTO n FROM USER_OBJECTS WHERE OBJECT_NAME='RH_NOM_RUN';
  IF n=0 THEN
    EXECUTE IMMEDIATE 'CREATE TABLE RH_NOM_RUN (
      ID_RUN NUMBER(10) NOT NULL,CODIGO_EMPRESA NUMBER(10) NOT NULL,ACTOR NUMBER(10) NOT NULL,
      ID_MODELO NUMBER(10) NOT NULL,VER_MODELO NUMBER(10) NOT NULL,
      MODO VARCHAR2(24 CHAR) NOT NULL,ESTADO VARCHAR2(16 CHAR) NOT NULL,
      CLAVE_SOL VARCHAR2(80 CHAR) NOT NULL,HASH_SOL VARCHAR2(64 CHAR) NOT NULL,
      DATOS_JSON CLOB NOT NULL,HASH_DATOS VARCHAR2(64 CHAR) NOT NULL,
      RESULT_JSON CLOB,HASH_RESULT VARCHAR2(64 CHAR),MENSAJE VARCHAR2(500 CHAR),
      VERSION NUMBER(10) DEFAULT 1 NOT NULL,CANCELAR NUMBER(1) DEFAULT 0 NOT NULL,
      TOKEN_RUN VARCHAR2(32 CHAR),VENCE_RUN DATE,INTENTOS NUMBER(3) DEFAULT 0 NOT NULL,
      FECHA_INS DATE DEFAULT SYSDATE NOT NULL,FECHA_INICIO DATE,FECHA_FIN DATE,
      CONSTRAINT PK_RH_NOM_RUN PRIMARY KEY(ID_RUN),
      CONSTRAINT UK_RH_NOM_RUN_SOL UNIQUE(CODIGO_EMPRESA,ACTOR,CLAVE_SOL),
      CONSTRAINT FK_RH_NOM_RUN_VER FOREIGN KEY(ID_MODELO,CODIGO_EMPRESA,VER_MODELO)
        REFERENCES RH_NOM_MOD_VER(ID_MODELO,CODIGO_EMPRESA,VERSION),
      CONSTRAINT CK_RH_NOM_RUN_MOD2 CHECK(MODO IN (''LOTE_MANUAL'',''ACTUAL'',''COMPARACION_PRUEBA'',''CAPTURA_PRENOMINA'')),
      CONSTRAINT CK_RH_NOM_RUN_EST CHECK(ESTADO IN (''PENDIENTE'',''EN_CURSO'',''COMPLETADO'',''ERROR'',''CANCELADO'')),
      CONSTRAINT CK_RH_NOM_RUN_POS CHECK(CODIGO_EMPRESA>0 AND ACTOR>0 AND VERSION>0),
      CONSTRAINT CK_RH_NOM_RUN_CAN CHECK(CANCELAR IN (0,1)))';
    EXECUTE IMMEDIATE 'CREATE INDEX IX_RH_NOM_RUN_COLA ON RH_NOM_RUN(CODIGO_EMPRESA,ESTADO,VENCE_RUN,ID_RUN)';
  ELSE
    SELECT COUNT(*) INTO n FROM USER_OBJECTS WHERE OBJECT_NAME='RH_NOM_RUN' AND OBJECT_TYPE='TABLE';
    IF n<>1 THEN RAISE_APPLICATION_ERROR(-20001,'Conflicto de nombre RH_NOM_RUN.'); END IF;
  END IF;
  -- RH_NOM_RUN_ACT=14; mutex de creacion por empresa/actor, sin datos de nomina.
  SELECT COUNT(*) INTO n FROM USER_OBJECTS WHERE OBJECT_NAME='RH_NOM_RUN_ACT';
  IF n=0 THEN
    EXECUTE IMMEDIATE 'CREATE TABLE RH_NOM_RUN_ACT (
      CODIGO_EMPRESA NUMBER(10) NOT NULL,ACTOR NUMBER(10) NOT NULL,
      CONSTRAINT PK_RH_NOM_RUN_ACT PRIMARY KEY(CODIGO_EMPRESA,ACTOR),
      CONSTRAINT CK_RH_NOM_RUN_ACT CHECK(CODIGO_EMPRESA>0 AND ACTOR>0))';
  ELSE
    SELECT COUNT(*) INTO n FROM USER_OBJECTS WHERE OBJECT_NAME='RH_NOM_RUN_ACT' AND OBJECT_TYPE='TABLE';
    IF n<>1 THEN RAISE_APPLICATION_ERROR(-20001,'Conflicto de nombre RH_NOM_RUN_ACT.'); END IF;
  END IF;
  SELECT COUNT(*) INTO n FROM USER_OBJECTS WHERE OBJECT_NAME='RH_NOM_RUN_SEQ';
  IF n=0 THEN EXECUTE IMMEDIATE 'CREATE SEQUENCE RH_NOM_RUN_SEQ START WITH 1 INCREMENT BY 1 MAXVALUE 2147483647 NOCYCLE CACHE 20'; END IF;
END;
/
CREATE OR REPLACE TRIGGER TR_RH_NOM_RUN_IMM
BEFORE UPDATE OR DELETE ON RH_NOM_RUN
BEGIN
  IF DELETING OR UPDATING('ID_RUN') OR UPDATING('CODIGO_EMPRESA') OR UPDATING('ACTOR') OR UPDATING('ID_MODELO')
     OR UPDATING('VER_MODELO') OR UPDATING('MODO') OR UPDATING('CLAVE_SOL') OR UPDATING('HASH_SOL')
     OR UPDATING('DATOS_JSON') OR UPDATING('HASH_DATOS') OR UPDATING('FECHA_INS') THEN
    RAISE_APPLICATION_ERROR(-20004,'La solicitud y snapshot de corrida son inmutables.');
  END IF;
END;
