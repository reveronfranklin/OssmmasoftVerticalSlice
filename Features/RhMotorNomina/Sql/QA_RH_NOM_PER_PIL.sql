-- QA only: ordinary pilot explicitly requested for company13/type10/2026-11-23.
-- Existing RH_S_CODIGO_PERIODO=19 chars. No MAX(id)+1 or writer legacy.
-- Caller supplies private QA identity binds, owns transaction and verifies result.
DECLARE
  v_id NUMBER; v_n NUMBER; v_found BOOLEAN:=FALSE;
  v_desc VARCHAR2(100):='R57 QA ORDINARIA EMPLEADOS 2026-11-23';
BEGIN
  IF SYS_CONTEXT('USERENV','DB_NAME')<>:p_DB OR SYS_CONTEXT('USERENV','SERVER_HOST')<>:p_HOST
     OR SYS_CONTEXT('USERENV','SESSION_USER')<>'RH' OR SYS_CONTEXT('USERENV','CURRENT_SCHEMA')<>'RH' THEN
    RAISE_APPLICATION_ERROR(-20001,'Identidad QA RH requerida.');
  END IF;
  SELECT COUNT(*) INTO v_n FROM RH_NOM_FIN_CTL WHERE ACTIVO=1 OR LEGACY_RETIRADO=1;
  IF v_n<>0 THEN RAISE_APPLICATION_ERROR(-20001,'Puertas financieras deben permanecer cerradas.'); END IF;
  LOCK TABLE RH_PERIODOS IN EXCLUSIVE MODE NOWAIT;
  SELECT COUNT(*) INTO v_n FROM RH_PERIODOS WHERE CODIGO_EMPRESA=13 AND CODIGO_TIPO_NOMINA=10
    AND FECHA_NOMINA=DATE '2026-11-23' AND TIPO_NOMINA='N';
  IF v_n>1 THEN RAISE_APPLICATION_ERROR(-20001,'Periodo ambiguo; no se elige uno.'); END IF;
  :p_CREATED:=0;
  IF v_n=1 THEN
    SELECT CODIGO_PERIODO INTO v_id FROM RH_PERIODOS WHERE CODIGO_EMPRESA=13 AND CODIGO_TIPO_NOMINA=10
      AND FECHA_NOMINA=DATE '2026-11-23' AND TIPO_NOMINA='N';
    SELECT COUNT(*) INTO v_n FROM RH_PERIODOS WHERE CODIGO_PERIODO=v_id AND DESCRIPCION=v_desc
      AND PERIODO=2 AND FECHA_CIERRE IS NULL AND FECHA_PRECIERRE IS NULL AND CODIGO_PRESUPUESTO=0;
    IF v_n<>1 THEN RAISE_APPLICATION_ERROR(-20001,'Ya existe un periodo de otro flujo; no se modifica.'); END IF;
  ELSE
    FOR i IN 1..10000 LOOP
      SELECT RH_S_CODIGO_PERIODO.NEXTVAL INTO v_id FROM DUAL;
      SELECT (SELECT COUNT(*) FROM RH_PERIODOS WHERE CODIGO_PERIODO=v_id)
        +(SELECT COUNT(*) FROM RH_HISTORICO_NOMINA WHERE CODIGO_PERIODO=v_id)
        +(SELECT COUNT(*) FROM RH_HISTORICO_PERSONAL_CARGO WHERE CODIGO_PERIODO=v_id)
        +(SELECT COUNT(*) FROM RH_TMP_NOMINA WHERE CODIGO_PERIODO=v_id) INTO v_n FROM DUAL;
      IF v_n=0 THEN v_found:=TRUE; EXIT; END IF;
    END LOOP;
    IF NOT v_found OR v_id<=0 OR v_id>2147483647 THEN RAISE_APPLICATION_ERROR(-20001,'Secuencia sin identidad utilizable.'); END IF;
    -- Same business fields/default budget0 as existing period creation. No SIS impersonation.
    INSERT INTO RH_PERIODOS(CODIGO_PERIODO,CODIGO_EMPRESA,CODIGO_TIPO_NOMINA,FECHA_NOMINA,
      PERIODO,TIPO_NOMINA,CODIGO_PRESUPUESTO,DESCRIPCION,FECHA_INS)
    VALUES(v_id,13,10,DATE '2026-11-23',2,'N',0,v_desc,SYSDATE);
    :p_CREATED:=1;
  END IF;
  :p_PERIOD:=v_id;
END;
