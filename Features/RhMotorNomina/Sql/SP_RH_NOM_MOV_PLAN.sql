-- Oracle 10g. SP_RH_NOM_MOV_PLAN=18. Read-only financial preparation.
-- No sequence, DML, commits, ownership inference or legacy calculation calls.
CREATE OR REPLACE PROCEDURE RH.SP_RH_NOM_MOV_PLAN(
  p_EMPRESA NUMBER,p_TIPO NUMBER,p_PERSONA NUMBER,
  p_AJENOS OUT NUMBER,p_RESULT OUT SYS_REFCURSOR) AS
BEGIN
  IF p_EMPRESA IS NULL OR p_EMPRESA<=0 OR p_TIPO IS NULL OR p_TIPO<=0
     OR p_PERSONA IS NULL OR p_PERSONA<=0 THEN
    RAISE_APPLICATION_ERROR(-20001,'Empresa, tipo y persona positivos requeridos.');
  END IF;
  -- U2 omits CODIGO_EMPRESA/FRECUENCIA_ID. Fail closed on another company,
  -- including unknown company, without returning its financial images.
  SELECT COUNT(*) INTO p_AJENOS FROM RH.RH_MOV_NOMINA
   WHERE CODIGO_TIPO_NOMINA=p_TIPO AND CODIGO_PERSONA=p_PERSONA
     AND (CODIGO_EMPRESA<>p_EMPRESA OR CODIGO_EMPRESA IS NULL);
  OPEN p_RESULT FOR
    SELECT * FROM (
      SELECT CODIGO_MOV_NOMINA,CODIGO_EMPRESA,CODIGO_TIPO_NOMINA,
        CODIGO_PERSONA,CODIGO_CONCEPTO,FRECUENCIA_ID,TIPO,
        TO_CHAR(MONTO,'TM9','NLS_NUMERIC_CHARACTERS=''.,''') MONTO_TEXTO,
        STATUS,COMPLEMENTO_CONCEPTO,EXTRA1,EXTRA2,EXTRA3,
        USUARIO_INS,FECHA_INS,USUARIO_UPD,FECHA_UPD
      FROM RH.RH_MOV_NOMINA
      WHERE CODIGO_EMPRESA=p_EMPRESA AND CODIGO_TIPO_NOMINA=p_TIPO
        AND CODIGO_PERSONA=p_PERSONA
      ORDER BY CODIGO_MOV_NOMINA)
    WHERE ROWNUM<=2001;
END;
