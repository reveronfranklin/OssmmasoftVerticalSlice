-- Oracle 10g. SP_RH_NOM_PAR_CON=17. Solo lectura, sin ejecutar helper legacy.
CREATE OR REPLACE PROCEDURE RH.SP_RH_NOM_PAR_CON (
 p_EMPRESA NUMBER,p_TIPO NUMBER,p_FECHA DATE,p_CONCEPTO NUMBER,p_POLITICA VARCHAR2,p_RESULT OUT SYS_REFCURSOR
) AUTHID DEFINER AS
BEGIN
 IF p_EMPRESA IS NULL OR p_EMPRESA<=0 OR p_EMPRESA<>TRUNC(p_EMPRESA)
 OR p_TIPO IS NULL OR p_TIPO<=0 OR p_TIPO<>TRUNC(p_TIPO)
 OR p_CONCEPTO IS NULL OR p_CONCEPTO<=0 OR p_CONCEPTO<>TRUNC(p_CONCEPTO)
 OR p_FECHA IS NULL OR p_POLITICA IS NULL OR p_POLITICA NOT IN ('FECHA_CONTEXTO','HASTA_NULA') THEN
  RAISE_APPLICATION_ERROR(-20001,'Contexto/politica de parametro invalido.');
 END IF;
 OPEN p_RESULT FOR SELECT * FROM (
  SELECT F.CODIGO_FORMULA_CONCEPTO,F.CODIGO_EMPRESA,F.CODIGO_CONCEPTO,F.FECHA_DESDE,F.FECHA_HASTA,
   TO_CHAR(F.PORCENTAJE,'TM9','NLS_NUMERIC_CHARACTERS=''.,''') PORCENTAJE_TEXTO,
   TO_CHAR(F.MONTO_TOPE,'TM9','NLS_NUMERIC_CHARACTERS=''.,''') MONTO_TOPE_TEXTO,
   TO_CHAR(F.PORCENTAJE_PATRONAL,'TM9','NLS_NUMERIC_CHARACTERS=''.,''') PATRONAL_TEXTO,
   F.EXTRA2,F.EXTRA3,F.TIPO_SUELDO
  FROM RH.RH_FORMULA_CONCEPTOS F
  WHERE F.CODIGO_EMPRESA=p_EMPRESA AND F.CODIGO_CONCEPTO=p_CONCEPTO
    AND EXISTS(SELECT 1 FROM RH.RH_CONCEPTOS C WHERE C.CODIGO_EMPRESA=p_EMPRESA
      AND C.CODIGO_TIPO_NOMINA=p_TIPO AND C.CODIGO_CONCEPTO=F.CODIGO_CONCEPTO)
    AND ((p_POLITICA='HASTA_NULA' AND F.FECHA_HASTA IS NULL)
      OR (p_POLITICA='FECHA_CONTEXTO' AND (F.FECHA_DESDE IS NULL OR F.FECHA_DESDE<=p_FECHA)
          AND (F.FECHA_HASTA IS NULL OR F.FECHA_HASTA>=p_FECHA)))
  ORDER BY F.CODIGO_FORMULA_CONCEPTO
 ) WHERE ROWNUM<=2;
END;
