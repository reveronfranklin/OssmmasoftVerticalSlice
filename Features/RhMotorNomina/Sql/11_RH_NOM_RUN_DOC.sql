-- Oracle 10g. SP_RH_NOM_RUN_DOC: 17 characters. Read-only document cursor.
-- Existing RH_PKG_NOM_RUN.DOCUMENTO remains available for older clients.
CREATE OR REPLACE PROCEDURE RH.SP_RH_NOM_RUN_DOC
(
  p_EMPRESA IN NUMBER,
  p_ACTOR IN NUMBER,
  p_ID IN NUMBER,
  p_TIPO IN VARCHAR2,
  p_RESULT OUT SYS_REFCURSOR
) AS
BEGIN
  IF p_EMPRESA IS NULL OR p_EMPRESA<=0 OR p_ACTOR IS NULL OR p_ACTOR<=0
     OR p_ID IS NULL OR p_ID<=0 OR p_TIPO IS NULL
     OR p_TIPO NOT IN ('ENTRADA','RESULTADO') THEN
    RAISE_APPLICATION_ERROR(-20001,'Documento o alcance invalido.');
  END IF;
  IF p_TIPO='ENTRADA' THEN
    OPEN p_RESULT FOR
      SELECT DATOS_JSON DOCUMENTO,HASH_DATOS HUELLA,
             DBMS_LOB.GETLENGTH(DATOS_JSON) LARGO
        FROM RH.RH_NOM_RUN
       WHERE CODIGO_EMPRESA=p_EMPRESA AND ACTOR=p_ACTOR AND ID_RUN=p_ID;
  ELSE
    OPEN p_RESULT FOR
      SELECT RESULT_JSON DOCUMENTO,HASH_RESULT HUELLA,
             DBMS_LOB.GETLENGTH(RESULT_JSON) LARGO
        FROM RH.RH_NOM_RUN
       WHERE CODIGO_EMPRESA=p_EMPRESA AND ACTOR=p_ACTOR AND ID_RUN=p_ID;
  END IF;
END;
