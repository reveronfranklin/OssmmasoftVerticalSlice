CREATE OR REPLACE PACKAGE BODY RH_PKG_NOM_FIN_TX AS
 g_tx VARCHAR2(100);g_emp NUMBER;g_tipo NUMBER;g_person NUMBER;g_actor NUMBER;g_plan NUMBER;g_evt NUMBER;g_reloj DATE;g_cambios NUMBER;
 PROCEDURE guard IS BEGIN
  IF g_tx IS NULL OR DBMS_TRANSACTION.LOCAL_TRANSACTION_ID(FALSE) IS NULL
   OR g_tx<>DBMS_TRANSACTION.LOCAL_TRANSACTION_ID(FALSE) THEN
   RAISE_APPLICATION_ERROR(-20001,'Transaccion financiera no autorizada.'); END IF;
 END;
 PROCEDURE BLOQUEAR_FUENTES IS BEGIN
  -- Conservative global locks, deterministic order, NOWAIT. No legacy calculation.
  LOCK TABLE RH_ADMINISTRATIVOS IN SHARE MODE NOWAIT;
  LOCK TABLE RH_CONCEPTOS IN SHARE MODE NOWAIT;
  LOCK TABLE RH_CONCEPTOS_ACUMULA IN SHARE MODE NOWAIT;
  LOCK TABLE RH_DESCRIPTIVAS IN SHARE MODE NOWAIT;
  LOCK TABLE RH_EDUCACION IN SHARE MODE NOWAIT;
  LOCK TABLE RH_FORMULA_CONCEPTOS IN SHARE MODE NOWAIT;
  LOCK TABLE RH_HISTORICO_NOMINA IN SHARE MODE NOWAIT;
  LOCK TABLE RH_NOM_MOD_EST IN SHARE MODE NOWAIT;
  LOCK TABLE RH_PERIODOS IN SHARE MODE NOWAIT;
  LOCK TABLE RH_PERSONAS_MOV_CONTROL IN SHARE MODE NOWAIT;
  LOCK TABLE RH_RELACION_CARGOS IN SHARE MODE NOWAIT;
  LOCK TABLE RH_TIPOS_NOMINA IN SHARE MODE NOWAIT;
  LOCK TABLE RH_MOV_NOMINA IN EXCLUSIVE MODE NOWAIT;
  LOCK TABLE RH_NOM_FIN_EVT IN EXCLUSIVE MODE NOWAIT;
  LOCK TABLE RH_NOM_FIN_SOL IN EXCLUSIVE MODE NOWAIT;
 END;
 PROCEDURE INICIAR(p_EMPRESA NUMBER,p_TIPO NUMBER,p_PERSONA NUMBER,p_PERIODO NUMBER,p_FECHA DATE,p_PRESUPUESTO NUMBER,
  p_ACTOR NUMBER,p_PLAN NUMBER,p_MODELO NUMBER,p_VERSION NUMBER,p_HASH VARCHAR2,p_ESCENARIO VARCHAR2,p_ACCION VARCHAR2,
  p_EVT OUT NUMBER,p_RELOJ OUT DATE) IS n NUMBER;enabled NUMBER;retired NUMBER;
 BEGIN
  g_tx:=NULL;
  IF p_EMPRESA IS NULL OR p_EMPRESA<=0 OR p_TIPO IS NULL OR p_TIPO<=0 OR p_PERSONA IS NULL OR p_PERSONA<=0
   OR p_PERIODO IS NULL OR p_PERIODO<=0 OR p_FECHA IS NULL OR p_PRESUPUESTO IS NULL OR p_PRESUPUESTO<=0
   OR p_ACTOR IS NULL OR p_ACTOR<=0 OR p_PLAN IS NULL OR p_PLAN<=0 OR p_ACCION IS NULL
   OR p_ACCION NOT IN ('APLICACION','REVERSION') THEN RAISE_APPLICATION_ERROR(-20001,'Contexto financiero invalido.'); END IF;
  BEGIN SELECT ACTIVO,LEGACY_RETIRADO INTO enabled,retired FROM RH_NOM_FIN_CTL WHERE CODIGO_EMPRESA=p_EMPRESA FOR UPDATE NOWAIT;
   EXCEPTION WHEN NO_DATA_FOUND THEN RAISE_APPLICATION_ERROR(-20001,'Ejecucion financiera no habilitada.'); END;
  IF enabled<>1 OR retired<>1 THEN RAISE_APPLICATION_ERROR(-20001,'Ejecucion financiera o retiro legacy no habilitados.'); END IF;
  BLOQUEAR_FUENTES;
  SELECT COUNT(*) INTO n FROM USER_TRIGGERS WHERE TABLE_NAME='RH_MOV_NOMINA' AND STATUS='ENABLED';
  IF n<>0 THEN RAISE_APPLICATION_ERROR(-20001,'Triggers de movimientos no revisados por el adaptador.'); END IF;
  SELECT COUNT(*) INTO n FROM RH_NOM_FIN_PLAN WHERE ID_PLAN=p_PLAN AND CODIGO_EMPRESA=p_EMPRESA AND ACTOR=p_ACTOR;
  IF n<>1 THEN RAISE_APPLICATION_ERROR(-20001,'Plan propio requerido.'); END IF;
  SELECT COUNT(*) INTO n FROM RH_PERIODOS WHERE CODIGO_EMPRESA=p_EMPRESA AND CODIGO_TIPO_NOMINA=p_TIPO
   AND CODIGO_PERIODO=p_PERIODO AND FECHA_NOMINA=p_FECHA AND FECHA_CIERRE IS NULL;
  IF n<>1 THEN RAISE_APPLICATION_ERROR(-20001,'Periodo abierto unico requerido.'); END IF;
  SELECT COUNT(*) INTO n FROM RH_TIPOS_NOMINA WHERE CODIGO_EMPRESA=p_EMPRESA AND CODIGO_TIPO_NOMINA=p_TIPO
   AND CODIGO_PRESUPUESTO_ACTUAL=p_PRESUPUESTO;
  IF n<>1 THEN RAISE_APPLICATION_ERROR(-20001,'Presupuesto actual distinto.'); END IF;
  IF p_ACCION='APLICACION' THEN
   SELECT COUNT(*) INTO n FROM RH_NOM_MOD_EST E JOIN RH_NOM_MOD_VER V ON V.ID_MODELO=E.ID_MODELO
    AND V.CODIGO_EMPRESA=E.CODIGO_EMPRESA AND V.VERSION=E.VER_MODELO
    WHERE E.CODIGO_EMPRESA=p_EMPRESA AND E.ID_MODELO=p_MODELO AND E.VER_MODELO=p_VERSION
    AND E.HASH_MODELO=p_HASH AND E.ESTADO='PUBLICADO' AND E.APTA=1 AND E.NIVEL='INTEGRAL'
    AND E.DESDE<=TRUNC(p_FECHA) AND (E.HASTA IS NULL OR E.HASTA>=TRUNC(p_FECHA))
    AND V.CODIGO_TIPO_NOMINA=p_TIPO AND V.ESCENARIO=p_ESCENARIO;
   IF n<>1 THEN RAISE_APPLICATION_ERROR(-20001,'Revision integral publicada y vigente requerida.'); END IF;
  END IF;
  g_emp:=p_EMPRESA;g_tipo:=p_TIPO;g_person:=p_PERSONA;g_actor:=p_ACTOR;g_plan:=p_PLAN;
  g_evt:=RH_NOM_FIN_EVT_SEQ.NEXTVAL;g_reloj:=SYSDATE;g_cambios:=0;
  g_tx:=DBMS_TRANSACTION.LOCAL_TRANSACTION_ID(TRUE);p_EVT:=g_evt;p_RELOJ:=g_reloj;
 END;
 PROCEDURE SOLICITUD(p_EMPRESA NUMBER,p_ACTOR NUMBER,p_CLAVE VARCHAR2,p_RESULT OUT SYS_REFCURSOR) IS
 BEGIN OPEN p_RESULT FOR SELECT S.ID_EVT,S.HASH_SOL,E.ID_PLAN,E.HASH_EVT,E.FECHA_BD
  FROM RH_NOM_FIN_SOL S JOIN RH_NOM_FIN_EVT E ON E.ID_EVT=S.ID_EVT
  WHERE S.CODIGO_EMPRESA=p_EMPRESA AND S.ACTOR=p_ACTOR AND S.CLAVE_SOL=p_CLAVE; END;
 PROCEDURE NUEVO_ID(p_ID OUT NUMBER) IS n NUMBER;
 BEGIN guard;
  FOR i IN 1..1000 LOOP
   p_ID:=RH_NOM_FIN_ID_SEQ.NEXTVAL;SELECT COUNT(*) INTO n FROM RH_MOV_NOMINA WHERE CODIGO_MOV_NOMINA=p_ID;
   IF n=0 THEN RETURN; END IF;
  END LOOP;
  RAISE_APPLICATION_ERROR(-20001,'No se asigno ID libre en 1000 intentos; revisar secuencia.');
 END;
 PROCEDURE CREAR_MOV(p_ID NUMBER,p_CONCEPTO NUMBER,p_FRECUENCIA NUMBER,p_TIPO VARCHAR2,p_MONTO NUMBER,
  p_ESTADO VARCHAR2,p_COMPLEMENTO VARCHAR2,p_EXTRA1 VARCHAR2,p_EXTRA2 VARCHAR2,p_EXTRA3 VARCHAR2) IS
 BEGIN guard;
  IF p_ID IS NULL OR p_ID<=0 OR p_CONCEPTO IS NULL OR p_CONCEPTO<=0 OR p_FRECUENCIA IS NULL OR p_FRECUENCIA<=0
   OR p_TIPO IS NULL OR p_TIPO NOT IN ('F','V') OR p_MONTO IS NULL THEN RAISE_APPLICATION_ERROR(-20001,'Destino financiero invalido.'); END IF;
  INSERT INTO RH_MOV_NOMINA(CODIGO_MOV_NOMINA,CODIGO_EMPRESA,CODIGO_TIPO_NOMINA,CODIGO_PERSONA,CODIGO_CONCEPTO,
   FRECUENCIA_ID,TIPO,MONTO,STATUS,COMPLEMENTO_CONCEPTO,EXTRA1,EXTRA2,EXTRA3,USUARIO_INS,FECHA_INS)
   VALUES(p_ID,g_emp,g_tipo,g_person,p_CONCEPTO,p_FRECUENCIA,p_TIPO,p_MONTO,p_ESTADO,p_COMPLEMENTO,p_EXTRA1,p_EXTRA2,p_EXTRA3,g_actor,g_reloj);
  g_cambios:=g_cambios+1;
 END;
 PROCEDURE ACTUALIZAR_MOV(p_ID NUMBER,p_MONTO NUMBER) IS BEGIN guard;
  IF p_MONTO IS NULL THEN RAISE_APPLICATION_ERROR(-20001,'Monto requerido.'); END IF;
  UPDATE RH_MOV_NOMINA SET MONTO=p_MONTO,USUARIO_UPD=g_actor,FECHA_UPD=g_reloj
   WHERE CODIGO_MOV_NOMINA=p_ID AND CODIGO_EMPRESA=g_emp AND CODIGO_TIPO_NOMINA=g_tipo AND CODIGO_PERSONA=g_person;
  IF SQL%ROWCOUNT<>1 THEN RAISE_APPLICATION_ERROR(-20001,'Movimiento propio ausente o duplicado.'); END IF;g_cambios:=g_cambios+1;
 END;
 PROCEDURE RETIRAR_MOV(p_ID NUMBER) IS BEGIN guard;
  DELETE FROM RH_MOV_NOMINA WHERE CODIGO_MOV_NOMINA=p_ID AND CODIGO_EMPRESA=g_emp AND CODIGO_TIPO_NOMINA=g_tipo AND CODIGO_PERSONA=g_person;
  IF SQL%ROWCOUNT<>1 THEN RAISE_APPLICATION_ERROR(-20001,'Movimiento propio ausente o duplicado.'); END IF;g_cambios:=g_cambios+1;
 END;
 PROCEDURE REGISTRAR(p_CLAVE VARCHAR2,p_HASH_SOL VARCHAR2,p_DOC CLOB,p_HASH_DOC VARCHAR2,p_HASH_EVT VARCHAR2,
  p_ANT NUMBER,p_HASH_ANT VARCHAR2,p_CAMBIOS NUMBER) IS
 BEGIN guard;
  IF TRUNC(SYSDATE)<>TRUNC(g_reloj) THEN RAISE_APPLICATION_ERROR(-20001,'Cambio de fecha durante la transaccion; recapture.'); END IF;
  IF p_CAMBIOS IS NULL OR p_CAMBIOS NOT BETWEEN 1 AND 100 OR p_CAMBIOS<>g_cambios
   OR p_CLAVE IS NULL OR LENGTH(p_CLAVE)>80 OR NOT REGEXP_LIKE(p_CLAVE,'^[A-Za-z0-9:_-]+$')
   OR p_HASH_SOL IS NULL OR NOT REGEXP_LIKE(p_HASH_SOL,'^[A-F0-9]{64}$')
   OR p_HASH_DOC IS NULL OR NOT REGEXP_LIKE(p_HASH_DOC,'^[A-F0-9]{64}$')
   OR p_HASH_EVT IS NULL OR NOT REGEXP_LIKE(p_HASH_EVT,'^[A-F0-9]{64}$')
   OR p_DOC IS NULL OR DBMS_LOB.GETLENGTH(p_DOC) NOT BETWEEN 1 AND 524288 THEN RAISE_APPLICATION_ERROR(-20001,'Evento financiero invalido.'); END IF;
  INSERT INTO RH_NOM_FIN_EVT(ID_EVT,CODIGO_EMPRESA,CODIGO_TIPO_NOMINA,CODIGO_PERSONA,ID_PLAN,ACTOR,FECHA_BD,
   ID_ANT,HASH_ANT,HASH_DOC,HASH_EVT,DOCUMENTO)
   VALUES(g_evt,g_emp,g_tipo,g_person,g_plan,g_actor,g_reloj,p_ANT,p_HASH_ANT,p_HASH_DOC,p_HASH_EVT,p_DOC);
  INSERT INTO RH_NOM_FIN_SOL(CODIGO_EMPRESA,ACTOR,CLAVE_SOL,HASH_SOL,ID_EVT)VALUES(g_emp,g_actor,p_CLAVE,p_HASH_SOL,g_evt);
  g_tx:=NULL;
 END;
END;
