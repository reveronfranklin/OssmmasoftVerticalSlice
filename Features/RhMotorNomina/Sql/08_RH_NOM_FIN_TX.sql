-- Oracle 10g. RH_NOM_FIN_CTL=14, RH_NOM_FIN_SOL=14, RH_NOM_FIN_ID_SEQ=17,
-- RH_PKG_NOM_FIN_TX=17. No company enabled by installation. No COMMIT/DDL at runtime.
DECLARE n NUMBER;
BEGIN
 IF SYS_CONTEXT('USERENV','SESSION_USER')<>'RH' OR SYS_CONTEXT('USERENV','CURRENT_SCHEMA')<>'RH' THEN
  RAISE_APPLICATION_ERROR(-20001,'Instalar como RH.'); END IF;
 SELECT COUNT(*) INTO n FROM USER_OBJECTS WHERE OBJECT_NAME='RH_NOM_FIN_CTL';
 IF n=0 THEN EXECUTE IMMEDIATE 'CREATE TABLE RH_NOM_FIN_CTL (
  CODIGO_EMPRESA NUMBER(10) NOT NULL,ACTIVO NUMBER(1) DEFAULT 0 NOT NULL,
  LEGACY_RETIRADO NUMBER(1) DEFAULT 0 NOT NULL,
  CONSTRAINT PK_RH_NOM_FIN_CTL PRIMARY KEY(CODIGO_EMPRESA),
  CONSTRAINT CK_RH_NOM_FIN_CTL CHECK(CODIGO_EMPRESA>0 AND ACTIVO IN(0,1) AND LEGACY_RETIRADO IN(0,1)))'; END IF;
 SELECT COUNT(*) INTO n FROM USER_OBJECTS WHERE OBJECT_NAME='RH_NOM_FIN_SOL';
 IF n=0 THEN EXECUTE IMMEDIATE 'CREATE TABLE RH_NOM_FIN_SOL (
  CODIGO_EMPRESA NUMBER(10) NOT NULL,ACTOR NUMBER(10) NOT NULL,CLAVE_SOL VARCHAR2(80 CHAR) NOT NULL,
  HASH_SOL VARCHAR2(64 CHAR) NOT NULL,ID_EVT NUMBER(10) NOT NULL,
  CONSTRAINT PK_RH_NOM_FIN_SOL PRIMARY KEY(CODIGO_EMPRESA,ACTOR,CLAVE_SOL),
  CONSTRAINT UK_RH_NOM_FIN_SOL_EVT UNIQUE(ID_EVT),
  CONSTRAINT FK_RH_NOM_FIN_SOL_EVT FOREIGN KEY(ID_EVT) REFERENCES RH_NOM_FIN_EVT(ID_EVT),
  CONSTRAINT CK_RH_NOM_FIN_SOL_POS CHECK(CODIGO_EMPRESA>0 AND ACTOR>0))'; END IF;
 SELECT COUNT(*) INTO n FROM USER_OBJECTS WHERE OBJECT_NAME='RH_NOM_FIN_ID_SEQ';
 IF n=0 THEN EXECUTE IMMEDIATE 'CREATE SEQUENCE RH_NOM_FIN_ID_SEQ START WITH 1 INCREMENT BY 1 MAXVALUE 2147483647 NOCYCLE CACHE 20'; END IF;
END;
