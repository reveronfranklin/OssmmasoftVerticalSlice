  p_ACTOR NUMBER,p_PLAN NUMBER,p_MODELO NUMBER,p_VERSION NUMBER,p_HASH VARCHAR2,p_ESCENARIO VARCHAR2,p_ACCION VARCHAR2,
  p_EVT OUT NUMBER,p_RELOJ OUT DATE);
 PROCEDURE SOLICITUD(p_EMPRESA NUMBER,p_ACTOR NUMBER,p_CLAVE VARCHAR2,p_RESULT OUT SYS_REFCURSOR);
 PROCEDURE NUEVO_ID(p_ID OUT NUMBER);
 PROCEDURE CREAR_MOV(p_ID NUMBER,p_CONCEPTO NUMBER,p_FRECUENCIA NUMBER,p_TIPO VARCHAR2,p_MONTO NUMBER,
  p_ESTADO VARCHAR2,p_COMPLEMENTO VARCHAR2,p_EXTRA1 VARCHAR2,p_EXTRA2 VARCHAR2,p_EXTRA3 VARCHAR2);
 PROCEDURE ACTUALIZAR_MOV(p_ID NUMBER,p_MONTO NUMBER);
 PROCEDURE RETIRAR_MOV(p_ID NUMBER);
 PROCEDURE REGISTRAR(p_CLAVE VARCHAR2,p_HASH_SOL VARCHAR2,p_DOC CLOB,p_HASH_DOC VARCHAR2,p_HASH_EVT VARCHAR2,
  p_ANT NUMBER,p_HASH_ANT VARCHAR2,p_CAMBIOS NUMBER);
END;
