DECLARE N NUMBER; BEGIN
 SELECT COUNT(*) INTO N FROM ALL_TABLES WHERE OWNER='RH' AND TABLE_NAME='RH_NOM_PRE_CTL';
 IF N=0 THEN EXECUTE IMMEDIATE 'CREATE TABLE RH.RH_NOM_PRE_CTL (
 CODIGO_EMPRESA NUMBER(10) NOT NULL,CODIGO_TIPO_NOMINA NUMBER(10) NOT NULL,CODIGO_PERIODO NUMBER(10) NOT NULL,
 ID_LOTE NUMBER(10) NOT NULL,ACTOR NUMBER(10) NOT NULL,HASH_TMP VARCHAR2(64),ESTADO VARCHAR2(20) NOT NULL,
 FECHA_PRE_ANT DATE,USUARIO_PRE_ANT NUMBER(10),FECHA_INS DATE DEFAULT SYSDATE NOT NULL,
 CONSTRAINT RH_NOM_PRE_CTL_PK PRIMARY KEY(CODIGO_EMPRESA,CODIGO_TIPO_NOMINA,CODIGO_PERIODO)) INITRANS 8'; END IF;
END;
