CREATE OR REPLACE TRIGGER RH.RH_TRG_NOM_PRE_CIERRE
 BEFORE UPDATE OF FECHA_PRECIERRE,FECHA_CIERRE ON RH.RH_PERIODOS FOR EACH ROW
DECLARE N NUMBER;BEGIN
 IF (:NEW.FECHA_PRECIERRE IS NOT NULL AND (:OLD.FECHA_PRECIERRE IS NULL OR :NEW.FECHA_PRECIERRE<>:OLD.FECHA_PRECIERRE))
 OR (:NEW.FECHA_CIERRE IS NOT NULL AND (:OLD.FECHA_CIERRE IS NULL OR :NEW.FECHA_CIERRE<>:OLD.FECHA_CIERRE)) THEN
  SELECT COUNT(*) INTO N FROM RH.RH_NOM_PRE_CTL WHERE CODIGO_EMPRESA=:NEW.CODIGO_EMPRESA AND CODIGO_TIPO_NOMINA=:NEW.CODIGO_TIPO_NOMINA AND CODIGO_PERIODO=:NEW.CODIGO_PERIODO;
  IF N>0 THEN RAISE_APPLICATION_ERROR(-20001,'Prenomina R57 en validacion QA: precierre/cierre no autorizado.'); END IF;
 END IF;
END;
