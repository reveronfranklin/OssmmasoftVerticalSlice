 PROCEDURE BLOQUEAR(p_EMPRESA NUMBER,p_TIPO NUMBER,p_PERIODO NUMBER,p_ACTOR NUMBER,p_LOTE NUMBER,p_REVERTIR NUMBER,p_HASH OUT VARCHAR2);
 PROCEDURE FILA(p_EMPRESA NUMBER,p_TIPO NUMBER,p_PERIODO NUMBER,p_FECHA DATE,p_PERSONA NUMBER,p_CONCEPTO NUMBER,p_FRECUENCIA NUMBER,p_CLASE VARCHAR2,p_MONTO NUMBER,p_STATUS VARCHAR2,p_COMPLEMENTO VARCHAR2,p_EXTRA1 VARCHAR2,p_EXTRA2 VARCHAR2,p_EXTRA3 VARCHAR2,p_ORIGEN NUMBER,p_USUARIO NUMBER);
 PROCEDURE FINALIZAR(p_EMPRESA NUMBER,p_TIPO NUMBER,p_PERIODO NUMBER,p_ACTOR NUMBER,p_LOTE NUMBER,p_HASH VARCHAR2,p_USUARIO NUMBER);
