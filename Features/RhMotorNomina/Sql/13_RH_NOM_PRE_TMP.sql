CREATE OR REPLACE PACKAGE BODY RH.RH_PKG_NOM_PRE_TMP AS
 PROCEDURE BLOQUEAR(p_EMPRESA NUMBER,p_TIPO NUMBER,p_PERIODO NUMBER,p_ACTOR NUMBER,p_LOTE NUMBER,p_REVERTIR NUMBER,p_HASH OUT VARCHAR2) IS
  N NUMBER; D DATE; C DATE; A DATE; U NUMBER; L NUMBER; X NUMBER;
 BEGIN
  -- NOWAIT: refuse concurrent editing; caller holds until commit/rollback.
  LOCK TABLE RH.RH_PERIODOS IN SHARE ROW EXCLUSIVE MODE NOWAIT;
  LOCK TABLE RH.RH_MOV_NOMINA IN SHARE MODE NOWAIT;
  LOCK TABLE RH.RH_RELACION_CARGOS IN SHARE MODE NOWAIT;
  LOCK TABLE RH.RH_PERSONAS IN SHARE MODE NOWAIT;
  LOCK TABLE RH.RH_TIPOS_NOMINA IN SHARE MODE NOWAIT;
  LOCK TABLE RH.RH_FORMULA_CONCEPTOS IN SHARE MODE NOWAIT;
  LOCK TABLE RH.RH_CONCEPTOS_ACUMULA IN SHARE MODE NOWAIT;
  LOCK TABLE RH.RH_HISTORICO_PERSONAL_CARGO IN SHARE MODE NOWAIT;
  LOCK TABLE RH.RH_CONCEPTOS IN SHARE MODE NOWAIT;
  LOCK TABLE RH.RH_DESCRIPTIVAS IN SHARE MODE NOWAIT;
  LOCK TABLE RH.RH_PERSONAS_MOV_CONTROL IN SHARE MODE NOWAIT;
  LOCK TABLE RH.RH_HISTORICO_NOMINA IN SHARE MODE NOWAIT;
  LOCK TABLE RH.RH_ADMINISTRATIVOS IN SHARE MODE NOWAIT;
  LOCK TABLE RH.RH_EDUCACION IN SHARE MODE NOWAIT;
  LOCK TABLE RH.RH_TMP_NOMINA IN EXCLUSIVE MODE NOWAIT;
  LOCK TABLE RH.RH_NOM_PRE_CTL IN EXCLUSIVE MODE NOWAIT;
  SELECT FECHA_PRECIERRE,FECHA_CIERRE,FECHA_PRENOMINA,USUARIO_PRENOMINA INTO D,C,A,U FROM RH.RH_PERIODOS
   WHERE CODIGO_EMPRESA=p_EMPRESA AND CODIGO_TIPO_NOMINA=p_TIPO AND CODIGO_PERIODO=p_PERIODO AND TIPO_NOMINA='N' FOR UPDATE NOWAIT;
  IF D IS NOT NULL OR C IS NOT NULL THEN RAISE_APPLICATION_ERROR(-20001,'Periodo cerrado o precerrado.'); END IF;
  IF p_REVERTIR=1 THEN
   SELECT ID_LOTE,ACTOR,HASH_TMP INTO L,X,p_HASH FROM RH.RH_NOM_PRE_CTL WHERE CODIGO_EMPRESA=p_EMPRESA AND CODIGO_TIPO_NOMINA=p_TIPO AND CODIGO_PERIODO=p_PERIODO AND ESTADO='GUARDADA' FOR UPDATE;
   IF L<>p_LOTE OR X<>p_ACTOR THEN RAISE_APPLICATION_ERROR(-20001,'Temporal de otro lote/actor.'); END IF;
  ELSE
   SELECT COUNT(*) INTO N FROM RH.RH_TMP_NOMINA WHERE CODIGO_EMPRESA=p_EMPRESA AND CODIGO_TIPO_NOMINA=p_TIPO AND CODIGO_PERIODO=p_PERIODO;
   IF N<>0 THEN RAISE_APPLICATION_ERROR(-20001,'El temporal ya contiene filas; no se reemplaza.'); END IF;
   SELECT COUNT(*) INTO N FROM RH.RH_NOM_PRE_CTL WHERE CODIGO_EMPRESA=p_EMPRESA AND CODIGO_TIPO_NOMINA=p_TIPO AND CODIGO_PERIODO=p_PERIODO;
   IF N<>0 THEN RAISE_APPLICATION_ERROR(-20001,'Periodo ya administrado por otro lote.'); END IF;
   INSERT INTO RH.RH_NOM_PRE_CTL(CODIGO_EMPRESA,CODIGO_TIPO_NOMINA,CODIGO_PERIODO,ID_LOTE,ACTOR,ESTADO,FECHA_PRE_ANT,USUARIO_PRE_ANT)
    VALUES(p_EMPRESA,p_TIPO,p_PERIODO,p_LOTE,p_ACTOR,'GUARDANDO',A,U);
  END IF;
 END;
 PROCEDURE FILA(p_EMPRESA NUMBER,p_TIPO NUMBER,p_PERIODO NUMBER,p_FECHA DATE,p_PERSONA NUMBER,p_CONCEPTO NUMBER,p_FRECUENCIA NUMBER,p_CLASE VARCHAR2,p_MONTO NUMBER,p_STATUS VARCHAR2,p_COMPLEMENTO VARCHAR2,p_EXTRA1 VARCHAR2,p_EXTRA2 VARCHAR2,p_EXTRA3 VARCHAR2,p_ORIGEN NUMBER,p_USUARIO NUMBER) IS
  M NUMBER;N NUMBER; BEGIN
  IF p_PERSONA<=0 OR p_CONCEPTO<=0 OR p_FRECUENCIA<=0 OR p_CLASE NOT IN ('F','V') OR p_MONTO IS NULL THEN RAISE_APPLICATION_ERROR(-20001,'Partida temporal invalida.'); END IF;
  SELECT COUNT(*) INTO N FROM RH.RH_NOM_PRE_CTL WHERE CODIGO_EMPRESA=p_EMPRESA AND CODIGO_TIPO_NOMINA=p_TIPO AND CODIGO_PERIODO=p_PERIODO AND ESTADO='GUARDANDO';
  IF N<>1 THEN RAISE_APPLICATION_ERROR(-20001,'Falta control de escritura temporal.'); END IF;
  M:=p_ORIGEN;
  IF M IS NULL THEN
   FOR K IN 1..100 LOOP
    SELECT RH.RH_S_CODIGO_MOV_NOMINA.NEXTVAL INTO M FROM DUAL;
    SELECT COUNT(*) INTO N FROM RH.RH_MOV_NOMINA WHERE CODIGO_MOV_NOMINA=M;
    IF N=0 THEN SELECT COUNT(*) INTO N FROM RH.RH_TMP_NOMINA WHERE CODIGO_MOV_NOMINA=M; END IF;
    EXIT WHEN N=0;
    M:=NULL;
   END LOOP;
   IF M IS NULL THEN RAISE_APPLICATION_ERROR(-20001,'No se pudo reservar identidad temporal.'); END IF;
  END IF;
  SELECT COUNT(*) INTO N FROM RH.RH_TMP_NOMINA WHERE CODIGO_MOV_NOMINA=M AND CODIGO_EMPRESA=p_EMPRESA AND CODIGO_TIPO_NOMINA=p_TIPO AND CODIGO_PERIODO=p_PERIODO;
  IF N<>0 THEN RAISE_APPLICATION_ERROR(-20001,'Identidad temporal repetida.'); END IF;
  INSERT INTO RH.RH_TMP_NOMINA(CODIGO_MOV_NOMINA,FECHA_NOMINA,CODIGO_PERIODO,CODIGO_TIPO_NOMINA,CODIGO_PERSONA,CODIGO_CONCEPTO,COMPLEMENTO_CONCEPTO,TIPO,FRECUENCIA_ID,MONTO,STATUS,EXTRA1,EXTRA2,EXTRA3,USUARIO_INS,FECHA_INS,USUARIO_UPD,FECHA_UPD,CODIGO_EMPRESA)
   VALUES(M,p_FECHA,p_PERIODO,p_TIPO,p_PERSONA,p_CONCEPTO,p_COMPLEMENTO,p_CLASE,p_FRECUENCIA,p_MONTO,p_STATUS,p_EXTRA1,p_EXTRA2,p_EXTRA3,p_USUARIO,SYSDATE,NULL,NULL,p_EMPRESA);
 END;
 PROCEDURE FINALIZAR(p_EMPRESA NUMBER,p_TIPO NUMBER,p_PERIODO NUMBER,p_ACTOR NUMBER,p_LOTE NUMBER,p_HASH VARCHAR2,p_USUARIO NUMBER) IS BEGIN
  UPDATE RH.RH_NOM_PRE_CTL SET ESTADO='GUARDADA',HASH_TMP=p_HASH WHERE CODIGO_EMPRESA=p_EMPRESA AND CODIGO_TIPO_NOMINA=p_TIPO AND CODIGO_PERIODO=p_PERIODO AND ID_LOTE=p_LOTE AND ACTOR=p_ACTOR AND ESTADO='GUARDANDO';
  IF SQL%ROWCOUNT<>1 THEN RAISE_APPLICATION_ERROR(-20002,'Control temporal cambiado.'); END IF;
  UPDATE RH.RH_PERIODOS SET FECHA_PRENOMINA=SYSDATE,USUARIO_PRENOMINA=p_USUARIO WHERE CODIGO_EMPRESA=p_EMPRESA AND CODIGO_TIPO_NOMINA=p_TIPO AND CODIGO_PERIODO=p_PERIODO;
 END;
 PROCEDURE REVERTIR(p_EMPRESA NUMBER,p_TIPO NUMBER,p_PERIODO NUMBER,p_ACTOR NUMBER,p_LOTE NUMBER,p_HASH VARCHAR2) IS A DATE;U NUMBER;BEGIN
  SELECT FECHA_PRE_ANT,USUARIO_PRE_ANT INTO A,U FROM RH.RH_NOM_PRE_CTL WHERE CODIGO_EMPRESA=p_EMPRESA AND CODIGO_TIPO_NOMINA=p_TIPO AND CODIGO_PERIODO=p_PERIODO AND ID_LOTE=p_LOTE AND ACTOR=p_ACTOR AND HASH_TMP=p_HASH AND ESTADO='GUARDADA' FOR UPDATE;
  DELETE FROM RH.RH_TMP_NOMINA WHERE CODIGO_EMPRESA=p_EMPRESA AND CODIGO_TIPO_NOMINA=p_TIPO AND CODIGO_PERIODO=p_PERIODO;
  UPDATE RH.RH_PERIODOS SET FECHA_PRENOMINA=A,USUARIO_PRENOMINA=U WHERE CODIGO_EMPRESA=p_EMPRESA AND CODIGO_TIPO_NOMINA=p_TIPO AND CODIGO_PERIODO=p_PERIODO;
  DELETE FROM RH.RH_NOM_PRE_CTL WHERE CODIGO_EMPRESA=p_EMPRESA AND CODIGO_TIPO_NOMINA=p_TIPO AND CODIGO_PERIODO=p_PERIODO AND ID_LOTE=p_LOTE AND ACTOR=p_ACTOR;
 END;
END;
