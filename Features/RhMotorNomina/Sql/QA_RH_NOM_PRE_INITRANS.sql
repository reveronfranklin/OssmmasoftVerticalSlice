-- QA guarded metadata change; no row changes or table/index rebuild.
-- Oracle 10g Serializable documentation requires INITRANS >= 3.
-- Reserve 8 for the four tables written by the reversible QA draft.
DECLARE V_INI NUMBER;
BEGIN
 IF SYS_CONTEXT('USERENV','DB_NAME')<>'XE'
 OR SYS_CONTEXT('USERENV','SERVER_HOST')<>'6d88ba053190'
 OR SYS_CONTEXT('USERENV','SESSION_USER')<>'RH' THEN
  RAISE_APPLICATION_ERROR(-20001,'Solo QA RH XE esperado.');
 END IF;
 FOR T IN (SELECT TABLE_NAME FROM ALL_TABLES WHERE OWNER='RH'
 AND TABLE_NAME IN ('RH_TMP_NOMINA','RH_PERIODOS','RH_NOM_PRE_LOT','RH_NOM_PRE_CTL')) LOOP
  SELECT INI_TRANS INTO V_INI FROM ALL_TABLES WHERE OWNER='RH' AND TABLE_NAME=T.TABLE_NAME;
  IF V_INI<8 THEN
   EXECUTE IMMEDIATE 'ALTER TABLE RH.'||T.TABLE_NAME||' INITRANS 8';
  END IF;
 END LOOP;
END;
