-- R57: diagnostico de solo lectura; no calcula ni modifica nomina.
-- :p_EMPRESA debe coincidir con settings:EmpresaConfig del ambiente.
-- No devuelve importes ni IDs/nombres de trabajadores.
SELECT CODIGO_TIPO_NOMINA, SIGLAS_TIPO_NOMINA
  FROM RH.RH_TIPOS_NOMINA
 WHERE CODIGO_EMPRESA = :p_EMPRESA
 ORDER BY CODIGO_TIPO_NOMINA;

SELECT *
  FROM (
    SELECT H.CODIGO_TIPO_NOMINA, H.CODIGO_PERIODO,
           H.FECHA_NOMINA,
           COUNT(*) PARTIDAS,
           COUNT(DISTINCT H.CODIGO_PERSONA) PERSONAS,
           SUM(CASE WHEN H.MONTO IS NULL THEN 1 ELSE 0 END) IMPORTES_NULOS,
           ROW_NUMBER() OVER (
             PARTITION BY H.CODIGO_TIPO_NOMINA
             ORDER BY H.FECHA_NOMINA DESC NULLS LAST,
                      H.CODIGO_PERIODO DESC NULLS LAST
           ) POSICION
      FROM RH.RH_HISTORICO_NOMINA H
     WHERE H.CODIGO_EMPRESA = :p_EMPRESA
     GROUP BY H.CODIGO_TIPO_NOMINA, H.CODIGO_PERIODO, H.FECHA_NOMINA
  )
 WHERE POSICION <= 4
 ORDER BY CODIGO_TIPO_NOMINA, POSICION;

-- Verificar cierre y unicidad de cada candidato, conservando sus IDs originales.
SELECT CODIGO_TIPO_NOMINA, CODIGO_PERIODO, FECHA_NOMINA,
       FECHA_CIERRE, FECHA_PRECIERRE
  FROM RH.RH_PERIODOS
 WHERE CODIGO_EMPRESA = :p_EMPRESA
   AND CODIGO_TIPO_NOMINA = :p_TIPO
   AND CODIGO_PERIODO = :p_PERIODO;
