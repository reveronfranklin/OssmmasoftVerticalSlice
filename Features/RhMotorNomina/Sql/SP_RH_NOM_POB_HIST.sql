-- Como RH. SP_RH_NOM_POB_HIST = 18 caracteres. Oracle 10g.
-- Universo completo por persona; sin importes, nombres ni datos actuales.
CREATE OR REPLACE PROCEDURE RH.SP_RH_NOM_POB_HIST (
  p_EMPRESA IN NUMBER, p_TIPO IN NUMBER, p_PERIODO IN NUMBER,
  p_FECHA IN DATE, p_RESULT OUT SYS_REFCURSOR
) AUTHID DEFINER AS
BEGIN
  IF p_EMPRESA IS NULL OR p_EMPRESA<=0 OR p_EMPRESA<>TRUNC(p_EMPRESA)
     OR p_TIPO IS NULL OR p_TIPO<=0 OR p_TIPO<>TRUNC(p_TIPO)
     OR p_PERIODO IS NULL OR p_PERIODO<=0 OR p_PERIODO<>TRUNC(p_PERIODO)
     OR p_FECHA IS NULL THEN
    RAISE_APPLICATION_ERROR(-20001,'Contexto de poblacion historica invalido.');
  END IF;
  OPEN p_RESULT FOR
    WITH C AS (
      SELECT CODIGO_PERSONA,COUNT(*) FILAS_CARGO,
             COUNT(DISTINCT CODIGO_RELACION_CARGO) RELACIONES,
             MIN(CODIGO_RELACION_CARGO) RELACION_MIN,
             SUM(CASE WHEN CODIGO_RELACION_CARGO IS NULL
                        OR CODIGO_RELACION_CARGO<=0
                        OR CODIGO_RELACION_CARGO<>TRUNC(CODIGO_RELACION_CARGO)
                      THEN 1 ELSE 0 END) REL_INVALIDAS
        FROM RH.RH_HISTORICO_PERSONAL_CARGO
       WHERE CODIGO_EMPRESA=p_EMPRESA AND CODIGO_TIPO_NOMINA=p_TIPO
         AND CODIGO_PERIODO=p_PERIODO AND FECHA_NOMINA=p_FECHA
       GROUP BY CODIGO_PERSONA
    ), N AS (
      SELECT CODIGO_PERSONA,COUNT(*) PARTIDAS
        FROM RH.RH_HISTORICO_NOMINA
       WHERE CODIGO_EMPRESA=p_EMPRESA AND CODIGO_TIPO_NOMINA=p_TIPO
         AND CODIGO_PERIODO=p_PERIODO AND FECHA_NOMINA=p_FECHA
       GROUP BY CODIGO_PERSONA
    ), K AS (
      SELECT CODIGO_PERSONA FROM C UNION SELECT CODIGO_PERSONA FROM N
    )
    SELECT * FROM (
      SELECT K.CODIGO_PERSONA,NVL(C.FILAS_CARGO,0) FILAS_CARGO,
             NVL(C.RELACIONES,0) RELACIONES,NVL(C.REL_INVALIDAS,0) REL_INVALIDAS,
             CASE WHEN C.FILAS_CARGO=1 AND C.REL_INVALIDAS=0
                  THEN C.RELACION_MIN END RELACION_UNICA,
             NVL(N.PARTIDAS,0) PARTIDAS
        FROM K LEFT JOIN C ON DECODE(K.CODIGO_PERSONA,C.CODIGO_PERSONA,1,0)=1
               LEFT JOIN N ON DECODE(K.CODIGO_PERSONA,N.CODIGO_PERSONA,1,0)=1
       WHERE (SELECT COUNT(*) FROM RH.RH_PERIODOS P
               WHERE P.CODIGO_EMPRESA=p_EMPRESA AND P.CODIGO_TIPO_NOMINA=p_TIPO
                 AND P.CODIGO_PERIODO=p_PERIODO AND P.FECHA_NOMINA=p_FECHA
                 AND P.FECHA_CIERRE IS NOT NULL)=1
       ORDER BY K.CODIGO_PERSONA NULLS FIRST
    ) WHERE ROWNUM<=5001;
END;
