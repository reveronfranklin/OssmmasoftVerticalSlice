-- Como RH. SP_RH_NOM_CTX_HIST=18 caracteres. Oracle 10g.
-- Solo lectura: contexto exacto y contadores; no devuelve personas ni importes.
CREATE OR REPLACE PROCEDURE RH.SP_RH_NOM_CTX_HIST (
  p_EMPRESA IN NUMBER, p_TIPO IN NUMBER, p_PERIODO IN NUMBER,
  p_FECHA IN DATE, p_RESULT OUT SYS_REFCURSOR
) AUTHID DEFINER AS
BEGIN
  IF p_EMPRESA IS NULL OR p_EMPRESA<=0 OR p_EMPRESA<>TRUNC(p_EMPRESA)
     OR p_TIPO IS NULL OR p_TIPO<=0 OR p_TIPO<>TRUNC(p_TIPO)
     OR p_PERIODO IS NULL OR p_PERIODO<=0 OR p_PERIODO<>TRUNC(p_PERIODO)
     OR p_FECHA IS NULL THEN
    RAISE_APPLICATION_ERROR(-20001,'Contexto historico invalido.');
  END IF;
  -- Una sola consulta mantiene consistentes contexto y contadores al mismo SCN.
  -- No TRUNC de fechas: se conserva la hora Oracle del contexto solicitado.
  OPEN p_RESULT FOR
    SELECT P.CODIGO_EMPRESA, P.CODIGO_TIPO_NOMINA, P.CODIGO_PERIODO,
           P.FECHA_NOMINA, P.FECHA_CIERRE, P.CODIGO_PRESUPUESTO,
           A.PARTIDAS, A.PERSONAS, A.MONTOS_NULOS, A.CLAVES_INVALIDAS,
           D.GRUPOS_DUPLICADOS
      FROM RH.RH_PERIODOS P,
           (SELECT COUNT(*) PARTIDAS, COUNT(DISTINCT H.CODIGO_PERSONA) PERSONAS,
                   NVL(SUM(CASE WHEN H.MONTO IS NULL THEN 1 ELSE 0 END),0) MONTOS_NULOS,
                   NVL(SUM(CASE WHEN H.CODIGO_PERSONA IS NULL OR H.CODIGO_PERSONA<=0
                                 OR H.CODIGO_CONCEPTO IS NULL OR H.CODIGO_CONCEPTO<=0
                                 OR H.FRECUENCIA_ID IS NULL OR H.FRECUENCIA_ID<=0
                                 OR H.TIPO IS NULL OR H.TIPO NOT IN ('F','V','E')
                               THEN 1 ELSE 0 END),0) CLAVES_INVALIDAS
              FROM RH.RH_HISTORICO_NOMINA H
             WHERE H.CODIGO_EMPRESA=p_EMPRESA AND H.CODIGO_TIPO_NOMINA=p_TIPO
               AND H.CODIGO_PERIODO=p_PERIODO AND H.FECHA_NOMINA=p_FECHA) A,
           (SELECT COUNT(*) GRUPOS_DUPLICADOS
              FROM (SELECT H.CODIGO_PERSONA,H.CODIGO_CONCEPTO,H.FRECUENCIA_ID,H.TIPO
                      FROM RH.RH_HISTORICO_NOMINA H
                     WHERE H.CODIGO_EMPRESA=p_EMPRESA AND H.CODIGO_TIPO_NOMINA=p_TIPO
                       AND H.CODIGO_PERIODO=p_PERIODO AND H.FECHA_NOMINA=p_FECHA
                     GROUP BY H.CODIGO_PERSONA,H.CODIGO_CONCEPTO,H.FRECUENCIA_ID,H.TIPO
                    HAVING COUNT(*)>1)) D
     WHERE P.CODIGO_EMPRESA=p_EMPRESA AND P.CODIGO_TIPO_NOMINA=p_TIPO
       AND P.CODIGO_PERIODO=p_PERIODO AND P.FECHA_NOMINA=p_FECHA;
END;
