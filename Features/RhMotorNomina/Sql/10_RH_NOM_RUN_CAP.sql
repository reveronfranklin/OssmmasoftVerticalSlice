-- Oracle 10g. CK_RH_NOM_RUN_MOD2=18. Metadata only; no payroll DML.
-- Deploy worker capable of format2 before enabling CorridasCapturaEnabled.
DECLARE n NUMBER;
BEGIN
  IF SYS_CONTEXT('USERENV','SESSION_USER')<>'RH' OR SYS_CONTEXT('USERENV','CURRENT_SCHEMA')<>'RH' THEN
    RAISE_APPLICATION_ERROR(-20001,'Instalar como RH.');
  END IF;
  SELECT COUNT(*) INTO n FROM USER_CONSTRAINTS
    WHERE TABLE_NAME='RH_NOM_RUN' AND CONSTRAINT_NAME='CK_RH_NOM_RUN_MOD2';
  IF n=0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE RH_NOM_RUN ADD CONSTRAINT CK_RH_NOM_RUN_MOD2
      CHECK(MODO IN (''LOTE_MANUAL'',''ACTUAL'',''COMPARACION_PRUEBA'',''CAPTURA_PRENOMINA'')) ENABLE VALIDATE';
  END IF;
  SELECT COUNT(*) INTO n FROM USER_CONSTRAINTS
    WHERE TABLE_NAME='RH_NOM_RUN' AND CONSTRAINT_NAME='CK_RH_NOM_RUN_MOD';
  IF n=1 THEN EXECUTE IMMEDIATE 'ALTER TABLE RH_NOM_RUN DROP CONSTRAINT CK_RH_NOM_RUN_MOD'; END IF;
END;
/
