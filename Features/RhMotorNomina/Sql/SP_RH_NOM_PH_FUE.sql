-- SP_RH_NOM_PH_FUE=16. Oracle 10g. Lecturas crudas para agregados PH.
-- No ejecuta funciones/paquetes de calculo. La multiplicidad de asociaciones
-- se aplica en C# desde el grupo congelado, no mediante joins que oculten filas.
CREATE OR REPLACE PROCEDURE RH.SP_RH_NOM_PH_FUE (
 p_EMPRESA IN NUMBER,p_TIPO IN NUMBER,p_PERIODO IN NUMBER,p_FECHA IN DATE,
 p_PERSONA IN NUMBER,p_REFERENCIA IN DATE,p_ORIGEN IN VARCHAR2,
 p_CONCEPTOS IN VARCHAR2,p_RESULT OUT SYS_REFCURSOR
) AUTHID DEFINER AS
 n NUMBER;m NUMBER;expected NUMBER;
BEGIN
 IF p_EMPRESA IS NULL OR p_EMPRESA<=0 OR p_EMPRESA<>TRUNC(p_EMPRESA)
 OR p_TIPO IS NULL OR p_TIPO<=0 OR p_TIPO<>TRUNC(p_TIPO)
 OR p_PERIODO IS NULL OR p_PERIODO<=0 OR p_PERIODO<>TRUNC(p_PERIODO)
 OR p_PERSONA IS NULL OR p_PERSONA<=0 OR p_PERSONA<>TRUNC(p_PERSONA)
 OR p_FECHA IS NULL OR p_REFERENCIA IS NULL OR p_ORIGEN IS NULL
 OR p_ORIGEN NOT IN ('ACTUAL','HISTORICO')
 OR p_CONCEPTOS IS NULL OR LENGTH(p_CONCEPTOS)>1200
 OR NOT REGEXP_LIKE(p_CONCEPTOS,'^[0-9]+(,[0-9]+)*$') THEN
  RAISE_APPLICATION_ERROR(-20001,'Contexto/origen/conceptos PH invalidos.');
 END IF;
 SELECT COUNT(*) INTO n FROM RH.RH_PERIODOS
 WHERE CODIGO_EMPRESA=p_EMPRESA AND CODIGO_TIPO_NOMINA=p_TIPO
 AND CODIGO_PERIODO=p_PERIODO AND FECHA_NOMINA=p_FECHA
 AND FECHA_CIERRE IS NULL;
 IF n<>1 THEN RAISE_APPLICATION_ERROR(-20001,'Periodo abierto unico requerido.'); END IF;
 expected:=LENGTH(p_CONCEPTOS)-LENGTH(REPLACE(p_CONCEPTOS,',',''))+1;
 IF expected>100 THEN RAISE_APPLICATION_ERROR(-20001,'Hasta 100 conceptos PH.'); END IF;
 SELECT COUNT(*),COUNT(DISTINCT CODIGO_CONCEPTO) INTO n,m FROM RH.RH_CONCEPTOS
 WHERE CODIGO_EMPRESA=p_EMPRESA AND CODIGO_TIPO_NOMINA=p_TIPO
 AND INSTR(','||p_CONCEPTOS||',',','||TO_CHAR(CODIGO_CONCEPTO,'TM9')||',')>0;
 IF n<>expected OR m<>expected THEN
  RAISE_APPLICATION_ERROR(-20001,'Conceptos PH inexistentes, duplicados o ajenos.');
 END IF;
 IF p_ORIGEN='ACTUAL' THEN
  OPEN p_RESULT FOR SELECT * FROM (
   SELECT M.CODIGO_MOV_NOMINA ID_FILA,M.CODIGO_EMPRESA,M.CODIGO_TIPO_NOMINA,
          M.CODIGO_PERSONA,M.CODIGO_CONCEPTO,M.FRECUENCIA_ID,M.TIPO,M.STATUS,
          TO_CHAR(M.MONTO,'TM9','NLS_NUMERIC_CHARACTERS=''.,''') MONTO_TEXTO
   FROM RH.RH_MOV_NOMINA M
   WHERE M.CODIGO_EMPRESA=p_EMPRESA AND M.CODIGO_TIPO_NOMINA=p_TIPO
   AND M.CODIGO_PERSONA=p_PERSONA
   AND INSTR(','||p_CONCEPTOS||',',','||TO_CHAR(M.CODIGO_CONCEPTO,'TM9')||',')>0
   ORDER BY M.CODIGO_MOV_NOMINA
  ) WHERE ROWNUM<=2001;
 ELSE
  OPEN p_RESULT FOR SELECT * FROM (
   SELECT H.CODIGO_HISTORICO_NOMINA ID_FILA,H.CODIGO_EMPRESA,H.CODIGO_TIPO_NOMINA,
          H.CODIGO_PERSONA,H.CODIGO_CONCEPTO,H.FRECUENCIA_ID,H.TIPO,H.STATUS,
          TO_CHAR(H.MONTO,'TM9','NLS_NUMERIC_CHARACTERS=''.,''') MONTO_TEXTO,
          H.CODIGO_PERIODO,H.FECHA_NOMINA,
          (SELECT COUNT(*) FROM RH.RH_PERIODOS P WHERE P.CODIGO_EMPRESA=H.CODIGO_EMPRESA
           AND P.CODIGO_TIPO_NOMINA=H.CODIGO_TIPO_NOMINA
           AND P.CODIGO_PERIODO=H.CODIGO_PERIODO AND P.FECHA_NOMINA=H.FECHA_NOMINA) PERIODOS,
          (SELECT MAX(P.FECHA_CIERRE) FROM RH.RH_PERIODOS P WHERE P.CODIGO_EMPRESA=H.CODIGO_EMPRESA
           AND P.CODIGO_TIPO_NOMINA=H.CODIGO_TIPO_NOMINA
           AND P.CODIGO_PERIODO=H.CODIGO_PERIODO AND P.FECHA_NOMINA=H.FECHA_NOMINA) FECHA_CIERRE
   FROM RH.RH_HISTORICO_NOMINA H
   WHERE H.CODIGO_EMPRESA=p_EMPRESA AND H.CODIGO_TIPO_NOMINA=p_TIPO
   AND H.CODIGO_PERSONA=p_PERSONA AND H.CODIGO_PERIODO<>p_PERIODO
   AND H.FECHA_NOMINA>=TRUNC(p_REFERENCIA,'MM')
   AND EXTRACT(YEAR FROM H.FECHA_NOMINA)=EXTRACT(YEAR FROM p_REFERENCIA)
   AND EXTRACT(MONTH FROM H.FECHA_NOMINA)=EXTRACT(MONTH FROM p_REFERENCIA)
   AND INSTR(','||p_CONCEPTOS||',',','||TO_CHAR(H.CODIGO_CONCEPTO,'TM9')||',')>0
   ORDER BY H.CODIGO_HISTORICO_NOMINA
  ) WHERE ROWNUM<=2001;
 END IF;
END;
