-- Oracle 10g: bounded, scoped CLOB read; immutable capsule storage unchanged.
CREATE OR REPLACE PROCEDURE RH.SP_RH_NOM_CAP_DOC(p_EMPRESA NUMBER,p_ACTOR NUMBER,p_ID NUMBER,p_RESULT OUT SYS_REFCURSOR) AS
BEGIN
 OPEN p_RESULT FOR SELECT DOCUMENTO,HASH_DOC HUella,DBMS_LOB.GETLENGTH(DOCUMENTO) LARGO FROM RH.RH_NOM_CAP_ARC
  WHERE CODIGO_EMPRESA=p_EMPRESA AND ACTOR=p_ACTOR AND ID_CAP=p_ID;
END;
/
