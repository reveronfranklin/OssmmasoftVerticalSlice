-- SP_RH_NOM_PER_FUE: 17 caracteres. Solo lectura; compatible Oracle 10g.
-- No entrega nombres, instituciones, cedulas ni datos bancarios.
CREATE OR REPLACE PROCEDURE RH.SP_RH_NOM_PER_FUE (
  p_EMPRESA IN NUMBER,p_PERSONA IN NUMBER,p_PROVEEDOR IN VARCHAR2,
  p_RESULT OUT SYS_REFCURSOR
) AUTHID DEFINER AS
BEGIN
  IF p_EMPRESA IS NULL OR p_EMPRESA<=0 OR p_EMPRESA<>TRUNC(p_EMPRESA)
     OR p_PERSONA IS NULL OR p_PERSONA<=0 OR p_PERSONA<>TRUNC(p_PERSONA)
     OR p_PROVEEDOR IS NULL OR p_PROVEEDOR NOT IN
       ('TITULO_EDUC_ULTIMO_REG','TITULO_EDUC_FECHA_NOMINA','FECHA_INGRESO_ADMIN_UNICO') THEN
    RAISE_APPLICATION_ERROR(-20001,'Contexto personal invalido.');
  END IF;
  IF p_PROVEEDOR='FECHA_INGRESO_ADMIN_UNICO' THEN
    OPEN p_RESULT FOR SELECT * FROM (
      SELECT A.CODIGO_ADMINISTRATIVO ID_FILA,A.CODIGO_EMPRESA EMPRESA,
             A.FECHA_INGRESO FECHA,CAST(NULL AS NUMBER) TITULO,A.STATUS ESTADO
        FROM RH.RH_ADMINISTRATIVOS A
       WHERE A.CODIGO_PERSONA=p_PERSONA
         AND (A.CODIGO_EMPRESA=p_EMPRESA OR A.CODIGO_EMPRESA IS NULL)
       ORDER BY A.CODIGO_ADMINISTRATIVO
    ) WHERE ROWNUM<=201;
  ELSE
    OPEN p_RESULT FOR SELECT * FROM (
      SELECT E.CODIGO_EDUCACION ID_FILA,E.CODIGO_EMPRESA EMPRESA,
             E.FECHA_FIN FECHA,E.TITULO_ID TITULO,CAST(NULL AS VARCHAR2(1)) ESTADO
        FROM RH.RH_EDUCACION E
       WHERE E.CODIGO_PERSONA=p_PERSONA
         AND (E.CODIGO_EMPRESA=p_EMPRESA OR E.CODIGO_EMPRESA IS NULL)
       ORDER BY E.CODIGO_EDUCACION
    ) WHERE ROWNUM<=201;
  END IF;
END;
