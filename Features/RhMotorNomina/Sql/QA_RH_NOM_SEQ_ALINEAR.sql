-- QA only. Advance the existing global movement sequence past both tables.
-- No DDL, row changes, reset, decrement, or replacement of existing identities.
-- NEXTVAL is not transactional; consumed values intentionally remain consumed.
DECLARE
 V_MAX NUMBER; V_NEXT NUMBER; V_INC NUMBER; V_CACHE NUMBER; V_CYCLE VARCHAR2(1);
BEGIN
 IF SYS_CONTEXT('USERENV','DB_NAME')<>'XE'
 OR SYS_CONTEXT('USERENV','SERVER_HOST')<>'6d88ba053190'
 OR SYS_CONTEXT('USERENV','SESSION_USER')<>'RH' THEN
  RAISE_APPLICATION_ERROR(-20001,'Solo QA RH XE esperado.');
 END IF;
 LOCK TABLE RH.RH_MOV_NOMINA IN SHARE MODE NOWAIT;
 LOCK TABLE RH.RH_TMP_NOMINA IN SHARE MODE NOWAIT;
 SELECT INCREMENT_BY,CACHE_SIZE,CYCLE_FLAG INTO V_INC,V_CACHE,V_CYCLE
 FROM ALL_SEQUENCES WHERE SEQUENCE_OWNER='RH'
 AND SEQUENCE_NAME='RH_S_CODIGO_MOV_NOMINA';
 IF V_INC<>1 OR V_CACHE<>0 OR V_CYCLE<>'N' THEN
  RAISE_APPLICATION_ERROR(-20001,'Contrato de secuencia distinto; no se modifica.');
 END IF;
 SELECT GREATEST(NVL((SELECT MAX(CODIGO_MOV_NOMINA) FROM RH.RH_MOV_NOMINA),0),
 NVL((SELECT MAX(CODIGO_MOV_NOMINA) FROM RH.RH_TMP_NOMINA),0)) INTO V_MAX FROM DUAL;
 FOR I IN 1..10000 LOOP
  SELECT RH.RH_S_CODIGO_MOV_NOMINA.NEXTVAL INTO V_NEXT FROM DUAL;
  EXIT WHEN V_NEXT>V_MAX;
 END LOOP;
 IF V_NEXT<=V_MAX THEN
  RAISE_APPLICATION_ERROR(-20001,'Limite de avance; requiere revision.');
 END IF;
 :p_MAXIMO:=V_MAX;
 :p_ULTIMO:=V_NEXT;
END;
