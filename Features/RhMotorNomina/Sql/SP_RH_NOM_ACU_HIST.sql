-- Oracle 10g. SP_RH_NOM_ACU_HIST=18. Solo lectura; no invoca paquete legacy.
-- Ventana calendario anterior [primer dia - meses, primer dia objetivo).
-- Subconsultas escalares detectan periodo ausente/duplicado sin multiplicar filas.
CREATE OR REPLACE PROCEDURE RH.SP_RH_NOM_ACU_HIST (
 p_EMPRESA NUMBER,p_TIPO NUMBER,p_PERIODO NUMBER,p_FECHA DATE,p_PERSONA NUMBER,
 p_MESES NUMBER,p_DESDE DATE,p_CONCEPTOS VARCHAR2,p_RESULT OUT SYS_REFCURSOR
) AUTHID DEFINER AS
 n NUMBER;
BEGIN
 IF p_EMPRESA IS NULL OR p_EMPRESA<=0 OR p_EMPRESA<>TRUNC(p_EMPRESA)
 OR p_TIPO IS NULL OR p_TIPO<=0 OR p_TIPO<>TRUNC(p_TIPO)
 OR p_PERIODO IS NULL OR p_PERIODO<=0 OR p_PERIODO<>TRUNC(p_PERIODO)
 OR p_PERSONA IS NULL OR p_PERSONA<=0 OR p_PERSONA<>TRUNC(p_PERSONA)
 OR p_FECHA IS NULL OR p_MESES IS NULL OR p_MESES NOT BETWEEN 1 AND 24
 OR p_MESES<>TRUNC(p_MESES) OR p_DESDE IS NULL OR p_DESDE<>TRUNC(p_DESDE,'MM')
 OR (EXTRACT(YEAR FROM p_FECHA)-EXTRACT(YEAR FROM p_DESDE))*12
    +EXTRACT(MONTH FROM p_FECHA)-EXTRACT(MONTH FROM p_DESDE)<>p_MESES OR p_CONCEPTOS IS NULL OR LENGTH(p_CONCEPTOS)>1200
 OR NOT REGEXP_LIKE(p_CONCEPTOS,'^[0-9]+(,[0-9]+)*$') THEN
  RAISE_APPLICATION_ERROR(-20001,'Contexto/ventana/conceptos historicos invalidos.');
 END IF;
 SELECT COUNT(*) INTO n FROM RH.RH_PERIODOS
 WHERE CODIGO_EMPRESA=p_EMPRESA AND CODIGO_TIPO_NOMINA=p_TIPO
 AND CODIGO_PERIODO=p_PERIODO AND FECHA_NOMINA=p_FECHA;
 IF n<>1 THEN RAISE_APPLICATION_ERROR(-20001,'Periodo objetivo unico requerido.'); END IF;
 OPEN p_RESULT FOR SELECT * FROM (
  SELECT H.CODIGO_HISTORICO_NOMINA,H.CODIGO_EMPRESA,H.CODIGO_TIPO_NOMINA,
   H.CODIGO_PERIODO,H.FECHA_NOMINA,H.CODIGO_PERSONA,H.CODIGO_CONCEPTO,
   H.FRECUENCIA_ID,H.TIPO,H.STATUS,
   TO_CHAR(H.MONTO,'TM9','NLS_NUMERIC_CHARACTERS=''.,''') MONTO_TEXTO,
   (SELECT COUNT(*) FROM RH.RH_PERIODOS P WHERE P.CODIGO_EMPRESA=H.CODIGO_EMPRESA
    AND P.CODIGO_TIPO_NOMINA=H.CODIGO_TIPO_NOMINA AND P.CODIGO_PERIODO=H.CODIGO_PERIODO
    AND P.FECHA_NOMINA=H.FECHA_NOMINA) PERIODOS,
   (SELECT MAX(P.FECHA_CIERRE) FROM RH.RH_PERIODOS P WHERE P.CODIGO_EMPRESA=H.CODIGO_EMPRESA
    AND P.CODIGO_TIPO_NOMINA=H.CODIGO_TIPO_NOMINA AND P.CODIGO_PERIODO=H.CODIGO_PERIODO
    AND P.FECHA_NOMINA=H.FECHA_NOMINA) FECHA_CIERRE
  FROM RH.RH_HISTORICO_NOMINA H
  WHERE H.CODIGO_EMPRESA=p_EMPRESA AND H.CODIGO_TIPO_NOMINA=p_TIPO
    AND H.CODIGO_PERSONA=p_PERSONA AND H.CODIGO_PERIODO<>p_PERIODO
    -- p_DESDE is computed using Gregorian DateTime; validated above without NLS calendar.
    AND H.FECHA_NOMINA>=p_DESDE
    AND H.FECHA_NOMINA<TRUNC(p_FECHA,'MM')
    AND INSTR(','||p_CONCEPTOS||',',','||TO_CHAR(H.CODIGO_CONCEPTO,'TM9')||',')>0
  ORDER BY H.CODIGO_HISTORICO_NOMINA
 ) WHERE ROWNUM<=2001;
END;
