-- SP_RH_NOM_BASE_PER=18 caracteres. Oracle 10g. Solo lectura.
-- No incorpora las salidas esperadas del modelo en la base de entrada.
CREATE OR REPLACE PROCEDURE RH.SP_RH_NOM_BASE_PER (
 p_EMPRESA IN NUMBER,p_TIPO IN NUMBER,p_PERIODO IN NUMBER,p_FECHA IN DATE,
 p_PERSONA IN NUMBER,p_RELACION IN NUMBER,p_CONCEPTOS IN VARCHAR2,
 p_SALIDAS IN VARCHAR2,p_RESULT OUT SYS_REFCURSOR
) AUTHID DEFINER AS
 n NUMBER;m NUMBER;closed_at DATE;
BEGIN
 IF p_EMPRESA IS NULL OR p_EMPRESA<=0 OR p_EMPRESA<>TRUNC(p_EMPRESA)
 OR p_TIPO IS NULL OR p_TIPO<=0 OR p_TIPO<>TRUNC(p_TIPO)
 OR p_PERIODO IS NULL OR p_PERIODO<=0 OR p_PERIODO<>TRUNC(p_PERIODO)
 OR p_PERSONA IS NULL OR p_PERSONA<=0 OR p_PERSONA<>TRUNC(p_PERSONA)
 OR p_RELACION IS NULL OR p_RELACION<=0 OR p_RELACION<>TRUNC(p_RELACION)
 OR p_FECHA IS NULL OR p_CONCEPTOS IS NULL OR LENGTH(p_CONCEPTOS)>1200
 OR p_SALIDAS IS NULL OR LENGTH(p_SALIDAS)>1200
 OR NOT REGEXP_LIKE(p_CONCEPTOS,'^[0-9]+(,[0-9]+)*$')
 OR NOT REGEXP_LIKE(p_SALIDAS,'^[0-9]+(,[0-9]+)*$')
 OR LENGTH(p_CONCEPTOS)-LENGTH(REPLACE(p_CONCEPTOS,',',''))+1>100
 OR LENGTH(p_SALIDAS)-LENGTH(REPLACE(p_SALIDAS,',',''))+1>100 THEN
  RAISE_APPLICATION_ERROR(-20001,'Contexto y conjuntos explicitos requeridos.');
 END IF;
 SELECT COUNT(*),MAX(FECHA_CIERRE) INTO n,closed_at FROM RH.RH_PERIODOS
 WHERE CODIGO_EMPRESA=p_EMPRESA AND CODIGO_TIPO_NOMINA=p_TIPO
 AND CODIGO_PERIODO=p_PERIODO AND FECHA_NOMINA=p_FECHA;
 IF n<>1 OR closed_at IS NULL THEN
  RAISE_APPLICATION_ERROR(-20001,'Periodo cerrado unico requerido.'); END IF;
 SELECT COUNT(*),SUM(DECODE(CODIGO_RELACION_CARGO,p_RELACION,1,0))
 INTO n,m FROM RH.RH_HISTORICO_PERSONAL_CARGO
 WHERE CODIGO_EMPRESA=p_EMPRESA AND CODIGO_TIPO_NOMINA=p_TIPO
 AND CODIGO_PERIODO=p_PERIODO AND FECHA_NOMINA=p_FECHA
 AND CODIGO_PERSONA=p_PERSONA;
 IF n<>1 OR NVL(m,0)<>1 THEN
  RAISE_APPLICATION_ERROR(-20001,'Base por persona requiere un solo cargo; defina segmentacion.');
 END IF;
 OPEN p_RESULT FOR SELECT * FROM (
  SELECT H.CODIGO_HISTORICO_NOMINA ID_FILA,H.CODIGO_EMPRESA,H.CODIGO_TIPO_NOMINA,
   H.CODIGO_PERSONA,H.CODIGO_CONCEPTO,H.FRECUENCIA_ID,H.TIPO,H.STATUS,
   TO_CHAR(H.MONTO,'TM9','NLS_NUMERIC_CHARACTERS=''.,''') MONTO_TEXTO,
   closed_at FECHA_CIERRE
  FROM RH.RH_HISTORICO_NOMINA H
  WHERE H.CODIGO_EMPRESA=p_EMPRESA AND H.CODIGO_TIPO_NOMINA=p_TIPO
  AND H.CODIGO_PERIODO=p_PERIODO AND H.FECHA_NOMINA=p_FECHA
  AND H.CODIGO_PERSONA=p_PERSONA
  AND INSTR(','||p_CONCEPTOS||',',','||TO_CHAR(H.CODIGO_CONCEPTO,'TM9')||',')>0
  AND INSTR(','||p_SALIDAS||',',','||TO_CHAR(H.CODIGO_CONCEPTO,'TM9')||',')=0
  ORDER BY H.CODIGO_HISTORICO_NOMINA
 ) WHERE ROWNUM<=2001;
END;
