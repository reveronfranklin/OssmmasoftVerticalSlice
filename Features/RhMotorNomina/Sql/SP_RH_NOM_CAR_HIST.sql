-- Como RH. SP_RH_NOM_CAR_HIST=18 caracteres. Oracle 10g.
-- Lectura individual de snapshot. Sin nombres, cedulas, cuentas ni tablas actuales.
CREATE OR REPLACE PROCEDURE RH.SP_RH_NOM_CAR_HIST (
  p_EMPRESA IN NUMBER, p_TIPO IN NUMBER, p_PERIODO IN NUMBER, p_FECHA IN DATE,
  p_PERSONA IN NUMBER, p_RELACION IN NUMBER, p_RESULT OUT SYS_REFCURSOR
) AUTHID DEFINER AS
BEGIN
  IF p_EMPRESA IS NULL OR p_EMPRESA<=0 OR p_EMPRESA<>TRUNC(p_EMPRESA)
     OR p_TIPO IS NULL OR p_TIPO<=0 OR p_TIPO<>TRUNC(p_TIPO)
     OR p_PERIODO IS NULL OR p_PERIODO<=0 OR p_PERIODO<>TRUNC(p_PERIODO)
     OR p_PERSONA IS NULL OR p_PERSONA<=0 OR p_PERSONA<>TRUNC(p_PERSONA)
     OR p_RELACION IS NULL OR p_RELACION<=0 OR p_RELACION<>TRUNC(p_RELACION)
     OR p_FECHA IS NULL THEN
    RAISE_APPLICATION_ERROR(-20001,'Contexto de snapshot invalido.');
  END IF;
  OPEN p_RESULT FOR
    SELECT S.CODIGO_EMPRESA,S.CODIGO_TIPO_NOMINA,S.CODIGO_PERIODO,S.FECHA_NOMINA,
           S.CODIGO_PERSONA,S.CODIGO_RELACION_CARGO,S.CODIGO_CARGO,
           TO_CHAR(S.SUELDO,'TM9','NLS_NUMERIC_CHARACTERS=''.,''') SUELDO_TEXTO,S.FRECUENCIA_PAGO_ID,S.FECHA_INGRESO
      FROM RH.RH_HISTORICO_PERSONAL_CARGO S
     WHERE S.CODIGO_EMPRESA=p_EMPRESA AND S.CODIGO_TIPO_NOMINA=p_TIPO
       AND S.CODIGO_PERIODO=p_PERIODO AND S.FECHA_NOMINA=p_FECHA
       AND S.CODIGO_PERSONA=p_PERSONA AND S.CODIGO_RELACION_CARGO=p_RELACION
       AND EXISTS (SELECT 1 FROM RH.RH_PERIODOS P
                    WHERE P.CODIGO_EMPRESA=p_EMPRESA AND P.CODIGO_TIPO_NOMINA=p_TIPO
                      AND P.CODIGO_PERIODO=p_PERIODO AND P.FECHA_NOMINA=p_FECHA
                      AND P.FECHA_CIERRE IS NOT NULL);
END;
