-- Oracle 10g: SP_RH_NOM_PRE_FUE=17. Source reads for a whole ordinary period.
CREATE OR REPLACE PROCEDURE RH.SP_RH_NOM_PRE_FUE
(p_EMPRESA NUMBER,p_TIPO NUMBER,p_PERIODO NUMBER,p_ORIGEN VARCHAR2,p_RESULT OUT SYS_REFCURSOR)
AS
BEGIN
  IF p_EMPRESA IS NULL OR p_EMPRESA<=0 OR p_TIPO IS NULL OR p_TIPO<=0 OR p_PERIODO IS NULL OR p_PERIODO<=0 THEN
    RAISE_APPLICATION_ERROR(-20001,'Ambito de prenomina invalido.');
  END IF;
  IF p_ORIGEN='PERIODO' THEN
    OPEN p_RESULT FOR SELECT P.CODIGO_PERIODO,P.CODIGO_TIPO_NOMINA,P.FECHA_NOMINA,P.PERIODO,P.TIPO_NOMINA,
      T.CODIGO_PRESUPUESTO_ACTUAL,P.CODIGO_PRESUPUESTO,P.FECHA_PRECIERRE,P.FECHA_CIERRE
      FROM RH.RH_PERIODOS P JOIN RH.RH_TIPOS_NOMINA T ON T.CODIGO_EMPRESA=P.CODIGO_EMPRESA AND T.CODIGO_TIPO_NOMINA=P.CODIGO_TIPO_NOMINA
      WHERE P.CODIGO_EMPRESA=p_EMPRESA AND P.CODIGO_TIPO_NOMINA=p_TIPO AND P.CODIGO_PERIODO=p_PERIODO;
  ELSIF p_ORIGEN='PERSONAS' THEN
    OPEN p_RESULT FOR SELECT R.CODIGO_PERSONA,R.CODIGO_RELACION_CARGO,
      TRIM(P.NOMBRE||' '||P.APELLIDO) NOMBRE,TO_CHAR(P.CEDULA) CEDULA,P.STATUS,
      CASE WHEN R.SUELDO IS NOT NULL AND (R.FECHA_INI IS NULL OR R.FECHA_INI<=F.FECHA_NOMINA)
        AND (R.FECHA_INI_VIGENCIA IS NULL OR R.FECHA_INI_VIGENCIA<=F.FECHA_NOMINA)
        AND (R.FECHA_FIN_VIGENCIA IS NULL OR R.FECHA_FIN_VIGENCIA>=F.FECHA_NOMINA) THEN 1 ELSE 0 END VIGENTE,
      (SELECT COUNT(*) FROM RH.RH_V_PERSONAL_CARGO V WHERE V.CODIGO_EMPRESA=R.CODIGO_EMPRESA AND V.CODIGO_TIPO_NOMINA=R.CODIGO_TIPO_NOMINA
        AND V.CODIGO_PERSONA=R.CODIGO_PERSONA AND V.CODIGO_RELACION_CARGO=R.CODIGO_RELACION_CARGO AND V.STATUS IN ('A','I','R')) COINCIDENCIAS
      FROM RH.RH_RELACION_CARGOS R JOIN RH.RH_TIPOS_NOMINA T ON T.CODIGO_EMPRESA=R.CODIGO_EMPRESA AND T.CODIGO_TIPO_NOMINA=R.CODIGO_TIPO_NOMINA
        AND R.CODIGO_PRESUPUESTO=T.CODIGO_PRESUPUESTO_ACTUAL
      JOIN RH.RH_PERIODOS F ON F.CODIGO_EMPRESA=R.CODIGO_EMPRESA AND F.CODIGO_TIPO_NOMINA=R.CODIGO_TIPO_NOMINA AND F.CODIGO_PERIODO=p_PERIODO
      LEFT JOIN RH.RH_PERSONAS P ON P.CODIGO_PERSONA=R.CODIGO_PERSONA AND P.CODIGO_EMPRESA=R.CODIGO_EMPRESA
      WHERE R.CODIGO_EMPRESA=p_EMPRESA AND R.CODIGO_TIPO_NOMINA=p_TIPO AND R.FECHA_FIN IS NULL
      ORDER BY R.CODIGO_PERSONA,R.CODIGO_RELACION_CARGO;
  ELSIF p_ORIGEN='CONCEPTOS' THEN
    OPEN p_RESULT FOR SELECT C.CODIGO_EMPRESA,C.CODIGO_TIPO_NOMINA,C.CODIGO_CONCEPTO,C.CODIGO,C.DENOMINACION,C.TIPO_CONCEPTO,C.FRECUENCIA_ID,C.STATUS,C.AUTOMATICO,C.EXTRA1,D.CODIGO MODULO,P.CODIGO PADRE
      FROM RH.RH_CONCEPTOS C LEFT JOIN RH.RH_DESCRIPTIVAS D ON D.DESCRIPCION_ID=C.MODULO_ID
      LEFT JOIN RH.RH_DESCRIPTIVAS P ON P.DESCRIPCION_ID=D.DESCRIPCION_FK_ID
      WHERE C.CODIGO_EMPRESA=p_EMPRESA AND C.CODIGO_TIPO_NOMINA=p_TIPO ORDER BY C.CODIGO_CONCEPTO;
  ELSIF p_ORIGEN='FRECUENCIAS' THEN
    OPEN p_RESULT FOR SELECT D.DESCRIPCION_ID,D.CODIGO FROM RH.RH_DESCRIPTIVAS D
      WHERE EXISTS(SELECT 1 FROM RH.RH_CONCEPTOS C WHERE C.CODIGO_EMPRESA=p_EMPRESA AND C.CODIGO_TIPO_NOMINA=p_TIPO AND C.FRECUENCIA_ID=D.DESCRIPCION_ID)
      OR EXISTS(SELECT 1 FROM RH.RH_MOV_NOMINA M WHERE M.CODIGO_EMPRESA=p_EMPRESA AND M.CODIGO_TIPO_NOMINA=p_TIPO AND M.FRECUENCIA_ID=D.DESCRIPCION_ID)
      ORDER BY D.DESCRIPCION_ID;
  ELSIF p_ORIGEN='TEMPORAL' THEN
    OPEN p_RESULT FOR SELECT CODIGO_MOV_NOMINA,FECHA_NOMINA,CODIGO_PERIODO,CODIGO_TIPO_NOMINA,CODIGO_PERSONA,CODIGO_CONCEPTO,COMPLEMENTO_CONCEPTO,TIPO,FRECUENCIA_ID,
      TO_CHAR(MONTO,'TM9','NLS_NUMERIC_CHARACTERS=''.,''') MONTO_TEXTO,STATUS,EXTRA1,EXTRA2,EXTRA3,USUARIO_INS,FECHA_INS,USUARIO_UPD,FECHA_UPD,CODIGO_EMPRESA
      FROM RH.RH_TMP_NOMINA WHERE CODIGO_EMPRESA=p_EMPRESA AND CODIGO_TIPO_NOMINA=p_TIPO AND CODIGO_PERIODO=p_PERIODO
      ORDER BY CODIGO_MOV_NOMINA,CODIGO_PERSONA,CODIGO_CONCEPTO;
  ELSE RAISE_APPLICATION_ERROR(-20001,'Fuente de prenomina invalida.'); END IF;
END;
