-- Oracle 10g. RH_NOM_FIN_PLAN=15, RH_NOM_FIN_PLAN_SEQ=19,
-- RH_PKG_NOM_FIN_PLAN=19, TR_RH_NOM_FIN_PLAN_IMM=22. No payroll DML.
DECLARE n NUMBER;
BEGIN
  IF SYS_CONTEXT('USERENV','SESSION_USER')<>'RH' OR SYS_CONTEXT('USERENV','CURRENT_SCHEMA')<>'RH' THEN
    RAISE_APPLICATION_ERROR(-20001,'Instalar como RH.');
  END IF;
  SELECT COUNT(*) INTO n FROM USER_OBJECTS WHERE OBJECT_NAME='RH_NOM_FIN_PLAN';
  IF n=0 THEN
    EXECUTE IMMEDIATE 'CREATE TABLE RH_NOM_FIN_PLAN (
      ID_PLAN NUMBER(10) NOT NULL,CODIGO_EMPRESA NUMBER(10) NOT NULL,ACTOR NUMBER(10) NOT NULL,
      CLAVE_SOL VARCHAR2(80 CHAR) NOT NULL,HASH_SOL VARCHAR2(64 CHAR) NOT NULL,
      DOCUMENTO CLOB NOT NULL,HASH_DOC VARCHAR2(64 CHAR) NOT NULL,
      FECHA_INS DATE DEFAULT SYSDATE NOT NULL,
      CONSTRAINT PK_RH_NOM_FIN_PLAN PRIMARY KEY(ID_PLAN),
      CONSTRAINT UK_RH_NOM_FIN_PLAN UNIQUE(CODIGO_EMPRESA,ACTOR,CLAVE_SOL),
      CONSTRAINT CK_RH_NOM_FIN_PLAN_POS CHECK(ID_PLAN>0 AND CODIGO_EMPRESA>0 AND ACTOR>0))';
  ELSE
    SELECT COUNT(*) INTO n FROM USER_OBJECTS WHERE OBJECT_NAME='RH_NOM_FIN_PLAN' AND OBJECT_TYPE='TABLE';
    IF n<>1 THEN RAISE_APPLICATION_ERROR(-20001,'Conflicto de nombre RH_NOM_FIN_PLAN.'); END IF;
  END IF;
  SELECT COUNT(*) INTO n FROM USER_OBJECTS WHERE OBJECT_NAME='RH_NOM_FIN_PLAN_SEQ';
  IF n=0 THEN EXECUTE IMMEDIATE 'CREATE SEQUENCE RH_NOM_FIN_PLAN_SEQ START WITH 1 INCREMENT BY 1 MAXVALUE 2147483647 NOCYCLE CACHE 20'; END IF;
END;
/
CREATE OR REPLACE TRIGGER TR_RH_NOM_FIN_PLAN_IMM
BEFORE UPDATE OR DELETE ON RH_NOM_FIN_PLAN
BEGIN
  RAISE_APPLICATION_ERROR(-20004,'El plan financiero previo es inmutable.');
END;
/
CREATE OR REPLACE PACKAGE RH_PKG_NOM_FIN_PLAN AS
  PROCEDURE CREAR(p_EMPRESA NUMBER,p_ACTOR NUMBER,p_CLAVE VARCHAR2,p_HASH_SOL VARCHAR2,
    p_DOC CLOB,p_HASH_DOC VARCHAR2,p_ID OUT NUMBER);
  PROCEDURE POR_CLAVE(p_EMPRESA NUMBER,p_ACTOR NUMBER,p_CLAVE VARCHAR2,p_RESULT OUT SYS_REFCURSOR);
  PROCEDURE LEER(p_EMPRESA NUMBER,p_ACTOR NUMBER,p_ID NUMBER,p_RESULT OUT SYS_REFCURSOR);
  PROCEDURE DOCUMENTO(p_EMPRESA NUMBER,p_ACTOR NUMBER,p_ID NUMBER,p_RESULT OUT SYS_REFCURSOR);
  PROCEDURE LISTAR(p_EMPRESA NUMBER,p_ACTOR NUMBER,p_PAGE NUMBER,p_SIZE NUMBER,
    p_RESULT OUT SYS_REFCURSOR,p_TOTAL OUT NUMBER);
END;
/
CREATE OR REPLACE PACKAGE BODY RH_PKG_NOM_FIN_PLAN AS
  PROCEDURE CREAR(p_EMPRESA NUMBER,p_ACTOR NUMBER,p_CLAVE VARCHAR2,p_HASH_SOL VARCHAR2,
    p_DOC CLOB,p_HASH_DOC VARCHAR2,p_ID OUT NUMBER) IS
    v_actor NUMBER;v_hash VARCHAR2(64);v_count NUMBER;
  BEGIN
    IF p_EMPRESA IS NULL OR p_EMPRESA<=0 OR p_ACTOR IS NULL OR p_ACTOR<=0
      OR p_CLAVE IS NULL OR LENGTH(p_CLAVE)>80 OR NOT REGEXP_LIKE(p_CLAVE,'^[A-Za-z0-9:_-]+$')
      OR p_HASH_SOL IS NULL OR NOT REGEXP_LIKE(p_HASH_SOL,'^[A-F0-9]{64}$')
      OR p_HASH_DOC IS NULL OR NOT REGEXP_LIKE(p_HASH_DOC,'^[A-F0-9]{64}$')
      OR p_DOC IS NULL OR DBMS_LOB.GETLENGTH(p_DOC)<1 OR DBMS_LOB.GETLENGTH(p_DOC)>4194304 THEN
      RAISE_APPLICATION_ERROR(-20001,'Plan previo invalido.');
    END IF;
    BEGIN INSERT INTO RH_NOM_RUN_ACT(CODIGO_EMPRESA,ACTOR) VALUES(p_EMPRESA,p_ACTOR);
      EXCEPTION WHEN DUP_VAL_ON_INDEX THEN NULL; END;
    SELECT ACTOR INTO v_actor FROM RH_NOM_RUN_ACT
      WHERE CODIGO_EMPRESA=p_EMPRESA AND ACTOR=p_ACTOR FOR UPDATE;
    BEGIN
      SELECT ID_PLAN,HASH_SOL INTO p_ID,v_hash FROM RH_NOM_FIN_PLAN
       WHERE CODIGO_EMPRESA=p_EMPRESA AND ACTOR=p_ACTOR AND CLAVE_SOL=p_CLAVE;
      IF v_hash<>p_HASH_SOL THEN RAISE_APPLICATION_ERROR(-20001,'La clave identifica otro plan.'); END IF;
      RETURN;
    EXCEPTION WHEN NO_DATA_FOUND THEN NULL; END;
    SELECT COUNT(*) INTO v_count FROM RH_NOM_FIN_PLAN WHERE CODIGO_EMPRESA=p_EMPRESA AND ACTOR=p_ACTOR;
    IF v_count>=500 THEN RAISE_APPLICATION_ERROR(-20001,'Limite de planes previos del usuario.'); END IF;
    p_ID:=RH_NOM_FIN_PLAN_SEQ.NEXTVAL;
    INSERT INTO RH_NOM_FIN_PLAN(ID_PLAN,CODIGO_EMPRESA,ACTOR,CLAVE_SOL,HASH_SOL,DOCUMENTO,HASH_DOC)
      VALUES(p_ID,p_EMPRESA,p_ACTOR,p_CLAVE,p_HASH_SOL,p_DOC,p_HASH_DOC);
    -- Caller owns commit/rollback. This journal grants no movement ownership.
  END;
  PROCEDURE POR_CLAVE(p_EMPRESA NUMBER,p_ACTOR NUMBER,p_CLAVE VARCHAR2,p_RESULT OUT SYS_REFCURSOR) IS
  BEGIN OPEN p_RESULT FOR SELECT ID_PLAN,CODIGO_EMPRESA,ACTOR,CLAVE_SOL,HASH_SOL,HASH_DOC,FECHA_INS
    FROM RH_NOM_FIN_PLAN WHERE CODIGO_EMPRESA=p_EMPRESA AND ACTOR=p_ACTOR AND CLAVE_SOL=p_CLAVE; END;
  PROCEDURE LEER(p_EMPRESA NUMBER,p_ACTOR NUMBER,p_ID NUMBER,p_RESULT OUT SYS_REFCURSOR) IS
  BEGIN OPEN p_RESULT FOR SELECT ID_PLAN,CODIGO_EMPRESA,ACTOR,CLAVE_SOL,HASH_SOL,HASH_DOC,FECHA_INS
    FROM RH_NOM_FIN_PLAN WHERE CODIGO_EMPRESA=p_EMPRESA AND ACTOR=p_ACTOR AND ID_PLAN=p_ID; END;
  PROCEDURE DOCUMENTO(p_EMPRESA NUMBER,p_ACTOR NUMBER,p_ID NUMBER,p_RESULT OUT SYS_REFCURSOR) IS
  BEGIN OPEN p_RESULT FOR SELECT X.HUELLA,X.LARGO,N.PARTE,
    DBMS_LOB.SUBSTR(X.DOC,1000,(N.PARTE-1)*1000+1) FRAGMENTO
    FROM (SELECT DOCUMENTO DOC,HASH_DOC HUELLA,DBMS_LOB.GETLENGTH(DOCUMENTO) LARGO
      FROM RH_NOM_FIN_PLAN WHERE CODIGO_EMPRESA=p_EMPRESA AND ACTOR=p_ACTOR AND ID_PLAN=p_ID) X,
      (SELECT LEVEL PARTE FROM DUAL CONNECT BY LEVEL<=4195) N
    WHERE N.PARTE<=CEIL(X.LARGO/1000) ORDER BY N.PARTE;
  END;
  PROCEDURE LISTAR(p_EMPRESA NUMBER,p_ACTOR NUMBER,p_PAGE NUMBER,p_SIZE NUMBER,
    p_RESULT OUT SYS_REFCURSOR,p_TOTAL OUT NUMBER) IS
  BEGIN
    IF p_PAGE IS NULL OR p_PAGE<1 OR p_PAGE>100000 OR p_PAGE<>TRUNC(p_PAGE)
      OR p_SIZE IS NULL OR p_SIZE<1 OR p_SIZE>100 OR p_SIZE<>TRUNC(p_SIZE) THEN
      RAISE_APPLICATION_ERROR(-20001,'Pagina invalida.'); END IF;
    SELECT COUNT(*) INTO p_TOTAL FROM RH_NOM_FIN_PLAN WHERE CODIGO_EMPRESA=p_EMPRESA AND ACTOR=p_ACTOR;
    OPEN p_RESULT FOR SELECT * FROM (SELECT ID_PLAN,CODIGO_EMPRESA,ACTOR,CLAVE_SOL,HASH_SOL,HASH_DOC,FECHA_INS,
      ROW_NUMBER() OVER(ORDER BY ID_PLAN DESC) RN FROM RH_NOM_FIN_PLAN WHERE CODIGO_EMPRESA=p_EMPRESA AND ACTOR=p_ACTOR)
      WHERE RN>(p_PAGE-1)*p_SIZE AND RN<=p_PAGE*p_SIZE;
  END;
END;
