CREATE OR REPLACE PACKAGE RH_PKG_NOM_CFG AS
  PROCEDURE VARS_GET(p_EMPRESA NUMBER,p_PAGE NUMBER,p_SIZE NUMBER,p_SEARCH VARCHAR2,
    p_RESULT OUT SYS_REFCURSOR,p_TOTAL OUT NUMBER);
  PROCEDURE VARS_LOTE(p_EMPRESA NUMBER,p_IDS VARCHAR2,p_RESULT OUT SYS_REFCURSOR);
  PROCEDURE VAR_SAVE(p_EMPRESA NUMBER,p_ACTOR NUMBER,p_ID NUMBER,p_VERSION NUMBER,
    p_CODIGO VARCHAR2,p_DESCRIPCION VARCHAR2,p_TIPO VARCHAR2,p_UNIDAD VARCHAR2,
    p_ORIGEN VARCHAR2,p_ACTIVA NUMBER,p_ID_OUT OUT NUMBER,p_VERSION_OUT OUT NUMBER);
  PROCEDURE MODELOS_GET(p_EMPRESA NUMBER,p_PAGE NUMBER,p_SIZE NUMBER,p_SEARCH VARCHAR2,
    p_RESULT OUT SYS_REFCURSOR,p_TOTAL OUT NUMBER);
  PROCEDURE VER_SAVE(p_EMPRESA NUMBER,p_ACTOR NUMBER,p_MODELO NUMBER,p_VERSION NUMBER,
    p_NOMINA NUMBER,p_ESCENARIO VARCHAR2,p_DESCRIPCION VARCHAR2,p_CONFIG CLOB,
    p_HASH VARCHAR2,p_REFS CLOB,p_CANT_VAR NUMBER,p_VERSION_OUT OUT NUMBER);
  PROCEDURE VER_GET(p_EMPRESA NUMBER,p_MODELO NUMBER,p_VERSION NUMBER,p_RESULT OUT SYS_REFCURSOR);
END RH_PKG_NOM_CFG;
/
CREATE OR REPLACE PACKAGE BODY RH_PKG_NOM_CFG AS
  PROCEDURE contexto(p_EMPRESA NUMBER,p_ACTOR NUMBER) IS
  BEGIN
    IF p_EMPRESA IS NULL OR p_EMPRESA<=0 OR p_ACTOR IS NULL OR p_ACTOR<=0 THEN
      RAISE_APPLICATION_ERROR(-20001,'Empresa/actor invalidos.');
    END IF;
  END;
  PROCEDURE pagina(p_PAGE NUMBER,p_SIZE NUMBER,p_SEARCH VARCHAR2) IS
  BEGIN
    IF p_PAGE IS NULL OR p_PAGE<1 OR p_PAGE>100000 OR p_PAGE<>TRUNC(p_PAGE)
       OR p_SIZE IS NULL OR p_SIZE<1 OR p_SIZE>100 OR p_SIZE<>TRUNC(p_SIZE)
       OR LENGTH(p_SEARCH)>100 THEN
      RAISE_APPLICATION_ERROR(-20001,'Paginacion invalida.');
    END IF;
  END;
  PROCEDURE VARS_GET(p_EMPRESA NUMBER,p_PAGE NUMBER,p_SIZE NUMBER,p_SEARCH VARCHAR2,
    p_RESULT OUT SYS_REFCURSOR,p_TOTAL OUT NUMBER) IS
  BEGIN
    contexto(p_EMPRESA,1); pagina(p_PAGE,p_SIZE,p_SEARCH);
    SELECT COUNT(*) INTO p_TOTAL FROM RH_NOM_VAR
     WHERE CODIGO_EMPRESA=p_EMPRESA AND (p_SEARCH IS NULL OR INSTR(UPPER(CODIGO||' '||DESCRIPCION),UPPER(p_SEARCH))>0);
    OPEN p_RESULT FOR
      SELECT * FROM (SELECT V.*,ROW_NUMBER() OVER(ORDER BY CODIGO,ID_VAR) RN FROM RH_NOM_VAR V
       WHERE CODIGO_EMPRESA=p_EMPRESA AND (p_SEARCH IS NULL OR INSTR(UPPER(CODIGO||' '||DESCRIPCION),UPPER(p_SEARCH))>0))
       WHERE RN BETWEEN (p_PAGE-1)*p_SIZE+1 AND p_PAGE*p_SIZE ORDER BY RN;
  END;
  PROCEDURE VARS_LOTE(p_EMPRESA NUMBER,p_IDS VARCHAR2,p_RESULT OUT SYS_REFCURSOR) IS
  BEGIN
    contexto(p_EMPRESA,1);
    IF p_IDS IS NULL OR LENGTH(p_IDS)>2200 OR NOT REGEXP_LIKE(p_IDS,'^[0-9]+(,[0-9]+)*$') THEN
      RAISE_APPLICATION_ERROR(-20001,'Lista de variables invalida.');
    END IF;
    OPEN p_RESULT FOR SELECT * FROM RH_NOM_VAR WHERE CODIGO_EMPRESA=p_EMPRESA
      AND INSTR(','||p_IDS||',',','||TO_CHAR(ID_VAR)||',')>0 ORDER BY ID_VAR;
  END;
  PROCEDURE VAR_SAVE(p_EMPRESA NUMBER,p_ACTOR NUMBER,p_ID NUMBER,p_VERSION NUMBER,
    p_CODIGO VARCHAR2,p_DESCRIPCION VARCHAR2,p_TIPO VARCHAR2,p_UNIDAD VARCHAR2,
    p_ORIGEN VARCHAR2,p_ACTIVA NUMBER,p_ID_OUT OUT NUMBER,p_VERSION_OUT OUT NUMBER) IS
    v_code RH_NOM_VAR.CODIGO%TYPE; v_version NUMBER;
  BEGIN
    contexto(p_EMPRESA,p_ACTOR);
    IF p_ID IS NULL OR p_ID<0 OR p_VERSION IS NULL OR p_VERSION<0 OR
       p_CODIGO IS NULL OR NOT REGEXP_LIKE(p_CODIGO,'^[A-Z][A-Z0-9_]{0,59}$') OR
       TRIM(p_DESCRIPCION) IS NULL OR LENGTH(TRIM(p_DESCRIPCION))>300 OR
       p_TIPO IS NULL OR p_TIPO NOT IN ('NUMERO','FECHA','BOOLEANO','TEXTO') OR p_UNIDAD IS NULL OR
       ((p_TIPO='NUMERO' AND p_UNIDAD NOT IN ('NUMERO','DINERO','TASA','PORCENTAJE','FACTOR','DIAS','CANTIDAD'))
        OR (p_TIPO<>'NUMERO' AND (p_UNIDAD<>p_TIPO OR p_ORIGEN='CALCULADA'))) OR
       p_ORIGEN IS NULL OR p_ORIGEN NOT IN ('ENTRADA','PARAMETRO','CALCULADA') OR
       p_ACTIVA IS NULL OR p_ACTIVA NOT IN (0,1) THEN
      RAISE_APPLICATION_ERROR(-20001,'Definicion de variable invalida.');
    END IF;
    IF p_ID=0 THEN
      IF p_VERSION<>0 THEN RAISE_APPLICATION_ERROR(-20002,'Version desactualizada.'); END IF;
      p_ID_OUT:=RH_NOM_VAR_SEQ.NEXTVAL;p_VERSION_OUT:=1;
      INSERT INTO RH_NOM_VAR(ID_VAR,CODIGO_EMPRESA,CODIGO,DESCRIPCION,TIPO,UNIDAD,ORIGEN,ACTIVA,VERSION,USUARIO_INS,FECHA_INS)
      VALUES(p_ID_OUT,p_EMPRESA,p_CODIGO,TRIM(p_DESCRIPCION),p_TIPO,p_UNIDAD,p_ORIGEN,p_ACTIVA,1,p_ACTOR,SYSDATE);
    ELSE
      BEGIN
        SELECT CODIGO,VERSION INTO v_code,v_version FROM RH_NOM_VAR
         WHERE ID_VAR=p_ID AND CODIGO_EMPRESA=p_EMPRESA FOR UPDATE NOWAIT;
      EXCEPTION WHEN NO_DATA_FOUND THEN RAISE_APPLICATION_ERROR(-20003,'Variable no encontrada.'); END;
      IF v_code<>p_CODIGO THEN RAISE_APPLICATION_ERROR(-20004,'El codigo de una variable no se cambia.'); END IF;
      IF v_version<>p_VERSION THEN RAISE_APPLICATION_ERROR(-20002,'Version desactualizada.'); END IF;
      UPDATE RH_NOM_VAR SET DESCRIPCION=TRIM(p_DESCRIPCION),TIPO=p_TIPO,UNIDAD=p_UNIDAD,
        ORIGEN=p_ORIGEN,ACTIVA=p_ACTIVA,VERSION=VERSION+1,USUARIO_UPD=p_ACTOR,FECHA_UPD=SYSDATE
       WHERE ID_VAR=p_ID AND CODIGO_EMPRESA=p_EMPRESA;
      p_ID_OUT:=p_ID;p_VERSION_OUT:=v_version+1;
    END IF;
  EXCEPTION WHEN DUP_VAL_ON_INDEX THEN RAISE_APPLICATION_ERROR(-20004,'El codigo ya existe en esta empresa.');
  END;
  PROCEDURE MODELOS_GET(p_EMPRESA NUMBER,p_PAGE NUMBER,p_SIZE NUMBER,p_SEARCH VARCHAR2,
    p_RESULT OUT SYS_REFCURSOR,p_TOTAL OUT NUMBER) IS
  BEGIN
    contexto(p_EMPRESA,1);pagina(p_PAGE,p_SIZE,p_SEARCH);
    SELECT COUNT(*) INTO p_TOTAL FROM SIS.OSS_MODELO_CALCULO M
     WHERE M.CODIGO_EMPRESA=p_EMPRESA AND (p_SEARCH IS NULL OR INSTR(UPPER(M.DESCRIPCION),UPPER(p_SEARCH))>0);
    OPEN p_RESULT FOR
      SELECT * FROM (SELECT M.ID ID_MODELO,M.DESCRIPCION,NVL(C.ULT_VERSION,0) ULT_VERSION,
        ROW_NUMBER() OVER(ORDER BY M.ID) RN FROM SIS.OSS_MODELO_CALCULO M
        LEFT JOIN RH_NOM_MOD_CTL C ON C.ID_MODELO=M.ID AND C.CODIGO_EMPRESA=M.CODIGO_EMPRESA
       WHERE M.CODIGO_EMPRESA=p_EMPRESA AND (p_SEARCH IS NULL OR INSTR(UPPER(M.DESCRIPCION),UPPER(p_SEARCH))>0))
       WHERE RN BETWEEN (p_PAGE-1)*p_SIZE+1 AND p_PAGE*p_SIZE ORDER BY RN;
  END;
  PROCEDURE VER_SAVE(p_EMPRESA NUMBER,p_ACTOR NUMBER,p_MODELO NUMBER,p_VERSION NUMBER,
    p_NOMINA NUMBER,p_ESCENARIO VARCHAR2,p_DESCRIPCION VARCHAR2,p_CONFIG CLOB,
    p_HASH VARCHAR2,p_REFS CLOB,p_CANT_VAR NUMBER,p_VERSION_OUT OUT NUMBER) IS
    v_count NUMBER;v_current NUMBER;v_vars NUMBER:=0;
  BEGIN
    contexto(p_EMPRESA,p_ACTOR);
    IF p_MODELO IS NULL OR p_MODELO<=0 OR p_VERSION IS NULL OR p_VERSION<0 OR
       p_NOMINA IS NULL OR p_NOMINA<=0 OR p_ESCENARIO IS NULL OR
       p_ESCENARIO NOT IN ('ADJUNTAR_CARGO','RECALCULA_VARIACIONES') OR
       TRIM(p_DESCRIPCION) IS NULL OR LENGTH(TRIM(p_DESCRIPCION))>300 OR
       p_CONFIG IS NULL OR DBMS_LOB.GETLENGTH(p_CONFIG)>1048576 OR DBMS_LOB.GETLENGTH(p_CONFIG)=0 OR
       p_HASH IS NULL OR NOT REGEXP_LIKE(p_HASH,'^[0-9A-F]{64}$') OR p_REFS IS NULL OR
       p_CANT_VAR IS NULL OR p_CANT_VAR<1 OR p_CANT_VAR>200 OR DBMS_LOB.GETLENGTH(p_REFS)>5000 THEN
      RAISE_APPLICATION_ERROR(-20001,'Definicion de revision invalida.');
    END IF;
    SELECT COUNT(*) INTO v_count FROM SIS.OSS_MODELO_CALCULO WHERE ID=p_MODELO AND CODIGO_EMPRESA=p_EMPRESA;
    IF v_count<>1 THEN RAISE_APPLICATION_ERROR(-20003,'Modelo SIS no encontrado en la empresa.'); END IF;
    SELECT COUNT(*) INTO v_count FROM RH_TIPOS_NOMINA WHERE CODIGO_TIPO_NOMINA=p_NOMINA AND CODIGO_EMPRESA=p_EMPRESA;
    IF v_count<>1 THEN RAISE_APPLICATION_ERROR(-20003,'Tipo de nomina no encontrado en la empresa.'); END IF;
    BEGIN
      INSERT INTO RH_NOM_MOD_CTL(ID_MODELO,CODIGO_EMPRESA,ULT_VERSION) VALUES(p_MODELO,p_EMPRESA,0);
    EXCEPTION WHEN DUP_VAL_ON_INDEX THEN NULL; END;
    SELECT ULT_VERSION INTO v_current FROM RH_NOM_MOD_CTL
     WHERE ID_MODELO=p_MODELO AND CODIGO_EMPRESA=p_EMPRESA FOR UPDATE NOWAIT;
    IF v_current<>p_VERSION THEN RAISE_APPLICATION_ERROR(-20002,'Version desactualizada.'); END IF;
    FOR r IN (SELECT ID_VAR,VERSION FROM RH_NOM_VAR WHERE CODIGO_EMPRESA=p_EMPRESA AND ACTIVA=1
      AND DBMS_LOB.INSTR(p_REFS,','||TO_CHAR(ID_VAR)||':'||TO_CHAR(VERSION)||',')>0 ORDER BY ID_VAR FOR UPDATE NOWAIT) LOOP
      v_vars:=v_vars+1;
    END LOOP;
    IF v_vars<>p_CANT_VAR THEN RAISE_APPLICATION_ERROR(-20002,'Cambio la version o vigencia de una variable.'); END IF;
    p_VERSION_OUT:=v_current+1;
    INSERT INTO RH_NOM_MOD_VER(ID_MODELO,CODIGO_EMPRESA,VERSION,CODIGO_TIPO_NOMINA,ESCENARIO,DESCRIPCION,
      CONFIG_JSON,CONFIG_HASH,USUARIO_INS,FECHA_INS)
    VALUES(p_MODELO,p_EMPRESA,p_VERSION_OUT,p_NOMINA,p_ESCENARIO,TRIM(p_DESCRIPCION),p_CONFIG,p_HASH,p_ACTOR,SYSDATE);
    UPDATE RH_NOM_MOD_CTL SET ULT_VERSION=p_VERSION_OUT WHERE ID_MODELO=p_MODELO AND CODIGO_EMPRESA=p_EMPRESA;
  END;
  PROCEDURE VER_GET(p_EMPRESA NUMBER,p_MODELO NUMBER,p_VERSION NUMBER,p_RESULT OUT SYS_REFCURSOR) IS
  BEGIN
    contexto(p_EMPRESA,1);
    IF p_MODELO IS NULL OR p_MODELO<=0 OR p_VERSION IS NULL OR p_VERSION<=0 THEN
      RAISE_APPLICATION_ERROR(-20001,'Modelo/version requeridos.');
    END IF;
    -- Bounded VARCHAR2 fragments avoid exposing CLOB locators to older Oracle drivers.
    OPEN p_RESULT FOR
      SELECT V.ID_MODELO,V.CODIGO_EMPRESA,V.VERSION,V.CODIGO_TIPO_NOMINA,V.ESCENARIO,
        V.DESCRIPCION,V.CONFIG_HASH,V.USUARIO_INS,V.FECHA_INS,
        DBMS_LOB.GETLENGTH(V.CONFIG_JSON) CONFIG_LARGO,B.NUM PARTE,
        DBMS_LOB.SUBSTR(V.CONFIG_JSON,1000,(B.NUM-1)*1000+1) CONFIG_PARTE
      FROM RH_NOM_MOD_VER V JOIN SIS.OSS_MODELO_CALCULO M ON M.ID=V.ID_MODELO,
        (SELECT LEVEL NUM FROM DUAL CONNECT BY LEVEL<=1049) B
      WHERE V.CODIGO_EMPRESA=p_EMPRESA AND M.CODIGO_EMPRESA=p_EMPRESA
        AND V.ID_MODELO=p_MODELO AND V.VERSION=p_VERSION
        AND B.NUM<=CEIL(DBMS_LOB.GETLENGTH(V.CONFIG_JSON)/1000)
      ORDER BY B.NUM;
  END;
END RH_PKG_NOM_CFG;
