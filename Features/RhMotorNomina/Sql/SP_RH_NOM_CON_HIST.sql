-- Como RH. SP_RH_NOM_CON_HIST=18 caracteres. Oracle 10g. Solo auditoria, sin catalogo actual.
CREATE OR REPLACE PROCEDURE RH.SP_RH_NOM_CON_HIST (
  p_EMPRESA IN NUMBER,p_TIPO IN NUMBER,p_PERIODO IN NUMBER,p_FECHA IN DATE,
  p_CONCEPTO IN NUMBER,p_RESULT OUT SYS_REFCURSOR
) AUTHID DEFINER AS
BEGIN
  IF p_EMPRESA IS NULL OR p_EMPRESA<=0 OR p_EMPRESA<>TRUNC(p_EMPRESA)
     OR p_TIPO IS NULL OR p_TIPO<=0 OR p_TIPO<>TRUNC(p_TIPO)
     OR p_PERIODO IS NULL OR p_PERIODO<=0 OR p_PERIODO<>TRUNC(p_PERIODO)
     OR p_CONCEPTO IS NULL OR p_CONCEPTO<=0 OR p_CONCEPTO<>TRUNC(p_CONCEPTO)
     OR p_FECHA IS NULL THEN
    RAISE_APPLICATION_ERROR(-20001,'Contexto de concepto invalido.');
  END IF;
  -- No filtrar el tipo de nomina de la imagen OLD antes de elegir fecha:
  -- un concepto pudo cambiar de tipo. Se valida el tipo elegido en C#.
  -- Tres filas bastan para diagnosticar empates; TOTAL_CANDIDATOS conserva el total.
  OPEN p_RESULT FOR SELECT * FROM (
    SELECT M.FECHA_EVENTO,M.EVENTOS_SIN_FECHA,
           (SELECT COUNT(*) FROM RH.RH_H_CONCEPTOS C
             WHERE C.CODIGO_EMPRESA=p_EMPRESA AND C.CODIGO_CONCEPTO=p_CONCEPTO
               AND C.FECHA_INS_H=M.FECHA_EVENTO) TOTAL_CANDIDATOS,
           A.CODIGO_H_CONCEPTO,A.CODIGO_EMPRESA,A.CODIGO_CONCEPTO,
           A.CODIGO_TIPO_NOMINA,A.FECHA_INS_H,A.FECHA_INS,
           A.TIPO_CONCEPTO,A.FRECUENCIA_ID,A.MODULO_ID,A.AUTOMATICO
      FROM (SELECT MIN(CASE WHEN H.FECHA_INS_H>=p_FECHA THEN H.FECHA_INS_H END) FECHA_EVENTO,
                   NVL(SUM(CASE WHEN H.FECHA_INS_H IS NULL THEN 1 ELSE 0 END),0) EVENTOS_SIN_FECHA
              FROM RH.RH_H_CONCEPTOS H
             WHERE H.CODIGO_EMPRESA=p_EMPRESA AND H.CODIGO_CONCEPTO=p_CONCEPTO) M
      LEFT JOIN RH.RH_H_CONCEPTOS A
        ON A.CODIGO_EMPRESA=p_EMPRESA AND A.CODIGO_CONCEPTO=p_CONCEPTO
       AND A.FECHA_INS_H=M.FECHA_EVENTO
     WHERE EXISTS(SELECT 1 FROM RH.RH_HISTORICO_NOMINA N
                   WHERE N.CODIGO_EMPRESA=p_EMPRESA AND N.CODIGO_TIPO_NOMINA=p_TIPO
                     AND N.CODIGO_PERIODO=p_PERIODO AND N.FECHA_NOMINA=p_FECHA
                     AND N.CODIGO_CONCEPTO=p_CONCEPTO)
       AND EXISTS(SELECT 1 FROM RH.RH_PERIODOS P
                   WHERE P.CODIGO_EMPRESA=p_EMPRESA AND P.CODIGO_TIPO_NOMINA=p_TIPO
                     AND P.CODIGO_PERIODO=p_PERIODO AND P.FECHA_NOMINA=p_FECHA
                     AND P.FECHA_CIERRE IS NOT NULL)
     ORDER BY A.CODIGO_H_CONCEPTO
  ) WHERE ROWNUM<=3;
END;
