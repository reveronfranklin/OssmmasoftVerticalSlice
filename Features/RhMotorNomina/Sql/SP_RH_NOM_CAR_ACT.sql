-- SP_RH_NOM_CAR_ACT: 17 caracteres. Lectura actual explicita, sin calculo ni DML.
CREATE OR REPLACE PROCEDURE RH.SP_RH_NOM_CAR_ACT (
  p_EMPRESA IN NUMBER,p_TIPO IN NUMBER,p_PERIODO IN NUMBER,p_FECHA IN DATE,
  p_PRESUPUESTO IN NUMBER,p_PERSONA IN NUMBER,p_RELACION IN NUMBER,p_RESULT OUT SYS_REFCURSOR
) AUTHID DEFINER AS
BEGIN
  IF p_EMPRESA IS NULL OR p_EMPRESA<=0 OR p_TIPO IS NULL OR p_TIPO<=0
     OR p_PERIODO IS NULL OR p_PERIODO<=0 OR p_FECHA IS NULL
     OR p_PRESUPUESTO IS NULL OR p_PRESUPUESTO<=0 OR p_PERSONA IS NULL OR p_PERSONA<=0
     OR p_RELACION IS NULL OR p_RELACION<=0 THEN
    RAISE_APPLICATION_ERROR(-20001,'Contexto actual invalido.');
  END IF;
  OPEN p_RESULT FOR
    SELECT P.CODIGO_EMPRESA,P.CODIGO_TIPO_NOMINA,P.CODIGO_PERIODO,P.FECHA_NOMINA,
           R.CODIGO_PRESUPUESTO,P.CODIGO_PRESUPUESTO PRESUPUESTO_PERIODO,P.FECHA_PRECIERRE,P.FECHA_CIERRE,
           R.CODIGO_PERSONA,R.CODIGO_RELACION_CARGO,R.CODIGO_CARGO,
           TO_CHAR(R.SUELDO,'TM9','NLS_NUMERIC_CHARACTERS=''.,''') SUELDO_TEXTO,
           R.EXTRA1,R.FECHA_INI,R.FECHA_FIN,R.FECHA_INI_VIGENCIA,R.FECHA_FIN_VIGENCIA,
           T.SIGLAS_TIPO_NOMINA,T.FRECUENCIA_PAGO_ID
      FROM RH.RH_PERIODOS P
      JOIN RH.RH_TIPOS_NOMINA T ON T.CODIGO_EMPRESA=P.CODIGO_EMPRESA
                              AND T.CODIGO_TIPO_NOMINA=P.CODIGO_TIPO_NOMINA
      JOIN RH.RH_RELACION_CARGOS R ON R.CODIGO_EMPRESA=P.CODIGO_EMPRESA
                                AND R.CODIGO_TIPO_NOMINA=P.CODIGO_TIPO_NOMINA
                                AND R.CODIGO_PRESUPUESTO=T.CODIGO_PRESUPUESTO_ACTUAL
     WHERE P.CODIGO_EMPRESA=p_EMPRESA AND P.CODIGO_TIPO_NOMINA=p_TIPO
       AND P.CODIGO_PERIODO=p_PERIODO AND P.FECHA_NOMINA=p_FECHA
       AND T.CODIGO_PRESUPUESTO_ACTUAL=p_PRESUPUESTO
       AND R.CODIGO_PERSONA=p_PERSONA AND R.CODIGO_RELACION_CARGO=p_RELACION
       AND R.FECHA_FIN IS NULL;
END;
