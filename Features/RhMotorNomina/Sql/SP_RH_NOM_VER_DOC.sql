-- Oracle 10g. Scoped CLOB read of immutable model revisions; VER_GET unchanged.
CREATE OR REPLACE PROCEDURE RH.SP_RH_NOM_VER_DOC(p_EMPRESA NUMBER,p_MODELO NUMBER,p_VERSION NUMBER,p_RESULT OUT SYS_REFCURSOR) AS
BEGIN
 OPEN p_RESULT FOR SELECT V.ID_MODELO,V.CODIGO_EMPRESA,V.VERSION,V.CODIGO_TIPO_NOMINA,V.ESCENARIO,V.DESCRIPCION,V.CONFIG_HASH,V.USUARIO_INS,V.FECHA_INS,
  DBMS_LOB.GETLENGTH(V.CONFIG_JSON) CONFIG_LARGO,V.CONFIG_JSON DOCUMENTO
  FROM RH.RH_NOM_MOD_VER V JOIN SIS.OSS_MODELO_CALCULO M ON M.ID=V.ID_MODELO
  WHERE V.CODIGO_EMPRESA=p_EMPRESA AND M.CODIGO_EMPRESA=p_EMPRESA AND V.ID_MODELO=p_MODELO AND V.VERSION=p_VERSION;
END;
/
