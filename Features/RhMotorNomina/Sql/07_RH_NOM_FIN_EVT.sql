-- RH_PKG_NOM_FIN_EVT=18, TR_RH_NOM_FIN_EVT_IMM=21.
-- Storage/read boundary only. No INSERT procedure, financial DML or test events.
DECLARE n NUMBER;
BEGIN
  IF SYS_CONTEXT('USERENV','SESSION_USER')<>'RH' OR SYS_CONTEXT('USERENV','CURRENT_SCHEMA')<>'RH' THEN
    RAISE_APPLICATION_ERROR(-20001,'Instalar como RH.');
  END IF;
  SELECT COUNT(*) INTO n FROM USER_OBJECTS WHERE OBJECT_NAME='RH_NOM_FIN_EVT';
  IF n=0 THEN
    EXECUTE IMMEDIATE 'CREATE TABLE RH_NOM_FIN_EVT (
      ID_EVT NUMBER(10) NOT NULL,CODIGO_EMPRESA NUMBER(10) NOT NULL,
      CODIGO_TIPO_NOMINA NUMBER(10) NOT NULL,CODIGO_PERSONA NUMBER(10) NOT NULL,
      ID_PLAN NUMBER(10) NOT NULL,ACTOR NUMBER(10) NOT NULL,FECHA_BD DATE NOT NULL,
      ID_ANT NUMBER(10),HASH_ANT VARCHAR2(64 CHAR),
      HASH_DOC VARCHAR2(64 CHAR) NOT NULL,HASH_EVT VARCHAR2(64 CHAR) NOT NULL,DOCUMENTO CLOB NOT NULL,
      CONSTRAINT PK_RH_NOM_FIN_EVT PRIMARY KEY(ID_EVT),
      CONSTRAINT UK_RH_NOM_FIN_EVT_CTX UNIQUE(CODIGO_EMPRESA,CODIGO_TIPO_NOMINA,CODIGO_PERSONA,ID_EVT),
      CONSTRAINT UK_RH_NOM_FIN_EVT_ANT UNIQUE(CODIGO_EMPRESA,CODIGO_TIPO_NOMINA,CODIGO_PERSONA,ID_ANT),
      CONSTRAINT FK_RH_NOM_FIN_EVT_ANT FOREIGN KEY(CODIGO_EMPRESA,CODIGO_TIPO_NOMINA,CODIGO_PERSONA,ID_ANT)
        REFERENCES RH_NOM_FIN_EVT(CODIGO_EMPRESA,CODIGO_TIPO_NOMINA,CODIGO_PERSONA,ID_EVT),
      CONSTRAINT FK_RH_NOM_FIN_EVT_PLAN FOREIGN KEY(ID_PLAN) REFERENCES RH_NOM_FIN_PLAN(ID_PLAN),
      CONSTRAINT CK_RH_NOM_FIN_EVT_POS CHECK(ID_EVT>0 AND CODIGO_EMPRESA>0 AND CODIGO_TIPO_NOMINA>0 AND CODIGO_PERSONA>0 AND ID_PLAN>0 AND ACTOR>0),
      CONSTRAINT CK_RH_NOM_FIN_EVT_ANT CHECK((ID_ANT IS NULL AND HASH_ANT IS NULL) OR (ID_ANT IS NOT NULL AND ID_ANT>0 AND ID_ANT<ID_EVT AND HASH_ANT IS NOT NULL)))';
  ELSE
    SELECT COUNT(*) INTO n FROM USER_OBJECTS WHERE OBJECT_NAME='RH_NOM_FIN_EVT' AND OBJECT_TYPE='TABLE';
    IF n<>1 THEN RAISE_APPLICATION_ERROR(-20001,'Conflicto de nombre RH_NOM_FIN_EVT.'); END IF;
  END IF;
  SELECT COUNT(*) INTO n FROM USER_OBJECTS WHERE OBJECT_NAME='RH_NOM_FIN_EVT_SEQ';
  IF n=0 THEN EXECUTE IMMEDIATE 'CREATE SEQUENCE RH_NOM_FIN_EVT_SEQ START WITH 1 INCREMENT BY 1 MAXVALUE 2147483647 NOCYCLE CACHE 20'; END IF;
END;
/
CREATE OR REPLACE TRIGGER TR_RH_NOM_FIN_EVT_IMM
BEFORE UPDATE OR DELETE ON RH_NOM_FIN_EVT
BEGIN
  RAISE_APPLICATION_ERROR(-20004,'El evento financiero confirmado es inmutable.');
END;
/
CREATE OR REPLACE PACKAGE RH_PKG_NOM_FIN_EVT AS
  PROCEDURE CADENA(p_EMPRESA NUMBER,p_TIPO NUMBER,p_PERSONA NUMBER,p_RESULT OUT SYS_REFCURSOR);
  PROCEDURE DOCUMENTO(p_EMPRESA NUMBER,p_ID NUMBER,p_RESULT OUT SYS_REFCURSOR);
END;
/
CREATE OR REPLACE PACKAGE BODY RH_PKG_NOM_FIN_EVT AS
  PROCEDURE CADENA(p_EMPRESA NUMBER,p_TIPO NUMBER,p_PERSONA NUMBER,p_RESULT OUT SYS_REFCURSOR) IS
  BEGIN
    IF p_EMPRESA IS NULL OR p_EMPRESA<=0 OR p_TIPO IS NULL OR p_TIPO<=0 OR p_PERSONA IS NULL OR p_PERSONA<=0 THEN
      RAISE_APPLICATION_ERROR(-20001,'Contexto financiero invalido.'); END IF;
    OPEN p_RESULT FOR SELECT * FROM (SELECT E.ID_EVT,E.CODIGO_EMPRESA,E.CODIGO_TIPO_NOMINA,E.CODIGO_PERSONA,
      E.ID_PLAN,E.ACTOR,E.FECHA_BD,E.ID_ANT,E.HASH_ANT,E.HASH_DOC,E.HASH_EVT,
      P.HASH_DOC HASH_PLAN,P.CODIGO_EMPRESA EMPRESA_PLAN
      FROM RH_NOM_FIN_EVT E JOIN RH_NOM_FIN_PLAN P ON P.ID_PLAN=E.ID_PLAN
      WHERE E.CODIGO_EMPRESA=p_EMPRESA AND E.CODIGO_TIPO_NOMINA=p_TIPO AND E.CODIGO_PERSONA=p_PERSONA
      ORDER BY E.ID_EVT) WHERE ROWNUM<=201;
  END;
  PROCEDURE DOCUMENTO(p_EMPRESA NUMBER,p_ID NUMBER,p_RESULT OUT SYS_REFCURSOR) IS
  BEGIN OPEN p_RESULT FOR SELECT X.HUELLA,X.LARGO,N.PARTE,
    DBMS_LOB.SUBSTR(X.DOC,1000,(N.PARTE-1)*1000+1) FRAGMENTO
    FROM (SELECT DOCUMENTO DOC,HASH_DOC HUELLA,DBMS_LOB.GETLENGTH(DOCUMENTO) LARGO
      FROM RH_NOM_FIN_EVT WHERE CODIGO_EMPRESA=p_EMPRESA AND ID_EVT=p_ID) X,
      (SELECT LEVEL PARTE FROM DUAL CONNECT BY LEVEL<=525) N
    WHERE N.PARTE<=CEIL(X.LARGO/1000) ORDER BY N.PARTE;
  END;
END;
