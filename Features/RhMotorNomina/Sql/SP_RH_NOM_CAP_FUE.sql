-- Oracle 10g. SP_RH_NOM_CAP_FUE=17. Read-only source cursors.
-- Caller must run all reads in one SERIALIZABLE transaction, then rollback.
CREATE OR REPLACE PROCEDURE RH.SP_RH_NOM_CAP_FUE(
  p_EMPRESA NUMBER,p_TIPO NUMBER,p_PERIODO NUMBER,p_PERSONA NUMBER,p_MANUALES VARCHAR2,
  p_AJENOS OUT NUMBER,p_CONTEXTO OUT SYS_REFCURSOR,p_MOVIMIENTOS OUT SYS_REFCURSOR,
  p_PERSONAL OUT SYS_REFCURSOR,p_FRECUENCIAS OUT SYS_REFCURSOR,p_CONCEPTOS OUT SYS_REFCURSOR) AS
BEGIN
  IF p_EMPRESA IS NULL OR p_EMPRESA<=0 OR p_TIPO IS NULL OR p_TIPO<=0
    OR p_PERIODO IS NULL OR p_PERIODO<=0 OR p_PERSONA IS NULL OR p_PERSONA<=0 THEN
    RAISE_APPLICATION_ERROR(-20001,'Contexto positivo requerido.');
  END IF;
  IF p_MANUALES IS NOT NULL AND (LENGTH(p_MANUALES)>1200
    OR NOT REGEXP_LIKE(p_MANUALES,'^[0-9]+(,[0-9]+)*$')) THEN
    RAISE_APPLICATION_ERROR(-20001,'Lista de conceptos manuales invalida.');
  END IF;
  OPEN p_CONTEXTO FOR SELECT P.CODIGO_EMPRESA,P.CODIGO_TIPO_NOMINA,P.CODIGO_PERIODO,
    P.FECHA_NOMINA,P.PERIODO NUM_PERIODO,P.TIPO_NOMINA,P.FECHA_CIERRE,P.FECHA_PRECIERRE,
    T.CODIGO_PRESUPUESTO_ACTUAL,P.CODIGO_PRESUPUESTO PRESUPUESTO_PERIODO
    FROM RH_PERIODOS P JOIN RH_TIPOS_NOMINA T
      ON T.CODIGO_EMPRESA=P.CODIGO_EMPRESA AND T.CODIGO_TIPO_NOMINA=P.CODIGO_TIPO_NOMINA
    WHERE P.CODIGO_EMPRESA=p_EMPRESA AND P.CODIGO_TIPO_NOMINA=p_TIPO AND P.CODIGO_PERIODO=p_PERIODO;
  SELECT COUNT(*) INTO p_AJENOS FROM RH_MOV_NOMINA
    WHERE CODIGO_TIPO_NOMINA=p_TIPO AND CODIGO_PERSONA=p_PERSONA
      AND (CODIGO_EMPRESA<>p_EMPRESA OR CODIGO_EMPRESA IS NULL);
  OPEN p_MOVIMIENTOS FOR SELECT * FROM (
    SELECT CODIGO_MOV_NOMINA,CODIGO_EMPRESA,CODIGO_TIPO_NOMINA,CODIGO_PERSONA,CODIGO_CONCEPTO,
      FRECUENCIA_ID,TIPO,TO_CHAR(MONTO,'TM9','NLS_NUMERIC_CHARACTERS=''.,''') MONTO_TEXTO,
      STATUS,COMPLEMENTO_CONCEPTO,EXTRA1,EXTRA2,EXTRA3,USUARIO_INS,FECHA_INS,USUARIO_UPD,FECHA_UPD
    FROM RH_MOV_NOMINA WHERE CODIGO_EMPRESA=p_EMPRESA AND CODIGO_TIPO_NOMINA=p_TIPO
      AND CODIGO_PERSONA=p_PERSONA ORDER BY CODIGO_MOV_NOMINA) WHERE ROWNUM<=2001;
  OPEN p_PERSONAL FOR SELECT * FROM (
    SELECT CODIGO_EMPRESA,CODIGO_TIPO_NOMINA,CODIGO_PERSONA,CODIGO_RELACION_CARGO,STATUS
    FROM RH_V_PERSONAL_CARGO WHERE CODIGO_EMPRESA=p_EMPRESA AND CODIGO_TIPO_NOMINA=p_TIPO
      AND CODIGO_PERSONA=p_PERSONA ORDER BY CODIGO_RELACION_CARGO,STATUS) WHERE ROWNUM<=2001;
  OPEN p_FRECUENCIAS FOR SELECT * FROM (
    SELECT D.DESCRIPCION_ID,D.CODIGO FROM RH_DESCRIPTIVAS D
    WHERE D.CODIGO_EMPRESA=p_EMPRESA AND EXISTS (SELECT 1 FROM RH_MOV_NOMINA M WHERE M.CODIGO_EMPRESA=p_EMPRESA
      AND M.CODIGO_TIPO_NOMINA=p_TIPO AND M.CODIGO_PERSONA=p_PERSONA
      AND M.FRECUENCIA_ID=D.DESCRIPCION_ID) ORDER BY D.DESCRIPCION_ID) WHERE ROWNUM<=2001;
  OPEN p_CONCEPTOS FOR SELECT * FROM (
    SELECT C.CODIGO_EMPRESA,C.CODIGO_TIPO_NOMINA,C.CODIGO_CONCEPTO,C.TIPO_CONCEPTO
    FROM RH_CONCEPTOS C WHERE C.CODIGO_EMPRESA=p_EMPRESA AND C.CODIGO_TIPO_NOMINA=p_TIPO
      AND (EXISTS (SELECT 1 FROM RH_MOV_NOMINA M WHERE M.CODIGO_EMPRESA=p_EMPRESA
        AND M.CODIGO_TIPO_NOMINA=p_TIPO AND M.CODIGO_PERSONA=p_PERSONA
        AND M.CODIGO_CONCEPTO=C.CODIGO_CONCEPTO)
        OR INSTR(','||p_MANUALES||',',','||TO_CHAR(C.CODIGO_CONCEPTO,'TM9')||',')>0)
    ORDER BY C.CODIGO_CONCEPTO) WHERE ROWNUM<=2001;
END;
