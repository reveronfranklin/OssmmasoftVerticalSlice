-- SP_RH_NOM_CON_CAT: 17 caracteres. Catalogo ACTUAL para borradores, no reconstruccion historica.
CREATE OR REPLACE PROCEDURE RH.SP_RH_NOM_CON_CAT (
  p_EMPRESA IN NUMBER,p_NOMINA IN NUMBER,p_PAGE IN NUMBER,p_SIZE IN NUMBER,
  p_SEARCH IN VARCHAR2,p_IDS IN VARCHAR2,p_RESULT OUT SYS_REFCURSOR,p_TOTAL OUT NUMBER
) AUTHID DEFINER AS
BEGIN
  IF p_EMPRESA IS NULL OR p_EMPRESA<=0 OR p_NOMINA IS NULL OR p_NOMINA<=0
     OR p_PAGE IS NULL OR p_PAGE<1 OR p_PAGE>100000 OR p_PAGE<>TRUNC(p_PAGE)
     OR p_SIZE IS NULL OR p_SIZE<1 OR p_SIZE>100 OR p_SIZE<>TRUNC(p_SIZE)
     OR LENGTH(p_SEARCH)>100 OR LENGTH(p_IDS)>1200
     OR (p_IDS IS NOT NULL AND NOT REGEXP_LIKE(p_IDS,'^[0-9]+(,[0-9]+)*$')) THEN
    RAISE_APPLICATION_ERROR(-20001,'Filtro de conceptos invalido.');
  END IF;
  SELECT COUNT(*) INTO p_TOTAL FROM RH.RH_CONCEPTOS C
   WHERE C.CODIGO_EMPRESA=p_EMPRESA AND C.CODIGO_TIPO_NOMINA=p_NOMINA
     AND (p_IDS IS NULL OR INSTR(','||p_IDS||',',','||TO_CHAR(C.CODIGO_CONCEPTO,'TM9')||',')>0)
     AND (p_SEARCH IS NULL OR INSTR(UPPER(C.CODIGO||' '||C.DENOMINACION),UPPER(p_SEARCH))>0);
  OPEN p_RESULT FOR SELECT * FROM (
    SELECT C.CODIGO_EMPRESA,C.CODIGO_TIPO_NOMINA,C.CODIGO_CONCEPTO,C.CODIGO,
           C.DENOMINACION,C.TIPO_CONCEPTO,C.FRECUENCIA_ID,C.STATUS,C.AUTOMATICO,
           ROW_NUMBER() OVER(ORDER BY C.DENOMINACION,C.CODIGO_CONCEPTO) RN
      FROM RH.RH_CONCEPTOS C
     WHERE C.CODIGO_EMPRESA=p_EMPRESA AND C.CODIGO_TIPO_NOMINA=p_NOMINA
       AND (p_IDS IS NULL OR INSTR(','||p_IDS||',',','||TO_CHAR(C.CODIGO_CONCEPTO,'TM9')||',')>0)
       AND (p_SEARCH IS NULL OR INSTR(UPPER(C.CODIGO||' '||C.DENOMINACION),UPPER(p_SEARCH))>0)
  ) WHERE RN>(p_PAGE-1)*p_SIZE AND RN<=p_PAGE*p_SIZE;
END;
