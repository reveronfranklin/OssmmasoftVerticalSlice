-- Oracle 10g. SP_RH_NOM_ACU_ACT=17. Solo lectura de movimientos actuales.
-- Sin join multiplicador con catalogo, sin SUM/NVL/DISTINCT ni DML de nomina.
CREATE OR REPLACE PROCEDURE RH.SP_RH_NOM_ACU_ACT (
 p_EMPRESA NUMBER,p_TIPO NUMBER,p_PERIODO NUMBER,p_FECHA DATE,p_PERSONA NUMBER,
 p_CONCEPTOS VARCHAR2,p_RESULT OUT SYS_REFCURSOR
) AUTHID DEFINER AS
 n NUMBER;
BEGIN
 IF p_EMPRESA IS NULL OR p_EMPRESA<=0 OR p_EMPRESA<>TRUNC(p_EMPRESA)
 OR p_TIPO IS NULL OR p_TIPO<=0 OR p_TIPO<>TRUNC(p_TIPO)
 OR p_PERIODO IS NULL OR p_PERIODO<=0 OR p_PERIODO<>TRUNC(p_PERIODO)
 OR p_PERSONA IS NULL OR p_PERSONA<=0 OR p_PERSONA<>TRUNC(p_PERSONA)
 OR p_FECHA IS NULL OR p_CONCEPTOS IS NULL OR LENGTH(p_CONCEPTOS)>1200
 OR NOT REGEXP_LIKE(p_CONCEPTOS,'^[0-9]+(,[0-9]+)*$') THEN
  RAISE_APPLICATION_ERROR(-20001,'Contexto/conceptos del acumulador invalidos.');
 END IF;
 SELECT COUNT(*) INTO n FROM RH.RH_PERIODOS
  WHERE CODIGO_EMPRESA=p_EMPRESA AND CODIGO_TIPO_NOMINA=p_TIPO
    AND CODIGO_PERIODO=p_PERIODO AND FECHA_NOMINA=p_FECHA AND FECHA_CIERRE IS NULL;
 IF n<>1 THEN RAISE_APPLICATION_ERROR(-20001,'Acumuladores actuales requieren un periodo abierto unico.'); END IF;
 OPEN p_RESULT FOR SELECT * FROM (
  SELECT M.CODIGO_MOV_NOMINA,M.CODIGO_EMPRESA,M.CODIGO_TIPO_NOMINA,M.CODIGO_PERSONA,
    M.CODIGO_CONCEPTO,M.FRECUENCIA_ID,M.TIPO,M.STATUS,M.COMPLEMENTO_CONCEPTO,
    TO_CHAR(M.MONTO,'TM9','NLS_NUMERIC_CHARACTERS=''.,''') MONTO_TEXTO
  FROM RH.RH_MOV_NOMINA M
  WHERE M.CODIGO_EMPRESA=p_EMPRESA AND M.CODIGO_TIPO_NOMINA=p_TIPO
    AND M.CODIGO_PERSONA=p_PERSONA
    AND INSTR(','||p_CONCEPTOS||',',','||TO_CHAR(M.CODIGO_CONCEPTO,'TM9')||',')>0
  ORDER BY M.CODIGO_MOV_NOMINA,M.CODIGO_CONCEPTO,M.FRECUENCIA_ID,M.TIPO
 ) WHERE ROWNUM<=2001;
END;
