-- Oracle 10g. SP_RH_NOM_CTL_ACT=17. Lectura de controles actuales, sin DML de nomina.
CREATE OR REPLACE PROCEDURE RH.SP_RH_NOM_CTL_ACT (
 p_EMPRESA NUMBER,p_TIPO NUMBER,p_PERIODO NUMBER,p_FECHA DATE,p_PERSONA NUMBER,
 p_CONCEPTO NUMBER,p_ALCANCE VARCHAR2,p_MODULO OUT NUMBER,p_RESULT OUT SYS_REFCURSOR
) AUTHID DEFINER AS
 n NUMBER;
BEGIN
 IF p_EMPRESA IS NULL OR p_EMPRESA<=0 OR p_EMPRESA<>TRUNC(p_EMPRESA)
 OR p_TIPO IS NULL OR p_TIPO<=0 OR p_TIPO<>TRUNC(p_TIPO)
 OR p_PERIODO IS NULL OR p_PERIODO<=0 OR p_PERIODO<>TRUNC(p_PERIODO)
 OR p_PERSONA IS NULL OR p_PERSONA<=0 OR p_PERSONA<>TRUNC(p_PERSONA)
 OR p_CONCEPTO IS NULL OR p_CONCEPTO<=0 OR p_CONCEPTO<>TRUNC(p_CONCEPTO)
 OR p_FECHA IS NULL OR p_ALCANCE IS NULL OR p_ALCANCE NOT IN ('CONCEPTO','MODULO_TIPO','MODULO_EMPRESA') THEN
  RAISE_APPLICATION_ERROR(-20001,'Contexto/alcance de control invalido.');
 END IF;
 SELECT COUNT(*) INTO n FROM RH.RH_PERIODOS WHERE CODIGO_EMPRESA=p_EMPRESA AND CODIGO_TIPO_NOMINA=p_TIPO
  AND CODIGO_PERIODO=p_PERIODO AND FECHA_NOMINA=p_FECHA AND FECHA_CIERRE IS NULL;
 IF n<>1 THEN RAISE_APPLICATION_ERROR(-20001,'Controles actuales requieren periodo abierto unico.'); END IF;
 BEGIN
  SELECT MODULO_ID INTO p_MODULO FROM RH.RH_CONCEPTOS
   WHERE CODIGO_EMPRESA=p_EMPRESA AND CODIGO_TIPO_NOMINA=p_TIPO AND CODIGO_CONCEPTO=p_CONCEPTO;
 EXCEPTION WHEN NO_DATA_FOUND THEN RAISE_APPLICATION_ERROR(-20001,'Concepto objetivo no encontrado.');
  WHEN TOO_MANY_ROWS THEN RAISE_APPLICATION_ERROR(-20001,'Concepto objetivo duplicado.');
 END;
 IF p_ALCANCE<>'CONCEPTO' AND (p_MODULO IS NULL OR p_MODULO<=0) THEN
  RAISE_APPLICATION_ERROR(-20001,'Concepto objetivo sin modulo valido.');
 END IF;
 OPEN p_RESULT FOR SELECT * FROM (
  SELECT P.CODIGO_PERSONA_MOV_CTRL,P.CODIGO_EMPRESA,P.CODIGO_PERSONA,P.CODIGO_CONCEPTO,
   C.CODIGO_TIPO_NOMINA,C.MODULO_ID,P.FECHA_INS,P.FECHA_UPD,
   TO_CHAR(P.CONTROL_APLICA,'TM9','NLS_NUMERIC_CHARACTERS=''.,''') CONTROL_TEXTO
  FROM RH.RH_PERSONAS_MOV_CONTROL P JOIN RH.RH_CONCEPTOS C ON C.CODIGO_CONCEPTO=P.CODIGO_CONCEPTO AND C.CODIGO_EMPRESA=p_EMPRESA
  WHERE P.CODIGO_PERSONA=p_PERSONA AND (P.CODIGO_EMPRESA=p_EMPRESA OR P.CODIGO_EMPRESA IS NULL)
   AND ((p_ALCANCE='CONCEPTO' AND C.CODIGO_CONCEPTO=p_CONCEPTO AND C.CODIGO_TIPO_NOMINA=p_TIPO)
    OR (p_ALCANCE IN ('MODULO_TIPO','MODULO_EMPRESA') AND C.MODULO_ID=p_MODULO
     AND (p_ALCANCE='MODULO_EMPRESA' OR C.CODIGO_TIPO_NOMINA=p_TIPO)))
  ORDER BY P.CODIGO_PERSONA_MOV_CTRL,C.CODIGO_CONCEPTO,C.CODIGO_TIPO_NOMINA
 ) WHERE ROWNUM<=201;
END;
