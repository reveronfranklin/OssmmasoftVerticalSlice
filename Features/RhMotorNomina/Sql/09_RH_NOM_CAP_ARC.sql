-- Oracle 10g: RH_NOM_CAP_ARC=14, RH_NOM_CAP_ARC_SEQ=18,
-- RH_PKG_NOM_CAP_ARC=18, TR_RH_NOM_CAP_ARC_IMM=21.
-- Immutable capture archive only. No payroll DML or COMMIT in package.
DECLARE n NUMBER;
BEGIN
  IF SYS_CONTEXT('USERENV','SESSION_USER')<>'RH' OR SYS_CONTEXT('USERENV','CURRENT_SCHEMA')<>'RH' THEN
    RAISE_APPLICATION_ERROR(-20001,'Instalar como RH.');
  END IF;
  SELECT COUNT(*) INTO n FROM USER_TABLES WHERE TABLE_NAME='RH_NOM_RUN_ACT';
  IF n<>1 THEN RAISE_APPLICATION_ERROR(-20001,'Instalar primero las corridas de simulacion.'); END IF;
  SELECT COUNT(*) INTO n FROM USER_OBJECTS WHERE OBJECT_NAME='RH_NOM_CAP_ARC';
  IF n=0 THEN
    EXECUTE IMMEDIATE 'CREATE TABLE RH_NOM_CAP_ARC (
      ID_CAP NUMBER(10) NOT NULL,CODIGO_EMPRESA NUMBER(10) NOT NULL,ACTOR NUMBER(10) NOT NULL,
      CLAVE_SOL VARCHAR2(80 CHAR) NOT NULL,HASH_SOL VARCHAR2(64 CHAR) NOT NULL,
      CODIGO_TIPO_NOMINA NUMBER(10) NOT NULL,CODIGO_PERIODO NUMBER(10) NOT NULL,
      FECHA_NOMINA DATE NOT NULL,NUM_PERIODO NUMBER(1) NOT NULL,
      CODIGO_PRESUPUESTO NUMBER(10) NOT NULL,CODIGO_PERSONA NUMBER(10) NOT NULL,
      VERSION_DOC VARCHAR2(40 CHAR) NOT NULL,DOCUMENTO CLOB NOT NULL,
      HASH_DOC VARCHAR2(64 CHAR) NOT NULL,FECHA_INS DATE DEFAULT SYSDATE NOT NULL,
      CONSTRAINT PK_RH_NOM_CAP_ARC PRIMARY KEY(ID_CAP),
      CONSTRAINT UK_RH_NOM_CAP_ARC UNIQUE(CODIGO_EMPRESA,ACTOR,CLAVE_SOL),
      CONSTRAINT CK_RH_NOM_CAP_ARC_POS CHECK(ID_CAP>0 AND CODIGO_EMPRESA>0 AND ACTOR>0
        AND CODIGO_TIPO_NOMINA>0 AND CODIGO_PERIODO>0 AND NUM_PERIODO BETWEEN 0 AND 9
        AND CODIGO_PRESUPUESTO>0 AND CODIGO_PERSONA>0))';
  ELSE
    SELECT COUNT(*) INTO n FROM USER_TABLES WHERE TABLE_NAME='RH_NOM_CAP_ARC';
    IF n<>1 THEN RAISE_APPLICATION_ERROR(-20001,'Conflicto RH_NOM_CAP_ARC.'); END IF;
  END IF;
  SELECT COUNT(*) INTO n FROM USER_OBJECTS WHERE OBJECT_NAME='RH_NOM_CAP_ARC_SEQ';
  IF n=0 THEN
    EXECUTE IMMEDIATE 'CREATE SEQUENCE RH_NOM_CAP_ARC_SEQ START WITH 1 INCREMENT BY 1 MAXVALUE 2147483647 NOCYCLE CACHE 20';
  ELSE
    SELECT COUNT(*) INTO n FROM USER_SEQUENCES WHERE SEQUENCE_NAME='RH_NOM_CAP_ARC_SEQ';
    IF n<>1 THEN RAISE_APPLICATION_ERROR(-20001,'Conflicto RH_NOM_CAP_ARC_SEQ.'); END IF;
  END IF;
END;
/
CREATE OR REPLACE TRIGGER TR_RH_NOM_CAP_ARC_IMM
BEFORE UPDATE OR DELETE ON RH_NOM_CAP_ARC
BEGIN
  RAISE_APPLICATION_ERROR(-20004,'El archivo de capsulas es inmutable.');
END;
/
CREATE OR REPLACE PACKAGE RH_PKG_NOM_CAP_ARC AS
  PROCEDURE CREAR(p_EMPRESA NUMBER,p_ACTOR NUMBER,p_CLAVE VARCHAR2,p_HASH_SOL VARCHAR2,
    p_TIPO NUMBER,p_PERIODO NUMBER,p_FECHA DATE,p_NUM_PERIODO NUMBER,p_PRESUPUESTO NUMBER,
    p_PERSONA NUMBER,p_VERSION VARCHAR2,p_DOC CLOB,p_HASH_DOC VARCHAR2,p_ID OUT NUMBER);
  PROCEDURE POR_CLAVE(p_EMPRESA NUMBER,p_ACTOR NUMBER,p_CLAVE VARCHAR2,p_RESULT OUT SYS_REFCURSOR);
  PROCEDURE LEER(p_EMPRESA NUMBER,p_ACTOR NUMBER,p_ID NUMBER,p_RESULT OUT SYS_REFCURSOR);
  PROCEDURE DOCUMENTO(p_EMPRESA NUMBER,p_ACTOR NUMBER,p_ID NUMBER,p_RESULT OUT SYS_REFCURSOR);
END;
/
CREATE OR REPLACE PACKAGE BODY RH_PKG_NOM_CAP_ARC AS
  PROCEDURE POSITIVO(p_VALOR NUMBER) IS
  BEGIN
    IF p_VALOR IS NULL OR p_VALOR<1 OR p_VALOR>2147483647 OR p_VALOR<>TRUNC(p_VALOR) THEN
      RAISE_APPLICATION_ERROR(-20001,'Identidad positiva entera requerida.');
    END IF;
  END;
  PROCEDURE CREAR(p_EMPRESA NUMBER,p_ACTOR NUMBER,p_CLAVE VARCHAR2,p_HASH_SOL VARCHAR2,
    p_TIPO NUMBER,p_PERIODO NUMBER,p_FECHA DATE,p_NUM_PERIODO NUMBER,p_PRESUPUESTO NUMBER,
    p_PERSONA NUMBER,p_VERSION VARCHAR2,p_DOC CLOB,p_HASH_DOC VARCHAR2,p_ID OUT NUMBER) IS
    v_actor NUMBER;v_count NUMBER;v_row RH_NOM_CAP_ARC%ROWTYPE;
  BEGIN
    POSITIVO(p_EMPRESA);POSITIVO(p_ACTOR);POSITIVO(p_TIPO);POSITIVO(p_PERIODO);
    POSITIVO(p_PRESUPUESTO);POSITIVO(p_PERSONA);
    IF p_CLAVE IS NULL OR LENGTH(p_CLAVE)>80 OR NOT REGEXP_LIKE(p_CLAVE,'^[A-Za-z0-9:_-]+$')
      OR p_HASH_SOL IS NULL OR LENGTH(p_HASH_SOL)<>64 OR NOT REGEXP_LIKE(p_HASH_SOL,'^[A-F0-9]{64}$')
      OR p_HASH_DOC IS NULL OR LENGTH(p_HASH_DOC)<>64 OR NOT REGEXP_LIKE(p_HASH_DOC,'^[A-F0-9]{64}$')
      OR p_FECHA IS NULL OR p_FECHA<TO_DATE('19000101','YYYYMMDD')
      OR p_NUM_PERIODO IS NULL OR p_NUM_PERIODO<0 OR p_NUM_PERIODO>9 OR p_NUM_PERIODO<>TRUNC(p_NUM_PERIODO)
      OR p_VERSION IS NULL OR p_VERSION NOT IN ('CAPSULA_PRENOMINA_V1','CAPSULA_PRENOMINA_V2','CAPSULA_PRENOMINA_V3','CAPSULA_PRENOMINA_V4','CAPSULA_PRENOMINA_V5')
      OR p_DOC IS NULL OR DBMS_LOB.GETLENGTH(p_DOC)<1 OR DBMS_LOB.GETLENGTH(p_DOC)>2097152 THEN
      RAISE_APPLICATION_ERROR(-20001,'Capsula incompleta o invalida.');
    END IF;
    BEGIN INSERT INTO RH_NOM_RUN_ACT(CODIGO_EMPRESA,ACTOR) VALUES(p_EMPRESA,p_ACTOR);
      EXCEPTION WHEN DUP_VAL_ON_INDEX THEN NULL; END;
    SELECT ACTOR INTO v_actor FROM RH_NOM_RUN_ACT
      WHERE CODIGO_EMPRESA=p_EMPRESA AND ACTOR=p_ACTOR FOR UPDATE;
    BEGIN
      SELECT * INTO v_row FROM RH_NOM_CAP_ARC
        WHERE CODIGO_EMPRESA=p_EMPRESA AND ACTOR=p_ACTOR AND CLAVE_SOL=p_CLAVE;
      IF v_row.HASH_SOL<>p_HASH_SOL OR v_row.HASH_DOC<>p_HASH_DOC OR v_row.VERSION_DOC<>p_VERSION
        OR v_row.CODIGO_TIPO_NOMINA<>p_TIPO OR v_row.CODIGO_PERIODO<>p_PERIODO
        OR v_row.FECHA_NOMINA<>p_FECHA OR v_row.NUM_PERIODO<>p_NUM_PERIODO
        OR v_row.CODIGO_PRESUPUESTO<>p_PRESUPUESTO OR v_row.CODIGO_PERSONA<>p_PERSONA THEN
        RAISE_APPLICATION_ERROR(-20001,'La clave identifica otra captura.');
      END IF;
      p_ID:=v_row.ID_CAP;RETURN;
    EXCEPTION WHEN NO_DATA_FOUND THEN NULL; END;
    SELECT COUNT(*) INTO v_count FROM RH_NOM_CAP_ARC WHERE CODIGO_EMPRESA=p_EMPRESA AND ACTOR=p_ACTOR;
    IF v_count>=500 THEN RAISE_APPLICATION_ERROR(-20001,'Limite de capsulas del usuario.'); END IF;
    p_ID:=RH_NOM_CAP_ARC_SEQ.NEXTVAL;
    INSERT INTO RH_NOM_CAP_ARC(ID_CAP,CODIGO_EMPRESA,ACTOR,CLAVE_SOL,HASH_SOL,
      CODIGO_TIPO_NOMINA,CODIGO_PERIODO,FECHA_NOMINA,NUM_PERIODO,CODIGO_PRESUPUESTO,
      CODIGO_PERSONA,VERSION_DOC,DOCUMENTO,HASH_DOC)
      VALUES(p_ID,p_EMPRESA,p_ACTOR,p_CLAVE,p_HASH_SOL,p_TIPO,p_PERIODO,p_FECHA,
        p_NUM_PERIODO,p_PRESUPUESTO,p_PERSONA,p_VERSION,p_DOC,p_HASH_DOC);
    -- Caller owns commit/rollback. Stored metadata grants no payroll ownership.
  END;
  PROCEDURE POR_CLAVE(p_EMPRESA NUMBER,p_ACTOR NUMBER,p_CLAVE VARCHAR2,p_RESULT OUT SYS_REFCURSOR) IS
  BEGIN
    POSITIVO(p_EMPRESA);POSITIVO(p_ACTOR);
    OPEN p_RESULT FOR SELECT ID_CAP,CODIGO_EMPRESA,ACTOR,CLAVE_SOL,HASH_SOL,HASH_DOC,VERSION_DOC,
      CODIGO_TIPO_NOMINA,CODIGO_PERIODO,FECHA_NOMINA,NUM_PERIODO,CODIGO_PRESUPUESTO,CODIGO_PERSONA,FECHA_INS
      FROM RH_NOM_CAP_ARC WHERE CODIGO_EMPRESA=p_EMPRESA AND ACTOR=p_ACTOR AND CLAVE_SOL=p_CLAVE;
  END;
  PROCEDURE LEER(p_EMPRESA NUMBER,p_ACTOR NUMBER,p_ID NUMBER,p_RESULT OUT SYS_REFCURSOR) IS
  BEGIN
    POSITIVO(p_EMPRESA);POSITIVO(p_ACTOR);POSITIVO(p_ID);
    OPEN p_RESULT FOR SELECT ID_CAP,CODIGO_EMPRESA,ACTOR,CLAVE_SOL,HASH_SOL,HASH_DOC,VERSION_DOC,
      CODIGO_TIPO_NOMINA,CODIGO_PERIODO,FECHA_NOMINA,NUM_PERIODO,CODIGO_PRESUPUESTO,CODIGO_PERSONA,FECHA_INS
      FROM RH_NOM_CAP_ARC WHERE CODIGO_EMPRESA=p_EMPRESA AND ACTOR=p_ACTOR AND ID_CAP=p_ID;
  END;
  PROCEDURE DOCUMENTO(p_EMPRESA NUMBER,p_ACTOR NUMBER,p_ID NUMBER,p_RESULT OUT SYS_REFCURSOR) IS
  BEGIN
    POSITIVO(p_EMPRESA);POSITIVO(p_ACTOR);POSITIVO(p_ID);
    OPEN p_RESULT FOR SELECT X.HUELLA,X.LARGO,N.PARTE,DBMS_LOB.SUBSTR(X.DOC,1000,(N.PARTE-1)*1000+1) FRAGMENTO
      FROM (SELECT DOCUMENTO DOC,HASH_DOC HUELLA,DBMS_LOB.GETLENGTH(DOCUMENTO) LARGO
        FROM RH_NOM_CAP_ARC WHERE CODIGO_EMPRESA=p_EMPRESA AND ACTOR=p_ACTOR AND ID_CAP=p_ID) X,
        (SELECT LEVEL PARTE FROM DUAL CONNECT BY LEVEL<=2098) N
      WHERE N.PARTE<=CEIL(X.LARGO/1000) ORDER BY N.PARTE;
  END;
END;
