-- Durable period orchestration. No changes to RH_MOV_NOMINA.
DECLARE N NUMBER; BEGIN
 SELECT COUNT(*) INTO N FROM ALL_TABLES WHERE OWNER='RH' AND TABLE_NAME='RH_NOM_PRE_LOT';
 IF N=0 THEN EXECUTE IMMEDIATE 'CREATE TABLE RH.RH_NOM_PRE_LOT (
 ID_LOTE NUMBER(10) NOT NULL, CODIGO_EMPRESA NUMBER(10) NOT NULL, ACTOR NUMBER(10) NOT NULL,
 CLAVE_SOL VARCHAR2(80) NOT NULL, HASH_SOL VARCHAR2(64) NOT NULL, VERSION NUMBER(10) NOT NULL,
 ESTADO VARCHAR2(20) NOT NULL, DOCUMENTO CLOB NOT NULL, HASH_DOC VARCHAR2(64) NOT NULL, FECHA_INS DATE DEFAULT SYSDATE NOT NULL,
 FECHA_UPD DATE DEFAULT SYSDATE NOT NULL, CONSTRAINT RH_NOM_PRE_LOT_PK PRIMARY KEY(ID_LOTE),
 CONSTRAINT RH_NOM_PRE_LOT_UK UNIQUE(CODIGO_EMPRESA,ACTOR,CLAVE_SOL)) INITRANS 8'; END IF;
 SELECT COUNT(*) INTO N FROM ALL_SEQUENCES WHERE SEQUENCE_OWNER='RH' AND SEQUENCE_NAME='RH_NOM_PRE_LOT_SEQ';
 IF N=0 THEN EXECUTE IMMEDIATE 'CREATE SEQUENCE RH.RH_NOM_PRE_LOT_SEQ START WITH 1 INCREMENT BY 1 NOCYCLE'; END IF;
END;
/
CREATE OR REPLACE PACKAGE RH.RH_PKG_NOM_PRE AS
 PROCEDURE PENDIENTE(p_EMPRESA NUMBER,p_RESULT OUT SYS_REFCURSOR);
 PROCEDURE RESERVAR(p_EMPRESA NUMBER,p_ACTOR NUMBER,p_ID NUMBER,p_VERSION NUMBER);
 PROCEDURE LEER(p_EMPRESA NUMBER,p_ACTOR NUMBER,p_ID NUMBER,p_CLAVE VARCHAR2,p_RESULT OUT SYS_REFCURSOR);
 PROCEDURE CREAR(p_EMPRESA NUMBER,p_ACTOR NUMBER,p_CLAVE VARCHAR2,p_HASH_SOL VARCHAR2,p_DOC CLOB,p_HASH_DOC VARCHAR2,p_ESTADO VARCHAR2,p_ID OUT NUMBER);
 PROCEDURE GUARDAR(p_EMPRESA NUMBER,p_ACTOR NUMBER,p_ID NUMBER,p_VERSION NUMBER,p_DOC CLOB,p_HASH_DOC VARCHAR2,p_ESTADO VARCHAR2);
END;
/
CREATE OR REPLACE PACKAGE BODY RH.RH_PKG_NOM_PRE AS
 PROCEDURE RESERVAR(p_EMPRESA NUMBER,p_ACTOR NUMBER,p_ID NUMBER,p_VERSION NUMBER) IS V NUMBER;BEGIN
  SELECT VERSION INTO V FROM RH.RH_NOM_PRE_LOT WHERE ID_LOTE=p_ID AND CODIGO_EMPRESA=p_EMPRESA AND ACTOR=p_ACTOR FOR UPDATE NOWAIT;
  IF V<>p_VERSION THEN RAISE_APPLICATION_ERROR(-20002,'Lote modificado.'); END IF;
 END;
 PROCEDURE PENDIENTE(p_EMPRESA NUMBER,p_RESULT OUT SYS_REFCURSOR) IS BEGIN
  OPEN p_RESULT FOR SELECT ID_LOTE,ACTOR FROM (SELECT ID_LOTE,ACTOR FROM RH.RH_NOM_PRE_LOT WHERE CODIGO_EMPRESA=p_EMPRESA AND ESTADO IN ('CALCULANDO','GUARDANDO') ORDER BY ID_LOTE) WHERE ROWNUM=1;
 END;
 PROCEDURE LEER(p_EMPRESA NUMBER,p_ACTOR NUMBER,p_ID NUMBER,p_CLAVE VARCHAR2,p_RESULT OUT SYS_REFCURSOR) IS BEGIN
  OPEN p_RESULT FOR SELECT ID_LOTE,VERSION,HASH_SOL,DOCUMENTO,HASH_DOC FROM RH.RH_NOM_PRE_LOT
   WHERE CODIGO_EMPRESA=p_EMPRESA AND ACTOR=p_ACTOR AND (ID_LOTE=p_ID OR (p_ID IS NULL AND CLAVE_SOL=p_CLAVE));
 END;
 PROCEDURE CREAR(p_EMPRESA NUMBER,p_ACTOR NUMBER,p_CLAVE VARCHAR2,p_HASH_SOL VARCHAR2,p_DOC CLOB,p_HASH_DOC VARCHAR2,p_ESTADO VARCHAR2,p_ID OUT NUMBER) IS BEGIN
  IF p_EMPRESA<=0 OR p_ACTOR<=0 OR LENGTH(p_CLAVE)>80 OR LENGTH(p_HASH_SOL)<>64 OR LENGTH(p_HASH_DOC)<>64
   OR DBMS_LOB.GETLENGTH(p_DOC)>2097152 THEN RAISE_APPLICATION_ERROR(-20001,'Lote invalido.'); END IF;
  SELECT RH.RH_NOM_PRE_LOT_SEQ.NEXTVAL INTO p_ID FROM DUAL;
  INSERT INTO RH.RH_NOM_PRE_LOT(ID_LOTE,CODIGO_EMPRESA,ACTOR,CLAVE_SOL,HASH_SOL,VERSION,DOCUMENTO,HASH_DOC,ESTADO)
   VALUES(p_ID,p_EMPRESA,p_ACTOR,p_CLAVE,p_HASH_SOL,1,p_DOC,p_HASH_DOC,p_ESTADO);
 END;
 PROCEDURE GUARDAR(p_EMPRESA NUMBER,p_ACTOR NUMBER,p_ID NUMBER,p_VERSION NUMBER,p_DOC CLOB,p_HASH_DOC VARCHAR2,p_ESTADO VARCHAR2) IS BEGIN
  IF DBMS_LOB.GETLENGTH(p_DOC)>2097152 OR LENGTH(p_HASH_DOC)<>64 THEN RAISE_APPLICATION_ERROR(-20001,'Documento invalido.'); END IF;
  UPDATE RH.RH_NOM_PRE_LOT SET ESTADO=p_ESTADO,DOCUMENTO=p_DOC,HASH_DOC=p_HASH_DOC,VERSION=VERSION+1,FECHA_UPD=SYSDATE
   WHERE CODIGO_EMPRESA=p_EMPRESA AND ACTOR=p_ACTOR AND ID_LOTE=p_ID AND VERSION=p_VERSION;
  IF SQL%ROWCOUNT<>1 THEN RAISE_APPLICATION_ERROR(-20002,'Lote modificado; recargue.'); END IF;
 END;
END;
