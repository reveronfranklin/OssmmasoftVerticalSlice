-- Como RH. SP_RH_NOM_REF_HIST=18 caracteres. Oracle 10g.
-- Solo resultados almacenados. No consulta cargos/conceptos actuales ni calcula nomina.
CREATE OR REPLACE PROCEDURE RH.SP_RH_NOM_REF_HIST (
  p_EMPRESA IN NUMBER,p_TIPO IN NUMBER,p_PERIODO IN NUMBER,p_FECHA IN DATE,
  p_PERSONA IN NUMBER,p_RESULT OUT SYS_REFCURSOR
) AUTHID DEFINER AS
BEGIN
  IF p_EMPRESA IS NULL OR p_EMPRESA<=0 OR p_EMPRESA<>TRUNC(p_EMPRESA)
     OR p_TIPO IS NULL OR p_TIPO<=0 OR p_TIPO<>TRUNC(p_TIPO)
     OR p_PERIODO IS NULL OR p_PERIODO<=0 OR p_PERIODO<>TRUNC(p_PERIODO)
     OR p_PERSONA IS NULL OR p_PERSONA<=0 OR p_PERSONA<>TRUNC(p_PERSONA)
     OR p_FECHA IS NULL THEN
    RAISE_APPLICATION_ERROR(-20001,'Contexto de referencia invalido.');
  END IF;
  -- 1001 es centinela de exceso; la API no entrega referencias truncadas.
  OPEN p_RESULT FOR SELECT * FROM (
    SELECT H.CODIGO_HISTORICO_NOMINA,H.CODIGO_CONCEPTO,H.FRECUENCIA_ID,
           H.TIPO TIPO_MOVIMIENTO,H.STATUS ESTADO_REGISTRO,
           TO_CHAR(H.MONTO,'TM9','NLS_NUMERIC_CHARACTERS=''.,''') MONTO_TEXTO
      FROM RH.RH_HISTORICO_NOMINA H
     WHERE H.CODIGO_EMPRESA=p_EMPRESA AND H.CODIGO_TIPO_NOMINA=p_TIPO
       AND H.CODIGO_PERIODO=p_PERIODO AND H.FECHA_NOMINA=p_FECHA
       AND H.CODIGO_PERSONA=p_PERSONA
       AND EXISTS(SELECT 1 FROM RH.RH_PERIODOS P
                   WHERE P.CODIGO_EMPRESA=p_EMPRESA AND P.CODIGO_TIPO_NOMINA=p_TIPO
                     AND P.CODIGO_PERIODO=p_PERIODO AND P.FECHA_NOMINA=p_FECHA
                     AND P.FECHA_CIERRE IS NOT NULL)
     ORDER BY H.CODIGO_HISTORICO_NOMINA,H.CODIGO_CONCEPTO,H.FRECUENCIA_ID,H.TIPO
  ) WHERE ROWNUM<=1001;
END;
