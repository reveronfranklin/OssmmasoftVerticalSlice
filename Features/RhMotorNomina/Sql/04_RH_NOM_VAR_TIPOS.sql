-- Oracle 10g. CK_RH_NOM_VAR_TIP2 = 18 caracteres.
-- Nueva restriccion valida antes de retirar las anteriores; sin DML de negocio.
DECLARE n NUMBER; old_n NUMBER;
BEGIN
 SELECT COUNT(*) INTO n FROM USER_CONSTRAINTS WHERE TABLE_NAME='RH_NOM_VAR'
  AND CONSTRAINT_NAME='CK_RH_NOM_VAR_TIP2';
 IF n=0 THEN
  EXECUTE IMMEDIATE 'ALTER TABLE RH_NOM_VAR ADD CONSTRAINT CK_RH_NOM_VAR_TIP2 CHECK (
   (TIPO=''NUMERO'' AND UNIDAD IN (''NUMERO'',''DINERO'',''TASA'',''PORCENTAJE'',''FACTOR'',''DIAS'',''CANTIDAD''))
   OR (TIPO IN (''FECHA'',''BOOLEANO'',''TEXTO'') AND UNIDAD=TIPO AND ORIGEN IN (''ENTRADA'',''PARAMETRO''))) ENABLE VALIDATE';
 END IF;
 SELECT COUNT(*) INTO n FROM USER_CONSTRAINTS WHERE TABLE_NAME='RH_NOM_VAR'
  AND CONSTRAINT_NAME='CK_RH_NOM_VAR_TIP2' AND STATUS='ENABLED' AND VALIDATED='VALIDATED';
 IF n<>1 THEN RAISE_APPLICATION_ERROR(-20001,'Restriccion tipada no esta validada.'); END IF;
 FOR c IN (SELECT CONSTRAINT_NAME FROM USER_CONSTRAINTS WHERE TABLE_NAME='RH_NOM_VAR'
   AND CONSTRAINT_NAME IN ('CK_RH_NOM_VAR_TIPO','CK_RH_NOM_VAR_UNI')) LOOP
  EXECUTE IMMEDIATE 'ALTER TABLE RH_NOM_VAR DROP CONSTRAINT '||c.CONSTRAINT_NAME;
 END LOOP;
END;
/
