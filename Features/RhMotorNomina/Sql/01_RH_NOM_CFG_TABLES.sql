-- Ejecutar como RH. Oracle 10g. No modifica tablas de movimientos ni el paquete viejo.
-- Identificadores verificados: RH_NOM_VAR=10, RH_NOM_MOD_CTL=14,
-- RH_NOM_MOD_VER=14, RH_NOM_VAR_SEQ=14, RH_PKG_NOM_CFG=14.
DECLARE
  n NUMBER;
  PROCEDURE crear(p_name VARCHAR2, p_sql VARCHAR2) IS
    c NUMBER;
  BEGIN
    SELECT COUNT(*) INTO c FROM USER_OBJECTS WHERE OBJECT_NAME=p_name;
    IF c=0 THEN EXECUTE IMMEDIATE p_sql; END IF;
  END;
BEGIN
  IF SYS_CONTEXT('USERENV','CURRENT_SCHEMA') <> 'RH'
     OR SYS_CONTEXT('USERENV','SESSION_USER') <> 'RH' THEN
    RAISE_APPLICATION_ERROR(-20001,'Instalar como RH con CURRENT_SCHEMA RH.');
  END IF;
  -- Do not silently replace an existing object of an incompatible type.
  SELECT COUNT(*) INTO n FROM USER_OBJECTS
   WHERE (OBJECT_NAME IN ('RH_NOM_VAR','RH_NOM_MOD_CTL','RH_NOM_MOD_VER') AND OBJECT_TYPE<>'TABLE')
      OR (OBJECT_NAME='RH_NOM_VAR_SEQ' AND OBJECT_TYPE<>'SEQUENCE');
  IF n>0 THEN RAISE_APPLICATION_ERROR(-20001,'Conflicto de nombres en objetos de configuracion.'); END IF;
  crear('RH_NOM_VAR', 'CREATE TABLE RH_NOM_VAR (
    ID_VAR NUMBER(10) NOT NULL, CODIGO_EMPRESA NUMBER(10) NOT NULL,
    CODIGO VARCHAR2(60 CHAR) NOT NULL, DESCRIPCION VARCHAR2(300 CHAR) NOT NULL,
    TIPO VARCHAR2(12 CHAR) NOT NULL, UNIDAD VARCHAR2(12 CHAR) NOT NULL,
    ORIGEN VARCHAR2(12 CHAR) NOT NULL, ACTIVA NUMBER(1) NOT NULL,
    VERSION NUMBER(10) NOT NULL, USUARIO_INS NUMBER(10) NOT NULL, FECHA_INS DATE NOT NULL,
    USUARIO_UPD NUMBER(10), FECHA_UPD DATE,
    CONSTRAINT PK_RH_NOM_VAR PRIMARY KEY(ID_VAR),
    CONSTRAINT UK_RH_NOM_VAR UNIQUE(CODIGO_EMPRESA,CODIGO),
    CONSTRAINT CK_RH_NOM_VAR_ACT CHECK(ACTIVA IN (0,1)),
    CONSTRAINT CK_RH_NOM_VAR_TIPO CHECK(TIPO IN (''NUMERO'',''FECHA'',''BOOLEANO'',''TEXTO'')),
    CONSTRAINT CK_RH_NOM_VAR_UNI CHECK(UNIDAD IN (''NUMERO'',''DINERO'',''TASA'',''PORCENTAJE'',''FACTOR'',''DIAS'',''CANTIDAD'',''FECHA'',''BOOLEANO'',''TEXTO'')),
    CONSTRAINT CK_RH_NOM_VAR_ORI CHECK(ORIGEN IN (''ENTRADA'',''PARAMETRO'',''CALCULADA'')),
    CONSTRAINT CK_RH_NOM_VAR_VER CHECK(VERSION>=1),
    CONSTRAINT CK_RH_NOM_VAR_EMP CHECK(CODIGO_EMPRESA>0))');
  crear('RH_NOM_VAR_SEQ','CREATE SEQUENCE RH_NOM_VAR_SEQ START WITH 1 INCREMENT BY 1 MAXVALUE 2147483647 NOCYCLE CACHE 20');
  crear('RH_NOM_MOD_CTL', 'CREATE TABLE RH_NOM_MOD_CTL (
    ID_MODELO NUMBER(10) NOT NULL, CODIGO_EMPRESA NUMBER(10) NOT NULL,
    ULT_VERSION NUMBER(10) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_RH_NOM_MOD_CTL PRIMARY KEY(ID_MODELO,CODIGO_EMPRESA),
    CONSTRAINT FK_RH_NOM_CTL_MOD FOREIGN KEY(ID_MODELO) REFERENCES SIS.OSS_MODELO_CALCULO(ID),
    CONSTRAINT CK_RH_NOM_CTL_VER CHECK(ULT_VERSION>=0),
    CONSTRAINT CK_RH_NOM_CTL_EMP CHECK(CODIGO_EMPRESA>0))');
  crear('RH_NOM_MOD_VER', 'CREATE TABLE RH_NOM_MOD_VER (
    ID_MODELO NUMBER(10) NOT NULL, CODIGO_EMPRESA NUMBER(10) NOT NULL,
    VERSION NUMBER(10) NOT NULL, CODIGO_TIPO_NOMINA NUMBER(10) NOT NULL,
    ESCENARIO VARCHAR2(24 CHAR) NOT NULL, DESCRIPCION VARCHAR2(300 CHAR) NOT NULL,
    CONFIG_JSON CLOB NOT NULL, CONFIG_HASH VARCHAR2(64 CHAR) NOT NULL,
    USUARIO_INS NUMBER(10) NOT NULL, FECHA_INS DATE NOT NULL,
    CONSTRAINT PK_RH_NOM_MOD_VER PRIMARY KEY(ID_MODELO,CODIGO_EMPRESA,VERSION),
    CONSTRAINT FK_RH_NOM_VER_CTL FOREIGN KEY(ID_MODELO,CODIGO_EMPRESA)
      REFERENCES RH_NOM_MOD_CTL(ID_MODELO,CODIGO_EMPRESA),
    CONSTRAINT CK_RH_NOM_VER_NUM CHECK(VERSION>=1),
    CONSTRAINT CK_RH_NOM_VER_ESC CHECK(ESCENARIO IN (''ADJUNTAR_CARGO'',''RECALCULA_VARIACIONES'')))');
END;
/

-- Saved revisions are immutable. A new save appends a new revision.
CREATE OR REPLACE TRIGGER TR_RH_NOM_VER_IMM
BEFORE UPDATE OR DELETE ON RH_NOM_MOD_VER
BEGIN
  RAISE_APPLICATION_ERROR(-20004,'Las revisiones guardadas son inmutables. Cree una nueva revision.');
END;
