 crear('RH_NOM_MOD_AUD','TABLE','CREATE TABLE RH_NOM_MOD_AUD (
 ID_EVENTO NUMBER(10) NOT NULL,ID_MODELO NUMBER(10) NOT NULL,CODIGO_EMPRESA NUMBER(10) NOT NULL,
