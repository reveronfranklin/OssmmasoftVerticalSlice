CREATE OR REPLACE PACKAGE BODY RH_PKG_NOM_EST AS
 PROCEDURE base(p_EMPRESA NUMBER,p_MODELO NUMBER,p_VERSION NUMBER) IS
 BEGIN
  IF p_EMPRESA IS NULL OR p_EMPRESA<=0 OR p_MODELO IS NULL OR p_MODELO<=0 OR p_VERSION IS NULL OR p_VERSION<=0 THEN
   RAISE_APPLICATION_ERROR(-20001,'Contexto de estado invalido.'); END IF;
 END;
 PROCEDURE contexto(p_EMPRESA NUMBER,p_ACTOR NUMBER,p_MODELO NUMBER,p_VERSION NUMBER,p_HASH VARCHAR2,p_VER_EST NUMBER,p_MOTIVO VARCHAR2) IS
 BEGIN
  base(p_EMPRESA,p_MODELO,p_VERSION);
  IF p_ACTOR IS NULL OR p_ACTOR<=0 OR p_VER_EST IS NULL OR p_VER_EST<0 OR p_VER_EST<>TRUNC(p_VER_EST)
    OR p_HASH IS NULL OR LENGTH(p_HASH)<>64 OR TRIM(p_MOTIVO) IS NULL OR LENGTH(TRIM(p_MOTIVO)) NOT BETWEEN 10 AND 500 THEN
   RAISE_APPLICATION_ERROR(-20001,'Actor/hash/version/motivo invalidos.'); END IF;
 END;
 PROCEDURE bloquear(p_EMPRESA NUMBER,p_MODELO NUMBER,p_VERSION NUMBER,p_HASH VARCHAR2,p_VER_EST NUMBER,p_EST OUT VARCHAR2) IS
  n NUMBER; h VARCHAR2(64); v NUMBER;
 BEGIN
  SELECT ULT_VERSION INTO n FROM RH_NOM_MOD_CTL WHERE CODIGO_EMPRESA=p_EMPRESA AND ID_MODELO=p_MODELO FOR UPDATE NOWAIT;
  SELECT CONFIG_HASH INTO h FROM RH_NOM_MOD_VER WHERE CODIGO_EMPRESA=p_EMPRESA AND ID_MODELO=p_MODELO AND VERSION=p_VERSION;
  IF h<>p_HASH THEN RAISE_APPLICATION_ERROR(-20002,'Hash modelo cambio.'); END IF;
  BEGIN SELECT ESTADO,VER_ESTADO INTO p_EST,v FROM RH_NOM_MOD_EST WHERE CODIGO_EMPRESA=p_EMPRESA AND ID_MODELO=p_MODELO AND VER_MODELO=p_VERSION;
  EXCEPTION WHEN NO_DATA_FOUND THEN p_EST:='BORRADOR';v:=0; END;
  IF v<>p_VER_EST THEN RAISE_APPLICATION_ERROR(-20002,'Version de estado cambio.'); END IF;
 END;
 PROCEDURE scope_lock(p_EMPRESA NUMBER,p_MODELO NUMBER,p_VERSION NUMBER,p_TIPO OUT NUMBER,p_ESC OUT VARCHAR2) IS n NUMBER;
 BEGIN
  SELECT CODIGO_TIPO_NOMINA,ESCENARIO INTO p_TIPO,p_ESC FROM RH_NOM_MOD_VER WHERE CODIGO_EMPRESA=p_EMPRESA AND ID_MODELO=p_MODELO AND VERSION=p_VERSION;
  BEGIN INSERT INTO RH_NOM_PUB_LCK(CODIGO_EMPRESA,CODIGO_TIPO_NOMINA,ESCENARIO) VALUES(p_EMPRESA,p_TIPO,p_ESC);EXCEPTION WHEN DUP_VAL_ON_INDEX THEN NULL;END;
  SELECT CODIGO_EMPRESA INTO n FROM RH_NOM_PUB_LCK WHERE CODIGO_EMPRESA=p_EMPRESA AND CODIGO_TIPO_NOMINA=p_TIPO AND ESCENARIO=p_ESC FOR UPDATE NOWAIT;
 END;
 PROCEDURE evento(p_EMPRESA NUMBER,p_ACTOR NUMBER,p_MODELO NUMBER,p_VERSION NUMBER,p_ACC VARCHAR2,p_ANT VARCHAR2,p_NUEVO VARCHAR2,p_MOTIVO VARCHAR2,p_HASH_VAL VARCHAR2) IS
 BEGIN
  INSERT INTO RH_NOM_MOD_AUD(ID_EVENTO,ID_MODELO,CODIGO_EMPRESA,VER_MODELO,ACCION,ESTADO_ANT,ESTADO_NUEVO,ACTOR,FECHA,MOTIVO,HASH_VALIDACION)
  VALUES(RH_NOM_AUD_SEQ.NEXTVAL,p_MODELO,p_EMPRESA,p_VERSION,p_ACC,p_ANT,p_NUEVO,p_ACTOR,SYSDATE,TRIM(p_MOTIVO),p_HASH_VAL);
 END;
 PROCEDURE LEER(p_EMPRESA NUMBER,p_MODELO NUMBER,p_VERSION NUMBER,p_RESULT OUT SYS_REFCURSOR) IS
 BEGIN
  base(p_EMPRESA,p_MODELO,p_VERSION);
  OPEN p_RESULT FOR SELECT V.ID_MODELO,V.VERSION,V.CONFIG_HASH,V.USUARIO_INS,
   NVL(E.ESTADO,'BORRADOR') ESTADO,NVL(E.VER_ESTADO,0) VER_ESTADO,
   E.ACTOR_VAL,E.ACTOR_PUB,E.FECHA_VAL,E.FECHA_PUB,E.FECHA_RET,E.DESDE,E.HASTA,E.MOTIVO,
   E.HASH_VALIDACION,E.NIVEL,NVL(E.APTA,0) APTA,
   DBMS_LOB.SUBSTR(E.EVIDENCIA,2000,1) E1,DBMS_LOB.SUBSTR(E.EVIDENCIA,2000,2001) E2,
   DBMS_LOB.SUBSTR(E.EVIDENCIA,2000,4001) E3,DBMS_LOB.SUBSTR(E.EVIDENCIA,2000,6001) E4,
   DBMS_LOB.SUBSTR(E.EVIDENCIA,2000,8001) E5,DBMS_LOB.SUBSTR(E.EVIDENCIA,2000,10001) E6,
   DBMS_LOB.SUBSTR(E.EVIDENCIA,2000,12001) E7,DBMS_LOB.SUBSTR(E.EVIDENCIA,2000,14001) E8,
   DBMS_LOB.GETLENGTH(E.EVIDENCIA) E_LARGO
   FROM RH_NOM_MOD_VER V LEFT JOIN RH_NOM_MOD_EST E ON E.ID_MODELO=V.ID_MODELO AND E.CODIGO_EMPRESA=V.CODIGO_EMPRESA AND E.VER_MODELO=V.VERSION
   WHERE V.CODIGO_EMPRESA=p_EMPRESA AND V.ID_MODELO=p_MODELO AND V.VERSION=p_VERSION;
 END;
 PROCEDURE AUDITORIA(p_EMPRESA NUMBER,p_MODELO NUMBER,p_VERSION NUMBER,p_PAGE NUMBER,p_SIZE NUMBER,p_TOTAL OUT NUMBER,p_RESULT OUT SYS_REFCURSOR) IS
 BEGIN
  base(p_EMPRESA,p_MODELO,p_VERSION);
  IF p_PAGE IS NULL OR p_PAGE NOT BETWEEN 1 AND 100000 OR p_PAGE<>TRUNC(p_PAGE) OR p_SIZE IS NULL OR p_SIZE NOT BETWEEN 1 AND 100 OR p_SIZE<>TRUNC(p_SIZE) THEN RAISE_APPLICATION_ERROR(-20001,'Pagina invalida.');END IF;
  SELECT COUNT(*) INTO p_TOTAL FROM RH_NOM_MOD_AUD WHERE CODIGO_EMPRESA=p_EMPRESA AND ID_MODELO=p_MODELO AND VER_MODELO=p_VERSION;
  OPEN p_RESULT FOR SELECT * FROM (SELECT A.*,ROW_NUMBER() OVER(ORDER BY ID_EVENTO DESC) RN FROM RH_NOM_MOD_AUD A WHERE CODIGO_EMPRESA=p_EMPRESA AND ID_MODELO=p_MODELO AND VER_MODELO=p_VERSION) WHERE RN>(p_PAGE-1)*p_SIZE AND RN<=p_PAGE*p_SIZE;
 END;
 PROCEDURE VALIDAR(p_EMPRESA NUMBER,p_ACTOR NUMBER,p_MODELO NUMBER,p_VERSION NUMBER,p_HASH VARCHAR2,p_VER_EST NUMBER,
  p_EVIDENCIA CLOB,p_HASH_VAL VARCHAR2,p_NIVEL VARCHAR2,p_APTA NUMBER,p_MOTIVO VARCHAR2) IS s VARCHAR2(12);
 BEGIN
  contexto(p_EMPRESA,p_ACTOR,p_MODELO,p_VERSION,p_HASH,p_VER_EST,p_MOTIVO);bloquear(p_EMPRESA,p_MODELO,p_VERSION,p_HASH,p_VER_EST,s);
  IF s NOT IN ('BORRADOR','VALIDADO') OR p_EVIDENCIA IS NULL OR DBMS_LOB.GETLENGTH(p_EVIDENCIA)>16000 OR p_HASH_VAL IS NULL OR LENGTH(p_HASH_VAL)<>64
    OR p_NIVEL IS NULL OR p_NIVEL NOT IN ('TECNICO','INTEGRAL') OR p_APTA IS NULL OR p_APTA NOT IN (0,1) OR (p_APTA=1 AND p_NIVEL<>'INTEGRAL') THEN RAISE_APPLICATION_ERROR(-20001,'Evidencia/estado invalidos.');END IF;
  IF s='BORRADOR' THEN
   INSERT INTO RH_NOM_MOD_EST(ID_MODELO,CODIGO_EMPRESA,VER_MODELO,ESTADO,VER_ESTADO,HASH_MODELO) VALUES(p_MODELO,p_EMPRESA,p_VERSION,'VALIDADO',1,p_HASH);
  ELSE UPDATE RH_NOM_MOD_EST SET VER_ESTADO=VER_ESTADO+1 WHERE ID_MODELO=p_MODELO AND CODIGO_EMPRESA=p_EMPRESA AND VER_MODELO=p_VERSION;END IF;
  UPDATE RH_NOM_MOD_EST SET ESTADO='VALIDADO',EVIDENCIA=p_EVIDENCIA,HASH_VALIDACION=p_HASH_VAL,NIVEL=p_NIVEL,APTA=p_APTA,ACTOR_VAL=p_ACTOR,FECHA_VAL=SYSDATE,MOTIVO=TRIM(p_MOTIVO)
   WHERE ID_MODELO=p_MODELO AND CODIGO_EMPRESA=p_EMPRESA AND VER_MODELO=p_VERSION;
  evento(p_EMPRESA,p_ACTOR,p_MODELO,p_VERSION,'VALIDAR',s,'VALIDADO',p_MOTIVO,p_HASH_VAL);
 END;
 PROCEDURE PUBLICAR(p_EMPRESA NUMBER,p_ACTOR NUMBER,p_MODELO NUMBER,p_VERSION NUMBER,p_HASH VARCHAR2,p_VER_EST NUMBER,
  p_HASH_VAL VARCHAR2,p_DESDE DATE,p_HASTA DATE,p_MOTIVO VARCHAR2) IS s VARCHAR2(12);n NUMBER;t NUMBER;sc VARCHAR2(24);a NUMBER;author NUMBER;h VARCHAR2(64);apt NUMBER;nivel VARCHAR2(12);
 BEGIN
  contexto(p_EMPRESA,p_ACTOR,p_MODELO,p_VERSION,p_HASH,p_VER_EST,p_MOTIVO);scope_lock(p_EMPRESA,p_MODELO,p_VERSION,t,sc);bloquear(p_EMPRESA,p_MODELO,p_VERSION,p_HASH,p_VER_EST,s);
  IF s<>'VALIDADO' OR p_DESDE IS NULL OR p_DESDE<>TRUNC(p_DESDE) OR (p_HASTA IS NOT NULL AND (p_HASTA<>TRUNC(p_HASTA) OR p_HASTA<p_DESDE)) THEN RAISE_APPLICATION_ERROR(-20001,'Estado/vigencia de publicacion invalidos.');END IF;
  SELECT ACTOR_VAL,HASH_VALIDACION,APTA,NIVEL INTO a,h,apt,nivel FROM RH_NOM_MOD_EST WHERE ID_MODELO=p_MODELO AND CODIGO_EMPRESA=p_EMPRESA AND VER_MODELO=p_VERSION;
  SELECT USUARIO_INS INTO author FROM RH_NOM_MOD_VER WHERE ID_MODELO=p_MODELO AND CODIGO_EMPRESA=p_EMPRESA AND VERSION=p_VERSION;
  IF p_ACTOR=author OR p_HASH_VAL IS NULL OR h<>p_HASH_VAL OR apt<>1 OR nivel<>'INTEGRAL' THEN RAISE_APPLICATION_ERROR(-20001,'Aprobacion integral independiente requerida.');END IF;
  SELECT COUNT(*) INTO n FROM RH_NOM_MOD_EST E JOIN RH_NOM_MOD_VER V ON V.ID_MODELO=E.ID_MODELO AND V.CODIGO_EMPRESA=E.CODIGO_EMPRESA AND V.VERSION=E.VER_MODELO
   WHERE E.CODIGO_EMPRESA=p_EMPRESA AND E.ESTADO='PUBLICADO' AND V.CODIGO_TIPO_NOMINA=t AND V.ESCENARIO=sc
    AND (p_HASTA IS NULL OR E.DESDE<=p_HASTA) AND (E.HASTA IS NULL OR p_DESDE<=E.HASTA);
  IF n>0 THEN RAISE_APPLICATION_ERROR(-20001,'Publicacion superpuesta por empresa/tipo/escenario.');END IF;
  UPDATE RH_NOM_MOD_EST SET ESTADO='PUBLICADO',VER_ESTADO=VER_ESTADO+1,ACTOR_PUB=p_ACTOR,FECHA_PUB=SYSDATE,DESDE=p_DESDE,HASTA=p_HASTA,MOTIVO=TRIM(p_MOTIVO)
   WHERE ID_MODELO=p_MODELO AND CODIGO_EMPRESA=p_EMPRESA AND VER_MODELO=p_VERSION;
  evento(p_EMPRESA,p_ACTOR,p_MODELO,p_VERSION,'PUBLICAR',s,'PUBLICADO',p_MOTIVO,p_HASH_VAL);
 END;
 PROCEDURE RETIRAR(p_EMPRESA NUMBER,p_ACTOR NUMBER,p_MODELO NUMBER,p_VERSION NUMBER,p_HASH VARCHAR2,p_VER_EST NUMBER,p_MOTIVO VARCHAR2) IS s VARCHAR2(12);t NUMBER;sc VARCHAR2(24);h VARCHAR2(64);
 BEGIN
  contexto(p_EMPRESA,p_ACTOR,p_MODELO,p_VERSION,p_HASH,p_VER_EST,p_MOTIVO);scope_lock(p_EMPRESA,p_MODELO,p_VERSION,t,sc);bloquear(p_EMPRESA,p_MODELO,p_VERSION,p_HASH,p_VER_EST,s);
  IF s NOT IN ('VALIDADO','PUBLICADO') THEN RAISE_APPLICATION_ERROR(-20001,'Solo retirar revision validada o publicada.');END IF;
  SELECT HASH_VALIDACION INTO h FROM RH_NOM_MOD_EST WHERE ID_MODELO=p_MODELO AND CODIGO_EMPRESA=p_EMPRESA AND VER_MODELO=p_VERSION;
  UPDATE RH_NOM_MOD_EST SET ESTADO='RETIRADO',VER_ESTADO=VER_ESTADO+1,FECHA_RET=SYSDATE,MOTIVO=TRIM(p_MOTIVO) WHERE ID_MODELO=p_MODELO AND CODIGO_EMPRESA=p_EMPRESA AND VER_MODELO=p_VERSION;
  evento(p_EMPRESA,p_ACTOR,p_MODELO,p_VERSION,'RETIRAR',s,'RETIRADO',p_MOTIVO,h);
 END;
END RH_PKG_NOM_EST;
