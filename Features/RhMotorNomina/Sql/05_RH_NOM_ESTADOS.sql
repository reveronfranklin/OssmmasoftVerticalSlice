 PROCEDURE crear(p_name VARCHAR2,p_type VARCHAR2,p_sql VARCHAR2) IS c NUMBER;
 BEGIN
  SELECT COUNT(*) INTO c FROM USER_OBJECTS WHERE OBJECT_NAME=p_name AND OBJECT_TYPE<>p_type;
  IF c>0 THEN RAISE_APPLICATION_ERROR(-20001,'Conflicto de objetos de estados.'); END IF;
  SELECT COUNT(*) INTO c FROM USER_OBJECTS WHERE OBJECT_NAME=p_name;
  IF c=0 THEN EXECUTE IMMEDIATE p_sql; END IF;
 END;
BEGIN
 IF SYS_CONTEXT('USERENV','SESSION_USER')<>'RH' OR SYS_CONTEXT('USERENV','CURRENT_SCHEMA')<>'RH' THEN
  RAISE_APPLICATION_ERROR(-20001,'Instalar estados como RH.'); END IF;
 crear('RH_NOM_MOD_EST','TABLE','CREATE TABLE RH_NOM_MOD_EST (
