 EVIDENCIA CLOB,HASH_VALIDACION VARCHAR2(64 CHAR),NIVEL VARCHAR2(12 CHAR),APTA NUMBER(1) DEFAULT 0 NOT NULL,
 ACTOR_VAL NUMBER(10),ACTOR_PUB NUMBER(10),FECHA_VAL DATE,FECHA_PUB DATE,FECHA_RET DATE,
 DESDE DATE,HASTA DATE,MOTIVO VARCHAR2(500 CHAR),
 CONSTRAINT PK_RH_NOM_MOD_EST PRIMARY KEY(ID_MODELO,CODIGO_EMPRESA,VER_MODELO),
 CONSTRAINT FK_RH_NOM_EST_VER FOREIGN KEY(ID_MODELO,CODIGO_EMPRESA,VER_MODELO)
 REFERENCES RH_NOM_MOD_VER(ID_MODELO,CODIGO_EMPRESA,VERSION),
 CONSTRAINT CK_RH_NOM_EST_EST CHECK(ESTADO IN (''VALIDADO'',''PUBLICADO'',''RETIRADO'')),
