 PROCEDURE LEER(p_EMPRESA NUMBER,p_MODELO NUMBER,p_VERSION NUMBER,p_RESULT OUT SYS_REFCURSOR);
 PROCEDURE AUDITORIA(p_EMPRESA NUMBER,p_MODELO NUMBER,p_VERSION NUMBER,p_PAGE NUMBER,p_SIZE NUMBER,p_TOTAL OUT NUMBER,p_RESULT OUT SYS_REFCURSOR);
