 crear('RH_NOM_AUD_SEQ','SEQUENCE','CREATE SEQUENCE RH_NOM_AUD_SEQ START WITH 1 INCREMENT BY 1 MAXVALUE 2147483647 NOCYCLE CACHE 20');
 crear('RH_NOM_PUB_LCK','TABLE','CREATE TABLE RH_NOM_PUB_LCK (
 CODIGO_EMPRESA NUMBER(10) NOT NULL,CODIGO_TIPO_NOMINA NUMBER(10) NOT NULL,ESCENARIO VARCHAR2(24 CHAR) NOT NULL,
 CONSTRAINT PK_RH_NOM_PUB_LCK PRIMARY KEY(CODIGO_EMPRESA,CODIGO_TIPO_NOMINA,ESCENARIO))');
