 PROCEDURE PUBLICAR(p_EMPRESA NUMBER,p_ACTOR NUMBER,p_MODELO NUMBER,p_VERSION NUMBER,p_HASH VARCHAR2,p_VER_EST NUMBER,
  p_HASH_VAL VARCHAR2,p_DESDE DATE,p_HASTA DATE,p_MOTIVO VARCHAR2);
 PROCEDURE RETIRAR(p_EMPRESA NUMBER,p_ACTOR NUMBER,p_MODELO NUMBER,p_VERSION NUMBER,p_HASH VARCHAR2,p_VER_EST NUMBER,p_MOTIVO VARCHAR2);
