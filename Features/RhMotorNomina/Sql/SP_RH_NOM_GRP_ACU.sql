-- SP_RH_NOM_GRP_ACU = 17 caracteres. Oracle 10g, solo lectura.
-- Descriptiva identifica/rotula el grupo. Empresa/tipo delimitan conceptos y asociaciones.
CREATE OR REPLACE PROCEDURE RH.SP_RH_NOM_GRP_ACU (
 p_EMPRESA NUMBER,p_TIPO NUMBER,p_GRUPO NUMBER,p_POLITICA VARCHAR2,p_FECHA DATE,
 p_CODIGO OUT VARCHAR2,p_RESULT OUT SYS_REFCURSOR
) AUTHID DEFINER AS
 n NUMBER;
BEGIN
 IF p_EMPRESA IS NULL OR p_EMPRESA<=0 OR p_EMPRESA<>TRUNC(p_EMPRESA)
 OR p_TIPO IS NULL OR p_TIPO<=0 OR p_TIPO<>TRUNC(p_TIPO) THEN
  RAISE_APPLICATION_ERROR(-20001,'Empresa/tipo invalidos.');
 END IF;
 p_CODIGO:=NULL;
 IF p_GRUPO IS NULL THEN
  IF p_POLITICA IS NOT NULL OR p_FECHA IS NOT NULL THEN
   RAISE_APPLICATION_ERROR(-20001,'Catalogo no admite politica/fecha sin grupo.');
  END IF;
  OPEN p_RESULT FOR SELECT * FROM (
   SELECT D.DESCRIPCION_ID,D.CODIGO FROM RH.RH_DESCRIPTIVAS D
   WHERE EXISTS(SELECT 1 FROM RH.RH_CONCEPTOS_ACUMULA A
    WHERE CASE WHEN REGEXP_LIKE(TRIM(A.TIPO_ACUMULADO_ID),'^[0-9]{1,10}$')
          THEN TO_NUMBER(TRIM(A.TIPO_ACUMULADO_ID)) END=D.DESCRIPCION_ID
    AND (A.CODIGO_EMPRESA=p_EMPRESA OR A.CODIGO_EMPRESA IS NULL)
    AND EXISTS(SELECT 1 FROM RH.RH_CONCEPTOS C WHERE C.CODIGO_EMPRESA=p_EMPRESA
     AND C.CODIGO_TIPO_NOMINA=p_TIPO AND C.CODIGO_CONCEPTO=A.CODIGO_CONCEPTO))
   ORDER BY D.CODIGO,D.DESCRIPCION_ID
  ) WHERE ROWNUM<=201;
 ELSE
  IF p_GRUPO<=0 OR p_GRUPO<>TRUNC(p_GRUPO) OR p_POLITICA IS NULL
  OR p_POLITICA NOT IN ('HASTA_NULA','FECHA_CONTEXTO') OR p_FECHA IS NULL THEN
   RAISE_APPLICATION_ERROR(-20001,'Grupo/politica/fecha invalidos.');
  END IF;
  SELECT COUNT(*) INTO n FROM RH.RH_DESCRIPTIVAS WHERE DESCRIPCION_ID=p_GRUPO;
  IF n<>1 THEN RAISE_APPLICATION_ERROR(-20001,'Descriptiva de grupo inexistente o duplicada.'); END IF;
  SELECT CODIGO INTO p_CODIGO FROM RH.RH_DESCRIPTIVAS WHERE DESCRIPCION_ID=p_GRUPO;
  OPEN p_RESULT FOR SELECT * FROM (
   SELECT A.CODIGO_CONCEPTO_ACUMULA,A.CODIGO_EMPRESA,A.CODIGO_CONCEPTO,
    A.TIPO_ACUMULADO_ID,A.FECHA_DESDE,A.FECHA_HASTA,A.CODIGO_CONCEPTO_ASOCIADO,
    A.EXTRA1,A.EXTRA2,A.EXTRA3,ROWIDTOCHAR(A.ROWID) REFERENCIA_FILA,
    (SELECT COUNT(*) FROM RH.RH_CONCEPTOS C WHERE C.CODIGO_EMPRESA=p_EMPRESA
     AND C.CODIGO_TIPO_NOMINA=p_TIPO AND C.CODIGO_CONCEPTO=A.CODIGO_CONCEPTO) CONCEPTOS
   FROM RH.RH_CONCEPTOS_ACUMULA A
   WHERE CASE WHEN REGEXP_LIKE(TRIM(A.TIPO_ACUMULADO_ID),'^[0-9]{1,10}$')
         THEN TO_NUMBER(TRIM(A.TIPO_ACUMULADO_ID)) END=p_GRUPO
    AND (A.CODIGO_EMPRESA=p_EMPRESA OR A.CODIGO_EMPRESA IS NULL)
    AND EXISTS(SELECT 1 FROM RH.RH_CONCEPTOS C WHERE C.CODIGO_EMPRESA=p_EMPRESA
     AND C.CODIGO_TIPO_NOMINA=p_TIPO AND C.CODIGO_CONCEPTO=A.CODIGO_CONCEPTO)
    AND ((p_POLITICA='HASTA_NULA' AND A.FECHA_HASTA IS NULL)
      OR (p_POLITICA='FECHA_CONTEXTO' AND (A.FECHA_DESDE IS NULL OR A.FECHA_DESDE<=p_FECHA)
       AND (A.FECHA_HASTA IS NULL OR A.FECHA_HASTA>=p_FECHA)))
   ORDER BY A.CODIGO_CONCEPTO_ACUMULA,A.CODIGO_CONCEPTO
  ) WHERE ROWNUM<=101;
 END IF;
END;
