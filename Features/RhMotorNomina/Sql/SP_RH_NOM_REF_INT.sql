-- Oracle 10g. SP_RH_NOM_REF_INT=17. Solo lectura, sin funciones de calculo legacy.
-- Seleccion del ultimo periodo abierto con precierre; sin candidato usa reloj
-- Oracle. Una duplicidad del join se conserva para que C# la rechace.
CREATE OR REPLACE PROCEDURE RH.SP_RH_NOM_REF_INT (
 p_EMPRESA IN NUMBER,p_TIPO IN NUMBER,p_PERIODO IN NUMBER,p_FECHA IN DATE,
 p_RESULT OUT SYS_REFCURSOR
) AUTHID DEFINER AS
 n NUMBER;
BEGIN
 IF p_EMPRESA IS NULL OR p_EMPRESA<=0 OR p_EMPRESA<>TRUNC(p_EMPRESA)
 OR p_TIPO IS NULL OR p_TIPO<=0 OR p_TIPO<>TRUNC(p_TIPO)
 OR p_PERIODO IS NULL OR p_PERIODO<=0 OR p_PERIODO<>TRUNC(p_PERIODO)
 OR p_FECHA IS NULL THEN
  RAISE_APPLICATION_ERROR(-20001,'Contexto temporal integral invalido.');
 END IF;
 SELECT COUNT(*) INTO n FROM RH.RH_PERIODOS P
 WHERE P.CODIGO_EMPRESA=p_EMPRESA AND P.CODIGO_TIPO_NOMINA=p_TIPO
 AND P.CODIGO_PERIODO=p_PERIODO AND P.FECHA_NOMINA=p_FECHA
 AND P.FECHA_CIERRE IS NULL;
 IF n<>1 THEN RAISE_APPLICATION_ERROR(-20001,'Periodo objetivo abierto unico requerido.'); END IF;
 OPEN p_RESULT FOR SELECT * FROM (
 SELECT 0 ES_CANDIDATO,TRUNC(SYSDATE) RELOJ_ORACLE,
        TO_NUMBER(NULL) CODIGO_PERIODO,CAST(NULL AS DATE) FECHA_NOMINA,
        TO_NUMBER(NULL) PERIODO,CAST(NULL AS DATE) FECHA_PRECIERRE,
        CAST(NULL AS VARCHAR2(100)) FRECUENCIA FROM DUAL
 UNION ALL
 SELECT 1,CAST(NULL AS DATE),P.CODIGO_PERIODO,P.FECHA_NOMINA,P.PERIODO,
        P.FECHA_PRECIERRE,D.CODIGO
 FROM RH.RH_PERIODOS P,RH.RH_TIPOS_NOMINA T,RH.RH_DESCRIPTIVAS D
 WHERE P.CODIGO_EMPRESA=p_EMPRESA AND P.CODIGO_TIPO_NOMINA=p_TIPO
 AND T.CODIGO_EMPRESA=P.CODIGO_EMPRESA
 AND T.CODIGO_TIPO_NOMINA=P.CODIGO_TIPO_NOMINA
 AND P.FECHA_CIERRE IS NULL AND P.FECHA_PRECIERRE IS NOT NULL
 AND P.FECHA_NOMINA=(SELECT MAX(Q.FECHA_NOMINA) FROM RH.RH_PERIODOS Q
      WHERE Q.CODIGO_EMPRESA=p_EMPRESA AND Q.CODIGO_TIPO_NOMINA=p_TIPO
      AND Q.FECHA_CIERRE IS NULL AND Q.FECHA_PRECIERRE IS NOT NULL)
 AND D.DESCRIPCION_FK_ID=T.FRECUENCIA_PAGO_ID
 AND SUBSTR(D.CODIGO,1,1)=TO_CHAR(P.PERIODO)
 ) WHERE ROWNUM<=52;
END;
