-- Solo lectura. Comparar documento, retencion persistida, catalogo y SP instalado.
SELECT DOC.CODIGO_DOCUMENTO_OP, DOC.TIPO_IMPUESTO_ID,
       IMP.DESCRIPCION IMPUESTO_DOCUMENTO, IMP.EXTRA1 ALICUOTA_DOCUMENTO,
       DOC.BASE_IMPONIBLE, DOC.MONTO_IMPUESTO, DOC.MONTO_RETENIDO
  FROM ADM.ADM_DOCUMENTOS_OP DOC
  LEFT JOIN ADM.ADM_DESCRIPTIVAS IMP ON IMP.DESCRIPCION_ID = DOC.TIPO_IMPUESTO_ID
 WHERE DOC.CODIGO_ORDEN_PAGO = 18409;

SELECT RET.CODIGO_RETENCION_OP, RET.TIPO_RETENCION_ID,
       DES.DESCRIPCION TIPO_PERSISTIDO, RET.CODIGO_RETENCION,
       RET.POR_RETENCION, RET.BASE_IMPONIBLE, RET.MONTO_RETENCION,
       RET.EXTRA1 IMPUESTO_ORIGEN, RET.EXTRA2 ALICUOTA_PERSISTIDA,
       RET.EXTRA3 DESCRIPCION_PERSISTIDA, RET.EXTRA4,
       RET.NUMERO_COMPROBANTE
  FROM ADM.ADM_RETENCIONES_OP RET
  LEFT JOIN ADM.ADM_DESCRIPTIVAS DES ON DES.DESCRIPCION_ID = RET.TIPO_RETENCION_ID
 WHERE RET.CODIGO_ORDEN_PAGO = 18409;

SELECT DES.DESCRIPCION_ID, DES.TITULO_ID, DES.CODIGO, DES.DESCRIPCION, DES.EXTRA1
  FROM ADM.ADM_DESCRIPTIVAS DES
 WHERE DES.CODIGO = 'IVA'
   AND DES.TITULO_ID IN (
       SELECT TIPO.TITULO_ID FROM ADM.ADM_RETENCIONES_OP RET
       JOIN ADM.ADM_DESCRIPTIVAS TIPO ON TIPO.DESCRIPCION_ID = RET.TIPO_RETENCION_ID
       WHERE RET.CODIGO_ORDEN_PAGO = 18409)
 ORDER BY DES.DESCRIPCION_ID;

SELECT STATUS, LAST_DDL_TIME FROM ALL_OBJECTS
 WHERE OWNER = 'ADM' AND OBJECT_NAME = 'SP_REP_ORD_PAGO_RET_GET'
   AND OBJECT_TYPE = 'PROCEDURE';

SELECT LINE, TEXT FROM ALL_SOURCE
 WHERE OWNER = 'ADM' AND NAME = 'SP_REP_ORD_PAGO_RET_GET' AND TYPE = 'PROCEDURE'
 ORDER BY LINE;
