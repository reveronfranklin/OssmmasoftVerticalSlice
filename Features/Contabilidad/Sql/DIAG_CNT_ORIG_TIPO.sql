-- R58: read-only diagnosis, QA XE / company 13. No procedure execution.
-- Validate the connected environment before use. Dates include document samples.
-- 1. Catalogs, including shared descriptions; not all pairs are compatible.
SELECT TITULO_ID, DESCRIPCION_ID, CODIGO, DESCRIPCION, CODIGO_EMPRESA
FROM CNT.CNT_DESCRIPTIVAS
WHERE TITULO_ID IN (1,5)
  AND (CODIGO_EMPRESA=13 OR CODIGO_EMPRESA IS NULL)
  AND SYS_CONTEXT('USERENV','DB_NAME')='XE'
  AND SYS_CONTEXT('USERENV','SERVER_HOST')='6d88ba053190'
ORDER BY TITULO_ID, CODIGO, DESCRIPCION_ID;

-- 2. Observed combinations, not an authorization matrix.
SELECT C.ORIGEN_ID, O.CODIGO ORIGEN, C.TIPO_COMPROBANTE_ID,
       T.CODIGO TIPO, C.ESTADO_CMP, COUNT(*) COMPROBANTES,
       MIN(C.FECHA_COMPROBANTE) PRIMERA_FECHA,
       MAX(C.FECHA_COMPROBANTE) ULTIMA_FECHA
FROM CNT.CNT_COMPROBANTES C
LEFT JOIN CNT.CNT_DESCRIPTIVAS O ON O.DESCRIPCION_ID=C.ORIGEN_ID
 AND O.TITULO_ID=1 AND (O.CODIGO_EMPRESA=13 OR O.CODIGO_EMPRESA IS NULL)
LEFT JOIN CNT.CNT_DESCRIPTIVAS T ON T.DESCRIPCION_ID=C.TIPO_COMPROBANTE_ID
 AND T.TITULO_ID=5 AND (T.CODIGO_EMPRESA=13 OR T.CODIGO_EMPRESA IS NULL)
WHERE C.CODIGO_EMPRESA=13
  AND C.FECHA_COMPROBANTE>=TO_DATE('20220701','YYYYMMDD')
  AND C.FECHA_COMPROBANTE<TO_DATE('20261125','YYYYMMDD')
  AND SYS_CONTEXT('USERENV','DB_NAME')='XE'
  AND SYS_CONTEXT('USERENV','SERVER_HOST')='6d88ba053190'
GROUP BY C.ORIGEN_ID,O.CODIGO,C.TIPO_COMPROBANTE_ID,T.CODIGO,C.ESTADO_CMP
ORDER BY O.CODIGO,T.CODIGO,C.ESTADO_CMP;

-- 3. Existing PUC/type/auxiliary configuration. Keep the stored type code.
-- TIPO_DOCUMENTO_ID is a code here; do not equate it to DESCRIPCION_ID.
SELECT P.TIPO_DOCUMENTO_ID, P.CODIGO_PUC,
       P.CODIGO_AUXILIAR, A.CODIGO_MAYOR, M.NUMERO_MAYOR,
       COUNT(*) RELACIONES
FROM CNT.CNT_AUXILIARES_PUC P
LEFT JOIN CNT.CNT_AUXILIARES A ON A.CODIGO_AUXILIAR=P.CODIGO_AUXILIAR
 AND A.CODIGO_EMPRESA=P.CODIGO_EMPRESA
LEFT JOIN CNT.CNT_MAYORES M ON M.CODIGO_MAYOR=A.CODIGO_MAYOR
 AND M.CODIGO_EMPRESA=A.CODIGO_EMPRESA
WHERE P.CODIGO_EMPRESA=13
  AND SYS_CONTEXT('USERENV','DB_NAME')='XE'
  AND SYS_CONTEXT('USERENV','SERVER_HOST')='6d88ba053190'
GROUP BY P.TIPO_DOCUMENTO_ID,P.CODIGO_PUC,P.CODIGO_AUXILIAR,
         A.CODIGO_MAYOR,M.NUMERO_MAYOR
ORDER BY P.TIPO_DOCUMENTO_ID,P.CODIGO_PUC,M.NUMERO_MAYOR,P.CODIGO_AUXILIAR;

-- 4. Detailed comparison sample. Opposite sides alone do not prove duplication.
SELECT C.CODIGO_COMPROBANTE, C.NUMERO_COMPROBANTE, C.FECHA_COMPROBANTE,
       C.ORIGEN_ID, C.TIPO_COMPROBANTE_ID, C.ESTADO_CMP,
       D.CODIGO_DETALLE_COMPROBANTE, D.CODIGO_MAYOR,
       M.NUMERO_MAYOR, D.CODIGO_AUXILIAR,
       A.CODIGO_MAYOR MAYOR_DEL_AUXILIAR,
       D.REFERENCIA1, D.REFERENCIA2, D.MONTO,
       CASE WHEN D.MONTO<0 THEN -D.MONTO ELSE 0 END DEBE,
       CASE WHEN D.MONTO>0 THEN D.MONTO ELSE 0 END HABER
FROM CNT.CNT_COMPROBANTES C
LEFT JOIN CNT.CNT_DETALLE_COMPROBANTE D
 ON D.CODIGO_COMPROBANTE=C.CODIGO_COMPROBANTE
 AND D.CODIGO_EMPRESA=C.CODIGO_EMPRESA
LEFT JOIN CNT.CNT_MAYORES M ON M.CODIGO_MAYOR=D.CODIGO_MAYOR
 AND M.CODIGO_EMPRESA=C.CODIGO_EMPRESA
LEFT JOIN CNT.CNT_AUXILIARES A ON A.CODIGO_AUXILIAR=D.CODIGO_AUXILIAR
 AND A.CODIGO_EMPRESA=C.CODIGO_EMPRESA
WHERE C.CODIGO_EMPRESA=13
  AND C.NUMERO_COMPROBANTE IN ('22-07-02-001','22-07-02-002','22-07-02-003')
  AND SYS_CONTEXT('USERENV','DB_NAME')='XE'
  AND SYS_CONTEXT('USERENV','SERVER_HOST')='6d88ba053190'
ORDER BY C.NUMERO_COMPROBANTE,C.CODIGO_COMPROBANTE,D.CODIGO_DETALLE_COMPROBANTE;
