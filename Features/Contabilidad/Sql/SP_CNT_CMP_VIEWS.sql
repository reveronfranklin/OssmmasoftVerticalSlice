-- Adapted existing views; opening balances retain their behavior.
CREATE OR REPLACE VIEW "CNT"."CNT_V_MAYOR_ANALITICO" ("CODIGO_COMPROBANTE", "CODIGO_MAYOR", "CODIGO_AUXILIAR", "CODIGO_CUENTA", "DENOMINACION_CUENTA", "NUMERO_COMPROBANTE", "FECHA_COMPROBANTE", "DESCRIPCION", "REFERENCIA1", "REFERENCIA2", "MONTO", "CODIGO_EMPRESA") AS 
  SELECT /*+ INDEX (A CNT_COMPROBANTES_U1) */ 
       A.CODIGO_COMPROBANTE, 
       B.CODIGO_MAYOR, 
       B.CODIGO_AUXILIAR, 
       D.NUMERO_MAYOR||'.'||C.SEGMENTO1||'.'||C.SEGMENTO2 CODIGO_CUENTA, 
       C.DENOMINACION DENOMINACION_CUENTA, 
       A.NUMERO_COMPROBANTE, 
       A.FECHA_COMPROBANTE, 
       B.DESCRIPCION, 
       B.REFERENCIA1, 
       B.REFERENCIA2, 
       B.MONTO, 
       A.CODIGO_EMPRESA 
  FROM CNT_COMPROBANTES A, 
       CNT_DETALLE_COMPROBANTE B, 
       CNT_AUXILIARES C, 
       CNT_MAYORES D 
 WHERE A.ESTADO_CMP = 'FINALIZADO'
   AND B.CODIGO_COMPROBANTE = A.CODIGO_COMPROBANTE 
   AND C.CODIGO_AUXILIAR = B.CODIGO_AUXILIAR 
   AND D.CODIGO_MAYOR = C.CODIGO_MAYOR 
 UNION 
SELECT TO_NUMBER(NULL) CODIGO_COMPROBANTE, 
       A.CODIGO_MAYOR, 
       A.CODIGO_AUXILIAR, 
       D.NUMERO_MAYOR||'-'||C.SEGMENTO1||'-'||C.SEGMENTO2 CODIGO_CUENTA, 
       C.DENOMINACION DENOMINACION_CUENTA, 
       NULL NUMERO_COMPROBANTE, 
       TO_DATE(NULL) FECHA_COMPROBANTE, 
       'SALDO AL '||TO_CHAR(B.FECHA_HASTA,'DD/MM/RRRR') DESCRIPCION, 
       NULL REFERENCIA1, 
       NULL REFERENCIA2, 
       A.MONTO, 
       A.CODIGO_EMPRESA 
  FROM CNT_SALDOS A, 
       CNT_PERIODOS B, 
       CNT_AUXILIARES C, 
       CNT_MAYORES D 
 WHERE A.CODIGO_PERIODO = 0/*(SELECT MIN(X.CODIGO_PERIODO) FROM CNT_PERIODOS X WHERE X.CODIGO_EMPRESA = A.CODIGO_EMPRESA)*/ 
   AND A.MONTO <> 0 
   AND B.CODIGO_PERIODO = A.CODIGO_PERIODO 
   AND C.CODIGO_AUXILIAR = A.CODIGO_AUXILIAR 
   AND D.CODIGO_MAYOR = C.CODIGO_MAYOR
;
/

CREATE OR REPLACE VIEW "CNT"."CNT_V_MOV_AUXILIAR" ("CODIGO_COMPROBANTE", "CODIGO_AUXILIAR", "NUMERO_CONTABLE", "NOMBRE_AUXILIAR", "NUMERO_COMPROBANTE", "FECHA_COMPROBANTE", "DESCRIPCION", "REFERENCIA1", "REFERENCIA2", "MONTO", "CODIGO_EMPRESA") AS 
  SELECT A.CODIGO_COMPROBANTE, 
	   B.CODIGO_AUXILIAR, 
	   C.NUMERO_MAYOR||'-'|| 
	   D.SEGMENTO1||'-'|| 
	   D.SEGMENTO2 NUMERO_CONTABLE, 
	   D.DENOMINACION NOMBRE_AUXILIAR, 
	   A.NUMERO_COMPROBANTE, 
	   A.FECHA_COMPROBANTE, 
	   B.DESCRIPCION, 
	   B.REFERENCIA1, 
	   B.REFERENCIA2, 
	   B.MONTO, 
	   A.CODIGO_EMPRESA 
  FROM CNT_COMPROBANTES A, 
  	   CNT_DETALLE_COMPROBANTE B, 
	   CNT_MAYORES C, 
	   CNT_AUXILIARES D 
 WHERE A.ESTADO_CMP = 'FINALIZADO'
   AND A.CODIGO_COMPROBANTE = B.CODIGO_COMPROBANTE 
   AND A.CODIGO_EMPRESA = B.CODIGO_EMPRESA 
   AND C.CODIGO_MAYOR = B.CODIGO_MAYOR 
   AND D.CODIGO_AUXILIAR = B.CODIGO_AUXILIAR 
 UNION 
SELECT 0, 
	   A.CODIGO_AUXILIAR, 
	   'S/NC', 
	   'S/D', 
	   'S/C', 
	   TO_DATE('31/12/2002','DD/MM/RRRR'), 
	   'SALDO FINAL AL 31/12/2002', 
	   NULL, 
	   NULL, 
	   A.MONTO, 
	   A.CODIGO_EMPRESA 
  FROM CNT_SALDOS A 
 WHERE A.CODIGO_PERIODO = 0 
ORDER BY 1 DESC
;
/

