-- Read-only inventory. Run before installation and save results with release evidence.
SELECT OWNER, TRIGGER_NAME, TABLE_NAME, STATUS, TRIGGERING_EVENT
  FROM ALL_TRIGGERS WHERE TABLE_OWNER = 'CNT'
   AND TABLE_NAME IN ('CNT_COMPROBANTES', 'CNT_DETALLE_COMPROBANTE', 'CNT_SALDOS', 'CNT_TMP_SALDOS');
SELECT OWNER, NAME, TYPE, REFERENCED_OWNER, REFERENCED_NAME
  FROM ALL_DEPENDENCIES WHERE REFERENCED_OWNER = 'CNT'
   AND REFERENCED_NAME IN ('CNT_COMPROBANTES', 'CNT_DETALLE_COMPROBANTE', 'CNT_SALDOS', 'CNT_V_MAYOR_ANALITICO', 'CNT_V_MOV_AUXILIAR')
 ORDER BY OWNER, NAME;
SELECT OWNER, NAME, TYPE, LINE, TEXT FROM ALL_SOURCE
 WHERE OWNER = 'CNT' AND (UPPER(TEXT) LIKE '%CNT_COMPROBANTES%'
    OR UPPER(TEXT) LIKE '%CNT_DETALLE_COMPROBANTE%' OR UPPER(TEXT) LIKE '%COMMIT%')
 ORDER BY NAME, TYPE, LINE;
SELECT c.CODIGO_EMPRESA, c.CODIGO_PERIODO, c.CODIGO_COMPROBANTE, c.NUMERO_COMPROBANTE,
       NVL(SUM(ROUND(d.MONTO,2)),0) DIFERENCIA, COUNT(d.CODIGO_DETALLE_COMPROBANTE) LINEAS
  FROM CNT.CNT_COMPROBANTES c LEFT JOIN CNT.CNT_DETALLE_COMPROBANTE d
    ON d.CODIGO_COMPROBANTE = c.CODIGO_COMPROBANTE AND d.CODIGO_EMPRESA = c.CODIGO_EMPRESA
 GROUP BY c.CODIGO_EMPRESA, c.CODIGO_PERIODO, c.CODIGO_COMPROBANTE, c.NUMERO_COMPROBANTE
HAVING NVL(SUM(ROUND(d.MONTO,2)),0) <> 0 OR COUNT(d.CODIGO_DETALLE_COMPROBANTE) = 0;
SELECT CODIGO_EMPRESA, CODIGO_PERIODO, TIPO_COMPROBANTE_ID, ORIGEN_ID,
       TRUNC(FECHA_COMPROBANTE) DIA, COUNT(*) CANTIDAD
  FROM CNT.CNT_COMPROBANTES WHERE EXTRA1 = 'AUTOMATICO'
 GROUP BY CODIGO_EMPRESA, CODIGO_PERIODO, TIPO_COMPROBANTE_ID, ORIGEN_ID, TRUNC(FECHA_COMPROBANTE)
HAVING COUNT(*) > 1;
SELECT OWNER, CONSTRAINT_NAME, TABLE_NAME FROM ALL_CONSTRAINTS
 WHERE CONSTRAINT_TYPE = 'R' AND R_OWNER = 'CNT'
   AND R_CONSTRAINT_NAME IN (SELECT CONSTRAINT_NAME FROM ALL_CONSTRAINTS
        WHERE OWNER = 'CNT' AND TABLE_NAME IN ('CNT_COMPROBANTES', 'CNT_DETALLE_COMPROBANTE') AND CONSTRAINT_TYPE IN ('P','U'));
