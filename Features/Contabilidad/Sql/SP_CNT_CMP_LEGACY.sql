  PROCEDURE CNT_PRECIERRE (
    P_CODIGO_PERIODO IN NUMBER,
    P_CODIGO_USUARIO IN NUMBER,
    P_CODIGO_EMPRESA IN NUMBER
    ) IS
    CURSOR C1 IS
    SELECT CODIGO_MAYOR,
           CODIGO_AUXILIAR,
           Cnt_Saldo_Inicial(P_CODIGO_PERIODO,CODIGO_MAYOR,CODIGO_AUXILIAR) SALDO_INICIAL,
           SUM(DEBITOS) DEBITOS,
           SUM(CREDITOS) CREDITOS
      FROM (
    SELECT B.CODIGO_MAYOR,
           B.CODIGO_AUXILIAR,
           NVL(B.MONTO,0) DEBITOS,
           0 CREDITOS
      FROM CNT_COMPROBANTES A,
           CNT_DETALLE_COMPROBANTE B
     WHERE A.CODIGO_PERIODO = P_CODIGO_PERIODO
       AND A.ESTADO_CMP = 'FINALIZADO'
       AND A.CODIGO_EMPRESA = P_CODIGO_EMPRESA
       AND B.CODIGO_COMPROBANTE = A.CODIGO_COMPROBANTE
       AND NVL(B.MONTO,0) > 0
     UNION ALL
    SELECT B.CODIGO_MAYOR,
           B.CODIGO_AUXILIAR,
           0 DEBITOS,
           NVL(B.MONTO,0) CREDITOS
      FROM CNT_COMPROBANTES A,
           CNT_DETALLE_COMPROBANTE B
     WHERE A.CODIGO_PERIODO = P_CODIGO_PERIODO
       AND A.ESTADO_CMP = 'FINALIZADO'
       AND A.CODIGO_EMPRESA = P_CODIGO_EMPRESA
       AND B.CODIGO_COMPROBANTE = A.CODIGO_COMPROBANTE
       AND NVL(B.MONTO,0) < 0
     UNION ALL
    SELECT A.CODIGO_MAYOR,
           A.CODIGO_AUXILIAR,
           0 DEBITOS,
           0 CREDITOS
      FROM CNT_SALDOS A
     WHERE A.CODIGO_PERIODO = (
    SELECT MAX(B.CODIGO_PERIODO)
      FROM CNT_SALDOS B
     WHERE B.CODIGO_PERIODO < DECODE(P_CODIGO_PERIODO,0,1,P_CODIGO_PERIODO)
       AND B.CODIGO_MAYOR = A.CODIGO_MAYOR
       AND B.CODIGO_AUXILIAR = A.CODIGO_AUXILIAR )
       AND A.CODIGO_EMPRESA = P_CODIGO_EMPRESA
       AND A.MONTO <> 0
       AND NOT EXISTS (
    SELECT NULL
      FROM CNT_COMPROBANTES B,
           CNT_DETALLE_COMPROBANTE C
     WHERE B.CODIGO_PERIODO = P_CODIGO_PERIODO
       AND B.ESTADO_CMP = 'FINALIZADO'
       AND B.CODIGO_EMPRESA = P_CODIGO_EMPRESA
       AND C.CODIGO_COMPROBANTE = B.CODIGO_COMPROBANTE
       AND C.CODIGO_MAYOR = A.CODIGO_MAYOR
       AND C.CODIGO_AUXILIAR = A.CODIGO_AUXILIAR
       AND NVL(C.MONTO,0) <> 0 )
           )
     GROUP BY
          CODIGO_MAYOR,
          CODIGO_AUXILIAR;
    CURSOR C2 IS
    SELECT C.CODIGO_TMP_SALDO,
           A.CODIGO_DETALLE_COMPROBANTE
      FROM CNT_DETALLE_COMPROBANTE A,
           CNT_COMPROBANTES B,
           CNT_TMP_SALDOS  C
     WHERE C.CODIGO_PERIODO = P_CODIGO_PERIODO
       AND C.CODIGO_EMPRESA = P_CODIGO_EMPRESA
       AND B.CODIGO_PERIODO = C.CODIGO_PERIODO
       AND B.ESTADO_CMP = 'FINALIZADO'
       AND A.CODIGO_COMPROBANTE = B.CODIGO_COMPROBANTE
       AND A.CODIGO_MAYOR = C.CODIGO_MAYOR
       AND A.CODIGO_AUXILIAR = C.CODIGO_AUXILIAR;
  BEGIN
--
    CNT.CNT_CMP_GUARD.LOCK_ALL;
    EXISTS_PERIODO(P_CODIGO_PERIODO,P_CODIGO_EMPRESA);
-- MIENTRAS SE REALIZAN LOS BLOQUEOS POR CUENTA 12/01/2007 --
/*
--
    LOCK TABLE CNT_COMPROBANTES        IN EXCLUSIVE MODE;
    LOCK TABLE CNT_DETALLE_COMPROBANTE IN EXCLUSIVE MODE;
    LOCK TABLE CNT_TMP_SALDOS          IN EXCLUSIVE MODE;
    LOCK TABLE CNT_TMP_ANALITICO       IN EXCLUSIVE MODE;
    LOCK TABLE CNT_PERIODOS            IN EXCLUSIVE MODE;
*/
--
    DELETE CNT_TMP_SALDOS
     WHERE CODIGO_PERIODO = P_CODIGO_PERIODO
       AND CODIGO_EMPRESA = P_CODIGO_EMPRESA;
    DELETE CNT_TMP_ANALITICO
     WHERE CODIGO_EMPRESA = P_CODIGO_EMPRESA;
--
    FOR R1 IN C1 LOOP
      INSERT INTO CNT_TMP_SALDOS
        (
         CODIGO_TMP_SALDO,
         CODIGO_PERIODO,
         CODIGO_MAYOR,
         CODIGO_AUXILIAR,
         SALDO_INICIAL,
         DEBITOS,
         CREDITOS,
         EXTRA1,
         EXTRA2,
         EXTRA3,
         USUARIO_INS,
         FECHA_INS,
         USUARIO_UPD,
         FECHA_UPD,
         CODIGO_EMPRESA
        )
      VALUES
        (
         CNT_S_CODIGO_TMP_SALDO.NEXTVAL,
         P_CODIGO_PERIODO,
         R1.CODIGO_MAYOR,
         R1.CODIGO_AUXILIAR,
         R1.SALDO_INICIAL,
         R1.DEBITOS,
         R1.CREDITOS,
         NULL,
         NULL,
         NULL,
         P_CODIGO_USUARIO,
         SYSDATE,
         NULL,
         NULL,
         P_CODIGO_EMPRESA
        );
    END LOOP;
    FOR R2 IN C2 LOOP
      INSERT INTO CNT_TMP_ANALITICO
        (
         CODIGO_TMP_ANALITICO,
         CODIGO_TMP_SALDO,
         CODIGO_DETALLE_COMPROBANTE,
         EXTRA1,
         EXTRA2,
         EXTRA3,
         USUARIO_INS,
         FECHA_INS,
         USUARIO_UPD,
         FECHA_UPD,
         CODIGO_EMPRESA
        )
      VALUES
        (
         CNT_S_CODIGO_TMP_ANALITICO.NEXTVAL,
         R2.CODIGO_TMP_SALDO,
         R2.CODIGO_DETALLE_COMPROBANTE,
         NULL,
         NULL,
         NULL,
         P_CODIGO_USUARIO,
         SYSDATE,
         NULL,
         NULL,
         P_CODIGO_EMPRESA
        );
    END LOOP;
--
    UPDATE CNT_PERIODOS
       SET FECHA_PRECIERRE = SYSDATE,
           USUARIO_PRECIERRE = P_CODIGO_USUARIO
     WHERE CODIGO_PERIODO = P_CODIGO_PERIODO
       AND CODIGO_EMPRESA = P_CODIGO_EMPRESA;
--
    COMMIT;
--
  END CNT_PRECIERRE;
