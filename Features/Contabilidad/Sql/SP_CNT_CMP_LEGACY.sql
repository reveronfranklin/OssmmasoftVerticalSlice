  PROCEDURE CNT_INGRESOS (
    P_CODIGO_PERIODO      IN NUMBER,
    P_CONCILIACION        IN NUMBER,        
    P_CODIGO_CUENTA_BANCO IN NUMBER,    
    P_CODIGO_USUARIO      IN NUMBER,
    P_CODIGO_EMPRESA      IN NUMBER
    ) IS
    V_EXISTE NUMBER(1)   :=0;
    V_FECHA_INICIO DATE  :=NULL;
    V_FECHA_FINAL  DATE  :=NULL;
    V_FECHA_MOV_CAJA DATE:=NULL;
    V_CODIGO_COMPROBANTE NUMBER:=0;    
    V_NUMERO_COMPROBANTE CNT_COMPROBANTES.NUMERO_COMPROBANTE%TYPE;
    V_NUM_COMPROBANTE NUMBER:=NULL;
    V_TIPO_COMPROBANTE_ID NUMBER:=17; -- ELIMINAR HC 
    V_MONTO RM_CIERRE_CAJA.MONTO%TYPE;
    -- VARIABLES PARA LA CONCILIACION --
    V_CODIGO_LIBRO CNT_LIBROS.CODIGO_LIBRO%TYPE;
    V_CODIGO_DETALLE_LIBRO CNT_DETALLE_LIBRO.CODIGO_DETALLE_LIBRO%TYPE;
    V_ORIGEN_ID    CNT_DETALLE_LIBRO.ORIGEN_ID%TYPE;
  BEGIN
    -- BUSCA PERIODOS DE CONTABILIDAD PARA REGISTRAR O CONCILIAR LOS INGRESOS, SIEMPRE QUE NO ESTE CERRADO.
    BEGIN
    SELECT FECHA_DESDE, FECHA_HASTA INTO V_FECHA_INICIO, V_FECHA_FINAL FROM CNT_PERIODOS CP
      WHERE CP.CODIGO_PERIODO = P_CODIGO_PERIODO
        AND USUARIO_CIERRE IS NULL
        AND FECHA_CIERRE  IS NULL
        ;
    -- MAESTRO DE RECAUDACION, USANDO EL CIERRE DE CAJA --
    FOR I IN (
    SELECT RCC.FECHA_MOV_CAJA, RCC.MONTO FROM RM_CIERRE_CAJA RCC WHERE RCC.FECHA_MOV_CAJA BETWEEN V_FECHA_INICIO AND V_FECHA_FINAL
    ORDER BY RCC.FECHA_MOV_CAJA
    ) LOOP    
    V_CODIGO_COMPROBANTE := NULL;
    V_NUMERO_COMPROBANTE := NULL;
    -- SI LA CONCILIACION ESTA ACTIVA 
    IF P_CONCILIACION = 1 THEN 
        -- SECUENCIA DEL MAESTRO DE LA CONCILIACION
        SELECT CNT_S_CODIGO_LIBRO.NEXTVAL INTO V_CODIGO_LIBRO FROM DUAL;
        -- SECUENCIA DEL ORIGEN DE LOS INGRESOS A CONCILIAR 
        SELECT X.DESCRIPCION_ID ORIGEN_ID --, X.CODIGO CODIGO_ORIGEN,X.DESCRIPCION ORIGEN 
          INTO V_ORIGEN_ID FROM CNT_DESCRIPTIVAS X,CNT_TITULOS Y WHERE X.CODIGO = 'RECAUDA' AND X.TITULO_ID = Y.TITULO_ID AND Y.CODIGO = 'OMLIBRO';
    END IF;
    -- SECUENCIA DEL MAESTRO CONTABILIDAD
    SELECT CNT_S_CODIGO_COMPROBANTE.NEXTVAL INTO V_CODIGO_COMPROBANTE FROM DUAL;
    -- NUMERO DE COMPROBANTE  CONTABILIDAD DE INGRESOS
    BEGIN  
       SELECT (NVL(MAX(TO_NUMBER(SUBSTR(A.NUMERO_COMPROBANTE,10))),0)+1)
         INTO V_NUM_COMPROBANTE
         FROM CNT_COMPROBANTES A
        WHERE A.CODIGO_PERIODO = P_CODIGO_PERIODO
          AND TO_CHAR(A.FECHA_COMPROBANTE,'RRRRMM') = TO_CHAR(V_FECHA_INICIO,'RRRRMM')
          AND A.TIPO_COMPROBANTE_ID = V_TIPO_COMPROBANTE_ID
          AND A.CODIGO_EMPRESA = P_CODIGO_EMPRESA;
     EXCEPTION
       WHEN NO_DATA_FOUND THEN
         V_NUMERO_COMPROBANTE := 1;
     END;       
     V_NUMERO_COMPROBANTE := TO_CHAR(I.FECHA_MOV_CAJA,'RR-MM')||'-'||V_TIPO_COMPROBANTE_ID||'-'||LTRIM(TO_CHAR(V_NUM_COMPROBANTE,'000'));

    -- RAISE_APPLICATION_ERROR(-20001,'Valores: '||v_fecha_mov_caja||' '||V_FECHA_INICIO||' '||V_FECHA_FINAL);
    -- INSERTA DATOS MAESTROS DE LOS INGRESOS DE LA CONTABILIDAD 
    INSERT INTO CNT_COMPROBANTES
    (
      CODIGO_COMPROBANTE   --NUMBER(10)               NOT NULL,
      ,CODIGO_PERIODO       --NUMBER(10)               NOT NULL,
      ,TIPO_COMPROBANTE_ID  --NUMBER(10)               NOT NULL,
      ,NUMERO_COMPROBANTE  -- VARCHAR2(20 BYTE)        NOT NULL,
      ,FECHA_COMPROBANTE    --DATE                     NOT NULL,
      ,ORIGEN_ID            --NUMBER(10),
      ,OBSERVACION          --VARCHAR2(1000 BYTE),
      ,EXTRA1               --VARCHAR2(100 BYTE),
      ,EXTRA2               --VARCHAR2(100 BYTE),
      ,EXTRA3               --VARCHAR2(100 BYTE),
      ,USUARIO_INS          --NUMBER(10),
      ,FECHA_INS            --DATE,
      ,USUARIO_UPD          --NUMBER(10),
      ,FECHA_UPD            --DATE,
      ,CODIGO_EMPRESA       --NUMBER(10)
    )
    VALUES
    (
      V_CODIGO_COMPROBANTE   --NUMBER(10)               NOT NULL,
      ,P_CODIGO_PERIODO       --NUMBER(10)               NOT NULL,
      ,17  --INGRESOS CAJA SAMI --TIPO_COMPROBANTE_ID  --NUMBER(10)               NOT NULL,
      ,V_NUMERO_COMPROBANTE  -- VARCHAR2(20 BYTE)        NOT NULL,
      ,I.FECHA_MOV_CAJA -- TRUNC(SYSDATE) --FECHA_COMPROBANTE    --DATE                     NOT NULL,
      ,89 --ORIGEN_ID            --NUMBER(10),
      ,'INGRESOS POR RECAUDACION CAJA SAMI' --OBSERVACION          --VARCHAR2(1000 BYTE),
      ,NULL --EXTRA1               --VARCHAR2(100 BYTE),
      ,NULL --EXTRA2               --VARCHAR2(100 BYTE),
      ,NULL --EXTRA3               --VARCHAR2(100 BYTE),
      ,P_CODIGO_USUARIO          --NUMBER(10),
      ,SYSDATE --FECHA_INS            --DATE,
      ,NULL --USUARIO_UPD          --NUMBER(10),
      ,NULL --FECHA_UPD            --DATE,
      ,P_CODIGO_EMPRESA       --NUMBER(10)
    );
    -- INSERTA DATOS MAESTROS DE LA CONCILIACION 
    IF P_CONCILIACION = 1 THEN     
        INSERT INTO CNT_LIBROS
        (
          CODIGO_LIBRO          --NUMBER(10)               NOT NULL,
          ,CODIGO_CUENTA_BANCO  --NUMBER(10)               NOT NULL,
          ,FECHA_LIBRO          --DATE,
          ,STATUS               --CHAR(1 BYTE),
          ,EXTRA1               --VARCHAR2(100 BYTE),
          ,EXTRA2               --VARCHAR2(100 BYTE),
          ,EXTRA3               --VARCHAR2(100 BYTE),
          ,USUARIO_INS          --NUMBER(10),
          ,FECHA_INS            --DATE,
          ,USUARIO_UPD          --NUMBER(10),
          ,FECHA_UPD            --DATE,
          ,CODIGO_EMPRESA       --NUMBER(10)
        ) 
        VALUES
        (
          V_CODIGO_LIBRO        --NUMBER(10)               NOT NULL,
          ,0 --CODIGO_CUENTA_BANCO  --NUMBER(10)               NOT NULL,
          ,I.FECHA_MOV_CAJA     --FECHA_LIBRO          --DATE,
          ,NULL --STATUS               --CHAR(1 BYTE),
          ,NULL --EXTRA1               --VARCHAR2(100 BYTE),
          ,NULL --EXTRA2               --VARCHAR2(100 BYTE),
          ,NULL --EXTRA3               --VARCHAR2(100 BYTE),
          ,P_CODIGO_USUARIO      --_INS          --NUMBER(10),
          ,SYSDATE               --FECHA_INS            --DATE,
          ,NULL                  --USUARIO_UPD          --NUMBER(10),
          ,NULL                  --FECHA_UPD            --DATE,
          ,P_CODIGO_EMPRESA      --NUMBER(10)
        );   
    END IF; -- CONCILIACION --
    FOR II IN (
    SELECT 
        0 DEBE,
        A.MONTO_CAPITAL HABER,
        B.CODIGO_AUXILIAR,
