  PROCEDURE CNT_CIERRE (
    P_CODIGO_PERIODO IN NUMBER,
    P_CODIGO_USUARIO IN NUMBER,
    P_CODIGO_EMPRESA IN NUMBER
    ) IS
    CURSOR C1 IS
    SELECT C.CODIGO_SALDO,
           A.CODIGO_DETALLE_COMPROBANTE
      FROM CNT_DETALLE_COMPROBANTE A,
           CNT_COMPROBANTES B,
           CNT_SALDOS  C
     WHERE C.CODIGO_PERIODO = P_CODIGO_PERIODO
       AND C.CODIGO_EMPRESA = P_CODIGO_EMPRESA
       AND B.CODIGO_PERIODO = C.CODIGO_PERIODO
       AND B.ESTADO_CMP = 'FINALIZADO'
       AND A.CODIGO_COMPROBANTE = B.CODIGO_COMPROBANTE
       AND A.CODIGO_MAYOR = C.CODIGO_MAYOR
       AND A.CODIGO_AUXILIAR = C.CODIGO_AUXILIAR;
  BEGIN
--
    CNT.CNT_CMP_GUARD.LOCK_ALL;
    DECLARE
      v_pend NUMBER;
    BEGIN
      SELECT COUNT(*) INTO v_pend FROM CNT.CNT_COMPROBANTES
       WHERE CODIGO_PERIODO = P_CODIGO_PERIODO AND CODIGO_EMPRESA = P_CODIGO_EMPRESA
         AND ESTADO_CMP = 'PENDIENTE';
      IF v_pend > 0 THEN
        RAISE_APPLICATION_ERROR(-20001, 'Existen comprobantes pendientes de correccion.');
      END IF;
    END;
    EXISTS_PERIODO(P_CODIGO_PERIODO,P_CODIGO_EMPRESA);
    DECLARE
      v_pre NUMBER;
    BEGIN
      SELECT COUNT(*) INTO v_pre FROM CNT.CNT_PERIODOS
       WHERE CODIGO_PERIODO = P_CODIGO_PERIODO AND CODIGO_EMPRESA = P_CODIGO_EMPRESA
         AND FECHA_PRECIERRE IS NOT NULL;
      IF v_pre = 0 THEN
        RAISE_APPLICATION_ERROR(-20001, 'Debe ejecutar el precierre antes del cierre.');
      END IF;
    END;
    IF CNT_EXISTS_MODIFICACIONES(P_CODIGO_PERIODO,P_CODIGO_EMPRESA) > 0 THEN 
      RAISE_APPLICATION_ERROR(-20001,'Existe modificaciones en los comprobantes despues del ultimo Precierre.');
    END IF;
--
    LOCK TABLE CNT_COMPROBANTES        IN EXCLUSIVE MODE;
    LOCK TABLE CNT_DETALLE_COMPROBANTE IN EXCLUSIVE MODE;
    LOCK TABLE CNT_TMP_SALDOS          IN EXCLUSIVE MODE;
    LOCK TABLE CNT_TMP_ANALITICO       IN EXCLUSIVE MODE;
    LOCK TABLE CNT_SALDOS              IN EXCLUSIVE MODE;
    LOCK TABLE CNT_HIST_ANALITICO      IN EXCLUSIVE MODE;
    LOCK TABLE CNT_PERIODOS            IN EXCLUSIVE MODE;
--
    INSERT INTO CNT_SALDOS
      (
       CODIGO_SALDO,
       CODIGO_PERIODO,
       CODIGO_MAYOR,
       CODIGO_AUXILIAR,
       DEBITOS,
       CREDITOS,
       MONTO,
       EXTRA1,
       EXTRA2,
       EXTRA3,
       USUARIO_INS,
       FECHA_INS,
       USUARIO_UPD,
       FECHA_UPD,
       CODIGO_EMPRESA
      )
    SELECT
       CNT_S_CODIGO_SALDO.NEXTVAL,
       A.CODIGO_PERIODO,
       A.CODIGO_MAYOR,
       A.CODIGO_AUXILIAR,
       A.DEBITOS,
       A.CREDITOS,
       A.SALDO_INICIAL + A.CREDITOS + A.DEBITOS,
       A.EXTRA1,
       A.EXTRA2,
       A.EXTRA3,
       A.USUARIO_INS,
       A.FECHA_INS,
       A.USUARIO_UPD,
       A.FECHA_UPD,
       A.CODIGO_EMPRESA
      FROM CNT_TMP_SALDOS A
     WHERE A.CODIGO_PERIODO = P_CODIGO_PERIODO
       AND A.CODIGO_EMPRESA = P_CODIGO_EMPRESA;
    FOR R1 IN C1 LOOP
      INSERT INTO CNT_HIST_ANALITICO
        (
         CODIGO_HIST_ANALITICO,
         CODIGO_SALDO,
         CODIGO_DETALLE_COMPROBANTE,
         EXTRA1,
         EXTRA2,
         EXTRA3,
         USUARIO_INS,
         FECHA_INS,
         USUARIO_UPD,
         FECHA_UPD,
         CODIGO_EMPRESA
        )
      VALUES
        (
         CNT_S_CODIGO_HIST_ANALITICO.NEXTVAL,
         R1.CODIGO_SALDO,
         R1.CODIGO_DETALLE_COMPROBANTE,
         NULL,
         NULL,
         NULL,
         P_CODIGO_USUARIO,
         SYSDATE,
         NULL,
         NULL,
         P_CODIGO_EMPRESA
        );
    END LOOP;
--
    UPDATE CNT_PERIODOS
       SET FECHA_CIERRE = SYSDATE,
           USUARIO_CIERRE = P_CODIGO_USUARIO
     WHERE CODIGO_PERIODO = P_CODIGO_PERIODO
       AND CODIGO_EMPRESA = P_CODIGO_EMPRESA;
--
    DELETE CNT_TMP_SALDOS
     WHERE CODIGO_PERIODO = P_CODIGO_PERIODO
       AND CODIGO_EMPRESA = P_CODIGO_EMPRESA;
    DELETE CNT_TMP_ANALITICO
     WHERE CODIGO_EMPRESA = P_CODIGO_EMPRESA;
--
    COMMIT;
--
  END CNT_CIERRE;
