  PROCEDURE CNT_REVERSO (
    P_CODIGO_PERIODO IN NUMBER,
    P_CODIGO_USUARIO IN NUMBER,
    P_CODIGO_EMPRESA IN NUMBER
    ) IS
    V_EXISTE NUMBER(1):=0;
  BEGIN
    CNT.CNT_CMP_GUARD.LOCK_ALL;
    BEGIN
    SELECT 1 INTO V_EXISTE FROM CNT_PERIODOS CP
      WHERE CP.CODIGO_PERIODO = P_CODIGO_PERIODO
        AND USUARIO_CIERRE IS NOT NULL
        AND FECHA_CIERRE  IS NOT NULL;
-- HISTORICO ANALITICO 
    DELETE
      FROM CNT_HIST_ANALITICO A
     WHERE EXISTS ( 
    SELECT NULL
      FROM CNT_SALDOS B
     WHERE B.CODIGO_SALDO = A.CODIGO_SALDO
       AND B.CODIGO_PERIODO = p_codigo_periodo
       AND B.CODIGO_EMPRESA = p_codigo_empresa );
-- SALDOS 
    DELETE
      FROM CNT_SALDOS
     WHERE CODIGO_PERIODO = p_codigo_periodo
       AND CODIGO_EMPRESA = p_codigo_empresa;       
-- PERIODO 
    UPDATE CNT_PERIODOS
       SET FECHA_PRECIERRE = NULL,
           USUARIO_PRECIERRE = NULL,
           FECHA_CIERRE = NULL,
           USUARIO_CIERRE = NULL,
           EXTRA1 = 'R1|'||SYSDATE, -- 16/01/14 -- EXTRA1|| 
           FECHA_UPD = SYSDATE           
     WHERE CODIGO_PERIODO = p_codigo_periodo
       AND CODIGO_EMPRESA = P_CODIGO_EMPRESA;
    COMMIT;
    EXCEPTION WHEN NO_DATA_FOUND THEN
      RAISE_APPLICATION_ERROR(-20001,'El periodo contable ya esta abierto.');
    END;    
  END CNT_REVERSO;
