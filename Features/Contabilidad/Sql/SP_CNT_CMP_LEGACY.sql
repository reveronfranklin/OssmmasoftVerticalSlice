  FUNCTION CNT_EXISTS_MODIFICACIONES (
    P_CODIGO_PERIODO IN NUMBER,
    P_CODIGO_EMPRESA IN NUMBER
    ) RETURN NUMBER IS
    V_COUNT NUMBER(10);
  BEGIN
    SELECT COUNT(*)
      INTO V_COUNT
      FROM CNT_PERIODOS A,
           (
    SELECT MAX(NVL(B.FECHA_UPD,B.FECHA_INS)) FECHA_MODIFICACION
      FROM CNT_COMPROBANTES A,
           CNT_DETALLE_COMPROBANTE B
     WHERE A.CODIGO_PERIODO = P_CODIGO_PERIODO
       AND A.ESTADO_CMP = 'FINALIZADO'
       AND A.CODIGO_EMPRESA = P_CODIGO_EMPRESA
       AND B.CODIGO_COMPROBANTE = A.CODIGO_COMPROBANTE
           ) B
     WHERE A.CODIGO_PERIODO = P_CODIGO_PERIODO
       AND A.CODIGO_EMPRESA = P_CODIGO_EMPRESA
       AND A.FECHA_PRECIERRE < B.FECHA_MODIFICACION;
--
    RETURN V_COUNT;
--
  END CNT_EXISTS_MODIFICACIONES;
