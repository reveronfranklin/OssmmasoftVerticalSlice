-- Oracle 10g. Execute as CNT during maintenance, after DIAG_CNT_CMP_PEND.sql.
-- Historical rows retain their accounting state; all historical automatics are protected.
-- Identifiers: ESTADO_CMP 10, AJUSTE_MANUAL 13, VERSION_CMP 11,
-- CNT_CMP_GUARD 13, CNT_CMP_AUD 11, CNT_CMP_AUD_DET 15.
DECLARE
    v_count NUMBER;
    PROCEDURE add_col(p_name VARCHAR2, p_definition VARCHAR2) IS
    BEGIN
        SELECT COUNT(*) INTO v_count FROM ALL_TAB_COLUMNS
         WHERE OWNER = 'CNT' AND TABLE_NAME = 'CNT_COMPROBANTES' AND COLUMN_NAME = p_name;
        IF v_count = 0 THEN
            EXECUTE IMMEDIATE 'ALTER TABLE CNT.CNT_COMPROBANTES ADD (' || p_definition || ')';
        END IF;
    END;
BEGIN
    add_col('ESTADO_CMP', 'ESTADO_CMP VARCHAR2(12) DEFAULT ''FINALIZADO'' NOT NULL');
    add_col('AJUSTE_MANUAL', 'AJUSTE_MANUAL NUMBER(1) DEFAULT 0 NOT NULL');
    add_col('VERSION_CMP', 'VERSION_CMP NUMBER(10) DEFAULT 1 NOT NULL');
    -- Do this only on first installation, tracked by the domain constraint.
    SELECT COUNT(*) INTO v_count FROM ALL_CONSTRAINTS WHERE OWNER = 'CNT' AND CONSTRAINT_NAME = 'CNT_CMP_EST_CK';
    IF v_count = 0 THEN
        -- Parse after add_col executes: this column does not exist on first installation.
        EXECUTE IMMEDIATE 'UPDATE CNT.CNT_COMPROBANTES SET AJUSTE_MANUAL = 1 WHERE EXTRA1 = ''AUTOMATICO''';
        EXECUTE IMMEDIATE 'ALTER TABLE CNT.CNT_COMPROBANTES ADD CONSTRAINT CNT_CMP_EST_CK CHECK (ESTADO_CMP IN (''PENDIENTE'', ''FINALIZADO''))';
    END IF;
    SELECT COUNT(*) INTO v_count FROM ALL_CONSTRAINTS WHERE OWNER = 'CNT' AND CONSTRAINT_NAME = 'CNT_CMP_AJU_CK';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE CNT.CNT_COMPROBANTES ADD CONSTRAINT CNT_CMP_AJU_CK CHECK (AJUSTE_MANUAL IN (0,1) AND VERSION_CMP > 0)';
    END IF;
    SELECT COUNT(*) INTO v_count FROM ALL_TABLES WHERE OWNER = 'CNT' AND TABLE_NAME = 'CNT_CMP_CTL';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE TABLE CNT.CNT_CMP_CTL (CODIGO NUMBER(1) PRIMARY KEY, HABILITADO NUMBER(1) DEFAULT 0 NOT NULL, CONSTRAINT CNT_CMP_CTL_CK CHECK (CODIGO = 1 AND HABILITADO IN (0,1)))';
        EXECUTE IMMEDIATE 'INSERT INTO CNT.CNT_CMP_CTL (CODIGO, HABILITADO) VALUES (1, 0)';
    END IF;
    SELECT COUNT(*) INTO v_count FROM ALL_TABLES WHERE OWNER = 'CNT' AND TABLE_NAME = 'CNT_CMP_AUD';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE TABLE CNT.CNT_CMP_AUD (AUD_ID VARCHAR2(32) PRIMARY KEY, CODIGO_COMPROBANTE NUMBER, CODIGO_EMPRESA NUMBER, VERSION_CMP NUMBER, ESTADO_CMP VARCHAR2(12), OPERACION VARCHAR2(20), USUARIO_ID NUMBER, FECHA DATE, NUMERO_COMPROBANTE VARCHAR2(20), OBSERVACION VARCHAR2(4000))';
    END IF;
    SELECT COUNT(*) INTO v_count FROM ALL_TABLES WHERE OWNER = 'CNT' AND TABLE_NAME = 'CNT_CMP_AUD_DET';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE TABLE CNT.CNT_CMP_AUD_DET (AUD_ID VARCHAR2(32), CODIGO_DETALLE_COMPROBANTE NUMBER, CODIGO_MAYOR NUMBER, CODIGO_AUXILIAR NUMBER, MONTO NUMBER, REFERENCIA1 VARCHAR2(4000), REFERENCIA2 VARCHAR2(4000), REFERENCIA3 VARCHAR2(4000), DESCRIPCION VARCHAR2(4000), CONSTRAINT CNT_CMP_AUD_DET_FK FOREIGN KEY (AUD_ID) REFERENCES CNT.CNT_CMP_AUD(AUD_ID))';
    END IF;
END;
/
COMMIT;
