CREATE OR REPLACE PROCEDURE RH.SP_RH_PER_SALUD_VAL (
    p_ESTADO IN NUMBER
) AS
    v_count NUMBER;
BEGIN
    IF p_ESTADO IS NULL THEN RETURN; END IF;
    IF p_ESTADO <> TRUNC(p_ESTADO) OR p_ESTADO < 1 OR p_ESTADO > 99999 THEN
        RAISE_APPLICATION_ERROR(-20001, 'Estado de salud invalido.');
    END IF;
    SELECT COUNT(*) INTO v_count FROM RH.RH_DESCRIPTIVAS
     WHERE DESCRIPCION_ID = p_ESTADO AND TITULO_ID = 72;
    IF v_count = 0 THEN
        RAISE_APPLICATION_ERROR(-20002, 'Estado de salud no pertenece al titulo 72.');
    END IF;
END SP_RH_PER_SALUD_VAL;
/
