CREATE OR REPLACE TRIGGER RH.TR_RH_PER_SALUD
BEFORE INSERT OR UPDATE OF ESTADO_SALUD_ID ON RH.RH_PERSONAS
FOR EACH ROW
BEGIN
    -- Unchanged historical values are preserved without new classification.
    IF INSERTING OR (:NEW.ESTADO_SALUD_ID <> :OLD.ESTADO_SALUD_ID)
       OR (:NEW.ESTADO_SALUD_ID IS NOT NULL AND :OLD.ESTADO_SALUD_ID IS NULL) THEN
        RH.SP_RH_PER_SALUD_VAL(:NEW.ESTADO_SALUD_ID);
    END IF;
END;
/
