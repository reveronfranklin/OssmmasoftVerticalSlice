-- R51: esquema activo RH. Seleccionar todo y ejecutar como UNA sentencia.
BEGIN
  IF SYS_CONTEXT('USERENV','CURRENT_SCHEMA') <> 'RH' THEN RAISE_APPLICATION_ERROR(-20010,'Seleccione RH como esquema activo.'); END IF;
  EXECUTE IMMEDIATE 'CREATE OR REPLACE PROCEDURE RH.SP_RH_RECIBO_PAGO_GET (
    p_EMPRESA IN NUMBER, p_NOMINA IN NUMBER, p_PERIODO IN NUMBER,
    p_ICP IN NUMBER, p_PERSONA IN NUMBER, p_SOLO_HIST IN NUMBER,
    p_TEMPORAL OUT NUMBER, p_DESC_NOMINA OUT VARCHAR2,
    p_MESSAGE OUT VARCHAR2, p_RESULT OUT SYS_REFCURSOR
) AS
    v_count NUMBER;
BEGIN
    p_TEMPORAL := 0;
    p_MESSAGE := ''success'';
    p_DESC_NOMINA := NULL;
    OPEN p_RESULT FOR SELECT * FROM RH.RH_V_REPORTE_NOMINA_HISTORICO WHERE 1 = 0;
    IF p_EMPRESA IS NULL OR p_EMPRESA <= 0 OR p_NOMINA IS NULL OR p_NOMINA <= 0
       OR p_PERIODO IS NULL OR p_PERIODO <= 0 OR NVL(p_ICP, 0) < 0 OR NVL(p_PERSONA, 0) < 0 THEN
        p_MESSAGE := ''Filtros de recibo invalidos''; RETURN;
    END IF;
    SELECT MAX(DESCRIPCION) INTO p_DESC_NOMINA FROM RH.RH_TIPOS_NOMINA
     WHERE CODIGO_TIPO_NOMINA = p_NOMINA AND CODIGO_EMPRESA = p_EMPRESA;
    IF p_DESC_NOMINA IS NULL THEN
        p_MESSAGE := ''No se pudo consultar el tipo de nomina''; RETURN;
    END IF;
    -- Elegir origen antes de filtrar oficina/persona: misma prioridad que legacy.
    IF NVL(p_SOLO_HIST, 0) = 0 THEN
        SELECT COUNT(*) INTO v_count FROM RH.RH_V_REPORTE_NOMINA_TEMPORAL
         WHERE CODIGO_EMPRESA = p_EMPRESA AND CODIGO_TIPO_NOMINA = p_NOMINA
           AND CODIGO_PERIODO = p_PERIODO;
        IF v_count > 0 THEN p_TEMPORAL := 1; END IF;
    END IF;
    CLOSE p_RESULT;
    IF p_TEMPORAL = 1 THEN
        OPEN p_RESULT FOR SELECT h.* FROM RH.RH_V_REPORTE_NOMINA_TEMPORAL h
         WHERE h.CODIGO_EMPRESA = p_EMPRESA AND h.CODIGO_TIPO_NOMINA = p_NOMINA
           AND h.CODIGO_PERIODO = p_PERIODO
           AND (NVL(p_ICP, 0) = 0 OR h.CODIGO_ICP = p_ICP)
           AND (NVL(p_PERSONA, 0) = 0 OR h.CODIGO_PERSONA = p_PERSONA)
         ORDER BY h.CODIGO_ICP_CONCAT, h.CODIGO_PERSONA, h.NUMERO_CONCEPTO,
                  h.COMPLEMENTO_CONCEPTO, h.MONTO;
    ELSE
        OPEN p_RESULT FOR SELECT h.* FROM RH.RH_V_REPORTE_NOMINA_HISTORICO h
         WHERE h.CODIGO_EMPRESA = p_EMPRESA AND h.CODIGO_TIPO_NOMINA = p_NOMINA
           AND h.CODIGO_PERIODO = p_PERIODO
           AND (NVL(p_ICP, 0) = 0 OR h.CODIGO_ICP = p_ICP)
           AND (NVL(p_PERSONA, 0) = 0 OR h.CODIGO_PERSONA = p_PERSONA)
         ORDER BY h.CODIGO_ICP_CONCAT, h.CODIGO_PERSONA, h.NUMERO_CONCEPTO,
                  h.COMPLEMENTO_CONCEPTO, h.MONTO;
    END IF;
EXCEPTION
    WHEN OTHERS THEN
        p_MESSAGE := SQLERRM;
        IF p_RESULT%ISOPEN THEN CLOSE p_RESULT; END IF;
        OPEN p_RESULT FOR SELECT * FROM RH.RH_V_REPORTE_NOMINA_HISTORICO WHERE 1 = 0;
END;';
  EXECUTE IMMEDIATE 'CREATE OR REPLACE PROCEDURE RH.SP_RH_REC_PERS_RES_GET (
    p_EMPRESA IN NUMBER, p_PERSONA IN NUMBER,
    p_MESSAGE OUT VARCHAR2, p_RESULT OUT SYS_REFCURSOR
) AS
BEGIN
    p_MESSAGE := ''success'';
    OPEN p_RESULT FOR
        SELECT h.CODIGO_PERSONA, h.CODIGO_TIPO_NOMINA, h.CODIGO_PERIODO,
               CAST(NULL AS VARCHAR2(200)) TIPO_NOMINA, h.FECHA_NOMINA
          FROM RH.RH_V_REPORTE_NOMINA_HISTORICO h WHERE 1=0;
    IF p_EMPRESA IS NULL OR p_EMPRESA<=0 OR p_PERSONA IS NULL OR p_PERSONA<=0 THEN
        p_MESSAGE := ''Empresa y persona son obligatorias''; RETURN;
    END IF;
    CLOSE p_RESULT;
    -- Una fila por recibo real; la fecha se presenta, nunca identifica el periodo.
    OPEN p_RESULT FOR
        SELECT h.CODIGO_PERSONA, h.CODIGO_TIPO_NOMINA, h.CODIGO_PERIODO,
               NVL(MAX(n.DESCRIPCION), TO_CHAR(h.CODIGO_TIPO_NOMINA)) TIPO_NOMINA,
               MAX(h.FECHA_NOMINA) FECHA_NOMINA
          FROM RH.RH_V_REPORTE_NOMINA_HISTORICO h
          LEFT JOIN RH.RH_TIPOS_NOMINA n ON n.CODIGO_TIPO_NOMINA=h.CODIGO_TIPO_NOMINA
           AND n.CODIGO_EMPRESA=h.CODIGO_EMPRESA
         WHERE h.CODIGO_EMPRESA=p_EMPRESA AND h.CODIGO_PERSONA=p_PERSONA
         GROUP BY h.CODIGO_PERSONA, h.CODIGO_TIPO_NOMINA, h.CODIGO_PERIODO
         ORDER BY MAX(h.FECHA_NOMINA) DESC, h.CODIGO_TIPO_NOMINA, h.CODIGO_PERIODO DESC;
EXCEPTION
    WHEN OTHERS THEN
        p_MESSAGE := SQLERRM;
        IF p_RESULT%ISOPEN THEN CLOSE p_RESULT; END IF;
        OPEN p_RESULT FOR
            SELECT h.CODIGO_PERSONA, h.CODIGO_TIPO_NOMINA, h.CODIGO_PERIODO,
                   CAST(NULL AS VARCHAR2(200)) TIPO_NOMINA, h.FECHA_NOMINA
              FROM RH.RH_V_REPORTE_NOMINA_HISTORICO h WHERE 1=0;
END;';
  DECLARE n NUMBER;
  BEGIN
    SELECT COUNT(*) INTO n FROM ALL_OBJECTS WHERE OWNER='RH'
     AND OBJECT_NAME IN ('SP_RH_RECIBO_PAGO_GET','SP_RH_REC_PERS_RES_GET') AND STATUS<>'VALID';
    IF n>0 THEN RAISE_APPLICATION_ERROR(-20001,'Procedimientos de recibos invalidos. Revise ALL_ERRORS.'); END IF;
  END;
  DBMS_OUTPUT.PUT_LINE('R51 instalado. Publicar backend y frontend.');
END;
