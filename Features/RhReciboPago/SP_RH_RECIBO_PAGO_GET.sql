CREATE OR REPLACE PROCEDURE RH.SP_RH_RECIBO_PAGO_GET (
    p_EMPRESA IN NUMBER, p_NOMINA IN NUMBER, p_PERIODO IN NUMBER,
    p_ICP IN NUMBER, p_PERSONA IN NUMBER, p_SOLO_HIST IN NUMBER,
    p_TEMPORAL OUT NUMBER, p_DESC_NOMINA OUT VARCHAR2,
    p_MESSAGE OUT VARCHAR2, p_RESULT OUT SYS_REFCURSOR
) AS
    v_count NUMBER;
BEGIN
    p_TEMPORAL := 0;
    p_MESSAGE := 'success';
    p_DESC_NOMINA := NULL;
    OPEN p_RESULT FOR SELECT * FROM RH.RH_V_REPORTE_NOMINA_HISTORICO WHERE 1 = 0;
    IF p_EMPRESA IS NULL OR p_EMPRESA <= 0 OR p_NOMINA IS NULL OR p_NOMINA <= 0
       OR p_PERIODO IS NULL OR p_PERIODO <= 0 OR NVL(p_ICP, 0) < 0 OR NVL(p_PERSONA, 0) < 0 THEN
        p_MESSAGE := 'Filtros de recibo invalidos'; RETURN;
    END IF;
    SELECT MAX(DESCRIPCION) INTO p_DESC_NOMINA FROM RH.RH_TIPOS_NOMINA
     WHERE CODIGO_TIPO_NOMINA = p_NOMINA AND CODIGO_EMPRESA = p_EMPRESA;
    IF p_DESC_NOMINA IS NULL THEN
        p_MESSAGE := 'No se pudo consultar el tipo de nomina'; RETURN;
    END IF;
    -- Elegir origen antes de filtrar oficina/persona: misma prioridad que legacy.
    IF NVL(p_SOLO_HIST, 0) = 0 THEN
        SELECT COUNT(*) INTO v_count FROM RH.RH_V_REPORTE_NOMINA_TEMPORAL
         WHERE CODIGO_EMPRESA = p_EMPRESA AND CODIGO_TIPO_NOMINA = p_NOMINA
           AND CODIGO_PERIODO = p_PERIODO;
        IF v_count > 0 THEN p_TEMPORAL := 1; END IF;
    END IF;
    CLOSE p_RESULT;
    IF p_TEMPORAL = 1 THEN
        OPEN p_RESULT FOR SELECT h.* FROM RH.RH_V_REPORTE_NOMINA_TEMPORAL h
         WHERE h.CODIGO_EMPRESA = p_EMPRESA AND h.CODIGO_TIPO_NOMINA = p_NOMINA
           AND h.CODIGO_PERIODO = p_PERIODO
           AND (NVL(p_ICP, 0) = 0 OR h.CODIGO_ICP = p_ICP)
           AND (NVL(p_PERSONA, 0) = 0 OR h.CODIGO_PERSONA = p_PERSONA)
         ORDER BY h.CODIGO_ICP_CONCAT, h.CODIGO_PERSONA, h.NUMERO_CONCEPTO,
                  h.COMPLEMENTO_CONCEPTO, h.MONTO;
    ELSE
        OPEN p_RESULT FOR SELECT h.* FROM RH.RH_V_REPORTE_NOMINA_HISTORICO h
         WHERE h.CODIGO_EMPRESA = p_EMPRESA AND h.CODIGO_TIPO_NOMINA = p_NOMINA
           AND h.CODIGO_PERIODO = p_PERIODO
           AND (NVL(p_ICP, 0) = 0 OR h.CODIGO_ICP = p_ICP)
           AND (NVL(p_PERSONA, 0) = 0 OR h.CODIGO_PERSONA = p_PERSONA)
         ORDER BY h.CODIGO_ICP_CONCAT, h.CODIGO_PERSONA, h.NUMERO_CONCEPTO,
                  h.COMPLEMENTO_CONCEPTO, h.MONTO;
    END IF;
EXCEPTION
    WHEN OTHERS THEN
        p_MESSAGE := SQLERRM;
        IF p_RESULT%ISOPEN THEN CLOSE p_RESULT; END IF;
        OPEN p_RESULT FOR SELECT * FROM RH.RH_V_REPORTE_NOMINA_HISTORICO WHERE 1 = 0;
END;
