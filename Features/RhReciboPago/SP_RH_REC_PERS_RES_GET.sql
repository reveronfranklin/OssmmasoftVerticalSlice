CREATE OR REPLACE PROCEDURE RH.SP_RH_REC_PERS_RES_GET (
    p_EMPRESA IN NUMBER, p_PERSONA IN NUMBER,
    p_MESSAGE OUT VARCHAR2, p_RESULT OUT SYS_REFCURSOR
) AS
BEGIN
    p_MESSAGE := 'success';
    OPEN p_RESULT FOR
        SELECT h.CODIGO_PERSONA, h.CODIGO_TIPO_NOMINA, h.CODIGO_PERIODO,
               CAST(NULL AS VARCHAR2(200)) TIPO_NOMINA, h.FECHA_NOMINA
          FROM RH.RH_V_REPORTE_NOMINA_HISTORICO h WHERE 1=0;
    IF p_EMPRESA IS NULL OR p_EMPRESA<=0 OR p_PERSONA IS NULL OR p_PERSONA<=0 THEN
        p_MESSAGE := 'Empresa y persona son obligatorias'; RETURN;
    END IF;
    CLOSE p_RESULT;
    -- Una fila por recibo real; la fecha se presenta, nunca identifica el periodo.
    OPEN p_RESULT FOR
        SELECT h.CODIGO_PERSONA, h.CODIGO_TIPO_NOMINA, h.CODIGO_PERIODO,
               NVL(MAX(n.DESCRIPCION), TO_CHAR(h.CODIGO_TIPO_NOMINA)) TIPO_NOMINA,
               MAX(h.FECHA_NOMINA) FECHA_NOMINA
          FROM RH.RH_V_REPORTE_NOMINA_HISTORICO h
          LEFT JOIN RH.RH_TIPOS_NOMINA n ON n.CODIGO_TIPO_NOMINA=h.CODIGO_TIPO_NOMINA
           AND n.CODIGO_EMPRESA=h.CODIGO_EMPRESA
         WHERE h.CODIGO_EMPRESA=p_EMPRESA AND h.CODIGO_PERSONA=p_PERSONA
         GROUP BY h.CODIGO_PERSONA, h.CODIGO_TIPO_NOMINA, h.CODIGO_PERIODO
         ORDER BY MAX(h.FECHA_NOMINA) DESC, h.CODIGO_TIPO_NOMINA, h.CODIGO_PERIODO DESC;
EXCEPTION
    WHEN OTHERS THEN
        p_MESSAGE := SQLERRM;
        IF p_RESULT%ISOPEN THEN CLOSE p_RESULT; END IF;
        OPEN p_RESULT FOR
            SELECT h.CODIGO_PERSONA, h.CODIGO_TIPO_NOMINA, h.CODIGO_PERIODO,
                   CAST(NULL AS VARCHAR2(200)) TIPO_NOMINA, h.FECHA_NOMINA
              FROM RH.RH_V_REPORTE_NOMINA_HISTORICO h WHERE 1=0;
END;
