DECLARE n NUMBER;
 PROCEDURE col(nm VARCHAR2, typ VARCHAR2) IS c NUMBER; BEGIN
 SELECT COUNT(*) INTO c FROM ALL_TAB_COLUMNS WHERE OWNER='SIS' AND TABLE_NAME='SIS_EMAIL_QUEUE' AND COLUMN_NAME=nm;
 IF c=0 THEN EXECUTE IMMEDIATE 'ALTER TABLE SIS.SIS_EMAIL_QUEUE ADD ('||nm||' '||typ||')'; END IF;
 END;
BEGIN
 col('RH_ACK','NUMBER(1) DEFAULT 0');
 col('RH_SOL','VARCHAR2(36)'); col('RH_PDF','BLOB'); col('RH_PDF_HASH','VARCHAR2(64)'); col('RH_ARCHIVO','VARCHAR2(150)'); col('RH_PAUSA','NUMBER(1) DEFAULT 0');
 SELECT COUNT(*) INTO n FROM ALL_INDEXES WHERE OWNER='SIS' AND INDEX_NAME='UK_EMAIL_RH_SOL';
 IF n=0 THEN EXECUTE IMMEDIATE 'CREATE UNIQUE INDEX SIS.UK_EMAIL_RH_SOL ON SIS.SIS_EMAIL_QUEUE(RH_SOL)'; END IF;
 SELECT COUNT(*) INTO n FROM ALL_TABLES WHERE OWNER='SIS' AND TABLE_NAME='SIS_EMAIL_CTL';
 IF n=0 THEN EXECUTE IMMEDIATE 'CREATE TABLE SIS.SIS_EMAIL_CTL(EMPRESA NUMBER(10) PRIMARY KEY, DIA DATE, CANTIDAD NUMBER DEFAULT 0 NOT NULL, ULTIMO DATE, PAUSADO NUMBER(1) DEFAULT 0 NOT NULL)'; END IF;
END;
/
