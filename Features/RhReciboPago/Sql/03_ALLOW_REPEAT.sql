-- Las revisiones sin confirmar tienen SOLICITUD NULL y pueden coexistir.
-- Solo las solicitudes confirmadas deben ser unicas por empresa y actor.
DECLARE n NUMBER;
BEGIN
 SELECT COUNT(*) INTO n FROM ALL_CONSTRAINTS
 WHERE OWNER='RH' AND TABLE_NAME='RH_REC_MAIL_LOT' AND CONSTRAINT_NAME='UK_RRM_SOL' AND CONSTRAINT_TYPE='U';
 IF n>0 THEN EXECUTE IMMEDIATE 'ALTER TABLE RH.RH_REC_MAIL_LOT DROP CONSTRAINT UK_RRM_SOL'; END IF;
 SELECT COUNT(*) INTO n FROM ALL_INDEXES WHERE OWNER='RH' AND INDEX_NAME='UX_RRM_SOL';
 IF n=0 THEN EXECUTE IMMEDIATE 'CREATE UNIQUE INDEX RH.UX_RRM_SOL ON RH.RH_REC_MAIL_LOT(
 CASE WHEN SOLICITUD IS NOT NULL THEN EMPRESA END,
 CASE WHEN SOLICITUD IS NOT NULL THEN ACTOR END,
 CASE WHEN SOLICITUD IS NOT NULL THEN SOLICITUD END)'; END IF;
END;
/
