 PROCEDURE LEER(p_ID VARCHAR2,p_EMPRESA NUMBER,p_ACTOR NUMBER,p_HEAD OUT SYS_REFCURSOR,p_ROWS OUT SYS_REFCURSOR) IS BEGIN
 OPEN p_HEAD FOR SELECT * FROM RH.RH_REC_MAIL_LOT WHERE LOTE_ID=p_ID AND EMPRESA=p_EMPRESA AND ACTOR=p_ACTOR;
 -- State queries do not need frozen source JSON or PDF LOB locators.
 OPEN p_ROWS FOR SELECT d.ITEM_ID,d.LOTE_ID,d.EMPRESA,d.PERSONA,d.NOMBRE,
 d.CORREO,d.ESTADO,d.ERROR,CAST(NULL AS VARCHAR2(1)) FUENTE,
 d.HUELLA,d.LOGO_HASH,d.PDF_HASH,d.TOKEN,d.SOL_SMTP,d.INTENTOS,
 d.ANTERIOR,d.ACTUALIZADO
 FROM RH.RH_REC_MAIL_DET d JOIN RH.RH_REC_MAIL_LOT l ON l.LOTE_ID=d.LOTE_ID
 WHERE l.LOTE_ID=p_ID AND l.EMPRESA=p_EMPRESA AND l.ACTOR=p_ACTOR ORDER BY d.ITEM_ID;
 END;
 PROCEDURE LOTES(p_EMPRESA NUMBER,p_ACTOR NUMBER,p_PAGE NUMBER,p_SIZE NUMBER,p_ROWS OUT SYS_REFCURSOR,p_TOTAL OUT NUMBER) IS BEGIN
 SELECT COUNT(*) INTO p_TOTAL FROM RH.RH_REC_MAIL_LOT WHERE EMPRESA=p_EMPRESA AND ACTOR=p_ACTOR;
 OPEN p_ROWS FOR SELECT * FROM (SELECT l.*,ROW_NUMBER() OVER(ORDER BY CREADO DESC) RN FROM RH.RH_REC_MAIL_LOT l WHERE EMPRESA=p_EMPRESA AND ACTOR=p_ACTOR) WHERE RN>(p_PAGE-1)*p_SIZE AND RN<=p_PAGE*p_SIZE;
 END;
 PROCEDURE BLOQUEAR(p_ID VARCHAR2,p_EMPRESA NUMBER,p_ACTOR NUMBER,p_SOL VARCHAR2,p_REV VARCHAR2,p_REPETIDO OUT NUMBER) IS l RH.RH_REC_MAIL_LOT%ROWTYPE; n NUMBER; BEGIN
 BEGIN INSERT INTO RH.RH_REC_MAIL_CTL VALUES(p_EMPRESA); EXCEPTION WHEN DUP_VAL_ON_INDEX THEN NULL; END;
 SELECT EMPRESA INTO n FROM RH.RH_REC_MAIL_CTL WHERE EMPRESA=p_EMPRESA FOR UPDATE;
 SELECT * INTO l FROM RH.RH_REC_MAIL_LOT WHERE LOTE_ID=p_ID AND EMPRESA=p_EMPRESA AND ACTOR=p_ACTOR FOR UPDATE;
 p_REPETIDO:=0;
 IF l.SOLICITUD IS NOT NULL THEN
 IF l.SOLICITUD=p_SOL AND l.REVISION=p_REV THEN p_REPETIDO:=1; RETURN; END IF;
 RAISE_APPLICATION_ERROR(-20051,''El lote ya fue confirmado con otra solicitud.''); END IF;
 IF l.ESTADO<>''ANALISIS'' OR l.VENCE<SYSDATE OR l.REVISION<>p_REV THEN RAISE_APPLICATION_ERROR(-20051,''Analisis vencido o modificado. Vuelva a analizar.''); END IF;
 END;
 PROCEDURE CONFIRMAR(p_ID VARCHAR2,p_EMPRESA NUMBER,p_SOL VARCHAR2) IS l RH.RH_REC_MAIL_LOT%ROWTYPE; BEGIN
 SELECT * INTO l FROM RH.RH_REC_MAIL_LOT WHERE LOTE_ID=p_ID AND EMPRESA=p_EMPRESA FOR UPDATE;
 IF p_SOL IS NULL THEN RAISE_APPLICATION_ERROR(-20051,''Solicitud requerida.''); END IF;
 IF l.SOLICITUD IS NOT NULL THEN
  IF l.SOLICITUD=p_SOL THEN RETURN; END IF;
  RAISE_APPLICATION_ERROR(-20051,''El lote ya fue confirmado con otra solicitud.'');
 END IF;
 IF l.ESTADO<>''ANALISIS'' THEN RAISE_APPLICATION_ERROR(-20051,''El lote no esta en revision.''); END IF;
 -- Cada analisis confirmado es un nuevo envio intencional. La misma solicitud sigue siendo idempotente.
 UPDATE RH.RH_REC_MAIL_DET SET ESTADO=''PENDIENTE'',ACTUALIZADO=SYSDATE
 WHERE LOTE_ID=p_ID AND EMPRESA=p_EMPRESA AND ESTADO=''APTO'';
 UPDATE RH.RH_REC_MAIL_LOT SET ESTADO=''ACTIVO'',SOLICITUD=p_SOL WHERE LOTE_ID=p_ID AND EMPRESA=p_EMPRESA;
 END;
 PROCEDURE TOMAR(p_EMPRESA NUMBER,p_TOKEN VARCHAR2,p_ROWS OUT SYS_REFCURSOR) IS id NUMBER; busy EXCEPTION; PRAGMA EXCEPTION_INIT(busy,-54); BEGIN
 UPDATE RH.RH_REC_MAIL_DET SET ESTADO=CASE WHEN PDF IS NULL THEN ''PENDIENTE'' ELSE ''LISTO'' END,TOKEN=NULL,ACTUALIZADO=SYSDATE WHERE EMPRESA=p_EMPRESA AND ESTADO IN (''GENERANDO'',''LISTO'') AND TOKEN IS NOT NULL AND ACTUALIZADO<SYSDATE-30/1440;
 FOR r IN (SELECT d.ITEM_ID FROM RH.RH_REC_MAIL_DET d JOIN RH.RH_REC_MAIL_LOT l ON l.LOTE_ID=d.LOTE_ID WHERE d.EMPRESA=p_EMPRESA AND l.ESTADO=''ACTIVO'' AND d.ESTADO IN (''PENDIENTE'',''LISTO'') AND d.TOKEN IS NULL ORDER BY d.ITEM_ID) LOOP
 BEGIN
 SELECT ITEM_ID INTO id FROM RH.RH_REC_MAIL_DET WHERE ITEM_ID=r.ITEM_ID AND TOKEN IS NULL AND ESTADO IN (''PENDIENTE'',''LISTO'') FOR UPDATE NOWAIT;
 UPDATE RH.RH_REC_MAIL_DET SET ESTADO=''GENERANDO'',TOKEN=p_TOKEN,ACTUALIZADO=SYSDATE WHERE ITEM_ID=id;
 EXIT;
 EXCEPTION WHEN busy THEN NULL; WHEN NO_DATA_FOUND THEN NULL; END;
 END LOOP;
 OPEN p_ROWS FOR SELECT d.ITEM_ID,d.LOTE_ID,d.PERSONA,d.NOMBRE,d.CORREO,d.ESTADO,d.ERROR,
 CAST(NULL AS VARCHAR2(1)) FUENTE,d.HUELLA,d.LOGO_HASH,d.SOL_SMTP,d.INTENTOS,
 d.PDF_HASH,d.TOKEN,l.NOMINA,l.PERIODO FROM RH.RH_REC_MAIL_DET d JOIN RH.RH_REC_MAIL_LOT l ON l.LOTE_ID=d.LOTE_ID WHERE d.ITEM_ID=id AND d.TOKEN=p_TOKEN;
 END;
 PROCEDURE PDF_LISTO(p_ID NUMBER,p_TOKEN VARCHAR2,p_PDF BLOB,p_HASH VARCHAR2) IS BEGIN
 UPDATE RH.RH_REC_MAIL_DET SET PDF=p_PDF,PDF_HASH=p_HASH,ESTADO=''LISTO'',ACTUALIZADO=SYSDATE WHERE ITEM_ID=p_ID AND TOKEN=p_TOKEN AND ESTADO=''GENERANDO'';
 IF SQL%ROWCOUNT<>1 THEN RAISE_APPLICATION_ERROR(-20051,''La toma del recibo cambio.''); END IF;
 END;
 PROCEDURE ENCOLADO(p_ID NUMBER,p_TOKEN VARCHAR2) IS BEGIN
 UPDATE RH.RH_REC_MAIL_DET SET ESTADO=''EN_COLA'',TOKEN=NULL,ACTUALIZADO=SYSDATE WHERE ITEM_ID=p_ID AND TOKEN=p_TOKEN AND ESTADO IN (''LISTO'',''GENERANDO'');
 IF SQL%ROWCOUNT<>1 THEN RAISE_APPLICATION_ERROR(-20051,''La toma del recibo cambio.''); END IF;
 END;
 PROCEDURE RESULTADO(p_EMPRESA NUMBER,p_ID NUMBER,p_SOL VARCHAR2,p_ESTADO VARCHAR2,p_ERROR VARCHAR2,p_PAUSA NUMBER,p_APLICADO OUT NUMBER) IS n NUMBER; BEGIN
 IF p_ESTADO NOT IN (''PENDIENTE'',''ENVIANDO'',''ACEPTADO_SMTP'',''ERROR'',''INCIERTO'') THEN RAISE_APPLICATION_ERROR(-20051,''Estado SMTP invalido.''); END IF;
 UPDATE RH.RH_REC_MAIL_DET SET ESTADO=CASE WHEN p_ESTADO=''PENDIENTE'' THEN ''EN_COLA'' ELSE p_ESTADO END,ERROR=p_ERROR,ACTUALIZADO=SYSDATE WHERE ITEM_ID=p_ID AND EMPRESA=p_EMPRESA AND SOL_SMTP=p_SOL AND ESTADO IN (''EN_COLA'',''ENVIANDO'');
 n:=SQL%ROWCOUNT; p_APLICADO:=n;
 IF p_APLICADO=0 THEN SELECT COUNT(*) INTO p_APLICADO FROM RH.RH_REC_MAIL_DET WHERE ITEM_ID=p_ID AND EMPRESA=p_EMPRESA AND (SOL_SMTP<>p_SOL OR ESTADO IN (''ACEPTADO_SMTP'',''ERROR'',''INCIERTO'')); END IF;
 IF n=1 AND p_PAUSA=1 THEN UPDATE RH.RH_REC_MAIL_LOT SET ESTADO=''PAUSADO'',MOTIVO=''SMTP no disponible. Corrija configuracion y reanude el lote.'' WHERE LOTE_ID=(SELECT LOTE_ID FROM RH.RH_REC_MAIL_DET WHERE ITEM_ID=p_ID); END IF;
 END;
 PROCEDURE ERROR_PDF(p_ID NUMBER,p_TOKEN VARCHAR2,p_ERROR VARCHAR2) IS BEGIN
 UPDATE RH.RH_REC_MAIL_DET SET ESTADO=''ERROR'',ERROR=p_ERROR,TOKEN=NULL,ACTUALIZADO=SYSDATE WHERE ITEM_ID=p_ID AND TOKEN=p_TOKEN;
 END;
 PROCEDURE REANUDAR(p_ID VARCHAR2,p_EMPRESA NUMBER,p_ACTOR NUMBER) IS BEGIN
 UPDATE RH.RH_REC_MAIL_LOT SET ESTADO=''ACTIVO'',MOTIVO=NULL WHERE LOTE_ID=p_ID AND EMPRESA=p_EMPRESA AND ACTOR=p_ACTOR AND ESTADO=''PAUSADO'';
 IF SQL%ROWCOUNT<>1 THEN RAISE_APPLICATION_ERROR(-20051,''Lote no pausado o no autorizado.''); END IF;
 UPDATE RH.RH_REC_MAIL_LOT SET ESTADO=''ACTIVO'',MOTIVO=NULL WHERE EMPRESA=p_EMPRESA AND ESTADO=''PAUSADO'';
 END;
 PROCEDURE REINTENTAR(p_ID NUMBER,p_EMPRESA NUMBER,p_ACTOR NUMBER,p_SOL VARCHAR2) IS l VARCHAR2(36); e VARCHAR2(20); s VARCHAR2(36); BEGIN
 SELECT d.LOTE_ID,d.ESTADO,d.SOL_SMTP INTO l,e,s FROM RH.RH_REC_MAIL_DET d JOIN RH.RH_REC_MAIL_LOT h ON h.LOTE_ID=d.LOTE_ID WHERE d.ITEM_ID=p_ID AND h.EMPRESA=p_EMPRESA AND h.ACTOR=p_ACTOR FOR UPDATE OF d.ESTADO;
