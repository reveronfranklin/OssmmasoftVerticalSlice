 PROCEDURE LOB_PARTE(p_EMPRESA NUMBER,p_ID NUMBER,p_TOKEN VARCHAR2,p_TIPO VARCHAR2,p_POS NUMBER,p_TEXTO OUT VARCHAR2,p_BIN OUT RAW,p_TOTAL OUT NUMBER,p_NEXT OUT NUMBER) IS
 v_text CLOB; v_bin BLOB;
 BEGIN
 IF p_POS IS NULL OR p_POS<1 OR p_POS<>TRUNC(p_POS) THEN RAISE_APPLICATION_ERROR(-20053,''Posicion invalida.''); END IF;
 SELECT FUENTE,PDF INTO v_text,v_bin FROM RH.RH_REC_MAIL_DET
 WHERE ITEM_ID=p_ID AND EMPRESA=p_EMPRESA AND TOKEN=p_TOKEN AND ESTADO=''GENERANDO'';
 p_TEXTO:=NULL; p_BIN:=NULL;
 IF p_TIPO=''T'' THEN
 p_TOTAL:=NVL(DBMS_LOB.GETLENGTH(v_text),0);
 p_TEXTO:=DBMS_LOB.SUBSTR(v_text,1000,p_POS);
 p_NEXT:=p_POS+NVL(LENGTH2(p_TEXTO),0);
