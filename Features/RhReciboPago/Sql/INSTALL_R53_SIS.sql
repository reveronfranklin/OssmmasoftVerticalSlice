 PROCEDURE TOMAR(p_EMPRESA NUMBER,p_TOKEN VARCHAR2,p_MAX_DIA NUMBER,p_INTERVALO NUMBER,p_ROWS OUT SYS_REFCURSOR) IS
 id NUMBER; c SIS.SIS_EMAIL_CTL%ROWTYPE; busy EXCEPTION; PRAGMA EXCEPTION_INIT(busy,-54);
 BEGIN
 BEGIN INSERT INTO SIS.SIS_EMAIL_CTL(EMPRESA) VALUES(p_EMPRESA); EXCEPTION WHEN DUP_VAL_ON_INDEX THEN NULL; END;
 BEGIN
 SELECT * INTO c FROM SIS.SIS_EMAIL_CTL WHERE EMPRESA=p_EMPRESA FOR UPDATE NOWAIT;
 IF c.DIA IS NULL OR c.DIA<>TRUNC(SYSDATE) THEN c.CANTIDAD:=0; END IF;
 UPDATE SIS.SIS_EMAIL_QUEUE SET RH_ACK=0,ESTADO=''INCIERTO'',ERROR_ENVIO=''Proceso interrumpido. No reenviar sin revisar.'',UPDATED_AT=SYSDATE WHERE CODIGO_EMPRESA=p_EMPRESA AND MODULO_ORIGEN IN (''MANUAL_R52'',''RH_RECIBO_R53'') AND ESTADO=''ENVIANDO'' AND UPDATED_AT<SYSDATE-30/1440;
 IF c.PAUSADO=0 AND c.CANTIDAD < GREATEST(1,p_MAX_DIA) AND (c.ULTIMO IS NULL OR c.ULTIMO<=SYSDATE-GREATEST(10,p_INTERVALO)/86400) THEN

 FOR r IN (SELECT EMAIL_ID FROM SIS.SIS_EMAIL_QUEUE WHERE CODIGO_EMPRESA=p_EMPRESA AND MODULO_ORIGEN IN (''MANUAL_R52'',''RH_RECIBO_R53'') AND ESTADO=''PENDIENTE'' ORDER BY EMAIL_ID) LOOP
 BEGIN
 SELECT EMAIL_ID INTO id FROM SIS.SIS_EMAIL_QUEUE WHERE EMAIL_ID=r.EMAIL_ID AND CODIGO_EMPRESA=p_EMPRESA AND ESTADO=''PENDIENTE'' FOR UPDATE NOWAIT;
 UPDATE SIS.SIS_EMAIL_QUEUE SET RH_ACK=0,ESTADO=''ENVIANDO'',CLAIM_TOKEN=p_TOKEN,INTENTOS=INTENTOS+1,UPDATED_AT=SYSDATE,MESSAGE_ID=p_TOKEN||SUBSTR(REMITENTE,INSTR(REMITENTE,''@'')) WHERE EMAIL_ID=id;
 UPDATE SIS.SIS_EMAIL_CTL SET DIA=TRUNC(SYSDATE),CANTIDAD=c.CANTIDAD+1,ULTIMO=SYSDATE WHERE EMPRESA=p_EMPRESA;
 EXIT;
 EXCEPTION WHEN busy THEN NULL; WHEN NO_DATA_FOUND THEN NULL; END;
 END LOOP;
 END IF;
 EXCEPTION WHEN busy THEN NULL; END;
 OPEN p_ROWS FOR SELECT MODULO_ORIGEN,EMAIL_ID,PARA_LIST,CC_LIST,CCO_LIST,SUBJECT,BODY_TEXT,REMITENTE,REMITENTE_NOMBRE,MESSAGE_ID,RH_PDF,RH_ARCHIVO,RH_PDF_HASH FROM SIS.SIS_EMAIL_QUEUE WHERE EMAIL_ID=id AND CLAIM_TOKEN=p_TOKEN AND CODIGO_EMPRESA=p_EMPRESA;
 END;
