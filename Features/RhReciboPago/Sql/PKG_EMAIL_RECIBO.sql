CREATE OR REPLACE PACKAGE SIS.PKG_EMAIL_RECIBO AS
 PROCEDURE ENCOLAR(p_EMPRESA NUMBER,p_ACTOR NUMBER,p_ITEM NUMBER,p_SOL VARCHAR2,p_CORREO VARCHAR2,p_ASUNTO VARCHAR2,p_TEXTO CLOB,p_FROM VARCHAR2,p_NOMBRE VARCHAR2,p_ARCHIVO VARCHAR2,p_PDF BLOB,p_HASH VARCHAR2);
 PROCEDURE TOMAR(p_EMPRESA NUMBER,p_TOKEN VARCHAR2,p_MAX_DIA NUMBER,p_INTERVALO NUMBER,p_ROWS OUT SYS_REFCURSOR);
 PROCEDURE FINALIZAR(p_EMPRESA NUMBER,p_ID NUMBER,p_TOKEN VARCHAR2,p_ESTADO VARCHAR2,p_ERROR VARCHAR2,p_PAUSA NUMBER);
 PROCEDURE REANUDAR(p_EMPRESA NUMBER);
 PROCEDURE PAUSA(p_EMPRESA NUMBER,p_VALOR OUT NUMBER);
 PROCEDURE ACK(p_EMPRESA NUMBER,p_ID NUMBER,p_SOL VARCHAR2,p_ESTADO VARCHAR2);
 PROCEDURE RESULTADOS(p_EMPRESA NUMBER,p_ROWS OUT SYS_REFCURSOR);
END;
/
CREATE OR REPLACE PACKAGE BODY SIS.PKG_EMAIL_RECIBO AS
 PROCEDURE ENCOLAR(p_EMPRESA NUMBER,p_ACTOR NUMBER,p_ITEM NUMBER,p_SOL VARCHAR2,p_CORREO VARCHAR2,p_ASUNTO VARCHAR2,p_TEXTO CLOB,p_FROM VARCHAR2,p_NOMBRE VARCHAR2,p_ARCHIVO VARCHAR2,p_PDF BLOB,p_HASH VARCHAR2) IS n NUMBER; BEGIN
 IF DBMS_LOB.GETLENGTH(p_PDF)>5242880 OR DBMS_LOB.GETLENGTH(p_PDF)=0 THEN RAISE_APPLICATION_ERROR(-20053,'PDF vacio o mayor a 5 MiB.'); END IF;
 BEGIN
 SELECT EMAIL_ID INTO n FROM SIS.SIS_EMAIL_QUEUE WHERE RH_SOL=p_SOL AND CODIGO_EMPRESA=p_EMPRESA AND REFERENCIA_ID=p_ITEM AND RH_PDF_HASH=p_HASH AND TO_EMAIL=p_CORREO;
 RETURN;
 EXCEPTION WHEN NO_DATA_FOUND THEN NULL; END;
 SELECT SIS.SEQ_EMAIL_Q.NEXTVAL INTO n FROM DUAL;
 BEGIN
 INSERT INTO SIS.SIS_EMAIL_QUEUE(EMAIL_ID,CODIGO_EMPRESA,MODULO_ORIGEN,REFERENCIA_ID,TO_EMAIL,SUBJECT,BODY_TEXT,ESTADO,MAX_INTENTOS,ACTOR_ID,REMITENTE,REMITENTE_NOMBRE,PARA_LIST,RH_SOL,RH_PDF,RH_PDF_HASH,RH_ARCHIVO)
 VALUES(n,p_EMPRESA,'RH_RECIBO_R53',p_ITEM,p_CORREO,p_ASUNTO,p_TEXTO,'PENDIENTE',1,p_ACTOR,p_FROM,p_NOMBRE,p_CORREO,p_SOL,p_PDF,p_HASH,p_ARCHIVO);
 EXCEPTION WHEN DUP_VAL_ON_INDEX THEN
 SELECT EMAIL_ID INTO n FROM SIS.SIS_EMAIL_QUEUE WHERE RH_SOL=p_SOL AND CODIGO_EMPRESA=p_EMPRESA AND REFERENCIA_ID=p_ITEM AND RH_PDF_HASH=p_HASH AND TO_EMAIL=p_CORREO;
 END;
 END;
 PROCEDURE TOMAR(p_EMPRESA NUMBER,p_TOKEN VARCHAR2,p_MAX_DIA NUMBER,p_INTERVALO NUMBER,p_ROWS OUT SYS_REFCURSOR) IS
 id NUMBER; c SIS.SIS_EMAIL_CTL%ROWTYPE; busy EXCEPTION; PRAGMA EXCEPTION_INIT(busy,-54);
 BEGIN
 BEGIN INSERT INTO SIS.SIS_EMAIL_CTL(EMPRESA) VALUES(p_EMPRESA); EXCEPTION WHEN DUP_VAL_ON_INDEX THEN NULL; END;
 BEGIN
 SELECT * INTO c FROM SIS.SIS_EMAIL_CTL WHERE EMPRESA=p_EMPRESA FOR UPDATE NOWAIT;
 IF c.DIA IS NULL OR c.DIA<>TRUNC(SYSDATE) THEN c.CANTIDAD:=0; END IF;
 UPDATE SIS.SIS_EMAIL_QUEUE SET RH_ACK=0,ESTADO='INCIERTO',ERROR_ENVIO='Proceso interrumpido. No reenviar sin revisar.',UPDATED_AT=SYSDATE WHERE CODIGO_EMPRESA=p_EMPRESA AND MODULO_ORIGEN IN ('MANUAL_R52','RH_RECIBO_R53') AND ESTADO='ENVIANDO' AND UPDATED_AT<SYSDATE-30/1440;
 IF c.PAUSADO=0 AND c.CANTIDAD < GREATEST(1,p_MAX_DIA) AND (c.ULTIMO IS NULL OR c.ULTIMO<=SYSDATE-GREATEST(10,p_INTERVALO)/86400) THEN

 FOR r IN (SELECT EMAIL_ID FROM SIS.SIS_EMAIL_QUEUE WHERE CODIGO_EMPRESA=p_EMPRESA AND MODULO_ORIGEN IN ('MANUAL_R52','RH_RECIBO_R53') AND ESTADO='PENDIENTE' ORDER BY EMAIL_ID) LOOP
 BEGIN
 SELECT EMAIL_ID INTO id FROM SIS.SIS_EMAIL_QUEUE WHERE EMAIL_ID=r.EMAIL_ID AND CODIGO_EMPRESA=p_EMPRESA AND ESTADO='PENDIENTE' FOR UPDATE NOWAIT;
 UPDATE SIS.SIS_EMAIL_QUEUE SET RH_ACK=0,ESTADO='ENVIANDO',CLAIM_TOKEN=p_TOKEN,INTENTOS=INTENTOS+1,UPDATED_AT=SYSDATE,MESSAGE_ID=p_TOKEN||SUBSTR(REMITENTE,INSTR(REMITENTE,'@')) WHERE EMAIL_ID=id;
 UPDATE SIS.SIS_EMAIL_CTL SET DIA=TRUNC(SYSDATE),CANTIDAD=c.CANTIDAD+1,ULTIMO=SYSDATE WHERE EMPRESA=p_EMPRESA;
 EXIT;
 EXCEPTION WHEN busy THEN NULL; WHEN NO_DATA_FOUND THEN NULL; END;
 END LOOP;
 END IF;
 EXCEPTION WHEN busy THEN NULL; END;
 OPEN p_ROWS FOR SELECT MODULO_ORIGEN,EMAIL_ID,PARA_LIST,CC_LIST,CCO_LIST,SUBJECT,BODY_TEXT,REMITENTE,REMITENTE_NOMBRE,MESSAGE_ID,RH_PDF,RH_ARCHIVO,RH_PDF_HASH FROM SIS.SIS_EMAIL_QUEUE WHERE EMAIL_ID=id AND CLAIM_TOKEN=p_TOKEN AND CODIGO_EMPRESA=p_EMPRESA;
 END;
 PROCEDURE FINALIZAR(p_EMPRESA NUMBER,p_ID NUMBER,p_TOKEN VARCHAR2,p_ESTADO VARCHAR2,p_ERROR VARCHAR2,p_PAUSA NUMBER) IS BEGIN
 IF p_ESTADO NOT IN ('ACEPTADO_SMTP','ERROR','INCIERTO') THEN RAISE_APPLICATION_ERROR(-20053,'Estado no valido.'); END IF;
 UPDATE SIS.SIS_EMAIL_QUEUE SET RH_ACK=0,ESTADO=p_ESTADO,ERROR_ENVIO=p_ERROR,RH_PAUSA=p_PAUSA,UPDATED_AT=SYSDATE,FECHA_ENVIO=CASE WHEN p_ESTADO='ACEPTADO_SMTP' THEN SYSDATE ELSE NULL END WHERE EMAIL_ID=p_ID AND CODIGO_EMPRESA=p_EMPRESA AND CLAIM_TOKEN=p_TOKEN AND ESTADO='ENVIANDO';
 IF SQL%ROWCOUNT<>1 THEN RAISE_APPLICATION_ERROR(-20053,'Toma de correo modificada. Revisar antes de reenviar.'); END IF;
 IF p_PAUSA=1 THEN UPDATE SIS.SIS_EMAIL_CTL SET PAUSADO=1 WHERE EMPRESA=p_EMPRESA; END IF;
 END;
 PROCEDURE REANUDAR(p_EMPRESA NUMBER) IS BEGIN UPDATE SIS.SIS_EMAIL_CTL SET PAUSADO=0 WHERE EMPRESA=p_EMPRESA; END;
 PROCEDURE PAUSA(p_EMPRESA NUMBER,p_VALOR OUT NUMBER) IS BEGIN SELECT NVL(MAX(PAUSADO),0) INTO p_VALOR FROM SIS.SIS_EMAIL_CTL WHERE EMPRESA=p_EMPRESA; END;
 PROCEDURE ACK(p_EMPRESA NUMBER,p_ID NUMBER,p_SOL VARCHAR2,p_ESTADO VARCHAR2) IS BEGIN
 UPDATE SIS.SIS_EMAIL_QUEUE SET RH_ACK=1 WHERE CODIGO_EMPRESA=p_EMPRESA AND EMAIL_ID=p_ID AND RH_SOL=p_SOL AND ESTADO=p_ESTADO;
 END;
 PROCEDURE RESULTADOS(p_EMPRESA NUMBER,p_ROWS OUT SYS_REFCURSOR) IS BEGIN
 OPEN p_ROWS FOR SELECT EMAIL_ID,REFERENCIA_ID,RH_SOL,ESTADO,ERROR_ENVIO,RH_PAUSA FROM SIS.SIS_EMAIL_QUEUE WHERE CODIGO_EMPRESA=p_EMPRESA AND MODULO_ORIGEN='RH_RECIBO_R53' AND NVL(RH_ACK,0)=0 AND ROWNUM<=200;
 END;
END;
