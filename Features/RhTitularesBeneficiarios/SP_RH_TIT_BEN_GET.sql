-- R55. Run as RH with direct SELECT on SIS.SIS_UBICACION_NACIONAL.
-- No tables or existing views are replaced. Oracle 10g compatible.
CREATE OR REPLACE PROCEDURE RH.SP_RH_TIT_BEN_GET (
    p_EMPRESA IN NUMBER, p_NOMINAS IN VARCHAR2,
    p_RESULT OUT SYS_REFCURSOR, p_FAMILIARES OUT SYS_REFCURSOR,
    p_DIRECCIONES OUT SYS_REFCURSOR
) AS
    v_AMBIGUOS NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_AMBIGUOS
      FROM (SELECT p.CEDULA, TRIM(p.NACIONALIDAD)
              FROM RH.RH_PERSONAS p
             WHERE p.CODIGO_EMPRESA = p_EMPRESA
               AND EXISTS (SELECT 1 FROM RH.RH_V_TITULAR_BENEFICIARIOS v
                    WHERE INSTR(',' || p_NOMINAS || ',', ',' || TO_CHAR(v.CODIGO_TIPO_NOMINA) || ',') > 0
                      AND TRIM(p.NACIONALIDAD) || '-' || TO_CHAR(p.CEDULA) = TRIM(v.CEDULA_TITULAR))
             GROUP BY p.CEDULA, TRIM(p.NACIONALIDAD) HAVING COUNT(*) > 1);
    IF v_AMBIGUOS > 0 THEN
        RAISE_APPLICATION_ERROR(-20055, 'Existen titulares con identidad duplicada en la empresa.');
    END IF;
    OPEN p_RESULT FOR
        SELECT v.*, p.CODIGO_PERSONA TIT_PERSONA
          FROM RH.RH_V_TITULAR_BENEFICIARIOS v
          JOIN RH.RH_PERSONAS p ON p.CODIGO_EMPRESA = p_EMPRESA
                   AND TRIM(p.NACIONALIDAD) || '-' || TO_CHAR(p.CEDULA) = TRIM(v.CEDULA_TITULAR)
         WHERE INSTR(',' || p_NOMINAS || ',', ',' || TO_CHAR(v.CODIGO_TIPO_NOMINA) || ',') > 0

         ORDER BY v.CODIGO_TIPO_NOMINA, v.CEDULA_TITULAR, v.ORDER_BY;

    OPEN p_FAMILIARES FOR
        SELECT f.CODIGO_PERSONA, f.CODIGO_FAMILIAR, f.CEDULA_FAMILIAR,
               f.NACIONALIDAD, f.NOMBRE, f.APELLIDO, f.FECHA_NACIMIENTO,
               r.DESCRIPCION PARENTESCO, f.EMAIL, f.NUMERO_COMUNICACION
          FROM RH.RH_FAMILIARES f
          JOIN RH.RH_PERSONAS p ON p.CODIGO_PERSONA = f.CODIGO_PERSONA
          LEFT JOIN RH.RH_DESCRIPTIVAS r ON r.DESCRIPCION_ID = f.PARIENTE_ID
         WHERE f.CODIGO_EMPRESA = p_EMPRESA AND EXISTS (SELECT 1 FROM RH.RH_V_TITULAR_BENEFICIARIOS v
                     WHERE INSTR(',' || p_NOMINAS || ',', ',' || TO_CHAR(v.CODIGO_TIPO_NOMINA) || ',') > 0
                       AND p.CODIGO_EMPRESA = p_EMPRESA
                   AND TRIM(p.NACIONALIDAD) || '-' || TO_CHAR(p.CEDULA) = TRIM(v.CEDULA_TITULAR));

    OPEN p_DIRECCIONES FOR
        SELECT d.CODIGO_PERSONA, d.CODIGO_DIRECCION, d.PRINCIPAL,
               (SELECT MAX(r.DESCRIPCION) FROM RH.RH_DESCRIPTIVAS r WHERE r.DESCRIPCION_ID = d.DIRECCION_ID) TIPO_DIRECCION,
               (SELECT MAX(r.DESCRIPCION) FROM RH.RH_DESCRIPTIVAS r WHERE r.DESCRIPCION_ID = d.TIPO_VIVIENDA_ID) TIPO_VIVIENDA,
               (SELECT MAX(r.DESCRIPCION) FROM RH.RH_DESCRIPTIVAS r WHERE r.DESCRIPCION_ID = d.TIPO_NIVEL_ID) TIPO_NIVEL,
               (SELECT MAX(r.DESCRIPCION) FROM RH.RH_DESCRIPTIVAS r WHERE r.DESCRIPCION_ID = d.TENENCIA_ID) TENENCIA,
               (SELECT MAX(u.EXTRA1) FROM SIS.SIS_UBICACION_NACIONAL u WHERE u.PAIS = d.PAIS_ID AND u.ENTIDAD = 0 AND u.MUNICIPIO = 0 AND u.CIUDAD = 0 AND u.PARROQUIA = 0 AND u.SECTOR = 0 AND u.URBANIZACION = 0 AND NVL(u.MANZANA, 0) = 0 AND NVL(u.PARCELA, 0) = 0) PAIS,
               (SELECT MAX(u.EXTRA1) FROM SIS.SIS_UBICACION_NACIONAL u WHERE u.PAIS = d.PAIS_ID AND u.ENTIDAD = d.ESTADO_ID AND u.MUNICIPIO = 0 AND u.CIUDAD = 0 AND u.PARROQUIA = 0 AND u.SECTOR = 0 AND u.URBANIZACION = 0 AND NVL(u.MANZANA, 0) = 0 AND NVL(u.PARCELA, 0) = 0) ESTADO,
               (SELECT MAX(u.EXTRA1) FROM SIS.SIS_UBICACION_NACIONAL u WHERE u.PAIS = d.PAIS_ID AND u.ENTIDAD = d.ESTADO_ID AND u.MUNICIPIO = d.MUNICIPIO_ID AND u.CIUDAD = 0 AND u.PARROQUIA = 0 AND u.SECTOR = 0 AND u.URBANIZACION = 0 AND NVL(u.MANZANA, 0) = 0 AND NVL(u.PARCELA, 0) = 0) MUNICIPIO,
               (SELECT MAX(u.EXTRA1) FROM SIS.SIS_UBICACION_NACIONAL u WHERE u.PAIS = d.PAIS_ID AND u.ENTIDAD = d.ESTADO_ID AND u.MUNICIPIO = d.MUNICIPIO_ID AND u.CIUDAD = d.CIUDAD_ID AND u.PARROQUIA = 0 AND u.SECTOR = 0 AND u.URBANIZACION = 0 AND NVL(u.MANZANA, 0) = 0 AND NVL(u.PARCELA, 0) = 0) CIUDAD,
               (SELECT MAX(u.EXTRA1) FROM SIS.SIS_UBICACION_NACIONAL u WHERE u.PAIS = d.PAIS_ID AND u.ENTIDAD = d.ESTADO_ID AND u.MUNICIPIO = d.MUNICIPIO_ID AND u.CIUDAD = d.CIUDAD_ID AND u.PARROQUIA = d.PARROQUIA_ID AND u.SECTOR = 0 AND u.URBANIZACION = 0 AND NVL(u.MANZANA, 0) = 0 AND NVL(u.PARCELA, 0) = 0) PARROQUIA,
               (SELECT MAX(u.EXTRA1) FROM SIS.SIS_UBICACION_NACIONAL u WHERE u.PAIS = d.PAIS_ID AND u.ENTIDAD = d.ESTADO_ID AND u.MUNICIPIO = d.MUNICIPIO_ID AND u.CIUDAD = d.CIUDAD_ID AND u.PARROQUIA = d.PARROQUIA_ID AND u.SECTOR = d.SECTOR_ID AND u.URBANIZACION = 0 AND NVL(u.MANZANA, 0) = 0 AND NVL(u.PARCELA, 0) = 0) SECTOR,
               (SELECT MAX(u.EXTRA1) FROM SIS.SIS_UBICACION_NACIONAL u WHERE u.PAIS = d.PAIS_ID AND u.ENTIDAD = d.ESTADO_ID AND u.MUNICIPIO = d.MUNICIPIO_ID AND u.CIUDAD = d.CIUDAD_ID AND u.PARROQUIA = d.PARROQUIA_ID AND u.SECTOR = d.SECTOR_ID AND u.URBANIZACION = d.URBANIZACION_ID AND NVL(u.MANZANA, 0) = 0 AND NVL(u.PARCELA, 0) = 0) URBANIZACION,
               d.VIALIDAD, d.VIVIENDA, d.NIVEL, d.NRO_VIVIENDA,
               d.COMPLEMENTO_DIR, d.CODIGO_POSTAL
          FROM RH.RH_DIRECCIONES d
          JOIN RH.RH_PERSONAS p ON p.CODIGO_PERSONA = d.CODIGO_PERSONA
         WHERE d.CODIGO_EMPRESA = p_EMPRESA AND EXISTS (SELECT 1 FROM RH.RH_V_TITULAR_BENEFICIARIOS v
                     WHERE INSTR(',' || p_NOMINAS || ',', ',' || TO_CHAR(v.CODIGO_TIPO_NOMINA) || ',') > 0
                       AND p.CODIGO_EMPRESA = p_EMPRESA
                   AND TRIM(p.NACIONALIDAD) || '-' || TO_CHAR(p.CEDULA) = TRIM(v.CEDULA_TITULAR))
         ORDER BY d.CODIGO_PERSONA, d.CODIGO_DIRECCION;
END;
/
SHOW ERRORS PROCEDURE RH.SP_RH_TIT_BEN_GET;
