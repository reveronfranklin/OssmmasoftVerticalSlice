CREATE OR REPLACE VIEW "RH"."RH_V_TIT_BEN_KEYS" ("CEDULA_TITULAR", "CEDULA_BENEFICIARIO", "APELLIDOS_TITU_BENE", "NOMBRES_TITU_BENE", "SEXO", "FECHA_NACIMIENTO_FAMILIAR", "EDAD", "ESTADO_CIVIL", "PARENTESCO", "VINCULO", "CD_LOCALIDAD", "CD_GRUPO", "CD_BANCO", "NU_CUENTA", "TP_CUENTA", "DE_EMAIL", "NRO_AREA", "NRO_TELEFONO", "CODIGO_TIPO_NOMINA", "TIPO_NOMINA", "FECHA_INGRESO", "FECHA_EGRESO", "CODIGO_ICP", "UNIDAD_ADSCRIPCION", "CARGO_NOMINAL", "ANTIGUEDAD_CMC", "ANTIGUEDAD_OTROS", "SUELDO_BASICO", "ANOS_ANTIGUEDAD_VACA", "DIAS_ANTIGUEDAD_VACA", "PERIODOS_VACA", "PERIODOS_VACA_DISFRU", "PERIODOS_VACA_PP_DISFRU", "ORDER_BY", "CODIGO_PERSONA", "CODIGO_FAMILIAR") AS
  SELECT D1.DESCRIPCION || A.CEDULA CEDULA_TITULAR
    ,D1.DESCRIPCION || A.CEDULA CEDULA_BENEFICIARIO
    ,A.APELLIDO APELLIDOS_TITU_BENE
    ,A.NOMBRE NOMBRES_TITU_BENE
    ,A.SEXO
    ,TO_DATE(TO_CHAR(A.FECHA_NACIMIENTO,'DD/MM/RRRR'),'DD/MM/RRRR') FECHA_NACIMIENTO
    ,NULL EDAD
    ,(SELECT D3.DESCRIPCION FROM RH_DESCRIPTIVAS D3 WHERE D3.DESCRIPCION_ID = A.ESTADO_CIVIL_ID) ESTADO_CIVIL
    ,'TITULAR '||' '||A.SEXO PARENTESCO
    ,(SELECT DECODE(A.SEXO,'F',DECODE(D2.DESCRIPCION,'HIJO','MADRE','HIJA','MADRE'),'M',DECODE(D2.DESCRIPCION,'HIJO','PADRE','HIJA','PADRE')) FROM RH_FAMILIARES RF,RH_DESCRIPTIVAS D2 WHERE  RF.PARIENTE_ID = D2.DESCRIPCION_ID AND ROWNUM = 1 AND RF.CODIGO_PERSONA = A.CODIGO_PERSONA    AND d2.descripcion LIKE '%HIJ%'
) VINCULO
    ,'CONCEJO MUNICIPAL DE CHACAO' CD_LOCALIDAD
    ,NULL CD_GRUPO
    ,BCO.BANCO CD_BANCO
    ,''''||BCO.CUENTA||'''' NU_CUENTA
    ,BCO.TIPO_CUENTA TP_CUENTA -- CORRIENTE | AHORRO
    ,RH.RH_F_MAIL( A.CODIGO_PERSONA ) DE_EMAIL
    ,COM2.CODIGO_AREA NRO_AREA -- 0212
    ,COM2.LINEA_COMUNICACION NRO_TELEFONO -- 1234554
    ,RTN.CODIGO_TIPO_NOMINA
    ,RTN.DESCRIPCION TIPO_NOMINA
    ,TO_DATE(TO_CHAR(RA.FECHA_INGRESO,'DD/MM/RRRR'),'DD/MM/RRRR') FECHA_INGRESO
    ,TO_DATE(TO_CHAR(EGRE.FECHA_EGRESO,'DD/MM/RRRR'),'DD/MM/RRRR') FECHA_EGRESO
    ,PICP.CODIGO_ICP
    ,PICP.DENOMINACION UNIDAD_ADSCRIPCION
    ,C.DENOMINACION CARGO_NOMINAL
    ,NULL ANTIGUEDAD_CMC
    ,NULL ANTIGUEDAD_OTROS    ,0 SUELDO_BASICO    ,0 ANOS_ANTIGUEDAD_VACA    ,0 DIAS_ANTIGUEDAD_VACA    ,NULL PERIODOS_VACA    ,NULL PERIODOS_VACA_DISFRU    ,NULL PERIODOS_VACA_PP_DISFRU
    ,1 ORDER_BY
    ,A.CODIGO_PERSONA
    ,CAST(NULL AS NUMBER) CODIGO_FAMILIAR
    FROM RH_PERSONAS A
     ,RH_ADMINISTRATIVOS RA
     ,RH_DESCRIPTIVAS D1
     ,RH_RELACION_CARGOS B
     ,PRE_CARGOS C
     ,PRE_INDICE_CAT_PRG PICP
     ,RH_TIPOS_NOMINA RTN
     ,(SELECT DISTINCT
              D.CODIGO_PERSONA
              ,D1.DESCRIPCION BANCO
              ,NO_CUENTA CUENTA
              ,D2.DESCRIPCION TIPO_CUENTA
         FROM RH_ADMINISTRATIVOS D,
              RH_DESCRIPTIVAS D1,
              RH_DESCRIPTIVAS D2
        WHERE D1.DESCRIPCION_ID = D.BANCO_ID
          AND D2.DESCRIPCION_ID = D.TIPO_CUENTA_ID
      ) BCO
      ,(
      SELECT RC.CODIGO_PERSONA, RC.CODIGO_AREA, RC.LINEA_COMUNICACION  FROM rh_comunicaciones rc, rh_descriptivas d4
       WHERE rc.tipo_comunicacion_id = d4.descripcion_id
         AND ( d4.codigo <> 'EMAIL' OR d4.codigo IS NULL )
         AND rc.codigo_area IS NOT NULL
         AND rc.principal = 1
         ) COM2
      ,(
      SELECT RE.CODIGO_PERSONA, MAX(RE.FECHA_EGRESO) FECHA_EGRESO FROM RH_EGRESOS RE
      --WHERE CODIGO_PERSONA = 4
      GROUP BY RE.CODIGO_PERSONA
      ) EGRE
      WHERE D1.DESCRIPCION_ID = A.IDENTIFICACION_ID
  AND B.CODIGO_PERSONA = A.CODIGO_PERSONA
  AND A.CODIGO_PERSONA = RA.CODIGO_PERSONA
  AND C.CODIGO_CARGO = B.CODIGO_CARGO
  AND B.CODIGO_TIPO_NOMINA = RTN.CODIGO_TIPO_NOMINA
  AND C.CODIGO_CARGO    = B.CODIGO_CARGO
  AND PICP.CODIGO_ICP   = B.CODIGO_ICP
  AND B.FECHA_FIN IS NULL
  AND BCO.CODIGO_PERSONA = A.CODIGO_PERSONA
--  AND COM1.CODIGO_PERSONA (+)= A.CODIGO_PERSONA
  AND COM2.CODIGO_PERSONA (+)= A.CODIGO_PERSONA
  AND EGRE.CODIGO_PERSONA (+)= A.CODIGO_PERSONA
  AND A.STATUS = 'A' --<> 'E'
  --AND rtn.codigo_tipo_nomina = 20
UNION
  SELECT D1.DESCRIPCION || A.CEDULA CEDULA_TITULAR
    ,DECODE(RF.NACIONALIDAD ||RF.CEDULA_FAMILIAR,'V0','MENOR',RF.NACIONALIDAD||RF.CEDULA_FAMILIAR) CEDULA_BENEFCIARIO
    ,RF.APELLIDO APELLIDOS_TITU_BENE
    ,RF.NOMBRE NOMBRES_TITU_BENE
    ,RF.SEXO
    ,TO_DATE(TO_CHAR(RF.FECHA_NACIMIENTO,'DD/MM/RRRR'),'DD/MM/RRRR') FECHA_NACIMIENTO
    ,NULL EDAD
    ,(SELECT D3.DESCRIPCION FROM RH_DESCRIPTIVAS D3 WHERE D3.DESCRIPCION_ID = A.ESTADO_CIVIL_ID) ESTADO_CIVIL
    ,(SELECT DESCRIPCION FROM RH_DESCRIPTIVAS RD1 WHERE RD1.DESCRIPCION_ID = RF.PARIENTE_ID)     ||' '|| (SELECT RD3.DESCRIPCION FROM RH_DESCRIPTIVAS RD3 WHERE RD3.DESCRIPCION_ID = RF.ESTADO_SALUD_ID) PARENTESCO    ,NULL VINCULO    ,'CONCEJO MUNICIPAL DE CHACAO' CD_LOCALIDAD
    ,NULL CD_GRUPO
    ,NULL  CD_BANCO
    ,NULL  NU_CUENTA
    ,NULL TP_CUENTA -- CORRIENTE | AHORRO
    ,NULL DE_EMAIL --YO@YO
    ,NULL  NRO_AREA -- 0212
    ,NULL NRO_TELEFONO -- 1234554
    ,RTN.CODIGO_TIPO_NOMINA
    ,RTN.DESCRIPCION  TIPO_NOMINA
    ,NULL FECHA_INGRESO
    ,NULL FECHA_EGRESO
    ,PICP.CODIGO_ICP
    ,PICP.DENOMINACION UNIDAD_ADSCRIPCION
    ,C.DENOMINACION CARGO_NOMINAL
    ,NULL ANTIGUEDAD_CMC
    ,NULL ANTIGUEDAD_OTROS    ,0 SUELDO_BASICO    ,0 ANOS_ANTIGUEDAD_VACA    ,0 DIAS_ANTIGUEDAD_VACA    ,NULL PERIODOS_VACA    ,NULL PERIODOS_VACA_DISFRU    ,NULL PERIODOS_VACA_PP_DISFRU
    ,2 ORDER_BY
    ,A.CODIGO_PERSONA
    ,RF.CODIGO_FAMILIAR
FROM RH_PERSONAS A
     ,RH_ADMINISTRATIVOS RA
     ,RH_DESCRIPTIVAS D1
     ,RH_RELACION_CARGOS B
     ,PRE_CARGOS C
     ,PRE_INDICE_CAT_PRG PICP
     ,RH_FAMILIARES RF
     ,RH_TIPOS_NOMINA RTN
  WHERE D1.DESCRIPCION_ID = A.IDENTIFICACION_ID
  AND B.CODIGO_PERSONA = A.CODIGO_PERSONA
  AND A.CODIGO_PERSONA = RA.CODIGO_PERSONA
  AND C.CODIGO_CARGO = B.CODIGO_CARGO
  AND B.CODIGO_TIPO_NOMINA = RTN.CODIGO_TIPO_NOMINA
  AND C.CODIGO_CARGO    = B.CODIGO_CARGO
  AND PICP.CODIGO_ICP   = B.CODIGO_ICP
  AND RF.CODIGO_PERSONA = A.CODIGO_PERSONA
  AND B.FECHA_FIN IS NULL
  AND A.STATUS = 'A' --<> 'E'
  --AND rtn.codigo_tipo_nomina = 20
--ORDER BY 1,28 --18,1,2 --7,1,14
