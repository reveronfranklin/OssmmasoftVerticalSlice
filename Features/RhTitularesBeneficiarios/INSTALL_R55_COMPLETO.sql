    ,NULL ANTIGUEDAD_OTROS    ,0 SUELDO_BASICO    ,0 ANOS_ANTIGUEDAD_VACA    ,0 DIAS_ANTIGUEDAD_VACA    ,NULL PERIODOS_VACA    ,NULL PERIODOS_VACA_DISFRU    ,NULL PERIODOS_VACA_PP_DISFRU
