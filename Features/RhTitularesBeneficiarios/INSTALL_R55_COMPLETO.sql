    FROM RH_PERSONAS A
     ,RH_ADMINISTRATIVOS RA
     ,RH_DESCRIPTIVAS D1
     ,RH_RELACION_CARGOS B
     ,PRE_CARGOS C
     ,PRE_INDICE_CAT_PRG PICP
     ,RH_TIPOS_NOMINA RTN
