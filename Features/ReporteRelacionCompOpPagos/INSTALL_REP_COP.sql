SET SERVEROUTPUT ON
SET DEFINE OFF
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
@@SP_REP_COP_BASE_GET.sql
@@SP_REP_COP_OP_GET.sql
@@SP_REP_COP_PAG_GET.sql
@@SP_REP_COP_PROV_GET.sql
SELECT OBJECT_NAME, STATUS FROM USER_OBJECTS
 WHERE OBJECT_NAME IN ('SP_REP_COP_BASE_GET', 'SP_REP_COP_OP_GET',
                       'SP_REP_COP_PAG_GET', 'SP_REP_COP_PROV_GET');
SELECT NAME, LINE, POSITION, TEXT FROM USER_ERRORS
 WHERE NAME IN ('SP_REP_COP_BASE_GET', 'SP_REP_COP_OP_GET',
                'SP_REP_COP_PAG_GET', 'SP_REP_COP_PROV_GET') ORDER BY NAME, SEQUENCE;
DECLARE
    v_invalidos NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_invalidos FROM USER_OBJECTS
     WHERE OBJECT_NAME IN ('SP_REP_COP_BASE_GET', 'SP_REP_COP_OP_GET',
                           'SP_REP_COP_PAG_GET', 'SP_REP_COP_PROV_GET') AND STATUS <> 'VALID';
    IF v_invalidos > 0 THEN
        RAISE_APPLICATION_ERROR(-20003, 'Hay procedimientos de REP_REL_COP invalidos. Revisar USER_ERRORS.');
    END IF;
END;
